# 1. Что такое Vault (и OpenBao) и какую задачу он решает?
Vault — централизованное хранилище секретов (пароли, API-токены,
сертификаты, ключи шифрования) с контролем доступа и аудитом всех
обращений. OpenBao — открытый форк Vault (создан после смены
лицензии HashiCorp на BUSL), полностью совместимый по API и
конфигурации с версией Vault до форка. Задача та же, что у
встроенных секретов CI/CD (см. `00_fundamentals.sh`, вопрос 3), но
централизованно для ВСЕЙ инфраструктуры, а не только пайплайнов —
с динамической генерацией временных секретов вместо хранения
статичных паролей вечно.

# 2. Из каких основных разделов состоит конфигурационный файл
Vault/OpenBao?
```hcl
# config.hcl
storage "raft" {
  path    = "/vault/data"
  node_id = "node1"
}

listener "tcp" {
  address     = "0.0.0.0:8200"
  tls_disable = 0
}

api_addr = "https://vault1.internal:8200"
cluster_addr = "https://vault1.internal:8201"
```
- `storage` — бэкенд хранения зашифрованных данных (встроенный
  `raft` для HA-кластера без внешней БД, либо внешний — Consul).
- `listener` — на каком адресе/порту слушать API-запросы.
- `api_addr`/`cluster_addr` — адреса для общения между узлами
  кластера и клиентами.

# 3. Что такое Seal/Unseal и зачем нужны Unseal-ключи?
Все данные на диске Vault зашифрованы мастер-ключом, который сам
НЕ хранится на диске в открытом виде. После каждого старта процесса
Vault находится в состоянии **Sealed** (запечатан, не может
расшифровывать данные), пока не будет собрано минимальное число
**Unseal-ключей** (по умолчанию Vault разбивает мастер-ключ на 5
частей по схеме Шамира, из которых достаточно 3 для восстановления)
— это защита от того, что получение доступа к диску/бэкапу само по
себе не даёт доступа к секретам.

# 4. Что такое Secrets Engines и какие основные типы есть в Vault?
Подключаемые модули (`vault secrets enable <тип>`), определяющие,
КАК именно Vault генерирует/хранит секрет под указанным путём.
- **KV (Key-Value)** — простое хранение статичных секретов
  (`vault kv put secret/myapp password=12345`).
- **Database** — динамически создаёт временные учётные записи в
  реальной БД (Postgres/MySQL) по запросу, с автоматическим
  истечением срока действия (TTL).
- **PKI** — выпускает TLS-сертификаты на лету, подписанные
  внутренним Certificate Authority.
- **Transit** — шифрование/расшифровка данных "как сервис" (сами
  данные через Vault не проходят на хранение, только операция
  шифрования), используется приложениями, которым нужно шифровать
  без собственного управления ключами.

# 5. Чем динамические секреты (Dynamic Secrets) лучше статических?
Статический секрет (пароль в KV) — такой же вечный пароль, как
любой другой, просто хранится централизованно. Динамический секрет
(Database/AWS Secrets Engine) Vault генерирует НА ЛЕТУ по запросу
клиента с ограниченным TTL — после истечения срока Vault сам
отзывает доступ (например, `DROP USER` в БД). Это резко сокращает
"окно жизни" скомпрометированного секрета и убирает проблему
ручной ротации вечных паролей.

# 6. Какие основные методы аутентификации (Auth Methods) в Vault
используются для CI/CD и Kubernetes?
- **AppRole** — для CI-пайплайнов: приложение аутентифицируется
  парой `role_id`/`secret_id` вместо постоянного токена.
- **Kubernetes Auth** — под в кластере аутентифицируется, предъявляя
  свой Service Account JWT-токен; Vault проверяет его через
  Kubernetes API и выдаёт Vault-токен с правами, привязанными к
  конкретному namespace/Service Account — не нужно отдельно
  раскладывать секреты Vault по подам вручную.
- **JWT/OIDC** — для интеграции с GitLab CI/GitHub Actions: раннер
  предъявляет подписанный CI-системой JWT-токен задания, Vault
  проверяет подпись и выдаёт временный доступ без постоянного
  токена, хранящегося в CI-переменных.

# 7. Что такое Vault Policies и как они определяют права доступа?
HCL-документ, описывающий, какие пути (`path`) и какие операции
(`capabilities`: `read`/`create`/`update`/`delete`/`list`) доступны
обладателю токена с этой политикой.
```hcl
# policy: ci-readonly
path "secret/data/myapp/*" {
  capabilities = ["read"]
}
```
Политика привязывается к Auth Method (вопрос 6) — например, токену,
выданному через Kubernetes Auth конкретному Service Account,
назначается конкретная политика, ограничивающая его только своим
путём секретов, а не всем хранилищем.
