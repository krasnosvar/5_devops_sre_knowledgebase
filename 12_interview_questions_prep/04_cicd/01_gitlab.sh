# 1. Из каких компонентов состоит установка self-hosted GitLab?
- **GitLab Rails (gitlab-rails/Puma)** — основное веб-приложение и
  API.
- **Gitaly** — отдельный сервис, обслуживающий Git-репозитории
  (git clone/push/pull идут через него, а не напрямую через Rails).
- **Sidekiq** — обработка фоновых асинхронных задач (отправка email,
  импорт проектов).
- **PostgreSQL** — основная реляционная БД (проекты, пользователи,
  issues, MR).
- **Redis** — кэш и очереди для Sidekiq.
- **GitLab Runner** — отдельно устанавливаемый компонент (не
  обязательно на том же сервере), исполняющий сами CI/CD джобы.
Для небольших инсталляций всё это разворачивается одной командой
через Omnibus-пакет (`gitlab-ce`/`gitlab-ee`) или Helm-чартом в
Kubernetes для более крупных.

# 2. Из каких основных ключей состоит файл `.gitlab-ci.yml`?
```yaml
stages:
  - build
  - test
  - deploy

build_job:
  stage: build
  image: golang:1.22
  script:
    - go build -o app .
  artifacts:
    paths:
      - app
```
- `stages` — список стадий пайплайна и их порядок.
- Имя джобы (`build_job`) — произвольное, с ключами `stage` (к
  какой стадии относится), `image` (Docker-образ исполнения),
  `script` (команды), `artifacts` (что передать в следующие стадии).

# 3. Что такое шаблоны (Templates) в GitLab CI — `include` и `extends`?
`include` подключает в текущий пайплайн содержимое ДРУГОГО
YAML-файла (локального, из другого проекта или удалённого URL) —
используется, чтобы не копировать одни и те же джобы в каждый
репозиторий.
```yaml
include:
  - project: 'templates/ci-templates'
    file: '/docker-build.yml'
```
`extends` — наследование внутри одного или подключённого файла:
джоба берёт все ключи от указанного "шаблона" (обычно джобы с
именем, начинающимся на `.`, которая сама не запускается) и может
переопределить часть из них.
```yaml
.go_build_template:
  image: golang:1.22
  script:
    - go build -o app .

build_job:
  extends: .go_build_template
  stage: build
```

# 4. Что такое Downstream/Multi-project Pipelines и ключевое слово
# `trigger`?
Позволяет одному пайплайну (upstream) запустить пайплайн в ДРУГОМ
проекте (downstream) — например, монорепозиторий-оркестратор
триггерит отдельные пайплайны деплоя для каждого сервиса.
```yaml
deploy_service_a:
  stage: deploy
  trigger:
    project: team/service-a
    branch: main
```
Есть также **Parent-Child Pipelines** — тот же механизм `trigger`,
но указывается не внешний проект, а локальный YAML-файл внутри
того же репозитория (`trigger: include: child.yml`), чтобы разбить
один огромный `.gitlab-ci.yml` на логические части.

# 5. Как работает ключевое слово `needs` и чем оно отличается от
# порядка `stages`?
По умолчанию джобы следующей стадии ждут ЗАВЕРШЕНИЯ ВСЕХ джоб
текущей стадии (строгий порядок стадий). `needs` позволяет
джобе стартовать сразу, как только завершатся конкретные
перечисленные джобы-зависимости, даже если они на других стадиях и
не все джобы текущей стадии ещё закончились — это строит DAG
(направленный граф) вместо линейной цепочки стадий и ускоряет
пайплайн.
```yaml
deploy_job:
  stage: deploy
  needs: ["build_job"]
```

# 6. Чем `rules` отличается от устаревшего `only`/`except`, и что
# такое `workflow:rules`?
`rules` — современный, более гибкий способ решить, запускать ли
джобу, с условиями `if`/`changes`/`exists` и явным действием
(`when: on_success`/`never`/`manual`).
```yaml
deploy_prod:
  stage: deploy
  rules:
    - if: '$CI_COMMIT_BRANCH == "main"'
      when: manual
    - when: never
```
`workflow:rules` — то же самое, но применяется на уровне ВСЕГО
пайплайна целиком (решает, запускать пайплайн вообще или нет, до
оценки правил отдельных джоб) — используется, например, чтобы не
запускать пайплайн дважды и на push, и на открытие Merge Request
для одной и той же ветки.

# 7. Что такое CI/CD Variables в GitLab и флаги Masked/Protected?
Переменные окружения, доступные джобам во время выполнения,
настраиваются в `.gitlab-ci.yml` или в UI проекта
(Settings → CI/CD → Variables).
- **Masked** — значение скрывается звёздочками в логах job, чтобы
  случайно не светить секрет в выводе команды.
- **Protected** — переменная передаётся только в джобы, запущенные
  на защищённых ветках/тегах (например, `main`), чтобы токен от
  прода не утёк в пайплайн произвольной feature-ветки.

# 8. Чем Executor Runner'а `docker` отличается от `shell` и `kubernetes`?
Executor определяет, ГДЕ физически выполняется `script` джобы.
- **shell** — команды выполняются напрямую на хост-машине раннера
  (быстро, но джобы не изолированы друг от друга и от хоста).
- **docker** — каждая джоба запускается в отдельном Docker-
  контейнере из указанного `image` (изоляция, воспроизводимость).
- **kubernetes** — каждая джоба запускается как под в Kubernetes-
  кластере (горизонтальное масштабирование раннеров через сам
  кластер, не нужен отдельный выделенный сервер раннера).
