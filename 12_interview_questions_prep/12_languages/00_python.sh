# 1. В чем разница между списками (List) и кортежами (Tuple) в Python?
Списки (`[1, 2, 3]`) — изменяемые (mutable). Их можно модифицировать после
создания: добавлять (`append`), удалять, изменять элементы. Из-за
изменяемости размер в памяти чуть больше (reserve). Кортежи (`(1, 2, 3)`) —
неизменяемые (immutable). После создания их содержимое нельзя изменить. За
счет этого кортежи работают быстрее, потребляют меньше памяти и, самое
главное, могут использоваться в качестве ключей в словарях (dict), в отличие
от списков.

# 2. Что такое словари (Dict) и как они реализованы под капотом?
Словари (`{"key": "value"}`) — это коллекции пар ключ-значение. Под капотом
они реализованы как хеш-таблицы (Hash Tables). При добавлении элемента
вычисляется хеш ключа, который определяет индекс в массиве, куда будет
сохранено значение. Это обеспечивает невероятно быстрый поиск, вставку и
удаление элементов со сложностью O(1) в среднем случае. Начиная с Python
3.7, словари гарантированно сохраняют порядок вставки элементов.

# 3. Разница между == и is в Python?
`==` проверяет равенство ЗНАЧЕНИЙ (содержимого) двух объектов. `is`
проверяет ИДЕНТИЧНОСТЬ объектов, то есть указывают ли обе переменные на одну
и ту же область памяти (один и тот же объект, проверяется через функцию
`id()`). Пример: `a = [1, 2]; b = [1, 2]`. Здесь `a == b` это True
(содержимое одинаковое), но `a is b` это False (это два разных списка в
памяти). (Исключение — маленькие целые числа и строки, которые кэшируются
Python/Интернирование).

# 4. Как в Python поменять значения двух переменных местами без третьей
переменной?
Благодаря механизму распаковки кортежей (tuple unpacking) в Python это
делается в одну элегантную строку:
```python
a, b = b, a
```
Сначала в памяти вычисляется и создается кортеж `(b, a)`, а затем его
значения распаковываются и присваиваются переменным слева.

# 5. Что такое GIL (Global Interpreter Lock) и зачем он нужен?
GIL — это глобальная блокировка в эталонной реализации Python (CPython). Она
гарантирует, что в любой момент времени байт-код Python выполняет только
ОДИН поток (Thread) операционной системы. Причина: встроенный сборщик мусора
(счетчик ссылок) не является потокобезопасным. Следствие: многопоточность
(threading) в Python не ускоряет математические (CPU-bound) задачи на
многоядерных процессорах. Для таких задач нужно использовать
многопроцессность (multiprocessing). Однако потоки отлично подходят для
IO-bound задач (сеть, базы данных).

# 6. Как работает сборщик мусора (Garbage Collector) в Python?
Основной механизм — подсчет ссылок (Reference Counting). У каждого объекта
есть счетчик того, сколько переменных на него ссылается. Когда счетчик
падает до нуля, память мгновенно освобождается. Однако этот метод не может
справиться с циклическими ссылками (объект A ссылается на B, а B на A). Для
этого существует второй механизм — Generational Garbage Collector
(Поколенческий GC), который периодически сканирует объекты, находит
изолированные циклы и удаляет их.

# 7. Что такое декораторы (Decorators) и как они работают?
Декоратор — это функция, которая принимает другую функцию в качестве
аргумента и расширяет ее поведение, не изменяя ее исходный код. По сути это
паттерн "Обёртка" (Wrapper).
```python
def my_decorator(func):
    def wrapper():
        print("До вызова")
        func()
        print("После вызова")
    return wrapper

@my_decorator
def say_hello():
    print("Привет!")
```
Символ `@` является синтаксическим сахаром для `say_hello =
my_decorator(say_hello)`.

# 8. Что такое List Comprehension (генераторы списков)?
Это лаконичный и быстрый способ создания нового списка на основе
существующей итерируемой последовательности. Пример: получить квадраты
четных чисел от 0 до 9:
```python
squares = [x**2 for x in range(10) if x % 2 == 0]
```
Это работает быстрее (на уровне C) и читается лучше, чем использование
обычного цикла `for` с вызовом `append`.

# 9. В чем разница между итератором и генератором?
Итератор — это объект, реализующий магические методы `__iter__()` и
`__next__()`. Он помнит свое состояние и выдает элементы по одному при
вызове `next()`. Генератор — это удобный способ создания итератора. Это
функция, которая вместо `return` использует ключевое слово `yield`.
Генератор не хранит все значения в памяти, а вычисляет их на лету (ленивая
загрузка, Lazy evaluation). Идеально подходит для чтения огромных файлов,
чтобы не получить Out of Memory.

# 10. Что делает ключевое слово yield?
Оно используется в генераторах вместо `return`. Когда функция доходит до
`yield`, она возвращает значение, но при этом "замораживает" свое состояние
(значения всех локальных переменных сохраняются). При следующем вызове
функции (через `next()`) выполнение продолжится ровно с того места, где оно
было приостановлено, до следующего `yield`.

# 11. Что такое args и kwargs?
Это синтаксис для передачи произвольного количества аргументов в функцию.
`*args` (args — convention name, важна звездочка) собирает все позиционные
аргументы в кортеж (Tuple). `**kwargs` (keyword arguments, две звездочки)
собирает все именованные аргументы (key=value) в словарь (Dict). Пример:
`def my_func(*args, **kwargs):`

# 12. Что такое Duck Typing (Утиная типизация)?
Принцип: "Если это выглядит как утка, плавает как утка и крякает как утка,
то это, вероятно, и есть утка". В Python (динамическая типизация) не нужно
жестко наследовать класс от интерфейса, чтобы передать его в функцию. Важно
лишь то, чтобы объект реализовывал необходимые методы. Например, если
функция вызывает `obj.read()`, вы можете передать открытый файл, сетевой
сокет или кастомный класс — главное, чтобы у них был метод `read()`.

# 13. Что такое магические (Dunder) методы?
Это специальные методы, имена которых начинаются и заканчиваются двойным
подчеркиванием (Double UNDERscore). Они реализуют перегрузку операторов и
базовое поведение объектов в Python. Например: `__init__` — конструктор
класса. `__str__` — строковое представление объекта (для пользователя, при
`print()`). `__len__` — вызывается при применении встроенной функции
`len(obj)`. `__add__` — определяет поведение объекта при использовании
оператора `+`.

# 14. Как скопировать список или словарь? В чем разница между shallow copy и
deep copy?
Обычное присваивание `a = b` не копирует объект, а создает новую ссылку на
тот же объект в памяти. Shallow copy (Поверхностная копия, `a = b.copy()`
или `a = list(b)`): создает новый список, но если внутри списка были другие
изменяемые объекты (например, списки списков), то ссылки на них останутся
общими. Изменение внутреннего списка отразится на обеих копиях. Deep copy
(Глубокая копия, `import copy; a = copy.deepcopy(b)`): рекурсивно копирует
всё, создавая абсолютно независимый клон.

# 15. Что такое контекстные менеджеры и оператор with?
Контекстные менеджеры управляют выделением и освобождением ресурсов (файлов,
сетевых соединений). Они реализуют магические методы `__enter__` и
`__exit__`. Использование оператора `with` (например, `with open('file.txt')
as f:`) гарантирует, что ресурс будет корректно закрыт (сработает метод
`__exit__`), даже если внутри блока произойдет исключение, избавляя от
необходимости писать `try...finally`.

# 16. Разница между методами класса @classmethod и статическими методами
@staticmethod?
`@staticmethod` — это просто обычная функция, помещенная внутрь класса для
логической группировки. Она не принимает ссылку на экземпляр (`self`) или
класс (`cls`) и не может изменять их состояние. `@classmethod` — принимает
класс в качестве первого аргумента (по конвенции `cls`, а не `self`). Может
изменять состояние класса (а не конкретного экземпляра). Часто используется
для создания альтернативных конструкторов (Фабричный метод).

# 17. Что такое Lambda-функции?
Это маленькие, анонимные функции, записанные в одну строку. Они могут
принимать любое количество аргументов, но содержат только одно выражение,
результат которого автоматически возвращается. Пример: `square = lambda x: x
* x`. Часто используются для одноразовых простых вычислений в функциях
высшего порядка: `sorted(data, key=lambda x: x[1])`.

# 18. В чем разница между Python 2 и Python 3?
Хотя Python 2 давно мертв (EOL в 2020), этот вопрос все еще встречается.
- В Python 2 `print` был оператором (`print "Hello"`), в Python 3 стал
  функцией (`print("Hello")`).
- В Python 2 строки по умолчанию — ASCII, в Python 3 все строки — Unicode по
  умолчанию (что решило огромную проблему с кодировками).
- В Python 2 целочисленное деление `5/2` давало `2`, в Python 3 оно дает
  `2.5` (для целочисленного нужен `//`).

# 19. Что такое PEP 8?
PEP 8 (Python Enhancement Proposal) — это официальное руководство по стилю
написания кода на Python. Оно описывает соглашения о форматировании:
- Отступы: 4 пробела (не табуляция).
- Максимальная длина строки: 79 символов (хотя сейчас часто смягчают до
  120).
- Именование переменных и функций: `snake_case`.
- Именование классов: `CamelCase` (PascalCase).
- Пустые строки вокруг классов и функций.

# 20. Как организовать виртуальное окружение в Python и зачем оно нужно?
Виртуальное окружение (venv, virtualenv, pipenv, poetry) создает
изолированную папку для конкретного проекта. Зачем нужно: чтобы избежать
конфликтов версий библиотек (dependency hell) между разными проектами на
одном компьютере (проект A требует Django 2, а проект B — Django 4).
Системный Python остается чистым. Создание встроенным модулем: `python3 -m
venv myenv`. Активация: `source myenv/bin/activate`.

# 21. Как запускать shell-команды из Python через модуль `subprocess`?
```python
import subprocess

result = subprocess.run(
    ["ls", "-la", "/tmp"],
    capture_output=True, text=True, check=True,
)
print(result.stdout)
```
`subprocess.run` — современный высокоуровневый способ: запускает команду,
ждет завершения, возвращает объект с `stdout`/`stderr`/ `returncode`
(`check=True` поднимет исключение при ненулевом коде возврата).
Низкоуровневый `subprocess.Popen` используется, когда нужно не ждать команду
целиком, а работать с ее вводом/выводом в реальном времени (пока процесс еще
выполняется). Критически важно: команду передают СПИСКОМ аргументов (`["ls",
"-la", ...]`), а не одной строкой с `shell=True`. `shell=True` запускает
команду через `/bin/sh`, и если хотя бы часть команды собирается из
пользовательского ввода, это прямой путь к command injection (см.
`10_devsecops.sh`) — `/bin/sh` интерпретирует спецсимволы ввода (`;`, `&&`,
`|`) как часть команды.

# 22. Что такое `asyncio` и чем он отличается от threading и
multiprocessing?
Уже разобрано (вопрос 5), что GIL не дает потокам Python реально параллельно
исполнять Python-байткод, поэтому threading хорош для I/O-bound задач, а
multiprocessing — для CPU-bound (обходит GIL ценой отдельных процессов и
памяти). `asyncio` — третий подход для I/O-bound задач, но БЕЗ потоков
вообще: один поток выполняет один **event loop**, который переключается
между задачами (`async def`/ `await`) САМ, кооперативно, именно в момент,
когда задача добровольно отдает управление на операции ожидания (сетевой
запрос, чтение файла), а не по таймеру ОС, как при вытесняющей
многопоточности.
```python
import asyncio

async def fetch(url):
    await asyncio.sleep(1)   # имитация I/O-ожидания
    return url

async def main():
    results = await asyncio.gather(*(fetch(u) for u in urls))
```
Плюс перед threading для большого числа конкурентных I/O-операций (десятки
тысяч сетевых запросов) — не нужно создавать тысячи ОС-потоков с их
накладными расходами; минус — требует, чтобы ВСЯ библиотека ввода-вывода
была написана в async-стиле (обычный блокирующий `requests.get()` застопорит
весь event loop целиком).

# 23. Как делают CLI-утилиты на Python (`argparse`, `click`)?
`argparse` — встроенный модуль стандартной библиотеки для парсинга
аргументов командной строки:
```python
import argparse
parser = argparse.ArgumentParser()
parser.add_argument("--env", required=True, choices=["dev", "prod"])
parser.add_argument("-v", "--verbose", action="store_true")
args = parser.parse_args()
```
`click` — сторонняя библиотека, решающая ту же задачу декларативно, через
декораторы, с автоматической генерацией `--help`, поддержкой вложенных
под-команд (`mytool deploy`, `mytool rollback` как отдельные команды одной
утилиты) и меньшим количеством шаблонного кода, чем у `argparse` для сложных
CLI. Для типичного DevOps-скрипта ("прими --env и --dry-run") `argparse`
обычно достаточно; `click` (или `typer`, построенный поверх него) берут,
когда CLI-утилита разрастается в полноценный инструмент с множеством
подкоманд.

# 24. Зачем использовать модуль `logging` вместо `print()` в
production-коде?
`print()` всегда пишет в stdout без уровней важности и без возможности
фильтрации — в проде либо видно ВСЁ, либо приходится вручную убирать
`print()` из кода. Модуль `logging` дает:
- **Уровни** (`DEBUG`/`INFO`/`WARNING`/`ERROR`/`CRITICAL`) — можно включить
  подробный `DEBUG`-вывод только при отладке, не трогая код.
- **Handlers** — один и тот же лог можно одновременно писать в файл, в
  stdout (для сборщика логов контейнера, см. `06_monitoring/03_elk.
  sh`/`05_loki.sh`) и/или отправлять во внешнюю систему, без изменения
  вызовов `logging.info(...)` в коде.
- **Formatters** — единый формат (timestamp, уровень, имя модуля) для всех
  сообщений, в том числе в структурированном JSON — что критически важно,
  чтобы агрегатор логов (Loki/ELK) мог парсить поля, а не просто грепать
  текст.
```python
import logging
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)
logger.info("Задача запущена", extra={"job_id": job_id})
```
