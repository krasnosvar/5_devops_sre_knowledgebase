# 1. Чем Redis Sentinel отличается от Redis Cluster?
Sentinel дает High Availability для схемы master-replica (один
master, автоматический failover на реплику) — данные НЕ шардируются,
все помещается на одном master целиком. Redis Cluster шардирует
данные по 16384 хэш-слотам между несколькими master-узлами — решает
другую задачу: масштабирование объема данных и записи.

# 2. Что настраивается в `sentinel.conf`?
```conf
sentinel monitor mymaster 10.0.0.1 6379 2
sentinel down-after-milliseconds mymaster 5000
sentinel failover-timeout mymaster 60000
sentinel parallel-syncs mymaster 1
```
- `monitor mymaster <ip> <port> 2` — за каким master'ом следить, и
  `2` — кворум (сколько Sentinel'ов должны согласиться, что master
  упал, прежде чем начать failover).
- `down-after-milliseconds` — через сколько считать master
  недоступным.
- `parallel-syncs` — сколько реплик одновременно могут
  ресинхронизироваться с новым master'ом после failover (больше
  параллелизма — быстрее, но больше нагрузка на новый master).

# 3. Что настраивается в основном `redis.conf`?
```conf
maxmemory 4gb
maxmemory-policy allkeys-lru
save 900 1
appendonly yes
appendfsync everysec
```
- `maxmemory` + `maxmemory-policy` — сколько памяти разрешено занять
  и что делать при достижении лимита (`allkeys-lru` — вытеснять
  давно не используемые ключи; `noeviction` — отказывать в записи
  новых данных вместо вытеснения).
- `save` — через сколько секунд и при скольких изменениях делать
  RDB-снэпшот на диск.
- `appendonly`/`appendfsync` — включить AOF-журнал (лог каждой
  операции записи) и как часто сбрасывать его на диск
  (`everysec` — баланс между надежностью и скоростью, `always` —
  максимально надежно, но медленно).

# 4. Как объединить несколько хостов Redis в кластер с
шардированием?
```bash
redis-cli --cluster create \
  10.0.0.1:6379 10.0.0.2:6379 10.0.0.3:6379 \
  10.0.0.4:6379 10.0.0.5:6379 10.0.0.6:6379 \
  --cluster-replicas 1
```
Эта команда сама распределяет 16384 слота между первыми тремя
узлами (master'ы) и назначает оставшиеся три как их реплики
(`--cluster-replicas 1` — одна реплика на master). Клиент сам
считает хэш ключа и обращается к нужному узлу напрямую, без
внешнего балансировщика.

# 5. Что такое модули Redis (Redis Modules) и какие используют чаще
всего?
Плагины, расширяющие Redis новыми типами данных и командами поверх
базового key-value:
- **RedisJSON** — хранить и запрашивать JSON-документы нативно,
  не сериализуя вручную в строку.
- **RediSearch** — полнотекстовый и векторный поиск прямо в Redis.
- **RedisTimeSeries** — эффективное хранение временных рядов
  (метрики) с агрегацией по окнам.
- **RedisBloom** — вероятностные структуры (Bloom filter,
  HyperLogLog) для задач вроде "видел ли я этот элемент раньше"
  без хранения всех элементов целиком.
Подключаются как `.so`-библиотека через `loadmodule` в `redis.conf`.

# 6. Как мониторить Redis?
`INFO` — команда, показывающая всё: память, клиенты, репликацию,
статистику команд. `SLOWLOG GET` — последние медленные команды
(порог задается `slowlog-log-slower-than` в конфиге, в
микросекундах). Для Prometheus — `redis_exporter`, читает тот же
`INFO` и отдает метрики наружу.

# 7. Как сделать бэкап Redis?
RDB-файл (`dump.rdb`) — просто бинарный снэпшот, его можно скопировать
как обычный файл (убедившись, что `save`-снэпшот из вопроса 3 уже
завершился, либо принудительно вызвав `BGSAVE`). AOF-файл можно
восстанавливать по частям за счет `BASE`/`INCR`-файлов (AOF
multi-part формат в современных версиях). Для кластера с
шардированием бэкап снимают с каждого master-узла отдельно — единого
"снэпшота всего кластера одной командой" нет.
