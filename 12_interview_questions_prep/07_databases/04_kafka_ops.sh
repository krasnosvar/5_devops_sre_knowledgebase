# 1. Из чего состоит кластер Kafka на уровне брокеров и партиций?
Топик делится на партиции — именно партиция (а не топик целиком)
физически лежит на диске одного брокера и является единицей
параллелизма. Чем больше партиций, тем на большее число брокеров и
consumer'ов можно распараллелить чтение/запись.

# 2. Что настраивается в `server.properties` брокера?
```properties
broker.id=1
listeners=PLAINTEXT://:9092
log.dirs=/var/lib/kafka/data
num.partitions=6
default.replication.factor=3
min.insync.replicas=2
log.retention.hours=168
log.retention.bytes=-1
```
- `default.replication.factor` — сколько копий каждой партиции на
  разных брокерах (см. вопрос 3).
- `min.insync.replicas` — сколько реплик обязаны подтвердить запись
  при `acks=all`, иначе запись отклоняется с ошибкой.
- `log.retention.hours`/`log.retention.bytes` — сколько хранить
  данные партиции (по времени и/или по размеру) до удаления.

# 3. Что такое Replication Factor и ISR?
Replication Factor — сколько копий партиции на разных брокерах
(обычно 3). Одна реплика — лидер (принимает запись), остальные —
фолловеры. ISR (In-Sync Replicas) — те реплики, что реально
синхронизированы с лидером; только они кандидаты на нового лидера
при падении текущего.

# 4. Что такое `acks` у producer и как это настроить?
```properties
acks=all
```
`acks=0` — не ждать подтверждения (риск потери). `acks=1` — ждать
подтверждения только от лидера. `acks=all` — ждать от всех реплик
в ISR (в паре с `min.insync.replicas=2` из вопроса 2 — надежная
связка для продакшена).

# 5. Что такое Consumer Group и как настроить параллельное чтение?
```properties
group.id=my-consumer-group
```
Все consumer'ы с одним `group.id` делят партиции между собой —
каждая партиция читается ровно одним consumer'ом группы одновременно.
Партиций больше — можно подключить больше параллельных consumer'ов;
"лишние" (сверх числа партиций) останутся без работы.

# 6. Что такое Kafka Connect и зачем он нужен?
Отдельный процесс с экосистемой готовых плагинов-коннекторов —
не нужно писать код самому, чтобы завести данные В Kafka (source
connector: из Postgres через Debezium CDC, из файлов, из JDBC) или
вывести данные ИЗ Kafka (sink connector: в Elasticsearch, в S3,
в другую БД). Конфигурируется JSON через REST API:
```json
{
  "name": "postgres-source",
  "config": {
    "connector.class": "io.debezium.connector.postgresql.PostgresConnector",
    "database.hostname": "pg1",
    "database.dbname": "mydb",
    "table.include.list": "public.orders"
  }
}
```

# 7. Что такое Schema Registry и зачем он нужен вместе с Kafka?
Kafka сама по себе хранит только байты, ничего не зная о структуре
сообщения. Schema Registry — отдельный сервис, хранящий схемы
сообщений (обычно Avro или Protobuf) с версионированием — producer
и consumer сверяются с ним, чтобы не сломать друг друга при
изменении формата сообщений (проверка совместимости схем при
добавлении/удалении полей).

# 8. Как мониторить Kafka?
Брокеры отдают метрики через JMX (Java Management Extensions) —
для Prometheus ставят `jmx-exporter` рядом с каждым брокером
(javaagent, который переводит JMX в `/metrics`). Смотрят в первую
очередь: consumer lag (насколько consumer отстаёт от последнего
offset партиции — главный показатель, не успевает ли обработка за
потоком), `UnderReplicatedPartitions` (партиции, где не все реплики
из ISR) и размер диска по `log.dirs`.

# 9. Как сделать репликацию между двумя разными кластерами Kafka
(не внутри одного, а между дата-центрами)?
Replication Factor из вопроса 3 реплицирует партиции ВНУТРИ одного
кластера. Для копирования данных МЕЖДУ разными кластерами (другой
дата-центр, DR) используют MirrorMaker 2 — отдельный процесс на
основе Kafka Connect, который читает топики одного кластера и
пишет их в другой, с возможностью переименования топиков и
сохранением consumer group offset'ов при переключении.
