# 1. Что такое Helm и какую проблему он решает по сравнению с
# обычными манифестами `kubectl apply -f`
Helm — пакетный менеджер для Kubernetes. Обычные YAML-манифесты
статичны — чтобы развернуть одно и то же приложение в dev/staging/
prod с разными значениями (реплики, домен, лимиты ресурсов),
пришлось бы держать отдельные копии файлов под каждое окружение.
Helm превращает манифесты в шаблоны (**Chart**) с параметрами
(**values**), и один и тот же чарт разворачивается в разные
окружения с разным набором значений — плюс Helm отслеживает версии
установок (**Release**) и умеет откатывать (`helm rollback`) на
предыдущую версию целиком.

# 2. Из каких файлов состоит структура Helm Chart?
```
mychart/
├── Chart.yaml          # метаданные: имя, версия чарта
├── values.yaml         # значения по умолчанию
├── templates/
│   ├── deployment.yaml
│   ├── service.yaml
│   └── _helpers.tpl    # переиспользуемые шаблонные функции
└── charts/             # вложенные под-чарты (зависимости)
```
- `Chart.yaml` — имя, версия самого чарта и версия приложения.
- `values.yaml` — дефолтные параметры, доступные в шаблонах через
  `.Values.<ключ>`.
- `templates/` — сами манифесты Kubernetes с шаблонизацией
  (Go templates).

# 3. Как выглядит шаблонизация в `templates/deployment.yaml` и
подстановка значений из `values.yaml`?
```yaml
# values.yaml
replicaCount: 3
image:
  repository: myapp
  tag: "1.0"
```
```yaml
# templates/deployment.yaml
spec:
  replicas: {{ .Values.replicaCount }}
  template:
    spec:
      containers:
        - image: "{{ .Values.image.repository }}:{{ .Values.image.tag }}"
```
При установке можно переопределить любое значение без правки
файлов: `helm install myapp . --set replicaCount=5` или через
отдельный файл `-f values-prod.yaml`.

# 4. В чем разница между `helm install`, `helm upgrade` и
`helm rollback`?
- **helm install** — первая установка чарта как нового Release.
- **helm upgrade** — применить изменения (новые values или новую
  версию чарта) к уже существующему Release.
- **helm rollback <release> <revision>** — откатить Release к
  одной из предыдущих ревизий (Helm хранит историю всех апгрейдов).

# 5. Что такое Helm Hooks и для чего они нужны?
Аннотация `helm.sh/hook` на ресурсе, указывающая Helm выполнить его
не как часть обычного релиза, а на определённой фазе жизненного
цикла — например, `pre-install`/`pre-upgrade` (запустить Job с
миграцией БД ДО раскатки новой версии приложения) или `post-
install` (прогнать smoke-тест после установки).
```yaml
metadata:
  annotations:
    "helm.sh/hook": pre-upgrade
```

# 6. Чем отличается Helm Chart от Kustomize с точки зрения подхода к
кастомизации манифестов?
Helm шаблонизирует YAML текстовой подстановкой переменных (`.Values`
внутри `{{ }}`) — гибко, но сам YAML превращается в "почти-код" с
условиями и циклами. 
Kustomize (см.
`4_kubernetes/09_manifests_management/03_kustomize/`) работает
иначе — берёт готовые, валидные YAML-манифесты как есть (base) и
накладывает поверх декларативные
патчи (overlay) без шаблонных синтаксических конструкций внутри
самого YAML. Helm лучше подходит для распространения переиспользуемых
пакетов приложений (чужих чартов из Artifact Hub), Kustomize — для
локального управления различиями между своими собственными
окружениями.

# 7. Что такое Helm репозиторий и файл `Chart.lock`?
Helm-репозиторий — HTTP-сервер, отдающий индекс (`index.yaml`) со
списком доступных чартов и их версий (аналог Docker Registry, но
для чартов) — подключается командой `helm repo add`. Если чарт
зависит от других чартов (секция `dependencies` в `Chart.yaml`),
`helm dependency update` скачивает их и фиксирует точные
версии зависимостей в `Chart.lock` — чтобы повторная сборка чарта
не подтянула случайно более новую несовместимую версию зависимости.
