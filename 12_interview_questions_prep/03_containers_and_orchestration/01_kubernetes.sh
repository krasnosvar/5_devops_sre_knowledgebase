# 1. Что такое Kubernetes (K8s) и зачем он нужен?
Kubernetes — это открытая платформа для автоматизации развертывания,
масштабирования и управления контейнеризированными приложениями
(оркестратор контейнеров). Он решает проблемы перезапуска упавших
контейнеров, балансировки нагрузки, накатывания обновлений без даунтайма,
управления секретами и масштабирования кластера.

# 2. Опишите архитектуру Kubernetes кластера (Control Plane и Worker Nodes).
Кластер делится на управляющий слой (Control Plane) и рабочие узлы
(Worker Nodes).
Control Plane (Master):
- kube-apiserver: единая точка входа для всех REST-запросов (от kubectl и
  других компонентов).
- etcd: распределенное key-value хранилище, где лежит всё состояние
  кластера.
- kube-scheduler: решает, на какой узел (Node) назначить новые поды на
  основе ресурсов.
- kube-controller-manager: следит за состоянием кластера и приводит его
  к желаемому (реплики, эндпоинты, ноды).
Worker Node (Узлы с нагрузкой):
- kubelet: агент на каждой ноде, который следит, чтобы контейнеры в подах
  работали.
- kube-proxy: управляет сетевыми правилами на ноде (iptables/IPVS) для
  маршрутизации трафика к подам (сервисы).
- Container Runtime (Containerd, CRI-O, Docker): запускает сами контейнеры.

# 3. Что такое Pod в Kubernetes?
Pod (Под) — это мельчайшая базовая единица развертывания в K8s. Под
представляет собой логический хост и может содержать один или несколько
контейнеров. Контейнеры внутри одного пода всегда запускаются на одной
ноде, делят один сетевой namespace (IP-адрес, localhost) и могут
разделять общие тома (Volumes).

# 4. Какие типы Service существуют в K8s?
Service обеспечивает стабильный IP-адрес и DNS-имя для доступа к
динамичным Подам (балансировка).
1. ClusterIP (по умолчанию): доступен только внутри кластера по
   внутреннему IP.
2. NodePort: открывает статический порт (по умолчанию 30000-32767) на
   каждой ноде кластера, маршрутизируя трафик в поды.
3. LoadBalancer: провижинит внешний балансировщик нагрузки облачного
   провайдера (AWS ELB, GCP Load Balancer) и направляет трафик на
   NodePort.
4. ExternalName: мапит сервис на DNS-имя (CNAME), не используя
   проксирование.

# 5. Что такое Deployment и чем он отличается от StatefulSet?
Deployment управляет приложениями без сохранения состояния (Stateless). Он
следит за ReplicaSet, обеспечивая нужное количество реплик подов. Поды в
Deployment взаимозаменяемы, их имена генерируются случайно, они могут
быть удалены и пересозданы на любых нодах.
StatefulSet используется для приложений с состоянием (Stateful, например
БД). Он гарантирует:
- Уникальные постоянные сетевые имена (pod-0, pod-1).
- Строгий порядок создания и удаления подов.
- Привязку к постоянным хранилищам (Persistent Volumes): при пересоздании
  pod-0 получит тот же диск, что был у него ранее.

# 6. Что такое Ingress и Ingress Controller?
Ingress — это объект API, описывающий правила маршрутизации внешнего
HTTP/HTTPS-трафика к внутренним сервисам кластера (маршрутизация на
основе URL-путей или доменов, TLS termination).
Ingress Controller (например, Nginx Ingress Controller, Traefik) — это
компонент (обычно деплоймент с балансировщиком), который считывает эти
правила и фактически реализует проксирование. Сам объект Ingress без
контроллера не работает.

# 7. Как K8s управляет секретными данными (пароли, ключи)?
Используются объекты Secret. K8s хранит их в etcd (по умолчанию они просто
закодированы в base64, поэтому etcd нужно шифровать в покое — encryption
at rest). Секреты можно пробрасывать в контейнеры как файлы через volume
(tmpfs) или как переменные окружения.

# 8. Что такое Namespace?
Namespace (Пространство имен) — это логическое разделение кластера K8s.
Позволяет разделить ресурсы между разными проектами, командами или
окружениями (dev, test, prod) внутри одного физического кластера. Объекты
с одинаковым именем могут существовать в разных неймспейсах.

# 9. Объясните, что такое Liveness, Readiness и Startup Probes (Пробы).
Это проверки состояния контейнера.
- Liveness Probe: проверяет, жив ли контейнер (не завис ли дедлоком).
  Если проверка провалена, kubelet перезапускает контейнер.
- Readiness Probe: проверяет, готово ли приложение принимать сетевой
  трафик (например, загрузились ли кэши). Если провалена, под исключается
  из балансировки Service, но не убивается.
- Startup Probe: используется для медленно стартующих приложений. Отключает
  Liveness/Readiness проверки, пока приложение окончательно не
  инициализируется.

# 10. Что такое DaemonSet?
DaemonSet гарантирует, что определенный Под будет запущен в единственном
экземпляре на каждой Worker-ноде кластера (или на нодах, соответствующих
селектору). Часто используется для инфраструктурных задач: сбор логов
(Fluentd/Promtail), мониторинг (Node Exporter), сетевые плагины
(Kube-proxy, CNI).

**Доп. вопрос: можно ли запустить через DaemonSet по 2 пода на одной
ноде?**
Нет — в отличие от Deployment, у DaemonSet вообще нет поля replicas:
его цикл сверки (reconciliation loop) буквально реализует правило
"ровно один под на каждую подходящую ноду", и это нельзя
параметризовать внутри ОДНОГО объекта DaemonSet. Реальных способа
получить 2 пода на ноду два:
- Завести ДВА отдельных DaemonSet-объекта (под разными именами) с
  одинаковым или похожим шаблоном пода — каждый независимо
  поддерживает правило "1 под на ноду", в сумме получается 2 пода на
  ноду (так иногда делают при осторожном параллельном запуске старой
  и новой версии агента).
- Если на самом деле нужны 2 совместно работающих ПРОЦЕССА на ноде, а
  не 2 независимых пода — положить оба контейнера В ОДИН под того же
  DaemonSet (паттерн sidecar, вопрос 30): это по-прежнему 1 под на
  ноду, но внутри 2 контейнера, с общим сетевым namespace и volumes.

# 11. Что такое ConfigMap?
ConfigMap используется для хранения неконфиденциальных конфигурационных
данных (конфиг-файлов, переменных окружения, аргументов командной строки)
в формате ключ-значение. Отделяет конфигурацию от образа контейнера,
позволяя переиспользовать образ в разных окружениях.

# 12. В чем разница между Persistent Volume (PV) и Persistent Volume Claim
(PVC)?
- PV — это абстрактный кусок хранилища в кластере (NFS, AWS EBS,
  локальный диск), созданный администратором или автоматически через
  StorageClass.
- PVC — это запрос пользователя/пода на выделение хранилища (с
  определенным объемом и режимом доступа, например ReadWriteOnce). PVC
  привязывается (binds) к подходящему PV, и затем монтируется в Под.

# 13. Скейлинг в Kubernetes: HPA, VPA и Cluster Autoscaler?
- **HPA (Horizontal Pod Autoscaler):** Автоматически увеличивает
  количество реплик (подов) в Deployment в ответ на рост нагрузки (CPU,
  RAM или custom metrics). Горизонтальное масштабирование.
- **VPA (Vertical Pod Autoscaler):** Анализирует историческое потребление
  ресурсов подами и автоматически изменяет им requests и limits
  (пересоздавая поды с новыми параметрами). Вертикальное масштабирование
  (полезно для БД или монолитов). Не рекомендуется использовать
  одновременно с HPA по одним и тем же метрикам.
- **Cluster Autoscaler (CA):** Работает на уровне инфраструктуры облака.
  Если в кластере не хватает железа (CPU/RAM) для запуска новых подов
  (поды висят в статусе Pending), CA обращается к облачному API (AWS ASG,
  GCP) и заказывает новую виртуальную машину (Worker Node) в кластер.
  Когда ноды простаивают, он их удаляет.

# 14. Что такое Taints и Tolerations?
Это механизм K8s, позволяющий нодам отталкивать (taint) определенные поды.
- Taint применяется к Node (например, нода только для GPU-нагрузок).
- Toleration применяется к Pod, позволяя ему быть запущенным на ноде с
  соответствующим Taint (разрешает, но не обязывает).
Для обязывания пода запускаться на конкретной ноде используют
NodeSelector или NodeAffinity.

# 15. Как происходит процесс обновления Deployment (Rolling Update)?
По умолчанию Deployment использует стратегию RollingUpdate. K8s создает
новый ReplicaSet и начинает постепенно (по одному или партиями,
контролируется maxSurge и maxUnavailable) запускать поды новой версии,
одновременно убивая старые. Это обеспечивает нулевой даунтайм. Если новые
поды падают, выкатка останавливается. Откат осуществляется командой
kubectl rollout undo.

# 16. Что такое RBAC в Kubernetes?
RBAC (Role-Based Access Control) — система управления доступом на основе
ролей.
- Role / ClusterRole — определяет разрешения (verbs: get, list, create,
  delete) на объекты (pods, secrets). Role действует в рамках неймспейса,
  ClusterRole — на весь кластер.
- RoleBinding / ClusterRoleBinding — привязывает роль к субъекту (User,
  Group или ServiceAccount).

# 17. Что такое Helm?
Helm — пакетный менеджер для Kubernetes: упаковывает манифесты в
шаблонизируемые Charts с параметрами в values.yaml, что позволяет
деплоить одно и то же приложение в разные окружения и управлять
версиями релиза (install/upgrade/rollback). Подробный разбор структуры
чарта, шаблонизации, hooks и отличий от Kustomize — см. `02_helm.sh`.

# 18. Какова роль etcd в кластере Kubernetes? Можно ли его забекапить?
etcd — это распределенная база данных кластера. Только kube-apiserver
взаимодействует с etcd. Если etcd упадет и потеряет данные, кластер
перестанет функционировать (хотя запущенные поды продолжат работу, вы не
сможете ими управлять). etcd бэкапится с помощью утилиты etcdctl snapshot
save, что является критически важной операцией для DR (Disaster Recovery).

# 19. Что такое CNI и CSI?
CNI (Container Network Interface) — стандарт, описывающий сетевые плагины
в K8s (Calico, Flannel, Cilium). Они отвечают за выдачу IP-адресов подам
и маршрутизацию между ними (Overlay сети, BGP).
CSI (Container Storage Interface) — стандарт, позволяющий производителям
хранилищ писать плагины для K8s, чтобы поды могли динамически монтировать
диски (EBS, Ceph) без внесения изменений в ядро Kubernetes.

**Доп. вопрос: чем CNI отличается от kube-proxy?**
Это РАЗНЫЕ уровни сети, решающие разные задачи.
- **CNI-плагин** отвечает за базовую связность под-под (L3): выдает
  поду IP-адрес и настраивает маршруты так, чтобы пакет от одного
  пода вообще мог физически дойти до IP другого пода (в том числе на
  другой ноде, через overlay-сеть или BGP). Вызывается kubelet-ом ОДИН
  РАЗ — в момент создания пода.
- **kube-proxy** работает НАД этой базовой связностью: следит за
  объектами Service/Endpoints через API и постоянно (как демон, обычно
  сам запущен через DaemonSet) программирует правила (iptables/IPVS)
  на ноде, транслирующие виртуальный ClusterIP сервиса в реальный IP
  ОДНОГО из подходящих подов — то есть реализует балансировку
  Service, а не саму возможность пакету дойти до адресата.
Без CNI пакет физически некуда будет доставить (нет связности между
подами в принципе); без kube-proxy пакет мог бы дойти до КОНКРЕТНОГО
пода по его реальному IP напрямую, но не было бы стабильного
виртуального адреса Service, за которым под можно было бы прятать и
балансировать между несколькими репликами.
Отдельно стоит знать: продвинутые CNI на базе eBPF (Cilium) умеют
ПОЛНОСТЬЮ заменить kube-proxy, реализуя балансировку Service прямо в
ядре через eBPF вместо iptables/IPVS — это быстрее, но означает, что
функция kube-proxy перестает быть отдельным компонентом и становится
частью самого CNI-плагина.

# 20. Что такое Init Containers?
Init-контейнеры — это специальные контейнеры, которые запускаются до
основных контейнеров в поде. Они всегда должны успешно завершиться
(код 0). Если init-контейнер падает, K8s будет перезапускать его до
успешного завершения. Их используют для подготовки среды: миграции БД,
ожидания доступности сервиса (wait-for-it), генерации конфигов,
скачивания данных.

# 21. В чем разница между Managed Kubernetes (EKS, GKE) и Self-hosted
(Kubespray, kubeadm)?
- **Managed K8s:** Облачный провайдер (AWS, Google) полностью берет на
  себя управление Control Plane (мастерами, базой etcd, API). Вы не
  имеете доступа к мастерам по SSH, но они высокодоступны и автоматически
  обновляются. Вы платите за удобство и управляете только Worker нодами.
- **Self-hosted:** Вы сами арендуете железо/ВМ и устанавливаете кластер
  (например, через Kubespray). Вы полностью контролируете конфигурацию,
  сертификаты, бэкапы etcd, но на вас лежит ответственность за
  отказоустойчивость мастеров и их обновление, что требует глубокой
  экспертизы.

# 22. Как контролировать размещение подов кроме Taints/Tolerations (Node
# Affinity и Pod Affinity)?
- **Node Affinity:** "Притяжение" к нодам. Заставляет под запускаться
  только на нодах с определенными лейблами (например, disktype=ssd).
  Бывает жесткое (requiredDuringScheduling...) и мягкое, в виде пожелания
  (preferredDuringScheduling...).
- **Pod Affinity / Anti-Affinity:** Размещение подов относительно других
  подов.
  - Affinity: разместить под веб-сервера на той же ноде (или в той же
    зоне доступности), где уже крутится под базы данных (для снижения
    задержки).
  - Anti-Affinity: запретить размещать несколько реплик одного и того же
    Deployment на одной ноде, чтобы при падении ноды не легло всё
    приложение.

# 23. Что такое Pod Disruption Budget (PDB)?
PDB — это объект, который гарантирует, что во время добровольных сбоев
(Voluntary Disruptions, например при обновлении нод, kubectl drain, или
работе Cluster Autoscaler) приложение останется доступным.
В PDB задается minAvailable (например, 2) или maxUnavailable (например, 1).
K8s не позволит админу или скриптам одновременно выключить больше нод, чем
разрешает PDB для подов, крутящихся на них. Это критически важно для
Zero-Downtime эксплуатации кластера.

# 24. Какова структура API в Kubernetes?
Kubernetes API имеет resource-based (RESTful) архитектуру, доступную по
протоколу HTTP/HTTPS через kube-apiserver.
Управление осуществляется через стандартные HTTP методы (GET, POST, PUT,
PATCH, DELETE).
Структура запросов строится по группам (API Groups), версиям (v1, apps/v1,
networking.k8s.io/v1) и ресурсам (pods, deployments). API полностью
задокументировано спецификацией OpenAPI, что позволяет легко генерировать
клиенты на разных языках программирования.

# 25. Что такое Operators (Операторы) и зачем они нужны?
Оператор в K8s — это паттерн создания приложений, который кодирует логику
ручного управления (знания администратора) в программный контроллер.
Он состоит из:
1. **CRD (Custom Resource Definition):** Расширяет Kubernetes API новыми
   объектами (например, сущность PostgresCluster).
2. **Controller (Контроллер):** Под в кластере, который работает в цикле
   (reconciliation loop). Он видит, что пользователь создал объект
   PostgresCluster, и сам автоматически создает нужные StatefulSet,
   Сервисы, секреты, а также управляет бэкапами и апгрейдами базы данных
   без участия человека.

# 26. Service mesh. Что это такое и зачем нужно?
Service mesh — это инфраструктурный уровень для управления сетевым
взаимодействием между микросервисами в кластере (например, Istio, Linkerd,
Consul Connect).
Основная особенность — внедрение прокси-контейнеров (sidecar proxies,
например Envoy) рядом с каждым сервисом (в тот же pod), которые
перехватывают весь входящий и исходящий трафик.
Зачем нужно:
1. **Шифрование и безопасность:** Взаимная аутентификация (mTLS) между
   микросервисами "из коробки", без изменения кода приложений.
2. **Продвинутый роутинг:** Балансировка нагрузки, Canary releases, A/B
   тестирование, circuit breakers, retries и timeouts.
3. **Observability:** Автоматический сбор метрик трафика, распределенная
   трассировка (tracing) и логирование всех сетевых вызовов в едином месте.
Service mesh выносит задачи сетевой безопасности, мониторинга и
отказоустойчивости из кода приложений в инфраструктурный слой.

# 27. Cluster federation. Что это такое и зачем нужно?
Cluster federation (федерация кластеров, например KubeFed) — технология,
позволяющая объединять несколько Kubernetes-кластеров и управлять ими
централизованно как единой системой.
Она нужна для:
- **Мульти-регионального развертывания:** Размещение сервисов в разных
  дата-центрах или облаках для снижения задержек пользователей и
  катастрофоустойчивости (Disaster Recovery).
- **Централизованного управления:** Возможность применять ресурсы
  (деплойменты, манифесты) сразу ко всем кластерам через federation
  control plane.
- **Глобальной балансировки нагрузки:** Перенаправление трафика в другой
  регион, если локальный кластер "упал" или перегружен.

# 28. Что такое Job и CronJob?
Job создает один или несколько подов и следит, чтобы заданное число из
них успешно завершилось (в отличие от Deployment, который следит, чтобы
поды работали ПОСТОЯННО). Используется для разовых задач: миграции БД,
batch-обработка данных, разовые скрипты. Параметр completions задает,
сколько успешных завершений нужно, parallelism — сколько подов может
работать параллельно, backoffLimit — сколько раз повторить попытку при
падении.
CronJob — это Job, запускаемый по расписанию (синтаксис cron, например
"0 2 * * *" — каждый день в 2 ночи). CronJob сам создает новый объект
Job на каждый запуск по расписанию.

# 29. Что такое QoS-классы подов (Guaranteed, Burstable, BestEffort)?
Kubernetes присваивает поду класс качества обслуживания на основе того,
как заданы requests и limits ресурсов (CPU/RAM) у его контейнеров —
класс влияет на то, какие поды будут "убиты" первыми при нехватке
ресурсов на ноде (eviction).
- **Guaranteed:** requests == limits для CPU и RAM у ВСЕХ контейнеров
  пода. Такие поды убиваются последними — приоритет для критичных
  сервисов (БД).
- **Burstable:** хотя бы у одного контейнера задан request, но
  request != limit (или limit не задан вовсе). Средний приоритет.
- **BestEffort:** requests и limits не заданы вообще ни у одного
  контейнера. Убиваются первыми при нехватке ресурсов на ноде.
requests используются kube-scheduler-ом для выбора ноды (вопрос 36),
limits — ограничение cgroups, которое не даст контейнеру превысить
указанный потолок.

# 30. Какие есть паттерны многоконтейнерных подов (sidecar, ambassador,
adapter)?
Это способы вынести вспомогательную логику в отдельный контейнер внутри
того же пода (общий сетевой namespace и возможность разделять volumes
с основным контейнером), не трогая код самого приложения.
- **Sidecar:** контейнер, расширяющий и дополняющий основное
  приложение (например, сбор логов, синхронизация файлов, Envoy-прокси
  в Service Mesh — см. вопрос 26).
- **Ambassador:** контейнер-прокси, упрощающий сетевое взаимодействие
  основного приложения с внешним миром (приложение общается с
  localhost, а ambassador-контейнер проксирует запрос наружу, пряча
  сложность — например, подключение к шардированной БД).
- **Adapter:** контейнер, приводящий вывод основного приложения к
  единому стандартному формату (например, конвертирует нестандартные
  логи приложения в формат, который понимает система мониторинга).

# 31. Какие основные стадии жизненного цикла пода и типичные проблемы
вы знаете?
Фазы пода (Pod Phase): Pending (под создан, но еще не размещен на ноде
или образы не скачаны) → Running (хотя бы один контейнер запущен) →
Succeeded/Failed (все контейнеры завершились).
Типичные проблемы при диагностике (kubectl describe pod, kubectl get
events):
- **ImagePullBackOff:** не удается скачать образ (неверный тег,
  приватный registry без Secret с credentials).
- **CrashLoopBackOff:** контейнер запускается и сразу падает, K8s
  повторяет попытки с экспоненциальной задержкой (смотреть kubectl
  logs --previous для логов упавшего контейнера).
- **OOMKilled:** контейнер превысил memory limit, ядро убило процесс
  через cgroups OOM-killer (см. `00_docker.sh`, вопрос 3).
- **Evicted:** kubelet сам принудительно удалил под из-за нехватки
  ресурсов на ноде (DiskPressure/MemoryPressure) — в первую очередь
  эвикшену подвергаются поды с классом BestEffort (вопрос 29).
- **Pending без размещения:** недостаточно ресурсов на нодах под
  requests пода, либо не удовлетворены Taints/Tolerations или
  Affinity-правила (вопросы 14, 22).

# 32. Что такое NetworkPolicy и как она работает?
NetworkPolicy — объект, ограничивающий сетевой трафик между подами на
уровне L3/L4 (IP/порт) — по умолчанию в Kubernetes ВСЕ поды могут
общаться друг с другом без ограничений (Nothing is denied), и
NetworkPolicy это меняет.
```yaml
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
spec:
  podSelector:
    matchLabels: {app: backend}
  policyTypes: ["Ingress"]
  ingress:
    - from:
        - podSelector: {matchLabels: {app: frontend}}
      ports: [{port: 8080}]
```
Как только на под навешан хотя бы один селектор NetworkPolicy (в
примере — под с лейблом app=backend), для него включается deny-by-
default режим, и разрешается только явно перечисленный трафик (здесь
— только от подов с лейблом app=frontend на порт 8080). NetworkPolicy
реализуется не самим control plane, а CNI-плагином (Calico, Cilium —
вопрос 19); CNI без поддержки NetworkPolicy (например, базовый Flannel)
такие объекты просто игнорирует.

# 33. Что такое SecurityContext и Pod Security Admission?
SecurityContext — настройки безопасности на уровне пода или контейнера:
```yaml
securityContext:
  runAsNonRoot: true
  runAsUser: 1000
  readOnlyRootFilesystem: true
  capabilities:
    drop: ["ALL"]
```
- runAsNonRoot — запрещает запуск процесса от root внутри контейнера.
- readOnlyRootFilesystem — корневая ФС контейнера доступна только для
  чтения (пишет только в смонтированные volumes).
- capabilities.drop — убирает Linux-capabilities (например, CAP_
  NET_RAW), сужая возможности процесса даже если он скомпрометирован.
Pod Security Admission (PSA, встроенная замена устаревшего
PodSecurityPolicy) — механизм на уровне namespace, который ЗАСТАВЛЯЕТ
поды соответствовать одному из трех стандартных профилей (Privileged/
Baseline/Restricted), выставляемых лейблом на namespace
(pod-security.kubernetes.io/enforce=restricted) — под, нарушающий
профиль (например, запрашивающий --privileged в Restricted
namespace), просто не будет создан.

# 34. Что такое Admission Controllers и Admission Webhooks?
Admission Controller — код внутри kube-apiserver, перехватывающий
запрос ПОСЛЕ аутентификации/авторизации, но ДО сохранения объекта в
etcd — может изменить объект (Mutating) или отклонить его (Validating).
Встроенные примеры: NamespaceLifecycle, ResourceQuota (вопрос 35),
PodSecurity (вопрос 33).
Admission Webhook — способ подключить СВОЙ внешний сервис в эту же
цепочку проверки:
- **MutatingAdmissionWebhook** — может на лету изменить объект перед
  сохранением (например, Istio автоматически инжектит sidecar-
  контейнер в каждый новый под).
- **ValidatingAdmissionWebhook** — может только разрешить или отклонить
  объект без изменений, часто без своего отдельного сервиса, а через
  готовые policy-движки (OPA Gatekeeper, Kyverno — см.
  `4_kubernetes/06_security/02_policy_engines/`), которые позволяют
  описывать правила декларативно, а не писать свой webhook-сервис
  с нуля.

# 35. Что такое ResourceQuota и LimitRange?
Оба объекта работают на уровне Namespace, но решают разные задачи.
- **ResourceQuota:** ограничивает СУММАРНОЕ потребление ресурсов ВСЕМИ
  подами в неймспейсе (например, не более 10 CPU и 20Gi RAM суммарно
  на весь namespace, не более 5 PVC, не более 20 подов) — защита одной
  команды/проекта от захвата всех ресурсов общего кластера.
- **LimitRange:** задает ограничения (min/max/default) для ОТДЕЛЬНОГО
  контейнера/пода в неймспейсе — например, если под создан без
  requests/limits вообще, LimitRange автоматически подставит значения
  по умолчанию (это прямо влияет на QoS-класс пода, вопрос 29).

# 36. Как работает kube-scheduler при выборе ноды для пода?
Планирование пода происходит в два этапа.
1. **Filtering (фильтрация):** отсеивает ноды, которые физически не
   подходят — недостаточно ресурсов под requests пода (вопрос 29), не
   пройдены Taints/Tolerations (вопрос 14), не выполнены обязательные
   (required) правила Node/Pod Affinity (вопрос 22).
2. **Scoring (скоринг):** оставшиеся подходящие ноды ранжируются по
   набору весовых функций (например, равномерное распределение нагрузки
   между нодами, предпочтительные (preferred) правила Affinity) — под
   размещается на ноду с лучшим суммарным баллом.
**Preemption (вытеснение):** если ни одна нода не подходит, но под
имеет более высокий Priority Class, чем уже запущенные на какой-то
ноде поды, scheduler может вытеснить (удалить) поды с более низким
приоритетом, чтобы освободить место для более приоритетного.

# 37. Как обновляют версию Kubernetes-кластера без даунтайма?
Для self-hosted кластеров (kubeadm) обновление выполняется узел за
узлом, в строгом порядке: сначала Control Plane (по одному мастеру за
раз — `kubeadm upgrade apply` на первом, затем `kubeadm upgrade node`
на остальных), затем Worker-ноды. Перед обновлением каждой ноды
(включая мастера) ее выводят из обслуживания:
1. `kubectl cordon <node>` — помечает ноду как недоступную для
   планирования НОВЫХ подов (существующие продолжают работать).
2. `kubectl drain <node>` — аккуратно вытесняет существующие поды с
   ноды на другие (с учетом Pod Disruption Budget, вопрос 23), давая
   приложениям команду на graceful shutdown.
3. Обновляют kubelet/kubeadm на ноде, перезапускают сервисы.
4. `kubectl uncordon <node>` — возвращают ноду обратно в работу.
Managed-кластеры (EKS, GKE — вопрос 21) делают то же самое
автоматически через managed node groups.

# 38. Как устроен High Availability (HA) Control Plane?
Для отказоустойчивости Control Plane разворачивают НЕСКОЛЬКО мастер-
нод (обычно нечетное число — 3 или 5) вместо одной.
- **kube-apiserver** — stateless-компонент, запускается на каждом
  мастере независимо, трафик к ним распределяется через внешний
  балансировщик нагрузки (или VIP) перед несколькими apiserver-ами.
- **etcd** (вопрос 18) — stateful-компонент, требует консенсуса по
  протоколу Raft: для принятия записи нужен кворум (quorum) — больше
  половины узлов etcd должны быть живы и согласны (при 3 узлах кластер
  переживает потерю ОДНОГО узла, при 5 — ДВУХ). Именно поэтому число
  узлов etcd всегда нечетное — четное число не увеличивает отказо-
  устойчивость, а только требует больше узлов для того же кворума.
- **kube-scheduler/kube-controller-manager** — запускаются на каждом
  мастере, но активен только ОДИН экземпляр в момент времени (leader
  election через блокировку в etcd) — остальные простаивают в режиме
  ожидания (standby), готовые перехватить лидерство при падении
  активного.

# 39. Что такое Headless Service и зачем он нужен для StatefulSet?
Обычный Service (ClusterIP) балансирует трафик между подами под одним
общим виртуальным IP — обратившись к имени сервиса, клиент не может
выбрать КОНКРЕТНЫЙ под. Headless Service (`clusterIP: None`) этого не
делает: DNS-запрос к имени сервиса возвращает СПИСОК IP-адресов ВСЕХ
подов напрямую, а не один виртуальный IP. Это обязательно для
StatefulSet (вопрос 5), где каждый под имеет собственную постоянную
сетевую идентичность (pod-0, pod-1) и клиенту/другим подам кластера
нужно уметь обращаться к КОНКРЕТНОМУ инстансу (например, напрямую к
primary-реплике БД), а не к случайному через балансировку.

# 40. Как работает service discovery (CoreDNS) внутри кластера?
CoreDNS — DNS-сервер кластера (по умолчанию в современных K8s, развернут
как Deployment), которому kubelet прописывает адрес в /etc/resolv.conf
каждого пода. Для каждого Service автоматически создается DNS-запись
вида `<имя-сервиса>.<namespace>.svc.cluster.local`, резолвящаяся в
ClusterIP сервиса (или в список подов для Headless Service, вопрос 39)
— благодаря этому приложения обращаются друг к другу по
человекочитаемым именам сервисов вместо захардкоженных IP-адресов,
которые в Kubernetes все равно постоянно меняются при пересоздании
подов.

# 41. Что такое Finalizers в Kubernetes, как они работают и почему
# ресурсы зависают в Terminating?
Finalizers (`metadata.finalizers`) — это массив строк (ключей-меток),
сообщающий API Server, что перед физическим удалением объекта из etcd
необходимо выполнить предварительную очистку (pre-delete cleanup hook).

Как устроен жизненный цикл удаления:
1. При вызове `kubectl delete` API Server не удаляет объект из etcd
   мгновенно, если список `metadata.finalizers` не пуст.
2. Вместо этого API Server проставляет поле `metadata.deletionTimestamp`
   (в выводе CLI объект переходит в статус `Terminating`) и переводит
   объект в режим «read-only для удаления».
3. Контроллер (или оператор), зарегистрировавший финалайзер, видит
   появление `deletionTimestamp` и выполняет асинхронную очистку:
   - Отвязка и удаление облачных ресурсов (диски EBS/CSI, балансировщики
     LoadBalancer, DNS-записи).
   - Защита ресурсов: например, встроенный финалайзер
     `kubernetes.io/pvc-protection` запрещает удаление PVC, пока том
     смонтирован в работающий Pod.
4. После успешной очистки контроллер отправляет patch-запрос и удаляет
   свой ключ из массива `metadata.finalizers`.
5. Как только список `finalizers` становится пустым (`[]`), API Server
   физически удаляет объект из etcd.

Почему ресурс или Namespace зависает в статусе Terminating:
- Контроллер/оператор, отвечающий за снятие финалайзера, был удален из
  кластера, завис, упал в CrashLoopBackOff или потерял доступ к внешнему
  API (например, к облачному провайдеру или Vault).
- Для Namespace: удаление блокируется финалайзером `kubernetes`, пока
  внутри namespace остаются ресурсы с собственными неснятыми
  финалайзерами или недоступные aggregated API services (`APIService`).

Частая ошибка: почему `kubectl delete --force --grace-period=0` не
помогает:
- Флаг `--force` инструктирует kubelet немедленно прибить контейнеры без
  graceful shutdown, но он не удаляет финалайзеры из etcd. Объект
  остается заблокированным в API Server.

Как SRE диагностирует и снимает зависший финалайзер:
1. Найти виновника:
   `kubectl get <type> <name> -o jsonpath='{.metadata.finalizers}'`
2. Проверить логи соответствующего контроллера/оператора и убедиться,
   что внешние ресурсы удалены или почищены вручную.
3. Снять финалайзер вручную (если очистка уже выполнена или безопасна):
   `kubectl patch <type> <name> -p '{"metadata":{"finalizers":null}}' \`
   `  --type=merge`
   (для зависшего Namespace используется `kubectl replace --raw` через
   подресурс `/api/v1/namespaces/<name>/finalize`).
