# 1. Что такое Docker и зачем он нужен?
Docker — это платформа для разработки, доставки и запуска приложений в
изолированных контейнерах. Он позволяет упаковать приложение со всеми его
зависимостями (библиотеками, конфигурациями) в единый стандартизированный
модуль (образ), который будет гарантированно одинаково работать в любой
среде: на ноутбуке разработчика, на тестовом сервере или в production.
Основная цель Docker — решить проблему "на моей машине работает",
обеспечивая повторяемость и изоляцию.

# 2. Как в Docker реализовано ограничение ресурсов (CPU, RAM) и изоляция?
Docker использует механизмы ядра Linux:
- Namespaces (пространства имен): Обеспечивают изоляцию (PID, NET, MNT,
  IPC, UTS, USER). Благодаря им контейнер не видит процессы хоста и имеет
  свою сеть и ФС.
- Cgroups (контрольные группы): Обеспечивают ограничение ресурсов. Именно
  cgroups не дают контейнеру съесть 100% CPU хоста или превысить
  выделенный лимит RAM, вызывая OOM-killer для этого конкретного
  контейнера.

# 3. Что такое cgroups (Control Groups) и как они работают под капотом?
cgroups — механизм ядра Linux, который ограничивает, учитывает и
приоритизирует ресурсы (CPU, память, I/O, число процессов) для групп
процессов. Это основа лимитов контейнеров (docker run --memory/--cpus).
Устройство: иерархия групп в виртуальной ФС /sys/fs/cgroup. Процесс
добавляется в группу записью PID в cgroup.procs, лимиты задаются записью
в файлы контроллеров.
cgroups v1 vs v2:
- v1 — отдельная иерархия на каждый контроллер (cpu, memory, blkio...),
  процесс может быть в разных деревьях; сложно и непредсказуемо.
- v2 — единая унифицированная иерархия, единый учет, pressure stall
  information (PSI), корректный учет page cache и writeback. Сейчас
  стандарт (systemd, современный Docker/K8s).
Ключевые файлы v2:
- memory.max — жесткий лимит; при превышении срабатывает OOM-killer
  внутри группы (контейнер убивается, хост живет). memory.high —
  мягкий лимит (троттлинг/reclaim).
- cpu.max — квота "QUOTA PERIOD" (например 50000 100000 = 0.5 CPU).
  При исчерпании квоты процессы троттлятся (CFS throttling), что видно
  в cpu.stat (nr_throttled) и дает рост latency.
- cpu.weight — относительный приоритет при конкуренции (аналог shares).
- pids.max — защита от fork-бомб.
- io.max — лимит IOPS/bandwidth по блочному устройству.
Диагностика: systemd-cgls, systemd-cgtop, cat /proc/<PID>/cgroup,
stat -fc %T /sys/fs/cgroup (cgroup2fs = v2).
Важно: cgroups ОГРАНИЧИВАЮТ ресурсы, а ИЗОЛИРУЮТ видимость namespaces.

# 4. Что такое namespaces (пространства имен) и какие они бывают?
Namespaces — механизм ядра Linux, при котором процессы видят свою
изолированную копию глобального системного ресурса. Контейнер — это
обычный процесс хоста, запущенный в наборе namespaces.
Типы:
- PID — своя нумерация процессов (в контейнере процесс имеет PID 1).
- NET — свой сетевой стек (интерфейсы, маршруты, iptables, порты).
- MNT — свое дерево точек монтирования (корневая ФС контейнера).
- UTS — свои hostname и domainname.
- IPC — свои очереди сообщений, семафоры, shared memory.
- USER — отдельное отображение UID/GID (root в контейнере = обычный
  непривилегированный пользователь на хосте; основа rootless-режима).
- CGROUP — своя "корневая" точка видимости иерархии cgroups.
- TIME — свои смещения системных часов (ядро 5.6+).
Syscalls:
- clone(CLONE_NEWPID | CLONE_NEWNET ...) — создать процесс сразу в
  новых namespaces.
- unshare(2) — отделить текущий процесс в новые namespaces.
- setns(2) — войти в уже существующий namespace (так работает
  docker exec и nsenter).
Диагностика и практика:
- ls -l /proc/<PID>/ns — inode-ссылки на namespaces процесса; если
  inode совпадают, процессы в одном namespace.
- lsns — список namespaces в системе.
- unshare --pid --fork --mount-proc bash — "ручная" песочница.
- nsenter -t <PID> -n ip a — выполнить команду в сетевом namespace
  контейнера (когда внутри нет нужных утилит).
Итого: namespaces — про ИЗОЛЯЦИЮ (что процесс видит), cgroups — про
ОГРАНИЧЕНИЕ (сколько ресурсов может использовать).

# 5. В чем разница между виртуальной машиной и Docker-контейнером?
Виртуальная машина (ВМ) включает в себя полноценную гостевую операционную
систему поверх гипервизора (что требует много памяти и CPU для старта).
Docker-контейнер не имеет своей ОС, он переиспользует ядро хостовой
системы через механизмы cgroups и namespaces, изолируя только окружение
(библиотеки, процессы, файловую систему). Контейнеры запускаются
мгновенно и потребляют меньше ресурсов.

# 6. Что такое Dockerfile и из чего он состоит?
Dockerfile — это текстовый файл с инструкциями для автоматической сборки
Docker-образа (Image).
Основные инструкции:
- FROM (базовый образ)
- RUN (выполнение команд при сборке)
- COPY/ADD (копирование файлов с хоста)
- WORKDIR (установка рабочей директории)
- EXPOSE (указание порта, который слушает приложение)
- ENV (переменные окружения)
- CMD/ENTRYPOINT (команда, выполняемая при старте контейнера).

# 7. В чем разница между командами COPY и ADD в Dockerfile?
COPY просто копирует файлы или директории из локальной файловой системы
(build context) в образ.
ADD делает то же самое, но дополнительно умеет автоматически распаковывать
локальные архивы (tar) и может скачивать файлы по URL (хотя скачивание по
URL через ADD считается плохой практикой — лучше использовать RUN curl).

# 8. В чем разница между CMD и ENTRYPOINT?
Обе инструкции задают команду, которая выполняется при запуске контейнера.
ENTRYPOINT задает неизменяемый исполняемый файл (основную команду
контейнера).
CMD передает аргументы по умолчанию для ENTRYPOINT, либо задает команду,
если ENTRYPOINT не указан. Если при docker run передать аргументы в конце
команды, они переопределят CMD, но ENTRYPOINT останется прежним и примет
эти новые аргументы.

# 9. Как уменьшить размер Docker-образа?
- Использовать легковесные базовые образы (Alpine Linux, distroless).
- Использовать многоэтапную сборку (multi-stage builds), чтобы оставлять
  компиляторы/тулзы в builder-слое, а в финальный образ переносить только
  скомпилированный бинарник.
- Объединять команды RUN (например, RUN apt-get update && apt-get install
  ... && rm -rf /var/lib/apt/lists/*), чтобы не создавать лишних слоев с
  временными файлами.
- Использовать файл .dockerignore для исключения локальных файлов из
  build context.

# 10. Что такое Docker-слои (layers)?
Каждая инструкция в Dockerfile (FROM, RUN, COPY, ADD) создает новый
"слой" в файловой системе (UnionFS). Слои доступны только для чтения и
кэшируются на хосте. При запуске контейнера поверх всех Read-Only слоев
добавляется один тонкий Read-Write слой. Это позволяет экономить дисковое
пространство, так как разные образы переиспользуют общие базовые слои.

# 11. Как работает кэширование при сборке Docker-образа?
Docker кэширует каждый слой, чтобы ускорить повторные сборки. Если
инструкция в Dockerfile и файлы, связанные с ней (например, в COPY), не
изменились, Docker берет слой из кэша.
Важное правило: если слой (строка в Dockerfile) изменился (кэш
инвалидирован), то кэш автоматически сбрасывается и для всех последующих
строк. Поэтому часто меняющиеся вещи (например, COPY . .) ставят в конец
Dockerfile, а редко меняющиеся (установка зависимостей) — в начало.

# 12. Что такое Docker Volumes (тома)?
По умолчанию данные, созданные внутри контейнера, пишутся в тонкий R/W
слой и удаляются вместе с контейнером. Volumes — это механизм
персистентного (постоянного) хранения данных. Docker хранит их на
хост-машине (обычно в /var/lib/docker/volumes/) вне зависимости от
жизненного цикла контейнера. Тома можно монтировать в несколько
контейнеров одновременно.

# 13. Какие существуют типы сетевых драйверов в Docker?
- bridge (по умолчанию) — создает виртуальную изолированную сеть внутри
  хоста; контейнеры могут общаться друг с другом по IP.
- host — контейнер не изолируется сетево, он использует сетевой стек
  хоста (порты контейнера = порты хоста).
- none — полная изоляция без доступа к сети.
- overlay — позволяет контейнерам общаться между собой, находясь на
  разных физических хостах (используется в Docker Swarm).
- macvlan — назначает контейнеру физический MAC-адрес, делая его видимым
  в локальной сети как физическое устройство.

# 14. Чем отличается Docker-образ (Image) от контейнера (Container)?
Образ — это неизменяемый шаблон, состоящий из слоев (read-only),
содержащий ОС, библиотеки и приложение. Аналог класса в ООП.
Контейнер — это запущенный экземпляр образа (добавляется read-write
слой, процессы начинают выполняться). Аналог объекта в ООП.

# 15. Что делает команда docker-compose и файл docker-compose.yml?
Docker Compose — инструмент для описания и запуска многоконтейнерных
приложений. В файле docker-compose.yml декларативно описываются сервисы
(контейнеры), сети, вольюмы и их взаимосвязи. Команда docker-compose up
поднимает всю инфраструктуру разом (например, БД, бэкенд и фронтенд).

# 16. Что происходит, когда контейнер падает или завершает работу?
Поведение зависит от политики перезапуска (restart policy):
- no (по умолчанию) — контейнер не перезапускается.
- always — всегда перезапускать контейнер (если он упал или после
  перезагрузки демона Docker).
- on-failure — перезапускать только если контейнер завершился с ненулевым
  кодом ошибки (можно задать лимит попыток).
- unless-stopped — перезапускать всегда, кроме случаев, когда
  пользователь явно его остановил (docker stop).

# 17. Зачем используется ключ --privileged?
Флаг --privileged дает контейнеру почти полный доступ ко всем устройствам
хост-машины и снимает ограничения cgroups/AppArmor/SELinux. Контейнер
фактически получает права root-пользователя хоста (например, может
монтировать файловые системы или управлять сетью). Использовать крайне не
рекомендуется из соображений безопасности.

# 18. Как передать переменные окружения в контейнер?
- Через флаг -e или --env при запуске: docker run -e MY_VAR="v" image
- Через файл с переменными (.env файл): docker run --env-file .env image
- Внутри Dockerfile через инструкцию ENV (но это зашивает их в образ).

# 19. Как запустить контейнер в фоне и как к нему подключиться?
Для запуска в фоновом (detached) режиме используется ключ -d:
docker run -d nginx.
Чтобы выполнить команду в запущенном контейнере (подключиться к оболочке),
используется docker exec: docker exec -it <container_id> /bin/bash

# 20. Что такое Docker Registry? Назовите примеры.
Registry — это хранилище для Docker-образов. Бывает публичным и приватным.
Примеры: Docker Hub (публичный по умолчанию), AWS ECR, Google Artifact
Registry, GitLab Container Registry, Nexus, Harbor.

# 21. Что такое Docker Swarm?
Docker Swarm — это нативный инструмент оркестрации от Docker для
управления кластером Docker-хостов (Swarm mode). Он позволяет объединять
несколько хостов в единый пул ресурсов, управлять деплоем сервисов,
балансировкой нагрузки и отказоустойчивостью. Менее сложен, чем K8s, но
сейчас реже используется в энтерпрайзе.

# 22. Как посмотреть логи контейнера, если он падает сразу после запуска?
Командой docker logs <container_id_или_name>.
Даже если контейнер остановился (status Exited), его файловая система и
логи сохраняются, пока вы явно не удалите его командой docker rm.

# 23. Что делает команда docker system prune?
Команда очищает неиспользуемые ресурсы Docker, освобождая место на диске.
По умолчанию удаляет все остановленные контейнеры, сети без хотя бы одного
контейнера, "болтающиеся" (dangling) образы (слои без тегов) и кэш
сборки. С флагом -a также удалит все образы, не связанные с запущенными
контейнерами.

# 24. Что такое multi-stage сборка (multi-stage build)?
Это метод создания Dockerfile с несколькими инструкциями FROM. Каждая
инструкция FROM начинает новую стадию сборки. Это позволяет использовать
один образ для компиляции кода (со всеми тяжелыми зависимостями, SDK,
компиляторами), а в финальную стадию (из легкого образа) просто
скопировать готовый бинарник (с помощью COPY --from=builder). Итог — очень
маленький и безопасный финальный образ.

# 25. С каким PID запускается процесс в контейнере?
Внутри контейнера основной процесс (определенный в ENTRYPOINT/CMD) всегда
имеет PID=1. Контейнер живет ровно столько, сколько живет его процесс с
PID 1. Если процесс с PID 1 завершается, Docker останавливает и весь
контейнер, даже если в фоне работают другие дочерние процессы.

# 26. Какое ограничение на количество слоев в Docker и зачем их уменьшать?
Ранее в Docker был лимит в 127 слоев, в современных версиях (overlay2)
лимит может быть снят (вплоть до лимита самой ФС), но хорошей практикой
считается минимизировать их.
Каждый слой — это накладные расходы при загрузке и распаковке. Оптимально
объединять команды RUN (&&), чтобы промежуточные временные файлы не
сохранялись в слоях, что кардинально уменьшает вес финального образа.

# 27. Чем Podman отличается от Docker?
Главное архитектурное отличие — демон. Docker работает через единый
фоновый демон dockerd с правами root, который управляет всеми
контейнерами (если демон упал — падает управление всеми контейнерами
сразу, это же единая точка отказа и расширенная поверхность атаки).
Podman — демонless (daemonless): команда podman напрямую создает
процессы-контейнеры (через runc/crun), без постоянно работающего
сервиса в фоне. Из этого вытекают другие отличия:
- Rootless по умолчанию: Podman изначально спроектирован для запуска
  без root (через USER namespaces), Docker тоже это умеет, но
  исторически был рассчитан на root-демон.
- Pods: Podman умеет группировать несколько контейнеров в один Pod
  (с общим network namespace), как в Kubernetes — у Docker такого
  нативного понятия нет.
- CLI-совместимость: команды Podman практически идентичны Docker
  (podman run, podman build), есть алиас docker=podman — миграция
  CLI-команд обычно не требует переобучения.
- systemd-интеграция: podman generate systemd позволяет превратить
  контейнер в обычный systemd-сервис (управляется systemctl, без
  отдельного демона-оркестратора).
docker-compose для Podman частично заменяется подменой podman-compose
или через Podman Kube Play (podman play kube — запуск по
Kubernetes-манифесту напрямую, без кластера).

# 28. Что такое образ FROM scratch и зачем его использовать?
scratch — не настоящий образ, а специальный пустой псевдо-образ в
Docker, у которого нет вообще никакой файловой системы, библиотек,
шелла или пакетного менеджера — абсолютный ноль байт.
```dockerfile
FROM scratch
COPY myapp /myapp
ENTRYPOINT ["/myapp"]
```
Используется для статически слинкованных бинарников (типично для Go
с CGO_ENABLED=0 или Rust), которым не нужны никакие системные
библиотеки для работы. Плюсы: минимальный возможный размер образа
(мегабайты вместо десятков/сотен) и минимальная поверхность атаки —
внутри контейнера физически нет ни shell, ни apt, ни других
бинарников, которыми мог бы воспользоваться атакующий при компрометации
приложения.
Минус: полное отсутствие инструментов отладки внутри контейнера —
нельзя сделать docker exec ... sh, так как шелла внутри нет вообще;
даже базовые вещи вроде сертификатов CA или часовых поясов (tzdata)
надо копировать в образ вручную. Поэтому на практике часто берут
distroless-образы (вопрос 9) как промежуточный вариант — почти такой
же маленький и безопасный, но с минимальным набором нужных системных
файлов (CA-сертификаты и т.п.) уже внутри.
