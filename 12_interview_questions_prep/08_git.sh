# 1. Что такое Git и в чем его отличие от SVN?
Git — это распределенная система контроля версий (DVCS). Каждый разработчик
имеет локально полную копию всего репозитория со всей историей коммитов. Это
позволяет работать оффлайн и делать локальные коммиты. SVN (Subversion) —
централизованная система (CVCS). Существует только один центральный сервер с
историей, а разработчики скачивают (checkout) только определенную версию
файлов. Работа с историей в SVN требует постоянного сетевого подключения.

# 2. Объясните разницу между git pull и git fetch. 
`git fetch` связывается с
удаленным репозиторием (origin) и скачивает все новые коммиты, ветки и теги
в ваш локальный кэш (origin/master), но при этом никак не меняет ваши
текущие локальные файлы и рабочую директорию. Вы можете просмотреть
изменения перед интеграцией. `git pull` делает две операции подряд: сначала
делает `git fetch`, а затем автоматически делает `git merge` (или `rebase`,
если настроено), пытаясь слить удаленные изменения с вашей текущей веткой.
Это может вызвать конфликты в рабочей директории.

# 3. В чем разница между git merge и git rebase?
Оба метода объединяют ветки, но по-разному работают с историей. `git merge`
берет вашу ветку (feature) и целевую ветку (master) и создает новый,
отдельный коммит слияния (Merge Commit), у которого два родителя. История
остается ветвистой (видно, кто когда ответвился), безопасно для публичных
веток. `git rebase` берет коммиты из вашей ветки (feature) и переписывает
историю так, будто они были сделаны поверх самых последних коммитов из
master. Коммиты получают новые хеши. История становится абсолютно линейной
(плоской), но rebase нельзя делать для веток, с которыми уже работают другие
люди (push -f сломает им работу).

# 4. Как отменить локальный коммит (но сохранить изменения в файлах)?
Используйте команду `git reset --soft HEAD~1` (или просто `HEAD^`). Это
отменит самый последний коммит, но изменения останутся в индексе (Staging
area), готовые к новому коммиту. Если использовать `--mixed` (по умолчанию),
изменения останутся в файлах, но будут убраны из индекса. Если использовать
`--hard`, изменения будут удалены безвозвратно.

# 5. Что такое Git Flow и Trunk Based Development (TBD)?
Git Flow — это модель ветвления на основе релизов. В ней есть долгоживущие
ветки (`master` для продакшена, `develop` для интеграции) и короткие
(`feature`, `release`, `hotfix`). Это громоздкая схема, которая плохо
подходит для быстрых процессов CI/CD из-за редких и сложных интеграций.
Trunk Based Development (Магистральная разработка) — современный метод,
когда все разработчики сливают свой код напрямую в основную ветку (`trunk`
или `main`) небольшими порциями по несколько раз в день (сразу пряча
неготовую фичу за Feature Flags). Это позволяет оптимизировать этапы слияния
и интеграции, являясь обязательной практикой для настоящего Continuous
Deployment.

# 6. Что такое индекс (Staging Area) в Git?
Staging Area (Индекс) — это промежуточная зона между вашей рабочей
директорией (где вы редактируете файлы) и репозиторием (историей коммитов).
С помощью `git add` вы добавляете измененные файлы в индекс, подготавливая
их. С помощью `git commit` в репозиторий попадает не всё, что вы изменили, а
только то, что лежало в индексе. Это позволяет разбивать масштабные
изменения на несколько логических коммитов.

# 7. Зачем нужна команда git stash?
`git stash` позволяет временно "спрятать" (сохранить) незакоммиченные
локальные изменения в специальный стек и вернуть рабочую директорию в чистое
состояние (к последнему коммиту). Это крайне полезно, если вы начали работу,
и тут вас попросили срочно переключиться на другую ветку, чтобы исправить
баг, но текущая работа еще не готова к коммиту. Вернуться к спрятанным
изменениям можно через `git stash pop` или `git stash apply`.

# 8. Что делает команда git cherry-pick?
`git cherry-pick <commit_hash>` берет конкретный коммит из одной ветки и
применяет (копирует) его в текущую ветку в качестве нового коммита. Очень
полезно, когда фича-ветка огромна, а вам нужен только один конкретный коммит
из нее с важным фиксом, и вы не хотите мержить всю ветку.

# 9. Как изменить сообщение последнего (уже сделанного) коммита?
Командой `git commit --amend -m "Новое сообщение"`. Важно помнить: если вы
уже отправили (push) этот коммит на удаленный сервер, после --amend у
коммита изменится хеш, и вам придется сделать принудительную отправку `git
push --force`.

# 10. В чем разница между git revert и git reset?
`git revert <commit>` создает НОВЫЙ коммит, который отменяет изменения,
внесенные указанным коммитом. История не переписывается, старый коммит
остается на месте. Это безопасный и правильный способ отката для общих веток
(например, master). `git reset` перемещает указатель HEAD и переписывает
историю (удаляя коммиты). Это безопасно делать только в своих локальных, еще
не отправленных на сервер ветках.

# 11. Что такое HEAD в Git?
HEAD — это указатель, который в каждый момент времени ссылается на текущий
коммит вашей рабочей директории. Обычно HEAD указывает на название вашей
текущей ветки (которая, в свою очередь, указывает на последний коммит в
ней).

# 12. Что такое "Detached HEAD" (отсоединенный HEAD)?
Это состояние возникает, когда вы делаете `git checkout` не на ветку, а
напрямую на конкретный коммит, тег или удаленную ветку (например, `git
checkout a1b2c3d`). HEAD теперь указывает на коммит, а не на ветку. Если в
этом состоянии сделать новые коммиты, они не будут привязаны ни к какой
ветке и в итоге будут удалены сборщиком мусора Git (Garbage Collector).
Нужно создать новую ветку (`git checkout -b new_branch`), чтобы сохранить
их.

# 13. Что такое .gitignore и как заставить Git игнорировать файл, который
уже был добавлен в репозиторий?
`.gitignore` — текстовый файл, в котором прописываются шаблоны (файлы,
папки, расширения), которые Git не должен отслеживать (например, собранные
бинарники, node_modules, IDE конфиги). Если файл УЖЕ был добавлен и
закоммичен, простое добавление его в .gitignore не сработает (он уже
отслеживается). Нужно удалить его из индекса: `git rm --cached filename`,
после чего закоммитить это удаление.

# 14. Чем отличается Squash от обычного Merge?
Squash ("сплющивание") берет все коммиты из фича-ветки и объединяет их в
один большой коммит перед слиянием с целевой веткой. Это помогает сохранить
историю `master` чистой и читаемой (одна фича = один коммит), скрывая
промежуточные коммиты (типа "fix typo", "WIP").

# 15. Как найти коммит, который "сломал" код (git bisect)?
Утилита `git bisect` использует бинарный поиск, чтобы быстро найти "плохой"
коммит. Вы говорите Git: текущий коммит плохой (`git bisect bad`), а вот
этот коммит месяц назад был хорошим (`git bisect good <hash>`). Git делит
коммиты пополам и переключает (checkout) на средний. Вы тестируете (или
запускаете скрипт) и говорите `good` или `bad`. Процесс повторяется,
логарифмически сужая область, пока виновник не будет найден.

# 16. Что такое git hooks (хуки)?
Хуки — это скрипты, которые Git автоматически выполняет до или после
определенных событий. Они лежат в папке `.git/hooks`.
- `pre-commit`: запускается перед коммитом (часто используется для запуска
  линтеров или форматирования кода, чтобы не пускать плохой код в
  репозиторий).
- `pre-push`: запускается перед отправкой на сервер (для запуска тестов).
- Существуют также серверные хуки (post-receive), на которых строились
  старые системы CI/CD.

# 17. Что такое Bare-репозиторий?
Bare (голый) репозиторий создается ключом `git init --bare`. В отличие от
обычного репозитория, он не имеет рабочей директории (вы не увидите там
исходников, только служебные файлы вроде objects, refs, HEAD). Серверные
репозитории (на GitHub, GitLab) всегда являются bare-репозиториями, они
служат только для синхронизации, в них нельзя вести разработку напрямую.

# 18. Как перенести свои незакоммиченные изменения из одной ветки в другую?
Если вы просто редактировали файлы (и не делали коммит), и ветки не имеют
серьезных конфликтов, достаточно просто сделать `git checkout другая_ветка`.
Незакоммиченные изменения (рабочая директория и индекс) переедут вместе с
вами. Если checkout не дает переключиться (ошибка конфликтов), нужно
"спрятать" их: `git stash`, затем `git checkout другая_ветка`, и потом `git
stash pop`.

# 19. Что такое Fork и чем он отличается от Branch?
Branch (Ветка) — это логическое ответвление внутри ОДНОГО репозитория. Fork
(Форк) — это фича не самого Git, а платформ (GitHub/GitLab). Форк — это
полная серверная копия чужого репозитория в ваше личное пространство.
Используется в Open-Source для предложения изменений через Pull
Requests/Merge Requests тем проектам, где у вас нет прав на запись и
создание веток.

# 20. Как восстановить случайно удаленную ветку, если в ней были уникальные
коммиты?
Используя инструмент `git reflog`. Он хранит локальную историю ВСЕХ
перемещений указателя HEAD (каждый checkout, commit, reset, pull). С помощью
`git reflog` находим хеш последнего коммита удаленной ветки, а затем просто
создаем новую ветку, указывающую на этот хеш: `git checkout -b
recovered_branch <hash>`.

# 21. В чем архитектурная и процессная разница между GitLab, GitHub и
Bitbucket?
Все три платформы используют Git "под капотом", но отличаются фокусом:
- **GitHub:** Крупнейшая платформа для Open-Source. Главный упор на
  комьюнити, Pull Requests, форки. Недавно добавили встроенный CI (GitHub
  Actions).
- **GitLab:** Позиционируется как "all-in-one DevOps платформа" для
  энтерпрайза. Главная фича — мощнейший встроенный GitLab CI/CD, Container
  Registry и инструменты безопасности прямо из коробки. Часто ставится
  on-premise (на свои сервера).
- **Bitbucket:** Продукт Atlassian. Его главное преимущество — глубочайшая
  интеграция с экосистемой Atlassian (Jira, Confluence). Отлично подходит
  корпоративным командам, жестко сидящим на Jira.

# 22. Что такое Git Submodules и в чем их главная боль?
Submodule — способ подключить один Git-репозиторий как поддиректорию внутри
другого, сохраняя у вложенного репозитория полностью отдельную историю
коммитов. Родительский репозиторий хранит не сам код подмодуля, а лишь путь
до него и ТОЧНЫЙ хеш коммита, на который он должен указывать. Главная боль:
подмодуль всегда выставлен в состояние detached HEAD (указывает на
конкретный коммит, а не на ветку), поэтому обычный `git pull` в родительском
репозитории НЕ подтягивает новые коммиты подмодуля автоматически — нужно
отдельно:
```bash
git clone --recurse-submodules <url>      # клонировать сразу со всеми
                                           # подмодулями
git submodule update --init --recursive   # или инициализировать/
                                           # обновить их в уже
                                           # склонированном репозитории
```
Если подмодулей становится много и команда часто забывает их обновлять,
альтернативой часто выбирают монорепозиторий (единая история для всего) или
вынос общего кода в отдельно версионируемый пакет (библиотеку/модуль),
подключаемый через обычный пакетный менеджер языка, а не через Git
submodule.

# 23. В чем разница между annotated и lightweight тегами в Git?
- **Lightweight (легковесный) тег** — просто именованный указатель на
  конкретный коммит (`git tag v1.0`), ничем принципиально не отличается от
  ветки, кроме того что не двигается сам по себе.
- **Annotated (аннотированный) тег** (`git tag -a v1.0 -m "Release 1.0"`) —
  полноценный объект в базе данных Git со своими метаданными: автор, дата,
  сообщение, и опционально GPG-подпись (вопрос 24). Для релизов всегда
  рекомендуют annotated-теги: они не просто указывают на коммит, а сохраняют
  ИСТОРИЮ того, кто и когда создал именно этот релиз, что важно для аудита и
  для верификации подлинности тега.

# 24. Как работает подпись коммитов (GPG/SSH signing) в Git и зачем она
нужна?
`git commit -S` подписывает коммит приватным ключом автора (GPG или, в
современных версиях Git, обычным SSH-ключом через `gpg.format = ssh`).
Подпись доказывает, что коммит действительно создан владельцем этого ключа,
а не кем-то, кто просто прописал чужое имя/email в `git config
user.name/email` (это делается тривиально и без подписи никак не
проверяется).
```bash
git commit -S -m "fix: критичный патч"
git log --show-signature   # показать и проверить подписи в истории
```
Это часть практики supply-chain security (см. `10_devsecops.sh`) — на
некоторые ветки можно настроить правило, требующее, чтобы ВСЕ коммиты (и/или
теги релизов) были подписаны доверенным ключом, прежде чем они будут приняты
в защищенную ветку.

# 25. Что такое `git worktree` и когда он полезен?
`git worktree add ../hotfix-dir hotfix-branch` создает ДОПОЛНИТЕЛЬНУЮ
рабочую директорию, подключенную к тому же самому репозиторию (тот же
`.git`, та же история, те же удаленные ветки), но позволяющую иметь РАЗНЫЕ
ветки выгруженными на диск ОДНОВРЕМЕННО в разных папках. Удобно, когда нужно
срочно переключиться на другую ветку (например, сделать hotfix), не коммитя
и не стэшируя текущую незавершенную работу в основной рабочей директории —
вместо `git stash` + `git checkout` + долгого `git checkout` обратно, просто
открываем вторую папку с нужной веткой параллельно.
