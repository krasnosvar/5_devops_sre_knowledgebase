# 1. Что такое PAM (Pluggable Authentication Modules) и как он устроен?
PAM — модульная система аутентификации в Linux: вместо того чтобы каждая
программа (login, sshd, su, sudo) сама реализовывала проверку пароля,
она вызывает единый API PAM, а администратор настраивает ЦЕПОЧКУ
модулей в `/etc/pam.d/<имя-сервиса>` без изменения самих программ.
Конфиг состоит из 4 типов проверок (stack), выполняемых по порядку:
- **auth** — собственно аутентификация (проверка пароля/ключа).
- **account** — проверки учетной записи (не истек ли срок действия, не
  заблокирован ли аккаунт).
- **password** — смена пароля (политика сложности).
- **session** — что сделать при открытии/закрытии сессии (создать
  домашнюю директорию, установить лимиты).
Популярные модули: `pam_unix` (классическая проверка через
`/etc/shadow`), `pam_faillock` (блокировка после N неудачных попыток
входа), `pam_limits` (применяет `/etc/security/limits.conf`).

# 2. В чем разница между `/etc/passwd` и `/etc/shadow`?
`/etc/passwd` — доступен на чтение ВСЕМ пользователям, содержит
публичную информацию об учетке: имя, UID, GID, домашнюю директорию,
логин-шелл. Поле пароля в нем сейчас всегда `x` — реальный хеш пароля
туда больше не пишут.
`/etc/shadow` — читается только root-ом, содержит сам хеш пароля
(алгоритм + соль + хеш, например `$6$...` для SHA-512) и поля политики
старения пароля (вопрос 4). Разделение на два файла сделано специально,
чтобы ЛЮБАЯ программа могла резолвить UID→имя пользователя (`/etc/
passwd` должен быть читаем всем), не имея при этом доступа к хешам
паролей.

# 3. Как устроены группы пользователей в Linux (primary и supplementary)?
У каждого пользователя есть ровно одна **первичная (primary)** группа
(указана в `/etc/passwd`, присваивается новым файлам пользователя по
умолчанию) и ноль или более **дополнительных (supplementary)** групп
(список в `/etc/group`), дающих доступ к дополнительным ресурсам (не
влияя на владельца новых файлов).
```bash
useradd -g developers -G docker,sudo alice   # -g: первичная, -G: доп.
usermod -aG docker alice                     # добавить в доп. группу
                                              # (-a обязателен, иначе
                                              # usermod ЗАМЕНИТ список
                                              # всех доп. групп!)
groups alice                                 # посмотреть все группы
```

# 4. Что такое политика старения пароля (`/etc/login.defs`, `chage`)?
`/etc/login.defs` задает значения ПО УМОЛЧАНИЮ для новых пользователей
(`PASS_MAX_DAYS`, `PASS_MIN_DAYS`, `PASS_WARN_AGE`). Команда `chage`
управляет этими параметрами для КОНКРЕТНОГО уже существующего
пользователя:
```bash
chage -l alice           # посмотреть текущую политику пользователя
chage -M 90 -W 7 alice    # пароль истекает через 90 дней, предупреждать
                          # за 7 дней до истечения
chage -E 2026-12-31 alice # дата, после которой аккаунт полностью
                          # отключается
```
Блокировку после нескольких неудачных попыток ВВОДА пароля (а не
истечение срока) настраивают отдельно, через модуль `pam_faillock`
(вопрос 1).

# 5. Как захардить доступ по SSH?
Основные параметры в `/etc/ssh/sshd_config`:
- `PermitRootLogin no` — запретить прямой вход под root, заставляя
  заходить под обычным пользователем и повышать привилегии через sudo.
- `PasswordAuthentication no` — разрешить вход ТОЛЬКО по SSH-ключам,
  отключив вход по паролю (защита от перебора пароля).
- `AllowUsers alice bob` / `AllowGroups ssh-users` — явный allowlist
  того, кому вообще разрешено логиниться по SSH, даже если у них есть
  валидный ключ.
- `Port 2222` — смена порта с 22 не добавляет реальной защиты
  (security through obscurity), но резко снижает шум от automated
  сканеров/ботов в логах.
Дополнительно ставят **fail2ban** — демон, который парсит логи
авторизации (`/var/log/auth.log` или journald) и временно банит
(через nftables/iptables) IP-адреса после нескольких неудачных попыток
входа за короткое время.

# 6. Как соотносятся firewalld, nftables и iptables?
Исторически `iptables` — классическая утилита настройки правил
фильтрации пакетов ядра (netfilter). `nftables` — современная замена
iptables (с Linux 3.13+, а по умолчанию используется, начиная с
большинства актуальных дистрибутивов) с более простым синтаксисом
правил и встроенной поддержкой множеств (sets) без необходимости
городить отдельные цепочки под каждый IP. Пакет `iptables` сейчас
обычно является лишь СОВМЕСТИМЫМ интерфейсом (`iptables-nft`),
транслирующим старые команды в nftables-правила под капотом.
`firewalld` — не альтернативный бэкенд, а демон управления верхнего
уровня НАД nftables (или iptables), вводящий понятие **зон** (zones —
например `public`, `trusted`, `internal`) с предустановленными
наборами правил на интерфейс, и позволяющий менять правила "на лету"
(`firewall-cmd --reload`) без разрыва существующих соединений — то,
что при работе с голым iptables исторически требовало осторожности.

# 7. Чем SELinux отличается от AppArmor?
Оба — механизмы Mandatory Access Control (MAC), дополняющие
классические Unix-права (Discretionary Access Control, DAC, вопрос
12) — то есть даже root, формально имеющий полный доступ по DAC,
может быть ограничен политикой MAC.
- **SELinux** (Red Hat/CentOS/Fedora): привязывает метки (контексты —
  `user:role:type:level`) к КАЖДОМУ файлу и процессу; политика
  описывает, каким типам процессов разрешено обращаться к каким типам
  файлов. Режимы: `enforcing` (блокирует), `permissive` (только
  логирует нарушения, не блокирует — удобно для отладки новой
  политики), `disabled`. Посмотреть контекст — `ls -Z`; разобрать
  ошибку и сгенерировать разрешающее правило из лога нарушения —
  `audit2allow`.
- **AppArmor** (Ubuntu/Debian/SUSE): привязывается не к меткам файлов,
  а к ПУТЯМ (path-based) — политика (профиль) описывается для
  конкретной программы и перечисляет, к каким путям в файловой системе
  и с какими правами ей разрешен доступ. Считается проще в написании
  профилей, чем SELinux-политики, но менее гранулярным при
  переименовании/перемещении файлов (путь меняется — правило больше не
  действует).

# 8. Что такое auditd и зачем он нужен, если уже есть обычные логи?
`auditd` — подсистема ядра для детального логирования событий
безопасности на уровне системных вызовов (кто, когда, каким процессом
прочитал/изменил/удалил конкретный файл, выполнил конкретный syscall).
Обычные логи приложений (journald, `/var/log/*`) фиксируют только то,
что ПРИЛОЖЕНИЕ само решило залогировать; auditd работает НИЖЕ — на
уровне ядра, и может отследить доступ к файлу даже если сама программа,
которая его открыла, ничего не пишет в свои логи. Используется, когда
нужна compliance-отчетность (PCI DSS, кто именно читал файл с
конфиденциальными данными) — правила задаются через `auditctl` или
`/etc/audit/rules.d/`, просмотр событий — `ausearch`/`aureport`.

# 9. Что такое Linux capabilities и как они связаны с root?
Исторически модель была бинарной: либо процесс запущен от root и может
ВСЁ, либо не от root и не может почти ничего из системных операций.
Capabilities разбивают "суперспособности" root на отдельные,
независимо выдаваемые флаги — например, `CAP_NET_BIND_SERVICE`
(разрешение слушать порты < 1024) или `CAP_NET_RAW` (создавать raw-
сокеты). Это позволяет дать непривилегированному процессу ОДНУ
конкретную привилегию root, не давая ему root целиком.
```bash
setcap 'cap_net_bind_service=+ep' /usr/bin/myserver
# теперь /usr/bin/myserver может слушать порт 80 от обычного
# пользователя, без необходимости в root/sudo и без SUID-бита
getcap /usr/bin/myserver
```
Именно capabilities (а не полный root) — то, что Docker оставляет
контейнеру по умолчанию (небольшой фиксированный набор), и то, что
полностью снимается флагом `--privileged` (см. `03_containers_and_
orchestration/00_docker.sh`, вопрос 17), и то, что можно явно сузить
через `securityContext.capabilities.drop` в Kubernetes (см.
`03_containers_and_orchestration/01_kubernetes.sh`, вопрос 33).

# 10. В чем разница между `su`, `su -` и `sudo`?
- `su alice` — переключает текущего пользователя на alice, НО
  оставляет текущее окружение (переменные, рабочую директорию) от
  прежнего пользователя.
- `su - alice` (или `su -l alice`) — полноценный "login shell":
  запускает весь процесс входа заново, как будто alice только что
  залогинилась (свои переменные окружения, `.bash_profile`, домашняя
  директория) — именно так обычно и нужно переключаться.
- `sudo <команда>` — не открывает интерактивную сессию под другим
  пользователем, а выполняет ОДНУ конкретную команду от имени другого
  пользователя (обычно root), с полным журналированием, кто именно и
  какую команду выполнил (в отличие от `su`, после которого в логах
  просто "кто-то стал root", без истории команд).

# 11. Где хранится конфигурация sudo и как дать доступ не трогая
# основной файл `/etc/sudoers`?
Базовая конфигурация sudo уже разбиралась (см. `00_general_and_tools.
sh`, вопрос 7) — редактируется ТОЛЬКО через `visudo` (валидирует
синтаксис перед сохранением, чтобы случайная опечатка не заблокировала
sudo вообще для всех). На практике права почти никогда не прописывают
напрямую в `/etc/sudoers`: вместо этого в `/etc/sudoers.d/` кладут
ОТДЕЛЬНЫЙ файл на команду/группу (например `/etc/sudoers.d/
deploy-user`) — так изменения для разных команд/автоматизации
(Ansible, вопрос в `05_iac/01_ansible.sh`) не конфликтуют друг с
другом при слиянии и легко накатываются/откатываются по отдельности.
