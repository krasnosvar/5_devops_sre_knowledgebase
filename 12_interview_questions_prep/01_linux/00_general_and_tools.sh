# 1. Что такое Linux? В чем разница между ядром и дистрибутивом?
Linux — строго говоря, ядро операционной системы (kernel), написанное
Линусом Торвальдсом в 1991 году (открытый код, лицензия GPL). Ядро управляет
железом, памятью, процессами, файлами и сетью. Дистрибутив = ядро + набор
программ поверх него (GNU-утилиты, shell, systemd, библиотека libc, пакетный
менеджер, конфигурации по умолчанию). Поэтому часто говорят GNU/Linux.
Основные семейства дистрибутивов:
- Debian-семейство (Debian, Ubuntu): пакеты `.deb`, менеджер apt;
- RHEL-семейство (RHEL, Rocky, AlmaLinux, Fedora): `.rpm`, dnf/yum;
- Alpine (musl + busybox, минималистичный, любимчик в Docker), Arch. Одно и
  то же ядро может быть в разных дистрибутивах, различия — в пакетах, цикле
  релизов и политиках поддержки (LTS). Посмотреть: `uname -r` (версия ядра),
  `cat /etc/os-release` (дистрибутив), `hostnamectl`.

# 2. Что такое kernel space, user space и системные вызовы (syscalls)?
Процессор умеет работать в разных режимах привилегий (rings):
- Kernel space (ring 0) — ядро: полный доступ к железу и ко всей памяти.
- User space (ring 3) — обычные программы: своё изолированное адресное
  пространство, прямого доступа к железу нет. Чтобы программа прочитала
  файл, отправила пакет или запустила процесс, она обращается к ядру через
  системный вызов (syscall): `open`, `read`, `write`, `fork`, `execve`,
  `mmap`, `socket`. Порядок:
1. Приложение вызывает функцию libc (например `read()`).
2. libc кладет номер syscall и аргументы в регистры и выполняет инструкцию
   `syscall` — CPU переключается в kernel mode.
3. Ядро проверяет права и аргументы, выполняет работу, возвращает результат
   и переключает CPU обратно в user mode. Смена режима дорогая, поэтому
   большое число syscalls заметно тормозит приложение (буферизация I/O
   уменьшает их число). Ошибка внутри ядра может ронять всю систему (kernel
   panic), ошибка программы в user space — только ее саму (segfault).
   Посмотреть syscalls программы: `strace -f -tt ./app` (все вызовы),
   `strace -c ./app` (статистика), `strace -p <PID>` (уже запущенный
   процесс). Дополнительно: код ядра можно расширять без перезагрузки
   загружаемыми модулями (`lsmod`, `modprobe`, драйверы устройств).

# 3. Что такое systemd и unit-файлы? Как управлять сервисами?
systemd — система init (PID 1) и менеджер сервисов в большинстве современных
дистрибутивов. Его задачи: запуск сервисов при загрузке (параллельно, по
зависимостям), перезапуск упавших, сбор логов (journald), таймеры,
управление ресурсами через cgroups. Unit — описание ресурса, которым
управляет systemd. Типы: `.service` (демон), `.socket`, `.timer` (замена
cron), `.mount`, `.target` (группа юнитов, аналог runlevel). Файлы:
системные в `/usr/lib/systemd/system/`, администраторские в
`/etc/systemd/system/` (имеют приоритет). Минимальный сервис:
```
[Unit]
Description=My App
After=network-online.target
[Service]
ExecStart=/usr/local/bin/myapp
Restart=on-failure
User=myapp
[Install]
WantedBy=multi-user.target
```
Команды:
- `systemctl start|stop|restart|reload|status myapp`;
- `systemctl enable --now myapp` (автозапуск при загрузке + старт);
- `systemctl daemon-reload` — обязательно после правки unit-файла;
- `journalctl -u myapp -f` — логи сервиса;
- `systemctl list-units --failed` — упавшие сервисы.

# 4. Как устроено управление пакетами в Linux (apt, dnf)?
Пакет — архив с программой, ее метаданными (версия, зависимости) и скриптами
установки. Пакетный менеджер скачивает пакеты из репозиториев, разрешает
зависимости, проверяет GPG-подписи и ведет базу установленных пакетов.
- Debian/Ubuntu: `apt update` (обновить индекс репозиториев), `apt install
  nginx`, `apt remove|purge`, `apt upgrade`; низкоуровневый `dpkg -i|-l|-L`;
  репозитории — `/etc/apt/sources.list(.d/)`.
- RHEL/Fedora: `dnf install|remove|update`, `dnf provides */file` (какой
  пакет дает файл); низкоуровневый `rpm -qa|-ql|-qf`; репозитории —
  `/etc/yum.repos.d/`. Важно для прода: фиксировать версии пакетов
  (`apt-mark hold`, `dnf versionlock`), не обновлять ядро/базу без плана,
  безопасные обновления делать через `unattended-upgrades`/`dnf-automatic`.

# 5. Как безопасно перезагрузить зависший сервер Linux, если не работает
консоль? (Magic SysRq) Если ядро все еще живо, используются комбинации
клавиш (SysRq). Метод называется REISUB: Alt + SysRq + R (возвращает
контроль над клавиатурой) Alt + SysRq + E (отправляет SIGTERM всем
процессам) Alt + SysRq + I (отправляет SIGKILL всем оставшимся) Alt + SysRq
+ S (Sync — сбрасывает буферы на диск) Alt + SysRq + U (Umount — переводит
ФС в режим только для чтения) Alt + SysRq + B (Reboot — жесткая
перезагрузка)

# 6. Что такое chroot и зачем он нужен?
chroot (change root) — операция, изменяющая видимый корневой каталог для
текущего процесса и его дочерних процессов. Приложение, запущенное в chroot,
не имеет доступа к файлам за пределами своей "тюрьмы". Используется для
изоляции небезопасных сервисов или тестирования (прообраз контейнеров).

# 7. Как работает команда sudo и где хранится её конфигурация?
Команда sudo позволяет пользователям выполнять команды от имени другого
пользователя (чаще всего root) с проверкой их собственного пароля (в отличие
от su). Конфигурация хранится в файле `/etc/sudoers` и директории
`/etc/sudoers.d/`. Редактировать sudoers следует только через утилиту
`visudo`, которая проверяет синтаксис при сохранении, предотвращая
блокировку доступа к системе.

# 8. Какова разница между systemctl restart и systemctl reload?
`restart` полностью останавливает сервис и запускает его заново (PID
процесса меняется, происходит даунтайм, если сервис не имеет механизмов
бесшовного рестарта). `reload` отправляет процессу сигнал (обычно SIGHUP)
перечитать конфигурационные файлы без завершения основного процесса. Сервис
продолжает обрабатывать соединения.

# 9. Как посмотреть историю команд, и как выполнить поиск по истории?
Команда `history` выводит список ранее введенных команд. Для быстрого поиска
используется сочетание клавиш `Ctrl+R` (reverse-i-search), где можно ввести
часть команды. Чтобы повторить последнюю команду: `!!`. Чтобы повторить
команду по номеру: `!123`.

# 10. Разница между утилитами grep, awk и sed?
`grep` (Global Regular Expression Print) — утилита для поиска строк,
соответствующих регулярному выражению. `sed` (Stream Editor) — потоковый
текстовый редактор, часто используемый для поиска и замены текста
(`s/old/new/g`). `awk` — мощный язык обработки текста и извлечения данных,
отлично подходящий для работы с табличными данными (разделенными пробелами
или другими разделителями), вычислений и форматирования.

# 11. Из каких основных подсистем состоит ядро Linux?
Ядро (Kernel) является прослойкой между "железом" (Hardware) и процессами
(User Space). Основные подсистемы:
1. **Process Scheduler (SCHED):** Планировщик процессов, делящий
   процессорное время (CPU) между процессами.
2. **Memory Manager (MM):** Менеджер памяти, раздающий ОЗУ процессам и
   управляющий виртуальной памятью (и Swap).
3. **Virtual File System (VFS):** Виртуальная файловая система,
   предоставляющая процессам единый интерфейс работы с файлами, абстрагируя
   реальные драйверы дисков и сетевых систем.
4. **Network Interface (NET):** Сетевой стек, обрабатывающий пакеты и
   протоколы (TCP/IP).
5. **Inter-Process Communication (IPC):** Механизмы обмена данными между
   процессами (сообщения, разделяемая память, семафоры).

# 12. В чем разница между `command1 & command2`, `command1 && command2`, и
`command1 || command2` в bash?
- `&`: Выполнить `command1` в фоне (background) и сразу же, параллельно
  начать `command2`.
- `&&`: Логическое И (AND). Выполнить `command2` ТОЛЬКО ЕСЛИ `command1`
  завершилась успешно (exit code = 0).
- `||`: Логическое ИЛИ (OR). Выполнить `command2` ТОЛЬКО ЕСЛИ `command1`
  завершилась с ошибкой (exit code != 0).

# 13. Вы пытаетесь удалить миллион файлов командой `rm -f *`, но получаете
ошибку `Argument list too long`. Что делать?
Оболочка bash подставляет список всех файлов вместо звездочки `*`, формируя
гигантскую строку команды, которая превышает лимиты буфера ядра
(определяемого в `getconf ARG_MAX`). Решения:
- Использовать `find` и `xargs` (разбивает список на куски): `find . -type f
  -print0 | xargs -0 rm -f`
- Использовать встроенный флаг `find`: `find . -type f -delete` (самый
  быстрый и безопасный способ).
- В цикле: `for f in *; do rm -f "$f"; done` (очень медленно).

# 14. Как ограничить доступные пользователю команды по SSH?
Например, чтобы определенный пользователь (или ключ) мог делать только
бэкапы, мы можем привязать конкретную команду к его публичному ключу в файле
`~/.ssh/authorized_keys`. Формат строки в authorized_keys:
`command="/usr/local/bin/backup_script.sh",no-pty,no-port-forwarding ssh-rsa
AAAAB3NzaC...` Когда пользователь зайдет с этим ключом, выполнится только
этот скрипт, а интерактивная оболочка (bash) выдана не будет.

# 15. Опишите процесс загрузки Linux от нажатия кнопки питания до login. 
1. Firmware (BIOS или UEFI). POST — самотестирование железа, инициализация
CPU/RAM/устройств. BIOS читает MBR (первые 512 байт диска) и передает
управление загрузчику первой стадии. UEFI читает NVRAM-переменные и
запускает `.efi`-приложение с ESP (EFI System Partition, FAT32),
поддерживает GPT и Secure Boot (проверка подписи загрузчика/ядра). 
2. Bootloader (GRUB2). Показывает меню, читает `/boot/grub/grub.cfg`
(генерируется из /etc/default/grub и /etc/grub.d/ командой `update-grub` /
`grub2-mkconfig`), загружает в память образ ядра (vmlinuz) и initramfs,
передает ядру параметры (cmdline: root=, ro, quiet, init= и т.д.). 
3. Ядро.
Распаковывается, инициализирует CPU, память, планировщик, драйверы,
монтирует initramfs как временный root (rootfs). 
4. initramfs/initrd.
Небольшой архив в RAM с минимальным набором модулей и скриптов. Задача:
загрузить драйверы дисков/RAID/LVM/ LUKS/сетевых ФС, найти настоящий
root-раздел (по UUID), смонтировать его и сделать `switch_root`. Без
initramfs ядро не смогло бы смонтировать корень, если драйвер диска собран
как модуль. 
5. Init (PID 1). Ядро запускает `/sbin/init` — в современных
дистрибутивах это systemd. Он монтирует ФС из /etc/fstab, поднимает сервисы
по зависимостям параллельно и выходит на `default.target` (multi-user.target
— текстовый режим, graphical.target — GUI). 
6. Login. Запускаются
getty/sshd, пользователь видит приглашение. Диагностика: - `systemd-analyze`
/ `systemd-analyze blame` / `critical-chain` — время загрузки и "узкие
места". - `journalctl -b` (текущая загрузка), `journalctl -b -1` (прошлая),
`dmesg` — сообщения ядра. - `cat /proc/cmdline` — параметры, с которыми
загружено ядро.

# 16. Сервер не загружается (kernel panic, "grub rescue", emergency mode).
Что делать?
Определяем, на какой стадии загрузки остановились:
- `grub rescue>` — GRUB не нашел конфиг/раздел. Командами `ls`, `set
  root=(hd0,gpt2)`, `insmod normal`, `normal` пытаемся загрузить; затем из
  загруженной ОС выполняем `grub-install` и `update-grub`. Если не
  получается — загрузка с Live-CD/rescue-образа и chroot: монтируем root в
  /mnt, bind-монтируем /dev /proc /sys, `chroot /mnt`, переустанавливаем
  GRUB.
- `Kernel panic - not syncing: VFS: Unable to mount root fs` — ядро не нашло
  корень: нет драйвера в initramfs, изменился UUID/имя диска, повреждена ФС.
  Выбираем в GRUB старое ядро (Advanced options), пересобираем initramfs
  (`update-initramfs -u` / `dracut -f`), проверяем root= в cmdline и
  /etc/fstab.
- `Emergency mode` — systemd не смог смонтировать ФС (чаще всего ошибка в
  /etc/fstab, битая ФС). Смотрим `journalctl -xb`, правим fstab (nofail для
  некритичных дисков), запускаем `fsck` на размонтированном разделе.
- Забыт пароль root — в GRUB нажимаем `e`, добавляем в строку linux
  `init=/bin/bash` (или `rd.break`), загружаемся, перемонтируем root: `mount
  -o remount,rw /`, меняем пароль `passwd`. На SELinux-системах
  дополнительно `touch /.autorelabel`. Профилактика: оставлять 2-3
  предыдущих ядра, использовать `nofail` в fstab для вторичных дисков, иметь
  доступ к консоли (IPMI/iDRAC/serial console в облаке) и проверять бэкапы
  конфигурации.

# 17. Какими инструментами проводят стресс-тестирование и бенчмаркинг
# компонентов сервера Linux (CPU, RAM, Disk I/O, Network)? В чём
# назначение `stress-ng`, `fio` и `iperf3`?
Перед вводом новых серверов/нод в кластер или расследованием деградации
производительности SRE-инженеры проводят нагрузочное тестирование и замеряют
предельные характеристики подсистем:

1. **CPU и оперативная память (`stress` / `stress-ng`):**
   - Утилита `stress-ng` (расширенный форк `stress`) позволяет точечно
     нагрузить процессор, память и системные вызовы ядра.
   - Сценарии использования:
     * Проверка стабильности разгона и охлаждения процессора (Thermal
       Throttling): `stress-ng --cpu 8 --timeout 60s`.
     * Тестирование поведения OOM Killer и нехватки оперативной памяти:
       `stress-ng --vm 4 --vm-bytes 80% --timeout 30s` (создает воркеры,
       выделяющие и непрерывно модифицирующие память, вызывая page faults).
     * Стресс переключения контекста и планировщика: `stress-ng --switch 4`.

2. **Дисковая подсистема и хранилища (`fio` — Flexible I/O Tester):**
   - **Индустриальный стандарт** для тестирования блочных устройств (NVMe,
     SATA SSD, HDD, AWS EBS, Ceph, NFS).
   - **Почему утилита `dd` не подходит для бенчмарков:** `dd` пишет через
     кэш страниц ядра (Page Cache), замеряя скорость оперативной памяти, а не
     диска, и выполняет только примитивную последовательную запись в 1 поток.
   - Что умеет `fio`: генерирует реалистичные профили нагрузки СУБД и очередей:
     * Случайное чтение/запись (`--rw=randread` или `--rw=randwrite`).
     * Размер блока (`--bs=4k` для OLTP баз данных, `--bs=1M` для бэкапов).
     * Обход кэша ОС (`--direct=1` — флаг O_DIRECT, честный замер диска).
     * Глубина очереди асинхронного I/O (`--ioengine=libaio --iodepth=32`).
     * Количество параллельных воркеров (`--numjobs=4`).
   - Ключевые метрики в выводе `fio`: IOPS (число операций ввода-вывода в
     секунду), пропускная способность (Bandwidth, MB/s) и перцентили задержки
     (p95, p99, p99.9 latency).

3. **Сетевой стек и пропускная способность (`iperf` / `iperf3`):**
   - Клиент-серверная утилита для измерения реальной скорости сети между
     двумя хостами.
   - Один сервер запускается как слушатель: `iperf3 -s`, а клиент генерирует
     нагрузку: `iperf3 -c <server_ip>`.
   - Режимы тестирования:
     * TCP throughput: замер максимальной скорости передачи с учетом TCP
       Window Size, алгоритма контроля перегрузки (BBR, Cubic) и MTU/Jumbo
       frames: `iperf3 -c <ip> -P 4` (в 4 параллельных TCP-потока).
     * UDP bandwidth & Jitter: замер потерь пакетов и дрожания задержки
       (jitter) на заданной скорости: `iperf3 -c <ip> -u -b 10G`.

4. **L7-нагрузка (Web/API):**
   - Для тестирования веб-сервисов и Ingress используются генераторы трафика:
     `wrk` (высокий RPS на epoll), `k6` (сценарное JS-тестирование)
     и `hey` (быстрый замер RPS и перцентилей задержки).
