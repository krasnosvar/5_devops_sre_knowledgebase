# 1. Как устроен сетевой стек Linux и по какому пути идет пакет?
Сетевой стек — часть ядра, реализующая протоколы TCP/IP. Путь входящего
пакета:
1. NIC (сетевая карта) принимает кадр, кладет его в кольцевой буфер (ring
   buffer) через DMA и посылает прерывание.
2. Драйвер + NAPI: вместо прерывания на каждый пакет ядро переходит в
   polling-режим и забирает пакеты пачками (softirq).
3. Пакет превращается в `sk_buff`, проходит L2 (Ethernet, VLAN, bridge),
   затем L3 (IP: маршрутизация, фрагментация).
4. Netfilter-хуки (PREROUTING, INPUT, FORWARD, OUTPUT, POSTROUTING): здесь
   работают iptables/nftables, NAT, conntrack.
5. L4 (TCP/UDP): пакет прикрепляется к сокету по четверке (src IP, src port,
   dst IP, dst port) и кладется в приемный буфер сокета.
6. Приложение читает данные через `recv()`/`read()`. Исходящий путь — в
   обратном порядке (сокет → TCP/IP → netfilter → очередь устройства (qdisc)
   → драйвер → NIC). Диагностика по уровням: `ip -s link` (ошибки/drop на
   интерфейсе), `ethtool -S` (статистика NIC), `ss -s` (сокеты),
   `nstat`/`netstat -s` (счетчики TCP), `tcpdump` (пакеты),
   `/proc/net/softnet_stat` (drop в softirq).

# 2. Что такое сокет и какие бывают виды сокетов?
Сокет — точка входа для сетевого обмена данными: объект ядра, который
приложение видит как обычный файловый дескриптор (read/write/close).
Создается вызовом `socket()`. Виды:
- `SOCK_STREAM` (TCP) — надежный поток с установкой соединения;
- `SOCK_DGRAM` (UDP) — дейтаграммы без гарантий доставки;
- `SOCK_RAW` — доступ к «сырым» пакетам (ping, tcpdump);
- Unix domain socket — связь между процессами на одном хосте через файл
  (например `/var/run/docker.sock`). Жизненный цикл TCP-сервера: `socket()`
  → `bind()` (привязать к IP:порт) → `listen()` (начать принимать, задать
  backlog) → `accept()` (взять соединение из очереди, получить новый сокет)
  → `read()`/`write()` → `close()`. Клиент: `socket()` → `connect()` →
  `read()`/`write()` → `close()`. Соединение определяется четверкой (src IP,
  src port, dst IP, dst port), поэтому один порт сервера может обслуживать
  тысячи клиентов. Посмотреть: `ss -tulpn` (слушающие), `ss -tan` (все TCP
  соединения и их состояния).

# 3. Как настраивается сеть в Linux: временно и постоянно?
Базовая настройка — IP-адрес, шлюз (default gateway), DNS. Временно (до
перезагрузки, только в ядре): `ip addr add 192.168.1.10/24 dev eth0` `ip
link set eth0 up` `ip route add default via 192.168.1.1` Постоянно — зависит
от дистрибутива и сетевого менеджера:
- Ubuntu Server: netplan (`/etc/netplan/*.yaml`, `netplan apply`);
- RHEL/CentOS/Fedora: NetworkManager (`nmcli`, `nmtui`, файлы в
  `/etc/NetworkManager/system-connections/`);
- Debian: `/etc/network/interfaces` или systemd-networkd
  (`/etc/systemd/network/*.network`). DNS: `/etc/resolv.conf` (часто это
  симлинк, управляемый `systemd-resolved`), локальные имена — `/etc/hosts`,
  имя хоста — `hostnamectl set-hostname`. Быстрая проверка связности по
  уровням: `ip a` (есть ли адрес) → `ip r` (есть ли маршрут) → `ping
  <gateway>` → `ping 8.8.8.8` (внешняя сеть) → `dig example.com` (DNS) →
  `curl -v` (приложение).

# 4. Как найти процесс, который использует определенный порт (например, 80)?
Используются утилиты netstat, ss или lsof. Примеры: ss -tulnp | grep :80
lsof -i :80 netstat -tulnp | grep :80

# 5. В чем разница между TCP-протоколами и UDP на уровне сетевого стека
Linux? (В контексте тюнинга) В Linux TCP требует выделения буферов
(tcp_rmem, tcp_wmem), управления конгестией (tcp_congestion_control) и
отслеживания состояний соединений (nf_conntrack). UDP — stateless, не
требует установления соединения, поэтому при высоких нагрузках не
переполняет таблицы состояний, но тюнинг ограничивается размером очередей
(rmem_max, wmem_max).

# 6. Почему `ss` считается заменой `netstat`, а не просто альтернативой?
`netstat` для каждого вызова парсит `/proc/net/tcp` и делает дополнительные
lookup'ы (например, резолвинг имен), что медленно на серверах с десятками
тысяч соединений. `ss` (socket statistics) общается напрямую с ядром через
netlink-сокеты, получая ту же информацию значительно быстрее, и умеет
фильтровать по состоянию соединения (`ss -tan state established`) без
внешнего grep/awk. `netstat` считается устаревшим (deprecated) в современных
дистрибутивах.

# 7. Что такое network namespace и как veth pair используется в контейнерах?
Network namespace — изолированный сетевой стек ядра (свои интерфейсы,
таблица маршрутизации, iptables-правила), не видящий остальные namespace'ы
системы. Контейнер обычно живет в своем network namespace, полностью
изолированном от хоста. `veth pair` — виртуальная пара сетевых интерфейсов,
работающая как "виртуальный кабель": один конец помещается внутрь network
namespace контейнера, другой остается в namespace хоста (обычно подключенный
к бриджу) — так контейнер получает связность с внешним миром.

# 8. Что такое conntrack и почему на NAT-шлюзе могут "тихо" отбрасываться
новые соединения?
conntrack — модуль ядра netfilter, отслеживающий состояние каждого
проходящего соединения (нужен для NAT и правил вида "разрешить
ESTABLISHED,RELATED"). Таблица conntrack имеет ограниченный размер
(`nf_conntrack_max`, обычно ~262144 записей по умолчанию). При интенсивном
трафике (много коротких соединений) таблица может исчерпаться, и ядро
начинает отбрасывать НОВЫЕ соединения без единого явного правила firewall'а,
что делает диагностику неочевидной без знания об этом лимите.

# 9. Как ОС определяет порядок поиска имени (например, файл hosts или DNS)
при резолвинге?
Порядок задается в `/etc/nsswitch.conf`, строка `hosts:` (обычно `files dns`
— сначала смотрит `/etc/hosts`, затем идет в DNS). Само DNS-резолвение на
уровне клиента настраивается через `/etc/resolv.conf` (nameserver, search
domains). Проверить фактический путь резолвинга конкретного имени: `getent
hosts example.com`.

# 10. Какие базовые команды `ip` заменяют устаревшие `ifconfig`/`route`?
- `ip addr show` (или `ip a`) — список интерфейсов и их IP-адресов (замена
  `ifconfig`).
- `ip link show` — состояние интерфейсов на уровне L2 (up/down, MAC-адрес).
- `ip route show` (или `ip r`) — таблица маршрутизации (замена `route -n`).
- `ip neigh show` — ARP-таблица (замена `arp -a`). Пакет `net-tools`
  (`ifconfig`, `netstat`, `route`) считается устаревшим в пользу пакета
  `iproute2`.

# 11. Что такое MTU и как посмотреть/поменять его значение интерфейса?
MTU (Maximum Transmission Unit) — максимальный размер пакета на канальном
уровне без фрагментации (обычно 1500 байт для Ethernet). Посмотреть: `ip
link show eth0 | grep mtu`. Поменять: `ip link set dev eth0 mtu 9000` (jumbo
frames). Несогласованный MTU между узлами одного сегмента (особенно в
оверлейных сетях типа VXLAN, добавляющих свои заголовки) — частая причина
"зависаний" именно на больших пакетах при исправно работающих маленьких
(Path MTU Discovery black hole).

# 12. Зачем нужен bonding/teaming сетевых интерфейсов?
Bonding объединяет несколько физических сетевых интерфейсов в один
логический — для отказоустойчивости (active-backup: при обрыве одного линка
трафик автоматически переключается на другой) или для увеличения пропускной
способности (LACP/802.3ad: суммирование полосы нескольких линков).
Настраивается через `/proc/net/bonding/` или NetworkManager/netplan в
современных дистрибутивах.

# 13. Что делает `sysctl net.ipv4.ip_forward=1` и когда это нужно?
Включает форвардинг IP-пакетов между сетевыми интерфейсами хоста — по
умолчанию обычный Linux-хост не пересылает чужие пакеты дальше (не работает
как роутер). Это нужно включать явно на любом хосте, который должен работать
как NAT-шлюз, VPN-сервер или Kubernetes-нода (форвардинг между Pod-сетью и
остальным миром). Без этой настройки правила iptables FORWARD/NAT физически
не будут иметь эффекта — пакеты будут отбрасываться ядром раньше, чем дойдут
до правил firewall'а.

# 14. Почему на нагруженном веб-сервере накапливаются тысячи соединений в
состоянии TIME_WAIT?
TIME_WAIT — финальное состояние TCP-соединения после закрытия, которое
сторона, инициировавшая закрытие, обязана выдержать (обычно 2×MSL, около
60-120 секунд) — механизм защиты от попадания "запоздалых" пакетов старого
соединения в новое с теми же портами. При очень высокой частоте
открытия/закрытия коротких соединений (например, HTTP без keep-alive)
TIME_WAIT-соединения накапливаются быстрее, чем истекают, и могут исчерпать
доступные эфемерные порты. Тюнится через `net.ipv4.tcp_tw_reuse=1`
(безопасно переиспользовать TIME_WAIT сокеты для новых исходящих соединений)
— `tcp_tw_recycle` считается устаревшим и опасным (ломается за NAT), убран
из современных ядер.

# 15. Зачем нужны опции сокета SO_REUSEADDR и SO_REUSEPORT?
`SO_REUSEADDR` позволяет процессу забиндиться на порт, который формально еще
"занят" TIME_WAIT-соединениями от предыдущего запуска того же сервиса (иначе
перезапуск сервиса упирается в "Address already in use" пока не истекут все
TIME_WAIT). `SO_REUSEPORT` (более новая возможность) позволяет НЕСКОЛЬКИМ
процессам/потокам одновременно слушать один и тот же порт — ядро само
балансирует входящие соединения между ними, что используют, например,
nginx/HAProxy для multi-worker моделей без единой точки блокировки на
accept().

# 16. Чем сетевой bridge отличается от veth pair в контексте контейнерных
сетей?
`veth pair` — виртуальный "кабель" между двумя network namespace (например,
контейнер ↔ хост). `bridge` — виртуальный L2-коммутатор внутри namespace
хоста, к которому подключаются "хостовые" концы нескольких veth-пар от
разных контейнеров — так контейнеры на одном хосте видят друг друга напрямую
на канальном уровне, как если бы были подключены к одному физическому
свитчу. Docker и большинство CNI-плагинов Kubernetes используют именно эту
комбинацию (veth + bridge) как базовый механизм.

# 17. Как работают traceroute/mtr — за счет чего они находят промежуточные
узлы маршрута?
Оба инструмента эксплуатируют поле TTL (Time To Live) в IP-заголовке.
Отправляется серия пакетов с последовательно увеличивающимся TTL (1, 2,
3...). Каждый промежуточный роутер, уменьшив TTL до 0, отбрасывает пакет и
отправляет обратно ICMP `Time Exceeded` со своим адресом — так
последовательно "проявляется" каждый хоп по пути. `mtr` делает то же самое
непрерывно, дополнительно считая статистику потерь/задержки по каждому хопу
в реальном времени.

# 18. Для чего используется утилита `ethtool`?
`ethtool` — инструмент для просмотра и настройки параметров физического
сетевого интерфейса на низком уровне: скорость и duplex-режим линка
(`ethtool eth0`), офлоад-функции NIC (checksum offload, TSO/GRO — снижают
нагрузку на CPU, перекладывая часть работы на сетевую карту), статистику
ошибок интерфейса (`ethtool -S eth0`). Часто используется при диагностике
"странных" просадок пропускной способности, не объяснимых на уровне
маршрутизации или firewall'а.

# 19. Что можно узнать из `/proc/net/tcp` и почему порты там в HEX?
`/proc/net/tcp` — сырое ядерное представление всех TCP-сокетов системы
(локальный/удаленный адрес и порт, состояние соединения численным кодом, UID
владельца, inode). Именно этот файл парсят `netstat`/`ss` под капотом.
Адреса и порты записаны в шестнадцатеричном виде в целях компактности и
исторически сложившегося формата ядра — читать напрямую неудобно, отсюда и
появились инструменты-обертки поверх этого файла.

# 20. В чем разница между VLAN и bonding, если оба "работают с несколькими
интерфейсами"?
Это решают разные задачи. Bonding объединяет НЕСКОЛЬКО физических
интерфейсов в ОДИН логический (для отказоустойчивости/полосы, см. вопрос
12). VLAN (802.1Q), наоборот, разбивает ОДИН физический интерфейс на
НЕСКОЛЬКО логических (виртуальных) сетей поверх общего провода, добавляя тег
VLAN ID в Ethernet-фрейм — используется для сегментации трафика разных
команд/окружений на общей физической инфраструктуре без прокладки отдельных
кабелей.

# 21. Как работает ARP и что такое ARP-кэш?
ARP (Address Resolution Protocol) разрешает IP-адрес в MAC-адрес в пределах
одного L2-сегмента сети (без ARP IP-пакет невозможно упаковать в
Ethernet-фрейм — нужен MAC назначения). Хост, не зная MAC для нужного IP,
рассылает broadcast ARP-запрос "кто владеет этим IP?"; владелец отвечает
unicast'ом со своим MAC. Результат кэшируется в ARP-таблице (`ip neigh
show`) на ограниченное время, чтобы не спрашивать заново на каждый пакет.
Проблемы с устаревшим ARP-кэшем (после замены сетевой карты/миграции VM) —
частая причина внезапной "недоступности" хоста в той же локальной сети.

# 22. Чем Unix domain socket отличается от TCP-сокета на localhost
(127.0.0.1)?
Unix domain socket — механизм межпроцессного взаимодействия через
специальный файл в файловой системе (например, `/var/run/docker.sock`),
работающий полностью в памяти ядра, без прохождения через сетевой стек (нет
IP-заголовков, TCP handshake, checksum). Это заметно быстрее TCP-сокета на
localhost и не требует выделения порта — используется для локального IPC
(Docker daemon, PostgreSQL, nginx-upstream к php-fpm), когда общение
гарантированно происходит только внутри одной машины.

# 23. Что такое raw socket и для чего его использует `tcpdump`?
Обычный сокет (TCP/UDP) дает приложению доступ только к payload'у нужного
уровня — заголовки ниже собирает и разбирает ядро прозрачно. Raw socket
(`AF_PACKET`/`SOCK_RAW`) дает процессу доступ к пакетам целиком, включая
Ethernet/IP-заголовки, в обход обычной обработки стека — именно так
`tcpdump` перехватывает и показывает сырые пакеты для анализа. Создание raw
socket требует повышенных привилегий (`CAP_NET_RAW`), поскольку позволяет
как читать чужой трафик, так и формировать произвольные (в том числе
поддельные) пакеты.

# 24. У нас нет команд ifconfig, ip, и поставить мы их не можем. Как нам
узнать IP-адреса, маски и маршруты?
Информацию можно достать напрямую из виртуальной файловой системы `/proc`,
которую ядро обновляет в реальном времени:
- **IP-адреса и маски:** `cat /proc/net/fib_trie`. Выведет структуру
  префиксов и локальных адресов.
- **Таблица маршрутизации (и имена интерфейсов):** `cat /proc/net/route`.
  Показывает Destination, Gateway, Mask в шестнадцатеричном виде.
- **ARP таблица (соседи):** `cat /proc/net/arp`.
- **Состояние интерфейсов (статистика RX/TX):** `cat /proc/net/dev`.
