# 1. Что такое файловая система в Linux и что означает "everything is a
file"?
Файловая система (ФС) — способ организации хранения данных на носителе: как
записаны имена, метаданные (inode) и сами блоки данных (ext4, xfs, btrfs). В
Linux единое дерево каталогов начинается с `/`, а разные ФС "подключаются" к
нему в точках монтирования (нет букв дисков как в Windows). "Everything is a
file" — философия Unix: почти все (обычные файлы, каталоги, устройства,
сокеты, пайпы) доступно через один интерфейс — `open/read/write/close`.
Поэтому одни и те же утилиты (`cat`, `echo`, перенаправления) работают и с
диском, и с ядром (`/proc`, `/sys`), и с устройствами (`/dev/null`). Типы
файлов (первая буква в `ls -l`):
- `-` обычный файл, `d` каталог, `l` символическая ссылка;
- `b` блочное устройство (`/dev/sda`), `c` символьное (`/dev/tty`,
  `/dev/null`);
- `s` сокет (`/var/run/docker.sock`), `p` именованный канал (FIFO). Само имя
  файла хранится в каталоге (таблица "имя → inode"), а данные и метаданные —
  в inode (см. отдельный вопрос про inode ниже).

# 2. Как подключается диск: устройство, раздел, ФС, монтирование?
Цепочка от железа до файлов:
1. Блочное устройство — диск виден ядру как `/dev/sda`, `/dev/nvme0n1`,
   `/dev/vda` (в виртуалках).
2. Разделы — диск делится таблицей разделов: MBR (до 2 ТБ, до 4 основных)
   или GPT (большие диски, много разделов, UEFI). Инструменты: `fdisk`,
   `gdisk`, `parted`. Раздел — `/dev/sda1`.
3. ФС — в разделе создается файловая система: `mkfs.ext4 /dev/sda1`.
4. Монтирование — привязка ФС к каталогу в дереве: `mount /dev/sda1
   /mnt/data`. Изменения такого `mount` временные; чтобы было постоянно —
   запись в `/etc/fstab` (лучше по UUID из `blkid`, а не по имени
   устройства, которое может смениться).
5. Размонтирование — `umount /mnt/data` (если "target is busy": кто держит —
   `lsof +f -- /mnt/data` или `fuser -vm /mnt/data`). Посмотреть: `lsblk -f`
   (дерево устройств, ФС, UUID), `df -hT` (занятое место), `findmnt` (дерево
   точек монтирования).

# 3. Как устроены права доступа, пользователи и группы в Linux?
У каждого файла есть владелец (user), группа (group) и три набора прав: user
/ group / other. Каждый набор — биты r (читать, 4), w (писать, 2), x
(исполнять, 1). Пример: `-rwxr-xr--` = 754: владелец rwx, группа r-x,
остальные r--. Для каталогов смысл другой: r — просмотр списка файлов, w —
создание и удаление файлов внутри, x — возможность зайти (`cd`) и обратиться
к файлам по имени. Команды: `chmod 640 f` / `chmod u+x f`, `chown user:group
f`, `ls -l`, `stat`. Пользователи и группы описаны в файлах:
- `/etc/passwd` — учетные записи (имя, UID, GID, home, shell);
- `/etc/shadow` — хэши паролей (читается только root);
- `/etc/group` — группы. root имеет UID 0 и обходит проверки прав. Системные
  пользователи (для сервисов) обычно имеют UID ниже 1000 и `nologin` в
  качестве shell. Посмотреть себя: `id`, `whoami`, `groups`. Управлять:
  `useradd`, `usermod`, `passwd`, `groupadd`. Дополнительные биты
  (SUID/SGID/sticky) и ACL — в вопросах ниже.

# 4. В чем разница между жесткими (hard) и символическими (soft/symlink)
ссылками?
Жесткая ссылка указывает непосредственно на inode файла. Если удалить
исходный файл, жесткая ссылка продолжит работать, так как данные не
удалятся, пока на inode есть хотя бы одна ссылка. Жесткие ссылки нельзя
создавать для директорий и файлов в других файловых системах. Символическая
ссылка — это отдельный файл, содержащий путь к целевому файлу. Если удалить
оригинал, симлинк станет нерабочим ("битым"). Симлинки работают между
разными файловыми системами и могут указывать на директории.

# 5. Что такое inode в файловой системе Linux?
inode (индексный дескриптор) — это структура данных, которая хранит
метаданные о файле: размер, права доступа, владельца, временные метки и
указатели на блоки данных на диске. inode не содержит имени файла (имя
хранится в структуре директории). Когда кончаются свободные inode (даже если
есть место на диске), создание новых файлов становится невозможным.

# 6. Как посмотреть, что занимает место на диске?
Для проверки общего свободного места используется `df -h` (показывает
использование дисков в человекочитаемом формате). Для поиска самых больших
файлов и директорий используется `du -sh *` (показывает размер папок в
текущей директории) или `ncdu`. Чтобы найти самые большие файлы в системе:
`find / -type f -exec du -h {} + | sort -rh | head -n 10`

# 7. Что произойдет, если удалить файл, который сейчас открыт и пишется
процессом?
Имя файла исчезнет из директории (ссылка на inode удалится), но место на
диске не освободится. Фактическое удаление данных произойдет только тогда,
когда процесс закроет файловый дескриптор. Чтобы освободить место без
перезапуска процесса, можно "обнулить" файл: `> filename` (или `echo "" >
filename`).

# 8. Как изменить права на файлы и директории рекурсивно, но задать разные
права?
Использовать команду find в связке с chmod: Директории (755): find /path
-type d -exec chmod 755 {} \; Файлы (644): find /path -type f -exec chmod
644 {} \;

# 9. Что такое Sticky bit, SUID и SGID?
SUID (Set owner User ID up on execution): позволяет запускать исполняемый
файл с правами владельца файла (например, /usr/bin/passwd запускается от
root). SGID (Set Group ID): аналогично SUID, но для группы. На директориях
означает, что все новые файлы внутри унаследуют группу директории. Sticky
bit: устанавливается на директории (например, /tmp) и означает, что удалить
или переименовать файл может только его владелец.

# 10. Что такое VFS (Virtual File System) и зачем он нужен?
VFS — абстрактный слой ядра Linux, который предоставляет единый интерфейс
системных вызовов (`open`, `read`, `write`, `stat`) для работы с ЛЮБОЙ
файловой системой (ext4, xfs, NFS, tmpfs), скрывая от приложений детали
конкретной реализации. Благодаря VFS одна и та же программа может одинаково
работать с локальным диском, сетевой шарой или файлом в оперативной памяти,
не зная, с чем именно она имеет дело физически.

# 11. В чем разница между ext4 и xfs, и когда что выбирать?
ext4 — самая распространенная, зрелая, универсальная ФС по умолчанию во
многих дистрибутивах; хорошо себя ведет на небольших/средних разделах и с
большим количеством мелких файлов. xfs изначально спроектирована для больших
файлов и высокопроизводительного параллельного I/O (лучше масштабируется на
многоядерных системах и больших разделах), но исторически сложнее уменьшить
размер существующего xfs-раздела (shrink не поддерживается штатно, в отличие
от ext4). Red Hat/CentOS используют xfs по умолчанию именно из-за
производительности на серверных нагрузках.

# 12. Что такое mount namespace и bind mount?
Mount namespace — изолированное дерево точек монтирования: процессы в разных
mount namespace могут видеть совершенно разную файловую структуру, даже
работая на одном ядре (основа изоляции контейнеров на уровне ФС). `bind
mount` (`mount --bind /src /dst`) монтирует уже существующую директорию в
другую точку дерева — это не копия, а alias: изменения в `/src` мгновенно
видны через `/dst` и наоборот, так как физически это один и тот же
inode/данные.

# 13. Что такое tmpfs и где он обычно используется?
tmpfs — файловая система, полностью находящаяся в оперативной памяти (и, при
нехватке RAM, может использовать swap). Данные в tmpfs исчезают при
перезагрузке. Используется для `/tmp` (быстрый временный storage),
`/dev/shm` (POSIX shared memory), а также как `emptyDir` том в Kubernetes с
`medium: Memory` — для сверхбыстрого доступа к временным данным без нагрузки
на реальный диск.

# 14. Диск заполнен, но `df` показывает свободное место. Почему?
Классический признак исчерпания inode, а не блоков данных: `df -h`
показывает свободное МЕСТО, а не свободные inode. Если на файловой системе
создано огромное количество мелких файлов (например, миллионы файлов
сессий/кэша), можно исчерпать лимит inode, оставаясь при этом с гигабайтами
свободного места. Проверяется командой `df -i` (покажет `IUse% 100%` при
исчерпании). Решение — увеличить лимит inode при форматировании (заранее)
или удалить лишние мелкие файлы.

# 15. Что дает журналирование (journaling) в файловой системе и от чего оно
защищает?
Журналируемая ФС (ext4, xfs) перед реальной записью данных на диск сначала
записывает в специальный журнал (лог) намерение о предстоящей операции. Если
система упадет (отключение питания, kernel panic) в середине записи, при
следующей загрузке ФС читает журнал и либо докатывает, либо откатывает
незавершенную операцию — вместо полного повреждения структуры файловой
системы, требующего долгого `fsck` со сканированием всего диска. Не
журналируемые ФС (старый ext2) после сбоя требуют полной проверки при
загрузке.

# 16. Что такое LVM и какую проблему он решает?
LVM (Logical Volume Manager) — слой абстракции между физическими дисками и
файловыми системами. Физические диски (PV — Physical Volumes) объединяются в
пул (VG — Volume Group), из которого нарезаются логические тома (LV —
Logical Volumes) произвольного размера, не привязанные к границам физических
дисков. Главное практическое преимущество — можно увеличить размер
логического тома "на лету" (добавив физический диск в VG), не имея
возможности сделать то же самое с обычным разделом без LVM без
переразметки/простоя.

# 17. Кратко: чем отличаются уровни RAID 0, 1, 5 и 10?
- RAID 0 (striping) — данные разбиваются между дисками, максимальная
  скорость, но НУЛЕВАЯ отказоустойчивость (один диск умер — данные потеряны
  полностью).
- RAID 1 (mirroring) — полное дублирование данных на двух дисках,
  отказоустойчивость ценой 50% полезного объема.
- RAID 5 — данные + контрольные суммы четности (parity), распределенные по
  всем дискам; переживает отказ ОДНОГО диска, эффективнее по объему чем RAID
  1, но пересборка (rebuild) после замены диска нагружает все оставшиеся
  диски и занимает много времени.
- RAID 10 — сочетание: зеркалирование пар дисков + страйпинг между парами —
  быстро и отказоустойчиво, но требует минимум 4 диска и теряет 50% объема,
  как RAID 1.

# 18. Что такое `/etc/fstab` и зачем там опция `noatime`?
`/etc/fstab` описывает, какие файловые системы монтировать при загрузке,
куда и с какими опциями. `noatime` отключает обновление времени последнего
доступа (atime) при каждом чтении файла — по умолчанию каждое чтение файла
означает ЗАПИСЬ метаданных (обновление atime), что создает лишнюю нагрузку
на диск особенно при большом количестве операций чтения. `noatime` —
стандартная оптимизация производительности для серверов, где точное время
последнего доступа к файлам не критично для бизнес-логики.

# 19. Как Docker использует OverlayFS для слоев образа?
OverlayFS объединяет несколько директорий в единую видимую файловую систему
через механизм upper/lower layers: нижние (lower) слои — read-only (слои
образа), верхний (upper) слой — read-write (изменения, сделанные в
запущенном контейнере). При чтении файла ядро ищет его сверху вниз по слоям
(copy-up: если файл нужно изменить, а он лежит в read-only нижнем слое,
сначала он копируется в верхний writable слой, и изменяется уже там, не
трогая нижний). Именно это позволяет тысячам контейнеров шарить одни и те же
базовые слои образа (ubuntu, alpine), физически храня их на диске только
один раз.

# 20. Что такое umask и как он влияет на права по умолчанию у создаваемых
файлов?
`umask` — маска, которая ВЫЧИТАЕТ права из максимально разрешенных при
создании нового файла/директории (по умолчанию файлы создаются с правами
666, директории — 777, из которых umask "вырезает" биты). Стандартный `umask
022` дает файлам права 644 (666 минус 022) и директориям 755 (777 минус
022). Проверить текущее значение: `umask`; временно поменять для сессии:
`umask 027` (более строгое, убирает права группе на запись и права остальным
вообще).

# 21. Когда и зачем запускать `fsck`, и почему нельзя делать это на
смонтированной в режиме записи ФС?
`fsck` (file system check) проверяет и по возможности исправляет
несогласованность файловой системы — обычно требуется после аварийного
выключения (не журналируемая ФС) или при явных признаках повреждения (ошибки
чтения, kernel-сообщения о corruption). Запускать `fsck` на смонтированной
read-write файловой системе опасно: пока идет проверка/исправление структур
на диске, ядро может параллельно менять эти же структуры через обычную
работу приложений — гонка состояний почти гарантированно приведет к еще
большему повреждению. Правильно — размонтировать ФС (или загрузиться с
live-образа/recovery-режима) перед запуском `fsck`.

# 22. Что такое ACL (Access Control List) в файловой системе и зачем он
нужен, если уже есть chmod?
Классические Unix-права (`rwx` для owner/group/other) не позволяют дать
точечный доступ ВТОРОМУ конкретному пользователю или группе, не входящей в
основную группу файла, без создания отдельной группы под каждый такой
случай. ACL (`setfacl`/`getfacl`) решает это точечно: `setfacl -m u:alice:rx
file.txt` дает конкретно пользователю alice права на чтение и выполнение, не
меняя базовые владельца/группу файла и не затрагивая остальных
пользователей.

# 23. Почему `du` и `df` иногда показывают РАЗНЫЕ цифры использования диска
для одного и того же раздела?
Кроме случая с удаленными, но открытыми файлами (см. вопрос 7, где `du` их
не видит, а место реально занято), частая причина — что-то ДРУГОЕ
примонтировано поверх директории, которую сканирует `du` (bind mount,
отдельный раздел смонтирован внутрь пути) — `du` при обычном вызове может
как учитывать, так и не учитывать содержимое вложенных точек монтирования в
зависимости от флагов (`-x`/`--one-file-system`). `df` всегда показывает
статистику именно ФАЙЛОВОЙ СИСТЕМЫ (раздела) целиком, а `du` — сумму по
факту обхода конкретного дерева директорий, что не всегда одно и то же.

# 24. Опишите назначение основных директорий в структуре файловой системы
Linux (/etc, /dev, /proc, /sys, /var)?
- `/etc` — Хранилище глобальных конфигурационных файлов (например,
  `/etc/fstab`, `/etc/passwd`).
- `/dev` — Содержит файлы устройств (device nodes). В Linux "всё есть файл",
  поэтому жесткие диски (`/dev/sda`), терминалы (`/dev/tty`), и виртуальные
  генераторы (`/dev/urandom`, `/dev/null`) находятся здесь.
- `/proc` — Виртуальная файловая система (procfs), предоставляющая
  информацию от ядра. Содержит папки для каждого запущенного процесса (по их
  PID, например `/proc/1234/`), а также статистику ОС (`/proc/cpuinfo`,
  `/proc/meminfo`).
- `/sys` — Виртуальная файловая система (sysfs), аналогичная `/proc`, но
  строже структурированная для взаимодействия с ядром, драйверами и
  аппаратными компонентами (например, конфигурация блочных устройств и
  сетевых интерфейсов).
- `/var` — Директория для изменяемых данных (variable data). Сюда пишутся
  системные логи (`/var/log`), кэши, базы данных, PID-файлы (`/var/run`),
  метрики.
- `/tmp` — Временные файлы (часто монтируется как `tmpfs` в оперативной
  памяти). Данные здесь могут удаляться при перезагрузке.

# 25. Мы случайно удалили файл (например лог-файл), но приложение всё еще
держит его открытым. Можно ли его восстановить?
Да, пока хотя бы один процесс держит файл открытым, его inode и блоки данных
не очищаются ядром.
1. Находим PID процесса, который держит файл: `lsof | grep deleted`
   (например, PID 1234, дескриптор 5w).
2. Копируем содержимое из файлового дескриптора процесса обратно на диск:
   `cat /proc/1234/fd/5 > /var/log/recovered.log`

# 26. Зачем файловые системы семейства ext (ext3, ext4) по умолчанию
резервируют 5% места?
Это пространство (`reserved block count`) резервируется специально для
пользователя `root`. Если диск забьется на 100% обычными пользователями,
системные демоны (запущенные от root) всё еще смогут писать свои логи, а
администратор сможет зайти по SSH (которому часто нужно писать во временные
файлы) и исправить проблему (удалить лишнее). Изменить этот процент
(например, на огромном диске 5% — это слишком много, гигабайты пустого
места) можно утилитой: `tune2fs -m 1 /dev/sda1` (установить резерв в 1%).

# 27. В чем главная разница между /proc и /sys?
Обе директории являются виртуальными файловыми системами
(pseudo-filesystems), которые существуют только в оперативной памяти и
создаются ядром при загрузке.
- **/proc (procfs):** Исторически была создана в основном для экспорта
  информации о запущенных **процессах** (каждая папка — это PID процесса).
  Позже туда стали сваливать вообще всю системную статистику (cpuinfo,
  meminfo, uptime) без строгой структуры.
- **/sys (sysfs):** Была добавлена в ядро Linux 2.6 для решения проблемы
  "хаоса" в `/proc`. Sysfs строго структурирована в виде дерева (иерархии) и
  сфокусирована на представлении аппаратных **устройств** (hardware),
  драйверов и модулей ядра. Через файлы в `/sys` (записывая в них) гораздо
  удобнее конфигурировать параметры конкретных устройств на лету (например,
  управлять энергосбережением диска).
