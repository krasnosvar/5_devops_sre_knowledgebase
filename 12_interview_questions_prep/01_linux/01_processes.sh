# 1. Что такое процесс в Linux и чем он отличается от программы?
Программа — пассивный файл на диске (исполняемый ELF-файл с кодом и
данными). Процесс — запущенный экземпляр программы, то есть активная
сущность, которой ядро выделило ресурсы:
- уникальный PID (и PPID — идентификатор родителя);
- собственное виртуальное адресное пространство (код, данные, куча, стек,
  отображенные библиотеки);
- таблицу открытых файловых дескрипторов (0 stdin, 1 stdout, 2 stderr);
- окружение (environment), текущую директорию, UID/GID, лимиты;
- состояние и контекст CPU (регистры, счетчик команд). Внутри ядра процесс
  описывается структурой `task_struct`. Одну и ту же программу можно
  запустить много раз — получится несколько независимых процессов с разными
  PID и разной памятью. Процессы образуют дерево: корень — PID 1
  (systemd/init), все остальные порождены через `fork()`. Посмотреть дерево:
  `pstree -p`, `ps -ef --forest`.

# 2. Каков жизненный цикл процесса и как с процессами работать из консоли?
Жизненный цикл:
1. Создание — родитель вызывает `fork()` (или `clone()`), потомок получает
   копию адресного пространства (COW).
2. Запуск программы — потомок вызывает `exec()`, заменяя свой образ.
3. Работа — планировщик поочередно дает процессу CPU; процесс может ждать
   I/O (sleep) или быть остановлен сигналом.
4. Завершение — `exit()` или смертельный сигнал, ядро освобождает ресурсы,
   процесс становится зомби до вызова `wait()` родителем. Основные
   инструменты:
- `ps aux`, `ps -ef` — снимок процессов; `pgrep -af nginx` — поиск.
- `top` / `htop` — динамический просмотр CPU и памяти.
- `kill -TERM <PID>`, `kill -9 <PID>`, `pkill`, `killall` — сигналы.
- `nice` / `renice` — приоритет; `lsof -p <PID>` — открытые файлы; `strace
  -p <PID>` — системные вызовы процесса.
- `/proc/<PID>/` — вся информация о процессе (cmdline, status, fd).

# 3. Как планировщик ядра распределяет CPU между процессами?
Планировщик (scheduler) решает, какой процесс из очереди готовых (runnable)
получит процессорное время и на сколько. Linux использует вытесняющую
многозадачность: по таймеру или при появлении более приоритетной задачи ядро
принудительно переключает процесс (context switch).
- Для обычных процессов (класс SCHED_OTHER) применяется CFS (Completely Fair
  Scheduler, в новых ядрах — EEVDF): каждому процессу стараются дать
  справедливую долю CPU, пропорциональную его весу. Вес зависит от значения
  nice (от -20 высокий приоритет до +19 низкий).
- Для реального времени есть классы SCHED_FIFO и SCHED_RR с приоритетами
  выше обычных процессов.
- Каждое ядро CPU имеет свою очередь (runqueue), ядро балансирует нагрузку
  между ними; привязать процесс к ядрам можно через `taskset` (CPU
  affinity).
- В контейнерах долю CPU ограничивают cgroups (`cpu.weight`, `cpu.max`).
  Посмотреть: `chrt -p <PID>` (класс и приоритет), `top` (колонки PR/NI),
  `pidstat -w` (context switches).

# 4. Что такое Load Average в Linux?
Load Average показывает среднее количество процессов, находящихся в очереди
на выполнение (в состоянии R - runnable) или ожидающих ввода-вывода (в
состоянии D - uninterruptible sleep) за последние 1, 5 и 15 минут. Значение
1.0 на одноядерном процессоре означает, что ядро загружено на 100%.

# 5. В чем разница между процессами в состоянии Zombie (z) и Orphan?
Процесс-зомби завершил свое выполнение, но его родительский процесс еще не
считал код его возврата (не вызвал wait()). Зомби не занимают память или
CPU, но занимают слот в таблице процессов (PID). Процесс-сирота (orphan) —
это процесс, родительский процесс которого завершился раньше него.
Процесс-сирота "удочеряется" процессом init (или systemd, PID 1), который
позже корректно его завершит.

# 6. Что такое OOM Killer и как он работает?
Out Of Memory (OOM) Killer — это механизм ядра Linux, который активируется
при критической нехватке оперативной памяти. Он анализирует процессы на
основе их `oom_score` (зависит от потребления памяти, прав, времени работы и
других факторов) и убивает процесс с наивысшим баллом (обычно тот, что
потребляет больше всего памяти), чтобы предотвратить падение всей системы
(kernel panic).

# 7. Как работают сигналы в Linux (SIGTERM, SIGKILL, SIGINT)?
Сигналы используются для межпроцессного взаимодействия (IPC).
- SIGTERM (15) — сигнал мягкого завершения. Процесс может перехватить его,
  закрыть файлы, сохранить данные и корректно завершиться.
- SIGKILL (9) — жесткое завершение. Процесс не может перехватить или
  проигнорировать его, ядро убивает процесс немедленно.
- SIGINT (2) — прерывание с клавиатуры (обычно отправляется при нажатии
  Ctrl+C).

# 8. Как работает fork() и почему говорят про copy-on-write?
`fork()` создает дочерний процесс — точную копию родителя (тот же код, стек,
дескрипторы). Вместо немедленного копирования всей памяти ядро использует
Copy-on-Write (COW): страницы памяти помечаются read-only и физически
расшариваются между родителем и потомком. Реальное копирование конкретной
страницы происходит только в момент, когда один из процессов пытается ее
изменить. Это делает `fork()` дешевым даже для процессов с гигабайтами
памяти.

# 9. В чем разница между fork() и exec()?
`fork()` создает копию текущего процесса (тот же код выполняется дальше в
двух местах). `exec()` (execve и семейство) полностью заменяет образ памяти
текущего процесса новым исполняемым файлом — PID остается тем же, но код,
данные и стек — уже от новой программы. Классический паттерн запуска нового
процесса в shell: `fork()` + `exec()` в дочернем процессе.

# 10. Какие бывают состояния процесса в выводе `ps aux` (R, S, D, Z, T) и
что они значат?
- R (Running/Runnable) — выполняется или готов к выполнению, ждет своей
  очереди CPU.
- S (Sleeping, interruptible) — ждет события (ввода, таймера), можно
  разбудить сигналом.
- D (Uninterruptible sleep) — обычно ждет дискового I/O, сигналом не
  прерывается — большое количество процессов в D обычно означает проблемы с
  диском.
- Z (Zombie) — завершился, ждет, пока родитель считает код возврата.
- T (Stopped) — приостановлен (например, сигналом SIGSTOP или Ctrl+Z).

# 11. Что такое демон (daemon) и зачем нужен double-fork?
Демон — процесс, работающий в фоне без привязки к терминалу. Double-fork
(`fork()` дважды подряд) — классическая техника демонизации: первый `fork()`
создает дочерний процесс и завершает родителя (дочерний становится сиротой и
переусыновляется init/systemd); второй `fork()` внутри дочернего
гарантирует, что новый процесс не является лидером сессии и никогда не
сможет снова получить управляющий терминал.

# 12. Почему обычный пользователь не может выполнить `renice -10` для своего
же процесса?
Приоритет процесса (nice value) находится в диапазоне от -20 (наивысший
приоритет) до 19 (низший). Понижать значение (повышать приоритет, уходить в
отрицательную область) может только root — иначе любой пользователь мог бы
забрать себе непропорционально много CPU-времени в ущерб остальным. Обычный
пользователь может только повышать nice value (понижать свой собственный
приоритет), но не понижать.

# 13. Что лежит в `/proc/PID/` и зачем это нужно при диагностике?
`/proc/PID/` — виртуальная файловая система, отражающая живое состояние
конкретного процесса: `status` (память, состояние), `fd/` (открытые файловые
дескрипторы), `maps` (карта памяти процесса), `cmdline` (аргументы запуска),
`environ` (переменные окружения), `cwd` (текущая директория, симлинк). Это
основной источник информации для live-диагностики процесса без остановки его
работы.

# 14. Чем отличается процесс от потока (thread) в Linux с точки зрения ядра?
В Linux ядро не делает жесткого архитектурного различия между процессом и
потоком — оба создаются системным вызовом `clone()`, разница только в том,
какими ресурсами они делятся с родителем (флаги `CLONE_VM`, `CLONE_FS`,
`CLONE_FILES` и т.д.). Поток — это "процесс", созданный с флагами,
разделяющими адресное пространство памяти, файловые дескрипторы и другие
ресурсы с родителем; отдельный процесс создается без этих флагов (обычный
`fork()` — это `clone()` без разделения памяти).

# 15. Зачем нужен `wait()`/`waitpid()` и что будет, если родитель никогда
его не вызовет?
Когда процесс завершается, ядро сохраняет код завершения в таблице
процессов, пока родитель не заберет его через `wait()`/`waitpid()`. Если
родитель никогда не вызывает `wait()`, завершившийся процесс навсегда
остается в состоянии Zombie — не потребляет память/CPU, но занимает
PID-слот. Массовое накопление зомби может исчерпать таблицу PID и
заблокировать создание новых процессов в системе.

# 16. Что произойдет с дочерними процессами, если родительский процесс убит
через SIGKILL?
Дочерние процессы продолжат работать (SIGKILL их не затрагивает напрямую),
но при завершении родителя ядро переусыновляет их процессом init/systemd
(PID 1) — они становятся orphan-процессами (см. вопрос 5), и PID 1 будет
отвечать за финальный `wait()` по ним, когда они сами завершатся.

# 17. Почему PID 1 в контейнере — особый случай, и зачем нужен
tini/dumb-init?
Обычно PID 1 (init/systemd на хосте) специально написан для переусыновления
сирот и сбора зомби через `wait()`. Если в контейнере PID 1 — это просто
ваше приложение (например, node или python-скрипт), оно обычно не реализует
эту логику — зомби-процессы (например, от порожденных подпроцессов)
накапливаются и не собираются. `tini`/`dumb-init` — минималистичные
init-обертки, которые запускаются как PID 1, корректно проксируют сигналы
приложению и подчищают зомби.

# 18. Что такое ulimit и какие параметры чаще всего настраивают на проде?
`ulimit` задает лимиты ресурсов для процесса и его потомков на уровне ядра.
Самые частые в проде: `nofile` (максимум открытых файловых дескрипторов —
критично для серверов с тысячами соединений), `nproc` (максимум
процессов/потоков для пользователя), `core` (размер core dump файла).
Проверить текущие: `ulimit -a`; постоянно задать — через
`/etc/security/limits.conf` или systemd unit (`LimitNOFILE=`).

# 19. Что такое context switch и почему их слишком много — плохо?
Context switch — переключение CPU с выполнения одного процесса/потока на
другой: ядро сохраняет регистры и состояние текущего процесса, загружает
состояние следующего. Само по себе переключение необходимо для
многозадачности, но слишком частые переключения (например, из-за огромного
числа потоков, конкурирующих за мало ядер) тратят CPU-время не на полезную
работу, а на накладные расходы (сохранение/восстановление состояния,
инвалидация кэшей CPU) — это видно в `vmstat` в колонке `cs`.

# 20. Как найти, какой именно ПОТОК внутри многопоточного процесса
потребляет больше всего CPU?
`top -H -p PID` покажет отдельные потоки процесса с их собственным
потреблением CPU (обычный `top` агрегирует по процессу целиком). Также можно
смотреть `/proc/PID/task/` — там отдельная директория на каждый поток с
собственным `status`/`stack`.

# 21. Что такое process group и session, и зачем они нужны?
Process Group — набор связанных процессов (обычно конвейер команд `cmd1 |
cmd2 | cmd3` образует одну группу), которым можно одновременно послать
сигнал (например, Ctrl+C убивает всю группу переднего плана разом). Session
— еще более крупная единица, обычно привязанная к терминалу, объединяющая
несколько process groups (foreground и background jobs). `setsid` создает
новую сессию, отвязывая процесс от управляющего терминала — основа техники
демонизации (см. вопрос 11).

# 22. Что такое `oom_score_adj` и как защитить критичный процесс от OOM
Killer?
`/proc/PID/oom_score_adj` — настраиваемое смещение (-1000 до 1000), влияющее
на итоговый `oom_score` процесса при принятии решения OOM Killer-ом.
Выставив `-1000`, процесс становится практически неубиваемым для OOM Killer
(используется для критичных системных демонов). В Kubernetes это ровно то,
что стоит за QoS-классом Guaranteed — подам с `requests == limits`
автоматически выставляется более отрицательный `oom_score_adj`, чем подам
класса BestEffort.

# 23. Как посмотреть, что именно ждет процесс, застрявший в состоянии D
(uninterruptible sleep)?
Уже стандартный `ps`/`top` не покажет причину — нужно смотреть
`/proc/PID/stack` (если доступно) или `cat /proc/PID/wchan` — покажет
функцию ядра, в которой процесс сейчас блокирован (часто что-то вроде
`wait_on_page_bit`, указывающее на ожидание диска). Также полезен `iostat -x
1` для проверки, не перегружен ли сам диск на уровне I/O. Процесс в D нельзя
убить даже через SIGKILL — сигналы не доставляются, пока не завершится
системный вызов, вызвавший блокировку.

# 24. Что может создавать высокую нагрузку на CPU, если процессы приложений
потребляют очень мало ресурсов (по `top` %us низкий)?
Если %us (User CPU time) низкий, а общая загрузка высока, проблема кроется в
системе:
1. **System / Kernel time (%sy):** Большое количество системных вызовов
   (system calls), переключений контекста (context switches) или работа
   тяжелых системных процессов.
2. **Hardware Interrupts (%hi / %si):** Аппаратные или программные
   прерывания. Проблема может быть в "кривых" драйверах, неисправном
   "железе" (сбойный диск, забитый сетевой адаптер). Можно посмотреть через
   `watch -n1 cat /proc/interrupts`.
3. **IO Wait (%wa):** Процессор простаивает, ожидая ответа от медленного
   диска. По факту это не нагрузка на CPU, но Load Average будет расти.
   Проверять через `iotop` и `iostat`.
4. **Steal Time (%st):** Актуально для виртуальных машин. Означает, что
   физический гипервизор (хост) перегружен и "крадет" такты процессора у
   вашей ВМ для других соседей (noisy neighbors). Вы ничего с этим не
   сделаете изнутри гостевой ОС.
