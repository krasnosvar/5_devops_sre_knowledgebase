# 1. Что такое shell и Bash? В чем разница между shell, терминалом и
консолью?
Shell (оболочка) — программа-интерпретатор команд, посредник между
пользователем и ядром. Она читает строку, разбирает ее, запускает нужные
программы и возвращает результат. Shell — это также язык программирования
(переменные, условия, циклы, функции), на котором пишутся скрипты.
- Bash (Bourne Again SHell) — самая распространенная оболочка в Linux,
  расширенная версия классического `sh`.
- Другие: `sh` (POSIX, в Debian/Ubuntu это обычно dash — быстрый, но без
  bash-изысков), `zsh`, `fish`, `ksh`.
- Терминал (terminal emulator) — окно/приложение, которое показывает текст и
  передает нажатия клавиш (через псевдотерминал `/dev/pts/N`). Терминал сам
  команды не исполняет, внутри него запускается shell.
- Консоль (console) — исторически физическая клавиатура и экран,
  подключенные к машине (или серийный порт/IPMI). Текущая оболочка: `echo
  $SHELL` (оболочка по умолчанию из `/etc/passwd`), `echo $0` (текущая).
  Список: `cat /etc/shells`. Виды запуска: interactive (диалог с
  пользователем) и non-interactive (скрипт); login shell (читает
  `/etc/profile`, `~/.bash_profile`) и non-login (читает `~/.bashrc`).

# 2. Как Bash выполняет команду, которую вы ввели?
От нажатия Enter до запуска программы:
1. Разбор (parsing): строка делится на слова и операторы (`|`, `&&`, `;`,
   `>`), учитываются кавычки.
2. Раскрытия (expansion) — в строгом порядке: brace `{a,b}` → tilde `~` →
   переменные `$VAR`, подстановка команд `$(cmd)`, арифметика `$((1+2))` →
   word splitting (разбиение по IFS) → glob (`*`, `?`) → удаление кавычек.
   Важно: glob `*` раскрывает именно shell, а не программа (отсюда ошибка
   "Argument list too long").
3. Перенаправления (`>`, `<`, `2>&1`) настраиваются до запуска.
4. Поиск команды в порядке: alias → функция shell → builtin (`cd`, `echo`,
   `export` — выполняются внутри самого shell) → внешняя программа из
   каталогов `$PATH` (первое совпадение).
5. Выполнение: для внешней команды shell делает `fork()` и в потомке
   `exec()`, затем ждет завершения (`wait()`) и сохраняет код возврата в
   `$?`. Builtin выполняется без fork. Вот почему `cd` обязан быть builtin:
   внешний процесс менял бы только свою текущую папку, а не папку shell.
6. Пайп `a | b` — shell создает pipe и запускает все команды пайплайна
   одновременно (каждую в своем процессе), соединив stdout первой с stdin
   второй. Полезно: `type -a ls` (что именно будет запущено), `which`, `bash
   -x script.sh` (трассировка после раскрытий).

# 3. Работа с переменными: чем отличаются локальная переменная, export и
source?
- Переменная shell: `NAME=value` (без пробелов вокруг `=`). Видна только в
  текущем shell, дочерние процессы ее не увидят.
- Environment-переменная: `export NAME=value`. Копируется в окружение всех
  запускаемых дочерних процессов (но не может поменять переменную у родителя
  — окружение передается только вниз, при `fork`/`exec`).
- Разово для одной команды: `LOG_LEVEL=debug ./app`.
- Локальная в функции: `local x=1` (иначе переменная в bash глобальная по
  умолчанию).
- Специальные: `$?` (код возврата), `$$` (PID shell), `$!` (PID последнего
  фонового процесса), `$0` (имя скрипта), `$1..$9`, `$#` (число аргументов).
  Ключевой момент — `./script.sh` и `source script.sh` (или `. script.sh`):
- `./script.sh` запускает скрипт в НОВОМ процессе (subshell): любые
  переменные и `cd` внутри не влияют на вызывающую оболочку.
- `source script.sh` выполняет скрипт в ТЕКУЩЕМ shell, поэтому переменные
  остаются доступны (так работают `~/.bashrc`, `source venv/bin/activate`).
  Посмотреть: `env` / `printenv` (окружение), `set` (все переменные shell),
  `export -p`.

# 4. Как в Bash прочитать файл построчно?
Используется цикл `while` в связке с командой `read`. Пример:
```bash
while IFS= read -r line; do
  echo "Строка: $line"
done < "filename.txt"
```
Флаг `-r` предотвращает интерпретацию бэкслешей (обратных слешей), а `IFS=`
сохраняет начальные и конечные пробелы.

# 5. Как перенаправить вывод ошибок (stderr) в стандартный вывод (stdout) в
Linux bash?
Используется конструкция `2>&1`. Файловые дескрипторы: 0 (stdin), 1
(stdout), 2 (stderr). Пример: `ls /not/exist > output.log 2>&1` Современный
и более короткий синтаксис в bash: `&> output.log`.

# 6. Что означают конструкции со знаком $ в Bash и какие они бывают?
Знак `$` говорит shell: "здесь нужна подстановка". Shell заменяет
конструкцию на значение ДО запуска команды (см. вопрос 2, раскрытия).
Основные виды:
1. Переменные:
- `$VAR` / `${VAR}` — значение переменной (скобки защищают имя от склеивания
  с текстом: `${VAR}able`);
- `${VAR:-default}` — значение по умолчанию, если пусто/не задано;
- `${#VAR}` — длина строки; `${VAR%.txt}` — отрезать суффикс.
2. Подстановка команды: `$(cmd)` — вывод команды подставляется как текст
   (`NOW=$(date +%F)`). Старый вид — обратные кавычки.
3. Арифметика: `$((a + b))` — вычисление целых чисел.
4. Специальные параметры (задаются самим shell, менять нельзя):
- `$?` — код возврата последней команды;
- `$$` — PID текущего shell; `$!` — PID последнего фонового процесса;
- `$0` — имя скрипта; `$1`..`$9` — позиционные аргументы;
- `$#` — число аргументов; `$@` и `$*` — все аргументы;
- `$_` — последний аргумент предыдущей команды. Одинарные кавычки `'...'`
  отключают подстановки полностью, двойные `"..."` — оставляют их работать
  (поэтому `"$VAR"` — это норма). Посмотреть, что получилось после
  подстановок: `bash -x script.sh`.

# 7. Что означает $? в Bash?
`$?` хранит код возврата (exit status) последней выполненной команды. Обычно
код `0` означает успешное выполнение, а любое число больше нуля (от 1 до
255) означает ошибку. Типичные коды:
- `1` — общая ошибка; `2` — неправильное использование команды;
- `126` — файл найден, но не исполняемый (нет прав на запуск);
- `127` — команда не найдена;
- `128+N` — процесс убит сигналом N (`130` — Ctrl+C/SIGINT, `137` — SIGKILL,
  часто OOM-killer, `143` — SIGTERM). Используется в условных конструкциях:
  `if [ $? -eq 0 ]; then echo "Success"; fi`. Важно: `$?` перезаписывается
  после КАЖДОЙ команды, поэтому его нужно читать сразу. Часто проще
  проверять команду напрямую: `if grep -q root /etc/passwd; then ...; fi`.
  Свой код возврата задают так: `exit 3` (скрипт) или `return 3` (функция).

# 8. Как написать скрипт на Bash, который остановит выполнение при любой
ошибке?
В начале скрипта нужно добавить команду `set -e` (или `set -o errexit`). По
умолчанию Bash продолжает выполнение скрипта, даже если одна из команд
завершилась с ошибкой. `set -e` заставит скрипт немедленно завершиться.
Рекомендуемый заголовок для надежных скриптов: `set -euxo pipefail`.

# 9. Что означает set -o pipefail?
В конвейере (pipe), например `command1 | command2`, код возврата всего пайпа
равен коду возврата последней команды (`command2`). Если `command1` упадет,
а `command2` выполнится успешно, скрипт (даже с `set -e`) продолжит работу.
`set -o pipefail` заставляет пайп возвращать статус ошибки, если хотя бы
ОДНА команда в цепочке завершилась с ошибкой.

# 10. В чем разница между $*, $@ и "$@"?
Все они используются для получения всех аргументов, переданных скрипту.
- `$*` — все аргументы как одна сплошная строка.
- `$@` — все аргументы как отдельные слова, но без защиты пробелов внутри
  аргументов.
- `"$@"` — сохраняет аргументы именно так, как они были переданы (с учетом
  пробелов). Это самый безопасный и правильный способ передачи аргументов
  (например, в цикле `for arg in "$@"`).

# 11. Как проверить, существует ли файл в Bash скрипте?
Используется оператор `-f` внутри конструкции `if` или `test` (`[ ]`).
```bash
if [ -f "/path/to/file.txt" ]; then
    echo "Файл существует."
fi
```
Для директорий используется `-d`, для символических ссылок `-L`, для
проверки на чтение `-r`.

# 12. Что такое Shebang (#!/bin/bash) и зачем он нужен?
Shebang — это последовательность символов `#!` в самом начале скрипта, за
которой следует путь к интерпретатору. Когда вы запускаете скрипт как
`./script.sh`, ядро Linux читает эту первую строку и понимает, какой
программе передать этот файл на выполнение (например, `/bin/bash`,
`/usr/bin/python3`, `/usr/bin/env node`).

# 13. Как в Bash получить текущую дату и время в нужном формате?
Используется команда `date` с форматом, начинающимся со знака `+`. Например,
для формата `ГГГГ-ММ-ДД`: `date +"%Y-%m-%d"` Для сохранения в переменную
(Command Substitution): `CURRENT_DATE=$(date +"%Y-%m-%d")`

# 14. В чем разница между [ ] и [[ ]] в Bash?
`[ ]` — это алиас для стандартной утилиты POSIX `test`. Внутри нужно
аккуратно экранировать переменные (двойными кавычками), чтобы избежать
проблем с пробелами или пустыми строками. `[[ ]]` — это расширенный,
встроенный синтаксис самого Bash (не поддерживается в чистом `sh`). Он более
безопасен (не требует кавычек вокруг переменных, не делает word splitting) и
поддерживает регулярные выражения (`=~`) и паттерн-матчинг.

# 15. Что делает команда awk '{print $1}'?
Утилита `awk` по умолчанию разбивает каждую строку ввода на поля (fields),
используя пробел или табуляцию в качестве разделителя. Переменные `$1`, `$2`
обозначают первое, второе поле. `$0` означает всю строку. Команда `awk
'{print $1}'` выведет только первое слово из каждой переданной ей строки.

# 16. Как с помощью sed заменить текст в файле?
Используется потоковый редактор `sed` с командой `s` (substitute). `sed -i
's/old_text/new_text/g' file.txt` Флаг `-i` (in-place) применяет изменения
прямо в файле, а не выводит в консоль. Флаг `g` (global) заменяет все
вхождения в строке, а не только первое.

# 17. Что такое xargs?
Утилита `xargs` читает данные из стандартного ввода (stdin) и выполняет
указанную команду, передавая ей эти данные в качестве аргументов. Часто
используется с `find`. Например, чтобы найти и удалить все `.log` файлы
(даже если их тысячи и обычный `rm` упадет с ошибкой "Argument list too
long"): `find /var/log -name "*.log" | xargs rm -f`

# 18. Как задать значение переменной по умолчанию, если она пустая или не
установлена?
Используется синтаксис параметра расширения (Parameter Expansion):
`PORT=${MY_PORT:-8080}` Если переменная `MY_PORT` не установлена или пуста,
переменной `PORT` будет присвоено значение `8080`.

# 19. В чем разница между переменными $VAR и ${VAR}?
Синтаксически это одно и то же — подстановка значения переменной. Однако
фигурные скобки `${VAR}` защищают имя переменной от склеивания с соседним
текстом. Пример: `echo "${VAR}able"`. Если написать `echo "$VARable"`, bash
будет искать несуществующую переменную `VARable`.

# 20. Что такое Heredoc (<<EOF) в Bash?
Heredoc — это способ передать многострочный текст на стандартный ввод
(stdin) команды, не используя внешние файлы. Пример:
```bash
cat <<EOF > config.txt
server_name localhost;
listen 80;
EOF
```
Если использовать кавычки `<<"EOF"`, bash не будет интерпретировать
переменные (например `$HOME`) внутри текста.

# 21. Как запустить процесс в фоне и как вернуть его на передний план?
Добавление амперсанда `&` в конце команды запускает её в фоновом режиме
(background). Пример: `sleep 100 &` Команда `jobs` покажет список фоновых
задач. Команда `fg %1` (foreground) вернет первую фоновую задачу на передний
план, а `bg %1` возобновит остановленную (через Ctrl+Z) задачу в фоне.

# 22. Как получить длину строки в переменной Bash?
Используется синтаксис параметра расширения с решеткой: `${#VAR_NAME}`.
Пример: `MY_STR="hello"` `echo ${#MY_STR}` (Выведет 5).

# 23. Что такое nohup?
Когда вы закрываете терминал (или SSH-сессию), всем процессам, запущенным в
этом терминале, отправляется сигнал `SIGHUP` (Hangup), который их завершает.
Команда `nohup` (No Hangup) запускает процесс с игнорированием этого
сигнала, так что процесс продолжит работу даже после вашего отключения.
Вывод по умолчанию сохраняется в файл `nohup.out`. Пример: `nohup
./my_script.sh &`

# 24. Как написать бесконечный цикл на Bash?
```bash
while true; do
    echo "Running..."
    sleep 1
done
```
Или с использованием `for`:
```bash
for (( ; ; )); do
    echo "Running..."
    sleep 1
done
```

# 25. Что такое `trap` и зачем он нужен в скриптах?
`trap` перехватывает сигналы (или особые события bash) и выполняет заданную
команду вместо стандартной реакции на них. Чаще всего используется для
гарантированной очистки временных ресурсов при завершении скрипта — неважно,
завершился ли он успешно, с ошибкой или был прерван пользователем:
```bash
tmpfile=$(mktemp)
trap 'rm -f "$tmpfile"' EXIT        # выполнится при ЛЮБОМ выходе из
                                     # скрипта, включая exit и ошибки
trap 'echo "Прервано"; exit 1' SIGINT SIGTERM
```
`EXIT` — псевдо-сигнал bash, срабатывающий при завершении скрипта по любой
причине; `SIGINT`/`SIGTERM` — реальные сигналы ОС (Ctrl+C и `kill`, см.
`01_processes.sh`). Без `trap` временные файлы/блокировки, созданные
скриптом, останутся висеть на диске, если скрипт упадет с ошибкой или будет
прерван раньше срока.

# 26. Как работают массивы (arrays) в Bash — индексные и ассоциативные?
Обычный (индексный) массив:
```bash
arr=(apple banana cherry)
echo "${arr[1]}"        # banana (индексация с 0)
echo "${arr[@]}"        # все элементы
echo "${#arr[@]}"       # длина массива: 3
arr+=(date)             # добавить элемент в конец
```
Ассоциативный массив (bash 4+) — ключи вместо числовых индексов, нужно
объявить ЗАРАНЕЕ через `declare -A`:
```bash
declare -A config
config[host]="db.local"
config[port]=5432
echo "${config[host]}"
for key in "${!config[@]}"; do   # перебор ключей
    echo "$key = ${config[$key]}"
done
```

# 27. Чем here-string (`<<<`) отличается от heredoc (`<<EOF`)?
Heredoc (`<<EOF ... EOF`) передает в команду МНОГОСТРОЧНЫЙ блок текста,
заданный между двумя маркерами. Here-string (`<<<`) — более короткая форма
для ОДНОЙ строки/переменной, без необходимости писать открывающий и
закрывающий маркер:
```bash
grep "error" <<< "$log_line"      # эквивалент echo "$log_line" | grep
                                   # "error", но без лишнего процесса
                                   # для echo и без потери кода
                                   # возврата через pipe
wc -l <<< "$multiline_var"
```
Here-string особенно удобен, когда переменная УЖЕ содержит нужный текст (в
том числе многострочный) и не нужно городить отдельный heredoc-блок только
ради передачи значения одной переменной на вход команде.
