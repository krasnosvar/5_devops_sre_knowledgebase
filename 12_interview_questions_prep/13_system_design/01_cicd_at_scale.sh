# 1. 50 микросервисов собираются по 3 минуты при каждом пуше, и CI стал
главным бутылочным горлышком разработки. В чём системная причина?
Скорее всего каждый сервис пересобирается с нуля без переиспользуемого
кэша слоёв/зависимостей, и/или сборки идут последовательно на
ограниченном пуле раннеров вместо параллельного масштабируемого пула.
Системное решение — распределённый кэш сборки (кэш слоёв Docker/
BuildKit, кэш зависимостей между джобами) плюс автомасштабируемый флот
самохостинг раннеров, параллельно обрабатывающий независимые сборки, а
не просто более мощный единственный раннер.

# 2. Что такое принцип "build once, deploy many" и почему он важен для
CI/CD на масштабе?
Артефакт (Docker-образ, бинарник) собирается ОДИН раз и затем
продвигается через окружения (dev -> stage -> prod) тем же самым
артефактом по неизменяемому тегу/digest, а не пересобирается на каждом
окружении. Пересборка на каждом окружении рискует дать технически
разные артефакты из "одного и того же" коммита (другие версии
транзитивных зависимостей на момент сборки), что ломает
воспроизводимость и усложняет диагностику расхождений между
окружениями.

# 3. Как масштабируют флот CI-раннеров при тысячах запусков пайплайнов
в день?
Managed shared-раннеры провайдера CI на таком объёме становятся либо
дорогими, либо медленными из-за очередей. Стандартный ответ —
самохостинг флот раннеров (часто сами в Kubernetes: GitLab Runner в
режиме Kubernetes executor, actions-runner-controller для GitHub
Actions) с автомасштабированием числа раннеров по длине очереди джобов
— похоже на KEDA-паттерн для event-driven воркеров. Изоляция раннеров
друг от друга (отдельные поды/VM на джобу) обязательна: один
скомпрометированный пайплайн не должен читать секреты/кэш другого.

# 4. В чём разница между push-моделью (Ansible по SSH) и pull-моделью
(Puppet/агент) при масштабировании конфигурации с 50 до 5000 хостов?
Push-модель упирается в накладные расходы центральной control-ноды:
fork процессов и SSH handshake на каждый хост линейно растут с числом
хостов, и единственная control-нода становится узким местом (лечится
батчами через serial: или ускоренным транспортом Mitogen). Pull-модель
нативно масштабируется горизонтально — каждый хост сам периодически
опрашивает центральный сервер, и вся работа применения конфигурации
распределена по самим хостам; цена — постоянно работающий агент на
каждом хосте.

# 5. Почему GitOps снижает риск компрометации CI-системы по сравнению с
классическим push-деплоем из CI напрямую в прод?
При push-деплое CI-система должна обладать широкими правами записи во
все продакшн-цели, что делает саму CI-систему крайне привлекательной
точкой атаки — компрометация CI даёт прямой путь во весь флот. При
GitOps каждая цель сама забирает (pull) желаемое состояние из Git и
применяет его локально — CI/CD-пайплайну достаточно прав только на
запись в Git-репозиторий, а не прямого доступа к продакшн-окружениям,
что резко уменьшает blast radius компрометации пайплайна.

# 6. Что произойдёт при canary-раскатке на флот из 2000 инстансов, если
сравнение метрик canary vs baseline делается вручную человеком?
На таком масштабе ручное сравнение метрик физически не успевает за
скоростью, с которой canary должен подтверждаться или откатываться —
регрессия может незаметно расползтись на весь флот, пока человек
анализирует дашборды. Решение — автоматизированный анализ метрик
(например, Argo Rollouts с AnalysisTemplate, сравнивающий error rate/
latency canary против baseline по порогам) с автоматическим
промотированием или автоматическим откатом без участия человека.

# 7. Почему blue-green деплой, отлично работающий для одного сервиса,
часто экономически неприемлем для всего флота из тысяч инстансов сразу?
Blue-green требует держать полную дублирующую ёмкость (старую и новую
версию одновременно) на время переключения. На масштабе одного сервиса
это приемлемая цена; умноженное на тысячи инстансов всего флота это
означает фактическое удвоение всей инфраструктуры разом — обычно
экономически неоправданно. Поэтому на масштабе флота чаще применяют
волновую (батчевую) раскатку по зонам/регионам.

# 8. В чём разница между ApplicationSets в Argo CD и копированием одного
манифеста Application в N файлов для N кластеров?
Копирование N файлов означает, что любое изменение шаблона (общей
политики, версии образа) нужно вручную вносить в каждую из N копий —
источник рассинхронизации на масштабе. ApplicationSet генерирует N
объектов Application динамически из одного шаблона и списка целей
(генератора), так что одно изменение шаблона автоматически
раскатывается на все цели по единому волновому принципу, без ручного
дублирования файлов.

# 9. Почему раскатка обновления сразу на ВСЕ кластеры флота одновременно
опасна, и как раскатывают правильно?
Это превращает флот из N независимых доменов отказа обратно в один —
ошибка в манифесте или в самом приложении мгновенно поражает все
кластеры разом. Правильный паттерн — волновая раскатка: сначала
canary-кластер с малой долей трафика, затем, при отсутствии алертов,
остальные волнами (по availability zone или региону), каждая следующая
волна стартует только после здоровья предыдущей.
