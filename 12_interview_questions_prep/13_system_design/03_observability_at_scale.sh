# 1. Один сервис добавил в метрику label с ID пользователя, и через
несколько дней весь Prometheus стал падать по OOM. В чём причина?
Проблема не в количестве метрик, а в cardinality — числе уникальных
комбинаций значений label'ов одного и того же имени метрики. Label с ID
пользователя создаёт отдельный уникальный временной ряд на каждого
пользователя, и Prometheus держит индекс каждого уникального ряда в
памяти — тысячи/миллионы пользователей превращают одну метрику в
миллионы рядов, взрывая потребление памяти непропорционально росту
трафика. Решение — убрать такие label'ы через relabeling, перенести
гранулярность в трейсинг/логи.

# 2. В чём разница между Federation и remote_write для сбора метрик с
нескольких Prometheus в одно место?
Federation — верхнеуровневый Prometheus периодически скрейпит
агрегированные метрики с нижнеуровневых через их /federate endpoint;
это ещё один scrape поверх scrape, и он так же уязвим к перегрузке
высококардинальными данными. remote_write — push сырых метрик из
каждого источника в горизонтально масштабируемое распределённое
хранилище (Thanos/VictoriaMetrics cluster/Mimir), изначально
спроектированное для распределённого хранения больших объёмов.

# 3. Почему централизованное кластерное хранилище метрик само по себе
не решает проблему cardinality explosion?
Распределённое хранилище решает проблему объёма и доступности, но если
источник продолжает присылать высококардинальные метрики, система
всё равно столкнётся с той же проблемой индексации, просто на большем
масштабе и позже по времени. Настоящее решение — не пускать
высококардинальные данные в систему вообще: relabeling на источнике и
явные лимиты cardinality (например, -storage.maxHourlySeries в
VictoriaMetrics) как предохранитель.

# 4. Почему для логов имеет смысл sampling для debug-уровня, но не для
логов с ошибками?
Debug-логи успешных операций создают огромный объём с низкой
информационной ценностью — потеря части из них не мешает диагностике.
Логи с ошибками малочисленны, но критичны для диагностики конкретного
инцидента — потеря даже части может скрыть единственное вхождение
важной ошибки. Biased sampling: "шумные" события сэмплируются
(сохраняется фиксированная малая доля), важные события сохраняются
полностью всегда.

# 5. Центральный Grafana/Thanos деградировал, и все 50 команд потеряли
возможность смотреть даже метрики своего собственного кластера. Что
спроектировано неправильно?
Централизация мониторинга не должна превращать единую точку агрегации
в единую точку отказа для базовой наблюдаемости каждого отдельного
кластера. Правильная архитектура держит маленький локальный Prometheus/
vmagent в каждом кластере, самодостаточный для локальных дашбордов и
алертов этого кластера независимо от состояния центрального хранилища;
центральное хранилище нужно для истории и кросс-кластерных запросов, но
не должно быть единственным путём увидеть состояние одного кластера.

# 6. Почему агрегированный глобальный error rate по 100 кластерам может
скрыть серьёзную проблему в одном из них?
Если 99 кластеров здоровы, а один деградировал до высокого error rate,
агрегированный по всему флоту показатель "размывает" проблему одного
кластера почти до незаметного значения на фоне общего здорового
трафика. Алертинг должен работать на двух уровнях одновременно:
глобальные SLO-алерты по агрегату флота и локальные пороговые алерты по
каждому отдельному кластеру/региону для обнаружения точечных
деградаций.

# 7. Чем структурированное логирование (JSON) помогает на масштабе
по сравнению с произвольным текстом в логах?
Парсинг неструктурированного текста на query-time над петабайтами логов
на порядки дороже, чем фильтрация по уже распарсенным полям. При росте
объёма логов до масштаба тысяч инстансов эта разница становится не
вопросом удобства, а вопросом того, успевает ли вообще система
обработать запрос за разумное время и сколько это стоит в вычислениях
на каждый поисковый запрос по логам.
