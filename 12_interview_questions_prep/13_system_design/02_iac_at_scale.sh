# 1. В организации 40 команд, и каждая вносит изменения в общую
инфраструктуру. В чём тут проблема масштаба — объём Terraform-кода?
Нет, объём кода Terraform обрабатывает одинаково что на 10, что на
10000 ресурсов. Настоящая проблема масштаба — координация: как 40
команд одновременно меняют общую инфраструктуру, не блокируя друг
друга (конкуренция за state lock), не имея возможности случайно задеть
чужой сервис (blast radius общего state), и как единообразно применить
security/cost-гейты ко всем 40 командам без ручного ревью каждого PR
силами одной центральной команды.

# 2. Почему общий Terraform state на несколько независимых команд —
анти-паттерн, даже если технически помещается в один backend?
Общий state означает общую блокировку: apply одной команды блокирует
apply всех остальных, работающих с тем же state, превращая параллельную
работу множества команд в последовательную очередь. Кроме того, общий
state означает общий blast radius — ошибка одной команды технически
способна затронуть ресурсы другой. Решение — разделение state по
владению (team/env/region) с явными "мостами" между слоями через
remote state data sources.

# 3. Чем модуль в приватном Terraform registry с SemVer лучше, чем
source = "git::...//modules/vpc" без фиксированной версии?
Без фиксированной версии (ref) потребитель модуля неявно читает
последнее состояние ветки main на каждый init — любое изменение модуля,
даже breaking, мгновенно и незаметно долетает до всех потребителей.
Версионирование с SemVer-контрактом (patch/minor/major) даёт
потребителю явный контроль над моментом обновления и явный сигнал,
безопасно ли оно (patch) или требует проверки интерфейса (major).

# 4. Зачем на масштабе организации нужен Policy as Code (Sentinel/OPA),
если уже есть обязательный ревью PR security-командой?
Ручной ревью security-командой не масштабируется линейно с ростом числа
PR в день — на определённом масштабе пропускная способность ревьюеров
становится бутылочным горлышком всей разработки. Policy as Code
переносит проверку формализуемых правил (запрет публичных бакетов,
обязательные теги, разрешённые регионы) в автоматическую, не обходимую
проверку сгенерированного plan до apply — человеческий ревью остаётся
для содержательных решений, а не для чек-листа правил.

# 5. Почему автоматически обнаруженный configuration drift не стоит
чинить автоматическим terraform apply без участия человека?
Изменение в обход Terraform иногда вносится намеренно — например,
экстренный ручной фикс прод-инцидента в консоли облака, когда времени
на PR и ревью не было. Слепой автоматический apply поверх такого
изменения откатит легитимную экстренную правку обратно к "правильному"
по коду, но устаревшему состоянию, потенциально воспроизводя инцидент.
Дрифт должен попадать в дашборд/алерт для осознанного решения человека.

# 6. В чём разница между монорепо и полирепо подходом к хранению
IaC-кода с точки зрения прав доступа CI?
В монорепо CI, технически работающий с одной "папкой" репозитория,
часто имеет права на весь репозиторий целиком, что усложняет строгое
разграничение "команда A не может тронуть ресурсы команды B" только
структурой директорий. Полирепо даёт естественную границу прав доступа
— репозиторий команды физически не содержит ресурсов других команд. На
практике часто комбинируют: монорепо для общих платформенных модулей,
полирепо/отдельные state-слои для конечных окружений приложений.

# 7. Зачем нужен Terragrunt, если Terraform и так умеет modules и
workspaces?
При разделении state по team/env/region (вопрос 2) конфигурация
backend/provider для КАЖДОГО из сотен разделённых state обычно
одинаковая с небольшими вариациями — без инструмента её пришлось бы
копировать вручную в каждый слой. Terragrunt генерирует эту
конфигурацию из общего шаблона (DRY), оставляя Terraform делать то, для
чего он спроектирован — применение изменений, а не дублирование
boilerplate.

# 8. terraform test и Terratest решают одну и ту же задачу — зачем
тестировать модуль, если его план и так виден в PR?
План в PR показывает, ЧТО изменится в конкретном вызове модуля, но не
проверяет общие инварианты модуля (например, "ресурс всегда создаётся
с шифрованием" или "выходные значения всегда в ожидаемом формате") на
произвольных входных данных. Тестирование модуля перед публикацией —
обязательная часть пайплайна релиза модуля: ломающееся изменение в
общем модуле на масштабе задевает все команды-потребители одновременно,
а не только автора PR.
