# 1. Как масштабировать высоконагруженное приложение без Kubernetes?
Классическая связка: Load Balancer + Auto Scaling Group + immutable
infrastructure. Образ сервера (AMI) собирается заранее через Packer со
всем нужным софтом, ASG следит за метрикой (CPU/RPS за ALB) и меняет
Desired Capacity, LB добавляет новый инстанс в ротацию только после
прохождения health check. Конфигурация флота из сотен хостов — через
Ansible (батчами, serial:) или pull-модель (Puppet/Chef/SaltStack).
Минус: разворачивание нового инстанса — минуты (boot ОС, cloud-init),
а не секунды.

# 2. Как масштабировать высоконагруженное приложение в Kubernetes?
Три независимых контроллера, которые нужно комбинировать осознанно:
- HPA — горизонтально добавляет/убирает реплики по метрике (CPU/memory
  или custom через Prometheus Adapter). Подходит для stateless
  request-driven нагрузки — 90% типовых веб-бэкендов.
- VPA — меняет requests/limits самого пода. Нужен для singleton-нагрузки,
  которую нельзя размножить горизонтально.
- KEDA — масштабирует по внешним событийным метрикам (глубина очереди
  Kafka/SQS), в том числе до нуля реплик — то, чего HPA не умеет.
Масштабирование подов (секунды) почти всегда быстрее масштабирования нод
под них (минуты) — см. вопрос 4.

# 3. В каких случаях выбирают один большой кластер, а в каких — несколько?
Технически один кластер держит до ~5000 нод и ~150000 подов (официальные
ориентиры k8s), но решение почти никогда не упирается в эти цифры. Один
кластер — проще операционно (один control plane, один мониторинг, один
апгрейд), но это ОДИН домен отказа (blast radius): баг CNI, плохой
admission webhook или ошибка апгрейда способны задеть всё сразу.
Разделение оправдано, когда: нужна физическая изоляция данных по
региону/юрисдикции (compliance), авария одной команды/продукта не
должна задевать другую, или команда готова поддерживать N апгрейдов
ради меньшего blast radius. Если причина — просто "разные команды",
часто достаточно namespace + RBAC + NetworkPolicy внутри ОДНОГО
кластера — дешевле операционно, но изоляция логическая, а не
физическая (шумный сосед по ядру/сети всё ещё возможен).

# 4. Почему HPA настроен правильно, а при резком всплеске трафика
# пользователи всё равно видят ошибки первые минуты?
HPA реагирует с задержкой (интервал сбора метрик + stabilization
window), а новым репликам может физически не хватить места в кластере —
они зависают в Pending, пока node autoscaler (Cluster Autoscaler —
минуты, или Karpenter — секунды-десятки секунд) не добавит серверы.
Закрыть разрыв помогает overprovisioning: держать в кластере
placeholder-поды с низким PriorityClass, которые ничего не делают, но
резервируют место — при реальном всплеске scheduler мгновенно вытесняет
их ради настоящих реплик, пока node autoscaler параллельно добавляет
серверы под освободившееся место.

# 5. Почему добавление реплик через HPA иногда УХУДШАЕТ ситуацию, если
# бэкенд — PostgreSQL без пулера соединений?
Каждая новая реплика приложения открывает собственный пул соединений к
БД. При резком росте числа реплик суммарное число соединений может за
секунды превысить max_connections PostgreSQL (каждое соединение —
отдельный процесс), и база начнёт деградировать или отклонять
подключения раньше, чем масштабирование помогло. Решение — поставить
PgBouncer между приложением и БД: число реальных соединений к базе
остаётся фиксированным независимо от числа реплик приложения.

# 6. Почему StatefulSet нельзя масштабировать так же бездумно, как
Deployment?
StatefulSet даёт стабильную сетевую идентичность и персональный PVC
каждой реплике (pod-0, pod-1, ...), но сам по себе ничего не знает про
бизнес-логику распределения данных. Увеличение replicas не означает,
что данные автоматически перебалансируются на новую реплику — это
всё ещё задача самого приложения (ребалансировка шардов, присоединение
нового узла к кластеру БД).

# 7. Что такое cache stampede и как его предотвращают на масштабе?
Ситуация, когда истечение TTL у популярного (или у множества
одновременно созданных) ключей кэша приводит к тому, что все
параллельные запросы одновременно идут мимо кэша в БД, резко повышая
на неё нагрузку. Предотвращается джиттером TTL (разный срок жизни у
ключей вместо одинакового), request coalescing/singleflight (только
один запрос реально идёт в БД, остальные ждут его результат) и
проактивным фоновым обновлением кэша до истечения TTL.

# 8. Что произойдёт, если раскатывать обновление сразу на все кластеры
# флота одновременно, и как правильно раскатывать на много кластеров?
Это превращает флот из N независимых доменов отказа обратно в один —
ошибка в манифесте мгновенно поражает все кластеры разом. Правильный
паттерн — волновая раскатка: сначала canary-кластер с малой долей
трафика, затем, при отсутствии алертов, остальные волнами (например,
через Argo CD ApplicationSets с управляемым порядком синхронизации или
Rancher Fleet).

# 9. Достаточно ли одного кластера с node pool в разных регионах для
требования "данные ЕС не покидают ЕС"?
Нет. Node pool в разных регионах одного кластера всё равно имеют единый
control plane и единый etcd, физически расположенный в одном месте.
Для настоящей резидентности данных нужен ОТДЕЛЬНЫЙ кластер (отдельный
control plane и etcd) в нужной юрисдикции, а не просто географически
распределённые ноды одного логического кластера.

# 10. Как управляют флотом из десятков/сотен кластеров, чтобы не
# повторять одну и ту же ручную операцию N раз?
Отдельным инструментарием поверх самих кластеров:
- Cluster API (CAPI) — декларативное управление жизненным циклом самих
  кластеров (создание/апгрейд/удаление) через Kubernetes-style манифесты.
- Karmada/KubeFed — распределение одного логического приложения по
  нескольким физическим кластерам с единой точкой управления политиками.
- Argo CD ApplicationSets / Flux multi-tenancy — GitOps-раскатка одного
  набора манифестов на N кластеров волнами.
- Rancher Fleet — централизованная панель для раскатки GitOps на большие
  флоты распределённых кластеров.
Без этого слоя N кластеров означает N раз повторённую ручную работу на
каждую операцию.

# 11. Почему "стало тормозить при росте нагрузки" иногда проблема не
кода и не количества реплик, а настроек ОС?
Классические примеры: лимит файловых дескрипторов (ulimit -n)
ограничивает число одновременных TCP-соединений на процесс независимо
от CPU/памяти; net.core.somaxconn и backlog сокета ограничивают
очередь на accept(); размер thread/worker pool бэкенда (worker_
processes/worker_connections в nginx, GOMAXPROCS в Go) ограничивает
параллелизм отдельно от аппаратных ресурсов. Масштабирование
такого неправильно настроенного процесса просто размножает узкое
место на N серверов вместо того, чтобы его устранить.
