# 1. Опишите архитектуру Prometheus и как он собирает метрики (Pull модель).
Prometheus Server сам периодически опрашивает (скрапит) HTTP-
эндпоинты (обычно `/metrics`) целевых сервисов и экспортеров.
Архитектура:
- **Prometheus Server** — хранит метрики в своей Time-Series
  Database (TSDB) и выполняет скрапинг.
- **Exporters** — агенты, транслирующие системные/сторонние метрики
  в формат Prometheus (например, Node Exporter — вопрос 5).
- **Pushgateway** — буфер для метрик от короткоживущих задач (cron),
  которые физически не могут быть отскрапены (успевают завершиться
  раньше следующего scrape).
- **Alertmanager** — отправка уведомлений (вопрос 3).

# 2. Что такое PromQL и какие основные типы метрик есть в
Prometheus?
PromQL — язык запросов для извлечения и агрегации метрик.
- **Counter** — число, только растёт (или сбрасывается в 0 при
  рестарте процесса). Пример: количество запросов.
- **Gauge** — число, может расти и падать. Пример: текущее
  использование RAM.
- **Histogram** — группирует наблюдения в "корзины" (buckets),
  считает сумму и количество — из него можно вычислить процентиль
  через `histogram_quantile` (вопрос 6).
- **Summary** — похожа на Histogram, но процентили вычисляются уже
  на стороне клиента (приложения), а не в PromQL.

# 3. Зачем нужен Alertmanager и как он работает с дубликатами?
Принимает алерты от Prometheus-серверов и:
- **Дедуплицирует** — убирает одинаковые алерты (если два Prometheus
  в HA прислали один и тот же).
- **Группирует** — несколько связанных алертов в одно сообщение
  (упало 50 подов на одной ноде — одно письмо, не 50).
- **Маршрутизирует** — по тегам в нужный канал (Slack, PagerDuty).
- **Подавляет (Silencing/Inhibition)** — отключает алерты на время
  работ или если уже сработал более общий алерт (нода упала — не
  слать алерты по каждому сервису на ней отдельно).

# 4. В чем разница между `rate` и `irate` в PromQL?
Обе считают скорость роста метрики-Counter. `rate(metric[5m])` —
средняя скорость за всё окно (сглаживает пики, используется для
алертинга). `irate(metric[5m])` — скорость только по двум последним
точкам внутри окна (показывает острые пики, годится только для
визуализации на графиках, не для алертов — слишком "дёрганый").

# 5. Что такое Node Exporter?
Официальный экспортер Prometheus для UNIX-подобных систем. Читает
системные метрики Linux (CPU, RAM, диски, сеть, число процессов) и
отдаёт их в формате Prometheus на HTTP-эндпоинте — обычно первое,
что ставят на каждый сервер при внедрении Prometheus.

# 6. Зачем нужна функция `histogram_quantile`?
Гистограмма сама по себе хранит только счётчики по корзинам
(buckets). Чтобы получить понятную метрику вроде "p99 задержки
ответа", применяют:
```promql
histogram_quantile(0.99, rate(http_request_duration_seconds_bucket[5m]))
```

# 7. Как Prometheus справляется с высокой нагрузкой и
масштабированием?
Prometheus не шардируется из коробки. Для HA запускают два
одинаковых сервера, скрапящих одни и те же таргеты независимо. Для
долгосрочного хранения и объединения метрик с множества серверов
Prometheus используют внешние системы — Thanos, Cortex или
**VictoriaMetrics** (см. `02_victoriametrics.sh` — там же разбор,
чем VictoriaMetrics в принципе отличается от просто "надстройки").
