# 1. Что такое Vector и какую задачу он решает?
Vector (vector.dev) — единый observability-конвейер (пайплайн) для
логов, метрик и трейсов, написанный на Rust. Вместо того чтобы
держать отдельно Filebeat для логов, отдельно vmagent для метрик и
отдельно что-то для трейсов, Vector одним агентом/процессом умеет
собирать, преобразовывать и отправлять дальше все виды данных —
с низким потреблением ресурсов за счёт Rust (в отличие от Logstash
на Java).

# 2. Опишите модель конфигурации Vector: Sources, Transforms, Sinks.
```toml
[sources.app_logs]
type = "file"
include = ["/var/log/app/*.log"]

[transforms.parse_json]
type = "remap"
inputs = ["app_logs"]
source = '. = parse_json!(.message)'

[sinks.loki_out]
type = "loki"
inputs = ["parse_json"]
endpoint = "http://loki:3100"
```
- **Sources** — откуда забирать данные (файл, journald, Kafka,
  Prometheus-эндпоинт, syslog).
- **Transforms** — как обработать (распарсить, отфильтровать,
  переименовать поля) с помощью встроенного языка **VRL** (Vector
  Remap Language).
- **Sinks** — куда отправить результат (Loki, Elasticsearch,
  Kafka, S3, Prometheus remote_write) — ОДИН и тот же поток данных
  можно направить сразу в несколько sinks.

# 3. Что такое VRL (Vector Remap Language)?
Встроенный предметно-ориентированный язык трансформации событий
внутри Vector (используется в блоке `transforms` типа `remap`,
вопрос 2) — компилируется, а не интерпретируется построчно как
Grok в Logstash, за счёт чего обработка заметно быстрее. Позволяет
парсить JSON/Grok-паттерны, переименовывать и удалять поля,
приводить типы, обогащать события (например, добавлять геоданные
по IP) — всё в одном декларативном скрипте на событие.

# 4. Чем Vector отличается от Filebeat/Fluentd/Logstash с точки
зрения выбора на проекте?
- **Filebeat/Fluent-bit** — лёгкие, но умеют только пересылать
  (минимум трансформаций), чаще всего работают только с логами.
- **Logstash** — мощная трансформация, но тяжёлый (JVM) и
  исторически только логи.
- **Vector** — сочетает лёгкость (как Filebeat) с мощной
  трансформацией (как Logstash через VRL), и, в отличие от всех
  трёх, одинаково хорошо работает с логами, метриками И трейсами
  одним и тем же агентом — поэтому его часто берут как замену сразу
  нескольким разным агентам в стеке.

# 5. Как Vector можно использовать как агрегатор (а не только агент
на каждом узле)?
Vector можно развернуть в двух ролях: **Agent** (DaemonSet в
Kubernetes — по одному на каждой ноде, собирает локальные логи) и
**Aggregator** (центральный Deployment — принимает данные от всех
Agent-ов по сети, например через `vector` source/sink между собой,
делает тяжёлую трансформацию/маршрутизацию в одном месте и уже
оттуда шлёт в конечные хранилища) — та же модель ролей, что
`vmagent`/VictoriaMetrics (см. `02_victoriametrics.sh`) или
Promtail/Loki (см. `05_loki.sh`).
