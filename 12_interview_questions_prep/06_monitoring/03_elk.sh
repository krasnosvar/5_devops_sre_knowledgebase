# 1. Что такое ELK стек и за что отвечает каждый компонент?
ELK — набор инструментов для централизованного сбора логов.
- **Elasticsearch** — распределённая поисковая NoSQL база, хранящая
  логи.
- **Logstash** — конвейер обработки: собирает, парсит, фильтрует и
  трансформирует логи перед отправкой в ES (сейчас часто заменяется
  более лёгкими Filebeat/Fluentd — вопрос 2).
- **Kibana** — веб-интерфейс для визуализации логов и поиска по
  Elasticsearch.

# 2. Зачем в ELK-стеке используют Filebeat (или Fluentd), если есть
Logstash?
Logstash написан на Java и потребляет много ресурсов (CPU/RAM) —
ставить его на КАЖДУЮ рабочую ноду слишком накладно. Поэтому на
серверы ставят лёгкие "шипперы" на Go/C/Rust (Filebeat, Fluent-bit,
Promtail) — они просто читают файлы логов и пересылают их по сети в
Logstash (для тяжёлой обработки) или сразу в Elasticsearch.

# 3. Что такое Grok-паттерны в Logstash?
Плагин-фильтр, который парсит неструктурированные текстовые логи
(строку Nginx, syslog) в структурированный JSON с помощью регулярных
выражений, присваивая имена частям лога (IP-адрес, HTTP-метод,
статус-код) — после Grok по этим полям можно фильтровать и
агрегировать в Kibana, а не искать подстроки по сырому тексту.

# 4. Почему Elasticsearch требует много RAM, но рекомендует отдавать
JVM Heap не более 50%?
ES использует Heap для внутренних структур, кэша запросов и
индексов. Но Lucene (поисковый движок под капотом ES) для быстрого
доступа к данным на диске полагается на файловый кэш страниц самой
ОС — если отдать весь RAM под JVM Heap, операционной системе будет
нечем кэшировать файлы, и производительность чтения с диска упадёт.
Максимальный рекомендуемый Heap — около 32GB (из-за особенностей
сжатых указателей JVM, compressed oops).

# 5. Что такое Индексы и Шарды в Elasticsearch?
Индекс — логическая база, куда складываются документы (логи). Для
распределения нагрузки индекс делится на Шарды (Primary shards) —
отдельные экземпляры Lucene-индекса на разных серверах кластера.
Реплики (Replica shards) — копии primary-шардов для
отказоустойчивости при падении ноды.

# 6. Как организовать ротацию логов на Linux, чтобы диск не
переполнился?
Системная утилита `logrotate`, настраивается через
`/etc/logrotate.conf` и `/etc/logrotate.d/`. Задаются правила: как
часто сжимать (`daily`/`weekly`), сколько архивов хранить
(`rotate 7`), максимальный размер (`size 100M`), и команда
уведомления сервиса после ротации (`postrotate kill -USR1 nginx`),
чтобы он переоткрыл файл лога, а не продолжал писать в уже
переименованный/удалённый файл.
