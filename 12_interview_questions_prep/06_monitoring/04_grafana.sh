# 1. Как работает Grafana?
Grafana — инструмент визуализации, сама не хранит данные. Она
подключается к источникам (Data Sources: Prometheus, VictoriaMetrics,
Elasticsearch, Loki, SQL-базы), выполняет к ним запросы (например,
PromQL или LogQL) и отрисовывает результат в виде графиков и
дашбордов.

# 2. Что такое Dashboards as Code в Grafana и зачем так делать вместо
ручного создания дашбордов в UI?
Дашборд Grafana — обычный JSON-документ. Вместо ручного клика в UI
его можно хранить в Git и накатывать через Provisioning — конфиг
`provisioning/dashboards/*.yaml`, указывающий Grafana, из какой
папки на диске подхватывать JSON-файлы дашбордов при старте.
Плюсы: дашборды версионируются вместе с кодом, ревьюятся в PR, не
теряются при пересоздании контейнера Grafana. Более продвинутый
подход — генерировать JSON программно через Grafonnet (Jsonnet-
библиотека) вместо ручного редактирования JSON.

# 3. Как настроить Data Source в Grafana через код, а не через UI?
```yaml
# provisioning/datasources/prometheus.yaml
apiVersion: 1
datasources:
  - name: Prometheus
    type: prometheus
    url: http://prometheus:9090
    access: proxy
    isDefault: true
```
Так же, как с дашбордами (вопрос 2) — Grafana при старте читает эту
папку и настраивает источники данных автоматически, без ручного
ввода URL в UI на каждом новом окружении.

# 4. Что такое переменные (Template Variables) в дашборде Grafana и
зачем они нужны?
Позволяют сделать один дашборд параметризуемым — например,
переменная `$environment` (dev/staging/prod) или `$pod`
(список текущих подов из запроса к Prometheus) превращается в
выпадающий список над графиками, и все запросы на дашборде
подставляют выбранное значение. Без переменных пришлось бы делать
отдельный дашборд на каждое окружение/под.

# 5. Чем Unified Alerting в Grafana отличается от использования
отдельного Alertmanager?
Начиная с Grafana 8+, алерты можно настраивать прямо в самой Grafana
(Unified Alerting) — на основе запросов к ЛЮБОМУ источнику данных
(не только Prometheus), с собственной маршрутизацией уведомлений.
Это удобно, когда нужны алерты по данным из источников, не умеющих
в принципе работать с классическим Prometheus Alertmanager (например,
по логам в Loki). Классический Alertmanager (см. `01_prometheus.sh`)
остаётся предпочтительным, если вся инфраструктура алертинга уже
построена вокруг Prometheus и нужна более тонкая дедупликация/
группировка, которую Grafana Unified Alerting реализует не так
давно и не всегда так гибко.

# 6. В чем принципиальное отличие Grafana от Kibana?
Grafana изначально заточена под визуализацию **метрик** (временных
рядов из Prometheus/VictoriaMetrics/Graphite) — графики CPU, RPS,
памяти. Kibana — часть стека ELK, заточена под **логи** (текстовые
данные в Elasticsearch) — полнотекстовый поиск, фильтрация по
полям. Grafana сейчас тоже умеет работать с логами через Loki
(см. `05_loki.sh`), но для полнотекстового поиска по логам Kibana
в связке с Elasticsearch по-прежнему мощнее.
