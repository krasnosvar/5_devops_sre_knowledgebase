# 1. Что такое распределённый трейсинг (Distributed Tracing) и
зачем он нужен?
Трейсинг показывает путь ОДНОГО запроса через несколько
микросервисов. Трейс состоит из **спанов (spans)** — каждый спан
это один этап обработки (вызов сервиса, запрос к БД) с временем
начала/окончания; спаны связаны родитель-потомок и образуют дерево.
Нужен, когда метрики и логи говорят "что-то медленно", но непонятно
КАКОЙ именно из 10 сервисов в цепочке вызовов стал узким местом —
трейс показывает это наглядно на временной шкале.

# 2. Что такое OpenTelemetry (OTel) и зачем он появился?
OpenTelemetry — открытый стандарт (спецификация + SDK + протокол
OTLP) для сбора метрик, логов и трейсов единым способом, не
привязываясь к конкретному вендору хранилища. До OTel приложения
встраивали SDK конкретного инструмента (например, Jaeger-client),
и при смене системы хранения трейсов приходилось переписывать код
инструментирования. С OTel приложение шлёт данные в формате OTLP в
**otel-collector**, а КУДА collector перешлёт их дальше (Jaeger,
Tempo, Zipkin) — вопрос конфигурации коллектора, а не кода
приложения.

# 3. Чем Jaeger отличается от Zipkin?
Оба — системы хранения и визуализации трейсов, решают одну задачу.
Zipkin появился раньше (изначально в Twitter), Jaeger — более новый
проект (изначально Uber, сейчас CNCF graduated), с более гибкой
архитектурой хранения (Cassandra/Elasticsearch/Kafka в качестве
бэкенда) и более активной интеграцией с OpenTelemetry "из коробки".
На практике сегодня оба обычно принимают данные именно через
OTLP/otel-collector (вопрос 2), а не через собственные legacy-SDK.

# 4. Что такое Grafana Tempo и чем он отличается от Jaeger?
Tempo — хранилище трейсов от Grafana Labs, спроектированное по
тому же принципу, что и Loki для логов (см. `05_loki.sh`): НЕ
индексирует трейсы полностью, а ищет их по `trace_id` напрямую
(или через связку с метриками/логами — exemplars), храня сами
данные в дешёвом объектном хранилище (S3). За счёт отказа от
полноценного индекса Tempo дешевле в эксплуатации на больших
объёмах, чем Jaeger с Elasticsearch-бэкендом, но хуже подходит для
ad-hoc поиска трейсов по произвольным тегам без известного
`trace_id`.

# 5. Что такое Sampling в трейсинге и зачем он нужен?
Отправлять в хранилище 100% трейсов с высоконагруженного сервиса
дорого и часто не нужно. Sampling — решение, какую долю трейсов
реально сохранять.
- **Head-based sampling** — решение принимается в начале запроса
  (например, случайно 1% трейсов) — просто и дёшево, но можно
  случайно не сохранить именно тот трейс, где была ошибка.
- **Tail-based sampling** — решение принимается ПОСЛЕ завершения
  всего трейса (например, собрать 100% трейсов с ошибкой или с
  аномально большой задержкой, и только 1% обычных) — точнее
  ловит проблемные запросы, но требует буферизации всех спанов
  перед принятием решения (это обычно делает otel-collector).

# 6. Что такое W3C Trace Context и зачем он нужен?
Стандарт заголовков HTTP (`traceparent`, `tracestate`), с помощью
которых `trace_id` и `span_id` передаются от одного сервиса к
другому при вызове по сети — без единого формата распространения
контекста каждый сервис в цепочке не смог бы понять, что его спан
относится к тому же трейсу, что и спан вызывающего сервиса, и
трейсы бы "обрывались" на границе между сервисами разных
команд/технологий.
