# 1. Что такое VictoriaMetrics и какую проблему она решает по
сравнению с обычным Prometheus?
VictoriaMetrics — быстрая и экономичная по памяти/диску TSDB
(Time-Series Database), совместимая с форматом Prometheus (понимает
PromQL, умеет быть источником данных в Grafana как есть). В отличие
от Thanos/Cortex (внешние надстройки НАД несколькими Prometheus),
VictoriaMetrics может работать и как самостоятельная замена
Prometheus целиком (с собственным скрапингом через `vmagent`), и
как централизованное долгосрочное хранилище для метрик, присылаемых
с нескольких Prometheus-серверов (`remote_write`). Основное
практическое преимущество — заметно меньшее потребление RAM/диска
на тот же объём метрик за счёт более плотного сжатия данных.

# 2. Из каких компонентов состоит кластерная версия VictoriaMetrics?
- **vminsert** — принимает входящие метрики (от vmagent или
  `remote_write` от Prometheus) и распределяет их по узлам хранения.
- **vmstorage** — хранит данные (шардируется горизонтально — чем
  больше узлов, тем больше суммарная ёмкость).
- **vmselect** — обрабатывает PromQL-запросы, собирая данные со
  всех нужных vmstorage узлов.
Одиночная (single-node) версия VictoriaMetrics совмещает все три
роли в одном процессе — кластерная нужна только при объёме данных,
не помещающемся на один сервер.

# 3. Что такое `vmagent` и чем он отличается от обычного Prometheus
в роли сборщика метрик?
`vmagent` — лёгкий агент, который умеет делать то же, что
Prometheus Server для скрапинга (читать `scrape_configs`, опрашивать
таргеты), но потребляет значительно меньше памяти, не хранит
данные локально сам, а сразу пересылает их дальше (`remote_write`)
в VictoriaMetrics или другую TSDB. Используют, когда не нужен
локальный Prometheus со своей TSDB на каждом периметре — только
сбор и пересылка.

# 4. Что такое MetricsQL и чем он отличается от PromQL?
MetricsQL — расширение PromQL в VictoriaMetrics: полностью обратно
совместим (любой PromQL-запрос работает как есть), но добавляет
дополнительные функции (например, более удобные `rollup`-функции,
`histogram_quantiles` для сразу нескольких квантилей одним запросом)
и исправляет несколько "сюрпризов" PromQL (например, более
интуитивное поведение `rate()` на границах окна).

# 5. Как VictoriaMetrics используется как долгосрочное хранилище
(Long-Term Storage) для нескольких отдельных Prometheus-серверов?
Каждый локальный Prometheus настраивается с секцией
`remote_write`, указывающей на VictoriaMetrics:
```yaml
remote_write:
  - url: http://victoriametrics:8428/api/v1/write
```
Данные продолжают локально храниться в Prometheus (на короткий
срок, для быстрых локальных запросов и независимости от сети), но
ТАКЖЕ асинхронно реплицируются в центральный VictoriaMetrics — так
получают единый Global View по метрикам со всех площадок/кластеров,
не теряя локальной отказоустойчивости каждого отдельного Prometheus.

# 6. Почему VictoriaMetrics обычно требует меньше диска на тот же
объём метрик, чем ванильный Prometheus?
За счёт более агрессивного и специализированного сжатия данных
временных рядов (похожий принцип на кодеки ClickHouse — см.
соответствующий файл в `07_databases/`): значения метрик обычно
меняются плавно или монотонно, и VictoriaMetrics использует это
свойство для более плотной упаковки, чем универсальный формат TSDB
ванильного Prometheus — на практике разница в занимаемом месте
может быть в несколько раз при одинаковом наборе метрик.
