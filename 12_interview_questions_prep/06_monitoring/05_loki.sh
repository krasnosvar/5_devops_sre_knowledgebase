# 1. Что такое Loki и чем он принципиально отличается от Elasticsearch
в ELK-стеке?
Loki — система сбора логов от Grafana Labs, спроектированная "как
Prometheus, только для логов". Главное отличие от Elasticsearch:
Loki НЕ индексирует полный текст лога, а индексирует только
небольшой набор **меток (labels)** — например, `{app="nginx",
env="prod"}`. Сам текст лога хранится сжатым блоком без индекса.
Это делает Loki заметно дешевле по диску/памяти, чем Elasticsearch,
но полнотекстовый поиск по большому объёму логов без фильтра по
меткам выполняется медленнее (приходится грепать сами данные).

# 2. Из каких компонентов состоит Loki?
- **Promtail** (или современный **Grafana Alloy**) — агент на
  каждом узле, читает файлы логов (как Filebeat в ELK) и
  отправляет их в Loki, уже проставляя метки (обычно взятые из
  Kubernetes-лейблов пода).
- **Loki** — сам сервер хранения и обработки запросов, пишет данные
  в объектное хранилище (S3/GCS/локальный диск).
- **Grafana** — интерфейс для просмотра и запросов к логам (тот же
  UI, что и для метрик — см. `04_grafana.sh`).

# 3. Что такое LogQL?
Язык запросов Loki, синтаксически похожий на PromQL.
```logql
{app="nginx", env="prod"} |= "error" | json | status_code >= 500
```
Сначала фильтр по меткам (быстрый, через индекс), затем конвейер
обработки текста: `|= "error"` — текстовый грепп, `| json` —
распарсить строку как JSON, `| status_code >= 500` — фильтр по
полю после парсинга.

# 4. Как Promtail определяет, какие метки присвоить логам в
Kubernetes?
Через `scrape_configs` в `promtail.yaml`, аналогично Prometheus —
используется Kubernetes Service Discovery, и метки (под, namespace,
контейнер, лейблы пода) автоматически прописываются на основе
метаданных Kubernetes API, без ручного перечисления каждого
источника.

# 5. Почему важно не делать метки (labels) в Loki слишком
высококардинальными (например, не ставить `request_id` меткой)?
Loki создаёт отдельный поток (stream) и отдельный индекс-ключ на
КАЖДУЮ уникальную комбинацию меток. Если в метку попадёт поле с
уникальным значением на каждый запрос (`request_id`, `user_id`),
число потоков взрывается — индекс распухает, а производительность
резко падает. Правило: в метки — только поля с небольшим числом
стабильных значений (app, env, namespace); уникальные поля ищутся
текстовым фильтром/`| json` внутри LogQL (вопрос 3), а не меткой.

# 6. В каком случае выбрать Loki, а в каком — ELK/Elasticsearch?
Loki — когда логи уже структурированы по известным меткам
(Kubernetes-окружение), важна низкая стоимость хранения, и команда
уже использует Grafana для метрик (единый UI для метрик и логов).
Elasticsearch — когда нужен настоящий полнотекстовый поиск по
большим объёмам неструктурированных логов с гибкими ad-hoc
запросами (например, security/compliance-логи, где заранее не
известно, что будут искать).
