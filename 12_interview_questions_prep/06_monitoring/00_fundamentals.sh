# 1. В чем разница между мониторингом (метрики), логированием и
# трейсингом — три столпа observability?
Метрики — числовые показатели системы во времени (CPU 80%, 500
запросов/сек, задержка 200мс). Идеальны для графиков и алертов, но
не скажут ПОЧЕМУ что-то сломалось.
Логи — текстовые записи о конкретных событиях (ошибка, действие
пользователя). Нужны для расследования (troubleshooting) — понять
причину проблемы, о которой сообщили метрики.
Трейсы — путь ОДНОГО конкретного запроса через несколько
микросервисов (см. `06_tracing.sh`). Нужны, когда проблема не "что-то
в среднем медленное", а "вот этот конкретный запрос тормозил именно
на сервисе X".
Три сигнала дополняют друг друга: метрика показывает ЧТО сломалось
(алерт), лог — ПОЧЕМУ (конкретная ошибка), трейс — ГДЕ именно в
цепочке вызовов (какой сервис).

# 2. Как эти три сигнала технически передаются от приложения до
системы хранения?
Общий паттерн один и тот же для всех трёх: легковесный агент на
каждом узле СОБИРАЕТ сигнал локально и отправляет его дальше —
приложение редко шлёт данные напрямую в центральное хранилище.
- Метрики: приложение отдаёт `/metrics` HTTP-эндпоинт (pull,
  Prometheus/VictoriaMetrics сами скрапят) либо активно пушит
  (StatsD/Telegraf).
- Логи: пишутся в stdout/файл, агент (Filebeat/Promtail/Vector —
  см. `03_elk.sh`, `05_loki.sh`, `07_vector.sh`) читает и
  пересылает в хранилище.
- Трейсы: приложение (через SDK OpenTelemetry) само отправляет
  готовые спаны коллектору (`otel-collector`), который уже
  пересылает их в Jaeger/Tempo.
Современный стандарт (OpenTelemetry) стремится унифицировать все три
канала под одним протоколом (OTLP) и одним коллектором вместо трёх
разных агентов.

# 3. Какие 4 золотых сигнала (Four Golden Signals) мониторинга по
методологии Google SRE?
1. Latency (Задержка) — время обслуживания запроса.
2. Traffic (Трафик) — объём нагрузки (RPS).
3. Errors (Ошибки) — доля запросов, завершившихся ошибкой (HTTP
   5xx).
4. Saturation (Насыщенность) — насколько "заполнена" система
   (утилизация CPU/памяти/диска/очередей).

# 4. Опишите методологии сбора метрик: USE, RED.
- **USE (Utilization, Saturation, Errors)** — для ресурсов железа
  (CPU, RAM, диски, очереди): утилизация, насыщенность, ошибки.
- **RED (Rate, Errors, Duration)** — для микросервисов и API: RPS,
  доля ошибок, задержка обработки.
Golden Signals (вопрос 3) — обобщение этих двух подходов в одну
методологию.

# 5. Что такое Blackbox и Whitebox мониторинг?
Whitebox — мониторинг изнутри на основе метрик, которые сама
система экспортирует (внутреннее состояние видно). Blackbox —
мониторинг снаружи, эмулирующий действия пользователя (HTTP ping,
ICMP echo) — система проверяется только по факту
"отвечает/не отвечает", без знания внутренностей.

# 6. В чем фундаментальная разница между Pull и Push моделями сбора
метрик?
Push (Telegraf, StatsD) — приложения сами отправляют метрики на
сервер. Хорошо для короткоживущих процессов и устройств за NAT, но
сервер легко перегрузить. Pull (Prometheus/VictoriaMetrics) —
сервер сам опрашивает известные таргеты, что упрощает обнаружение
упавших сервисов (таргет не ответил на pull — сразу алерт `up == 0`)
и контроль нагрузки на сборщик.

# 7. Что такое SLI, SLO и SLA?
- **SLI** — количественный показатель работы сервиса сейчас
  (например, "99.5% запросов за 5 минут вернули 200").
- **SLO** — внутренняя цель команды для SLI ("99.9% запросов должны
  быть успешными").
- **SLA** — внешний договор с клиентами с последствиями при
  невыполнении (обычно ниже SLO, чтобы был запас на починку).

# 8. Что лучше для оценки задержки — среднее значение или
процентили?
Среднее искажается выбросами (9 запросов по 10мс и один на 1000мс
дадут среднее ~109мс, нерепрезентативное ни для кого). Процентили
точнее: p50 (медиана) — типичный опыт; p95/p99 — опыт пользователей
с самыми долгими ответами (хвост распределения) — именно их обычно
берут для SLO.

# 9. Что такое ServiceMesh мониторинг (на примере Istio)?
Service Mesh проксирует весь трафик между микросервисами через
sidecar (Envoy) — это даёт золотые сигналы (задержки, HTTP-статусы,
трафик) для ВСЕХ сервисов сразу и граф зависимостей между ними, без
необходимости встраивать код экспорта метрик в каждое приложение
вручную.

# 10. Чем Zabbix отличается от связки Prometheus+Grafana?
Zabbix — классическая all-in-one система (сбор, хранение в SQL БД,
графики и алерты в одном UI), часто на push-агентах — хорошо
подходит для статической инфраструктуры (серверы, свитчи по SNMP).
Prometheus/VictoriaMetrics спроектированы под динамичные облачные
окружения (Docker/K8s, TSDB, pull-модель) и лучше справляются с
огромным объёмом временных рядов, но сами по себе не дают единого
UI — для визуализации нужна отдельная Grafana.
