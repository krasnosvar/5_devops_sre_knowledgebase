# 1. В чем разница между фазой `Prefill` и фазой `Decode` при инференсе LLM и
какие метрики за них отвечают?
1. **Prefill (обработка входного промпта):** все токены вопроса и контекста RAG
   известны сразу и перемножаются параллельно за один матричный проход
   (`GEMM`). Эта фаза упирается в вычислительную мощность ядер
   (**Compute-bound**) и определяет метрику **TTFT (Time To First Token)**.
2. **Decode (потокенная генерация ответа):** каждый следующий токен зависит от
   предыдущего, поэтому на каждый шаг генерации нужно прочитать из памяти все
   гигабайты весов модели ради вектора из 1 токена (`GEMV`). Эта фаза упирается
   в пропускную способность памяти (**Memory-bandwidth-bound**) и определяет
   метрику **TPOT / ITL (Time Per Output Token)**.

# 2. Что такое `KV-cache` в трансформерах, как рассчитать его объем в памяти и
как его уменьшает `GQA (Grouped-Query Attention)`?
При генерации токена №$t$ механизму внимания (`Self-Attention`) нужны векторы
ключей ($K$) и значений ($V$) всех предыдущих токенов $1 \dots t-1$. Чтобы не
пересчитывать их заново на каждом шаге (квадратичная сложность), их сохраняют в
оперативной/видеопамяти (**KV-cache**).
- Объем в `FP16` (2 байта) на 1 токен:
  $2 \times n_{\text{layers}} \times n_{\text{kv\_heads}} \times d_{\text{head}}
  \times 2\text{ байта}$.
- В архитектуре **GQA** (например, Llama-3 8B / Qwen2.5 7B) 32 головы запросов
  ($Q$) делят между собой всего 8 или 4 общие головы $K$ и $V$. Это сжимает
  размер `KV-cache` в **4–8 раз** (до ~128 КБ на токен, т.е. ~1 ГБ на контекст
  `8192` токена для одного слота).

# 3. Какую проблему решают `PagedAttention` и `Continuous Batching` в `vLLM` и
`llama.cpp`?
- **PagedAttention:** раньше под `KV-cache` каждого запроса заранее бронировался
  непрерывный кусок памяти под максимальный `max_model_len`, что приводило к
  потере 60–80% VRAM на фрагментацию. `PagedAttention` делит `KV-cache` на
  небольшие несмежные блоки фиксированного размера (страницы по 16 токенов) и
  выделяет их динамически по мере генерации, снижая потери памяти до `< 4%`.
- **Continuous (In-flight) Batching:** в отличие от статического батчинга, где
  короткие запросы ждут, пока самый длинный запрос в батче допишет 500 токенов,
  `Continuous Batching` освобождает слот сразу после генерации токена `<eos>` и
  на следующей же итерации вставляет в батч новый запрос из очереди.

# 4. Как выбрать между `Prompt Engineering`, `RAG` и `Fine-Tuning (LoRA)`?
Почему дообучение модели не заменяет RAG на документах компании?
- **Prompt Engineering** задает правила поведения, роль и формат ответа (JSON).
- **RAG (Retrieval-Augmented Generation)** используется, когда модели нужны
  точные, обновляемые или приватные факты (документы, анализы, регламенты) с
  обязательным цитированием источника и проверкой прав доступа (`ACL`).
- **Fine-Tuning (`LoRA / QLoRA`)** адаптирует стиль, доменный язык или учит
  компактную модель (`0.5B–3B`) специфическому навыку, но **не подходит для
  запоминания фактов**: дообученная без RAG модель будет правдоподобно
  галлюцинировать даты и цифры, а при обновлении документа её невозможно
  мгновенно переобучить.

# 5. Почему чистый векторный поиск (`Dense Embeddings`) плохо находит точные
номера договоров, КБК, артикулы и фамилии, и как устроен `Hybrid Search`?
Плотный эмбеддер (`bge-m3`, `e5`) сжимает весь абзац в один вектор из 1024
чисел, сглаживая редкие точные комбинации цифр и букв.
**Hybrid Search** запускает параллельно два поиска:
1. Семантический поиск по плотным векторам (**Dense**, индекс `HNSW` в Qdrant)
   — находит смысловые совпадения и синонимы.
2. Лексический поиск по ключевым словам (**Sparse / BM25**) — находит точные
   вхождения номеров и терминов.
Два ранжированных списка объединяются по формуле **RRF (Reciprocal Rank
Fusion)**: $\text{Score}(d) = \sum \frac{1}{60 + \text{rank}_i(d)}$.

# 6. Зачем в RAG после поиска в векторной БД (`Bi-Encoder`) ставят второй этап
— реранкер (`Cross-Encoder`), и почему нельзя сразу искать реранкером по всей
базе?
- **Bi-Encoder (эмбеддер):** кодирует вопрос и документ раздельно в два
  вектора. Благодаря этому миллион документов можно векторизовать заранее и
  находить `top-20` кандидатов за `5 мс`, но тонкие смысловые связи между
  словами вопроса и документа теряются.
- **Cross-Encoder (реранкер, например `bge-reranker-v2-m3`):** подает вопрос и
  чанк документа **вместе** на вход трансформера, вычисляя полное перекрестное
  внимание (`Attention`) между всеми словами. Это дает гораздо более высокую
  точность, но требует тяжелого прогона нейросети на каждую пару, поэтому
  реранкер применяют только к `top-20` кандидатам, отбирая из них `top-4` для
  подачи в LLM.

# 7. Какие ошибки при нарезке документов на чанки (`Chunking`) чаще всего ломают
качество RAG и как их исправить?
1. **Разрез таблиц и списков пополам** при тупом делении по числу символов
   (`Fixed-size`): шапка таблицы остается в первом чанке, а строки с цифрами —
   во втором. Решение: структурный чанкинг по Markdown-блокам и сохранение
   шапки таблицы в каждом фрагменте.
2. **Потеря контекста документа (`Orphaned Chunks`):** в чанк №8 попадает фраза
   `"Показатель снижен до 21, рекомендован повторный прием"`, но название
   анализа и дата остались в чанке №1. Решение: автоматически дописывать в
   начало каждого чанка шапку метаданных (`Contextual Header`: `[Документ |
   Дата | Категория]`) перед векторизацией.

# 8. Как разделить диагностику проблем RAG на контур поиска (`Retrieval`) и
контур генерации (`Generation`) с помощью метрик `Hit@k`, `MRR` и `RAGAS`?
- **Качество поиска (`Retrieval`, оценивается быстро и детерминированно без
  LLM):** метрики **`Hit Rate @ k (Recall@k)`** (попал ли нужный `doc_id` в
  первые $k$ чанков) и **`MRR (Mean Reciprocal Rank)`** (насколько высоко в
  выдаче стоит правильный документ). Если `Hit@5` низкий — чинить нужно парсинг
  PDF/OCR, чанкинг и `Hybrid Search`.
- **Качество ответа (`Generation`, фреймворк `RAGAS`):** метрики
  **`Faithfulness`** (не выдумала ли LLM факты, которых нет в найденных чанках)
  и **`Answer Relevancy`** (отвечает ли текст на поставленный вопрос).

# 9. Что случится с векторным поиском в `Qdrant`, если обновить модель
эмбеддингов в коде сервиса без переиндексации базы?
Поиск полностью деградирует (даже если размерность вектора, например `1024`,
совпадает и база не вернула ошибку). У каждой модели эмбеддингов (и даже у двух
версий одной модели) свое собственное векторное пространство, поэтому косинусное
расстояние между вектором вопроса от новой модели и старыми векторами в БД
лишено смысла. При смене эмбеддера всегда создают новую коллекцию `docs_v2`,
пересчитывают все векторы в фоне и атомарно переключают **Collection Alias** в
`Qdrant`.

# 10. Зачем в продакшене для LLM-приложений нужен специализированный трейсинг
(`Langfuse` / `OpenTelemetry`), если уже есть Prometheus?
Prometheus собирает только числовые временные ряды (RPS, общая латентность), но
не позволяет увидеть, почему на конкретном вопросе RAG выдал галлюцинацию.
`Langfuse` записывает полное иерархическое дерево выполнения (`Trace -> Spans`):
какую категорию вернул роутер, какие именно чанки и с каким скором достал
`Qdrant`, какой итоговый промпт ушел в LLM, сколько токенов потрачено на вход и
выход и сколько времени занял каждый шаг.

# 11. Почему для локального инференса LLM на процессоре с большим объемом ОЗУ
(например, 64 ГБ RAM) архитектура `MoE (Mixture-of-Experts)` дает огромный
выигрыш по сравнению с обычной `Dense`-моделью?
Скорость генерации токенов на CPU жестко ограничена пропускной способностью
оперативной памяти (`Memory Bandwidth`, на DDR5 $\approx 85\text{–}100\text{
ГБ/с}$).
- Плотная (`Dense`) модель на `30B` параметров в `Q4` весит `~18 ГБ`, и на
  каждый токен процессору нужно прочитать все 18 ГБ из RAM ($\approx 3\text{
  ток/с}$).
- `MoE`-модель (например, `Qwen3-30B-A3B`) также занимает `~18 ГБ` в памяти (что
  легко помещается в 64 ГБ ОЗУ), но для каждого токена активирует только `~3B`
  параметров (`~2 ГБ` весов). Чтение 2 ГБ вместо 18 ГБ ускоряет генерацию до
  **`20–30 ток/с`** при сохранении качества большой 30B-модели.

# 12. Почему на гибридных процессорах (например, Intel Core Ultra 7 155H с
P-ядрами и E-ядрами) запуск `llama.cpp` / `ONNX Runtime` на всех 22 потоках
работает медленнее, чем на 6 потоках с привязкой к P-ядрам?
В матричных движках (`ggml`, `OpenMP`) вычисления каждого слоя делятся поровну
между рабочими потоками, после чего все потоки ждут друг друга на барьере
синхронизации (`barrier`). Если задействовать медленные энергоэффективные
`E-ядра` (`CPU 12..21`) и `Hyper-Threading` сиблинги, быстрые производительные
`P-ядра` (`CPU 0..11`) будут простаивать в конце каждого слоя в ожидании
отстающих `E-ядер`. Поэтому число потоков инференса ограничивают числом
физических `P-ядер` (`--threads 6`, `cpuset: "0-11"`).

# 13. Как работают `Device Plugins` и `NVIDIA GPU Operator` в Kubernetes?
Планировщик Kubernetes из коробки не знает о существовании GPU/iGPU/NPU.
**Device Plugin** — это `DaemonSet` на узлах, который обнаруживает аппаратные
ускорители и регистрирует их в `kubelet` через Unix-сокет как расходуемый
ресурс (`nvidia.com/gpu`, `amd.com/gpu`, `gpu.intel.com/i915`).
**NVIDIA GPU Operator** автоматизирует всю подготовку GPU-нод в K8s через
контейнеры: сам собирает и грузит драйвер NVIDIA, настраивает
`nvidia-container-toolkit` в `containerd`, поднимает `Device Plugin`, вешает
лейблы характеристик карты (`GFD`) и запускает мониторинг `DCGM Exporter`.

# 14. В чем разница между разделением видеокарты в Kubernetes через `MIG
(Multi-Instance GPU)` и через `Time-Slicing`?
- **MIG (доступен на датацентровых `A30`, `A100`, `H100`, `H200`):** делит GPU
  **аппаратно** на физически изолированные партиции со своими собственными
  блоками памяти HBM, кэшем и ядрами `SM`. Если в одном поде случится `CUDA
  OOM`, соседние поды не пострадают.
- **Time-Slicing (доступен на любых картах, включая `RTX`):** делит карту
  **программно** по квантам времени. Видеопамять (`VRAM`) остается общей и не
  изолированной: один под может вычерпать всю память и уронить все соседние
  поды на этой же карте.

# 15. Почему метрика `GPU-Util` в `nvidia-smi` может показывать `99%` при
простое видеокарты, и какие метрики `DCGM Exporter` смотреть вместо неё?
Стандартная `DCGM_FI_DEV_GPU_UTIL` показывает лишь долю времени, когда на GPU
выполнялось **хотя бы одно ядро CUDA** (даже если работает 1 из 132 блоков `SM`
или ядро ждет подгрузки данных по медленной шине). Для оценки реальной загрузки
смотрят:
- `DCGM_FI_DEV_MEM_COPY_UTIL` (утилизация шины памяти — главное для инференса
  LLM);
- `DCGM_FI_DEV_PIPE_TENSOR_ACTIVE` и `DCGM_FI_DEV_SM_ACTIVE` (реальная загрузка
  тензорных блоков и потоковых мультипроцессоров);
- `DCGM_FI_DEV_POWER_USAGE` (реальное потребление в ваттах относительно TDP).
