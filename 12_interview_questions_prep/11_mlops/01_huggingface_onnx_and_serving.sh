# 1. Как устроено кэширование моделей в Hugging Face Hub (`HF_HOME`) и почему
два контейнера на одной ноде не дублируют файлы при обновлении одного конфига?
В каталоге `$HF_HOME/hub/models--<org>--<repo>/` библиотека `huggingface_hub`
разделяет физическое хранение и рабочее дерево:
1. В папке **`blobs/`** лежат реальные тяжелые файлы весов, названные по их
   `SHA256`-хэшу (контент-адресуемое хранилище).
2. В папке **`snapshots/<commit_sha>/`** создается дерево файлов с привычными
   именами (`config.json`, `model.safetensors`), которые являются
   **символическими ссылками (`symlinks`)** на соответствующие блобы в
   `../../blobs/<sha256>`.
Благодаря этому, если в новом коммите репозитория изменился только
`tokenizer_config.json`, а 15 ГБ весов остались прежними, новый снэпшот просто
сошлется симлинком на уже скачанный блоб весов без повторного скачивания и
дублирования на диске.

# 2. Почему в продакшене нельзя вызывать `from_pretrained("org/model")` без
указания `revision="<40-char-commit-sha>"` и `HF_HUB_OFFLINE=1`?
По умолчанию `from_pretrained()` при каждом старте контейнера обращается по
сети к ветке `main` на `huggingface.co`:
1. Автор публичного репозитория может в любой момент запушить в `main` новую
   несовместимую архитектуру, сломанный токенизатор или вредоносный код.
2. Если во время масштабирования (`HPA scale-out`) у Hugging Face Hub случится
   сетевой сбой или сработает Rate Limit (`HTTP 429`), ваши продакшен-поды не
   смогут запуститься.
В продакшене всегда фиксируют полный 40-символьный `commit SHA` в параметре
`revision`, прогревают кэш на этапе сборки/инициализации и выставляют
переменные `HF_HUB_OFFLINE=1` и `TRANSFORMERS_OFFLINE=1`.

# 3. Как хранить веса моделей внутри корпоративного Docker/OCI-реестра (Harbor,
GitLab Registry) с помощью `ORAS` и зачем это нужно?
В закрытых корпоративных контурах часто нет отдельного MLflow/HuggingFace Hub,
но уже есть отказоустойчивый OCI-реестр контейнеров (`Harbor`, `Nexus`) с
настроенным RBAC и гео-репликацией. Стандарт **OCI Artifacts** и утилита
**`oras` (OCI Registry As Storage)** позволяют пушить файлы моделей (`.gguf`,
`.onnx`, `.safetensors`) напрямую в реестр с кастомным `artifactType` (без
упаковки внутрь тяжелого Docker-образа ОС!):
`oras push registry.internal/ml/router:v1.2 --artifact-type
application/vnd.cncf.model.weight.v1 model.onnx`
На этапе старта пода `initContainer` скачивает только сам файл модели через
`oras pull` на максимальной скорости локальной сети.

# 4. В чем фундаментальное отличие форматов `Pickle (.bin/.pt)` и
`Safetensors` с точки зрения безопасности и скорости загрузки (`mmap`)?
1. **Безопасность:** `Pickle` — это стековая виртуальная машина Python, которая
   при десериализации (`torch.load`) может выполнить произвольный код
   (`os.system`, `subprocess`) через опкод `REDUCE`. Формат **`Safetensors`**
   состоит только из размера заголовка (8 байт), декларативного JSON-заголовка
   (имена тензоров, `dtype`, `shape` и байтовые смещения `[begin, end]`) и
   сырого массива байтов чисел — исполняемого кода в нем не может быть по
   спецификации.
2. **Скорость и память (`Zero-copy mmap`):** поскольку тензоры в `Safetensors`
   лежат без сжатия по известным смещениям, ОС отображает файл прямо в адресное
   пространство через системный вызов `mmap()`, не создавая промежуточную копию
   в RAM, а несколько процессов на одной ноде разделяют одни и те же физические
   страницы `Page Cache` ядра Linux.

# 5. Сравните форматы хранения моделей: `Safetensors`, `ONNX`, `GGUF` и
`OpenVINO IR` — какой и когда выбирать?
- **`Safetensors`:** хранит только словарь тензоров (весов) без вычислительного
  графа; стандарт для исходных чекпоинтов PyTorch, обучения, `LoRA` и `vLLM`.
- **`ONNX` (Open Neural Network Exchange):** хранит **и вычислительный граф
  операторов, и веса** в едином Protobuf-файле; лучший выбор для быстрого
  кроссплатформенного сервинга классических моделей, эмбеддеров (`bge-m3`),
  реранкеров и `DistilBERT` на CPU/GPU без привязки к Python.
- **`GGUF`:** однофайловый формат экосистемы `llama.cpp` / `Ollama` (шапка с
  метаданными архитектуры, словарь токенизатора и блочно-квантованные веса
  `Q4_K_M`/`Q8_0`), выровненный под быстрый `mmap` на CPU и гибридных CPU+iGPU.
- **`OpenVINO IR` (`.xml` + `.bin`):** специализированный формат для
  максимального ускорения на процессорах Intel (инструкции `VNNI`/`AMX`),
  встроенной графике `Intel Arc iGPU` и нейроускорителях `NPU`.

# 6. Зачем конвертировать классическую модель или трансформер в `ONNX Runtime`
на CPU и какие оптимизации графа он выполняет?
Запуск через `ONNX Runtime` вместо нативного `PyTorch` на CPU дает ускорение в
**2.5–4 раза** и уменьшает размер контейнера с гигабайтов до ~150 МБ:
1. **Graph Optimizations (Operator Fusion):** склеивает цепочки мелких
   операций (`MatMul + BiasAdd + LayerNorm + Gelu`) в одно скомпилированное
   ядро на C++, избегая лишних записей промежуточных тензоров в ОЗУ и накладных
   расходов интерпретатора Python.
2. **INT8 Quantization & VNNI:** при динамическом или статическом квантовании в
   `INT8` задействует векторные инструкции процессора `AVX2 / AVX-512 VNNI`,
   выполняя в 4 раза больше умножений за такт.

# 7. Почему запекать веса модели (5 ГБ) внутрь Docker-образа через `COPY` —
антипаттерн, и как правильно доставлять веса в Kubernetes Pod?
При вшивании весов в Docker-образ любое переобучение модели (даже без изменения
кода сервиса) требует пересборки и прокачки 5-гигабайтного слоя через CI и
Container Registry, замедляет старт новых реплик (`ImagePull`) и забивает диски
узлов K8s старыми слоями.
**Правильный паттерн в Kubernetes:**
- Docker-образ содержит только легковесный код сервера (~150 МБ);
- в Pod добавляется **`initContainer`** (или `storage-initializer` в KServe),
  который при старте пода скачивает нужную версию модели (например, по алиасу
  `@champion`) из S3/MinIO/ORAS в общий том `emptyDir` (или монтирует общий
  ReadOnlyMany PVC с кэшем моделей).

# 8. Что случится с Pod'ом в Kubernetes, если модель грузится в ОЗУ 50 секунд,
а настроен только `livenessProbe`, и как это исправить?
Если у `livenessProbe` стоят типичные настройки (`initialDelaySeconds: 10`,
`periodSeconds: 10`, `failureThreshold: 3`), то через 40 секунд с момента
создания контейнера `kubelet` зафиксирует 3 неудачи подряд, решит, что процесс
завис, и убьет контейнер сигналом `SIGKILL`. Контейнер начнет грузить 5 ГБ
весов с нуля и уйдет в бесконечный цикл **`CrashLoopBackOff`**.
**Решение:** обязательно добавить **`startupProbe`** (например,
`periodSeconds: 5, failureThreshold: 24` — до 120 секунд). Пока `startupProbe`
один раз не вернет `200 OK`, `kubelet` не запускает `livenessProbe`.

# 9. Почему запуск ML-сервиса через `uvicorn --workers 4` внутри одного
контейнера часто роняет Pod по `OOMKilled`?
Флаг `--workers 4` порождает 4 независимых процесса ОС Linux (`fork`). Если
каждый воркер при инициализации загружает веса модели (например, 2.5 ГБ) в
собственную кучу Python без использования разделяемой памяти (`mmap`),
потребление RAM умножается на 4 ($4 \times 2.5\text{ ГБ} = 10\text{ ГБ}$), и
ядро Linux убивает Pod по превышению `resources.limits.memory`. В Kubernetes в
одном контейнере запускают **1 воркер** (`--workers 1` с пулом потоков
`intra_op_num_threads`) и масштабируют числом реплик Pod'ов через `HPA`.

# 10. В чем опасность вызова синхронного `ort_session.run()` напрямую внутри
`async def predict()` в FastAPI?
В FastAPI все корутины `async def` выполняются в одном потоке единого цикла
событий (`asyncio event loop`). Если вызвать внутри `async def` синхронный
CPU-bound метод инференса на 50 мс, `event loop` полностью заблокируется на это
время и не сможет обрабатывать другие запросы и даже легкие проверки здоровья
`/health/live`.
**Решение:** объявлять эндпоинт как обычный синхронный `def predict()` или
вызывать `await loop.run_in_executor(None, session.run, ...)` — тогда FastAPI
отправит вызов в пул потоков (`ThreadPoolExecutor`), а Си-ядро `ONNX Runtime`
отпустит Python GIL на время матричных расчетов.

# 11. Что такое `Dynamic Batching` в NVIDIA Triton Inference Server и как он
повышает пропускную способность?
Одиночный запрос (`batch_size = 1`) плохо утилизирует параллельные векторные
блоки GPU и CPU из-за накладных расходов на запуск ядер и чтение весов. При
включении `dynamic_batching` в `config.pbtxt` Triton не отправляет каждый
входящий HTTP/gRPC-запрос в модель поодиночке, а ждет в очереди микроскопическое
окно времени (например, `max_queue_delay_microseconds: 1000` — 1 мс), склеивает
пришедшие за эту миллисекунду 16 одиночных запросов в один тензор
размерности `[16, features]` и прогоняет их за один матричный проход, повышая
Throughput в 3–8 раз.

# 12. Как устроен `KServe` (`InferenceService`) в Kubernetes и чем отличаются
его компоненты `Predictor`, `Transformer` и `Explainer`?
`KServe` — стандартный Kubernetes CRD для декларативного деплоя моделей:
1. **Predictor (обязательный):** сам движок инференса (`Triton`, `SKLearn`,
   `XGBoost`, `vLLM`), перед которым автоматически запускается initContainer
   `storage-initializer` для скачивания весов из `storageUri: s3://...`.
2. **Transformer (опциональный):** отдельный контейнер пре- и пост-обработки
   (например, токенизация текста, поход в `Feast` за признаками или маскирование
   PII до отправки тензора в Predictor).
3. **Explainer (опциональный):** сайдкар/сервис интерпретации предсказаний
   (`SHAP`, `Alibi`), объясняющий, какие именно признаки повлияли на решение.

# 13. В чем разница между выкаткой модели через `Shadow (Dark Launch)`,
`Canary` и `A/B Testing`?
- **Shadow Deployment:** копия (зеркало) 100% реального продакшен-трафика
  асинхронно отправляется на новую модель `v2`, но её ответы **не показываются
  пользователю**, а только записываются в лог. Позволяет безопасно проверить
  нагрузку, латентность и сдвиг предсказаний на реальных запросах.
- **Canary Deployment:** реальные пользователи на малой доле трафика (`1% ->
  5% -> 25% -> 100%`) получают ответы от `v2` под контролем технических SLI
  (ошибки, латентность) с авто-откатом.
- **A/B Testing:** параллельная работа `v1` и `v2` (обычно 50/50 со стабильным
  хэшированием по `user_id`) в течение дней или недель для статистической
  проверки **бизнес-гипотезы** (конверсия, деньги, удержание).

# 14. Зачем в архитектуру перед локальными (`Ollama`/`vLLM`) и облачными LLM
ставят шлюз `LiteLLM Proxy` (AI Gateway)?
Чтобы микросервисы не зависели от специфики конкретного провайдера и не хранили
десятки ключей и адресов моделей в своем коде. `LiteLLM Proxy` предоставляет:
1. Единый OpenAI-совместимый эндпоинт `/v1/chat/completions` для любых моделей.
2. Автоматический **Fallback и Load Balancing** (если основная модель недоступна
   или перегружена, запрос прозрачно перенаправляется на резервную).
3. Лимиты бюджетов, Rate Limiting по сервисным ключам и централизованный
   экспорт трейсов в `Langfuse` и метрик в `Prometheus`.

# 15. Почему после конвертации модели в `ONNX` или квантования в `INT8/Q4`
обязателен шаг `Numerical Parity Check`?
При экспорте вычислительного графа и особенно при снижении разрядности весов
(`FP32 -> INT8 / INT4`) возможна деградация точности из-за насыщения активаций
(`outliers`) или различий в реализации слоев нормализации. Поэтому перед
регистрацией конвертированной модели в реестре прогоняют контрольную выборку
через исходную модель и через экспортированную, проверяя косинусную близость
логитов (`assert_allclose`) и отсутствие падения `F1` на `Golden Dataset`.
