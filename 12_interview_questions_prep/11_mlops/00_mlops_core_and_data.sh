# 1. Что такое MLOps и чем он принципиально отличается от классического
DevOps?
MLOps (Machine Learning Operations) — инженерная дисциплина, объединяющая
разработку ML-моделей, инженерию данных и SRE-эксплуатацию для надежного
вывода моделей в продакшен и их непрерывного сопровождения.
- В классическом DevOps артефакт зависит только от **Кода (Code)**: если код
  прошел тесты и среда не менялась, сервис будет работать идентично и через
  год.
- В MLOps система зависит от трех осей: **Код (Code) + Данные (Data) + Веса
  модели (Model)**. Окружающий мир меняется, поэтому даже при 100% аптайме
  контейнера и нуле ошибок HTTP 500 модель со временем тихо деградирует из-за
  смещения данных (`Data Drift` и `Concept Drift`). Поэтому к `CI/CD` в MLOps
  добавляется **`CT` (Continuous Training)**, версионирование датасетов и
  мониторинг статистического качества предсказаний.

# 2. Какие уровни зрелости MLOps (Google MLOps Maturity Levels 0, 1, 2)
выделяют в индустрии?
- **Level 0 (Ручной процесс / Ноутбучный MLOps):** обучение запускается
  вручную в Jupyter Notebook, веса передаются файлом (`model.pkl`) инженерам
  для упаковки в сервис. Нет воспроизводимости, трекинга экспериментов и
  автоматического переобучения. Оправдано только для быстрых PoC и моделей,
  обновляемых раз в год.
- **Level 1 (Автоматизированный пайплайн обучения — CT):** в продакшене
  развернут автоматический оркестратор (`Airflow` / `Prefect` / `Kubeflow`),
  который по расписанию или триггеру дрейфа валидирует свежие данные, обучает
  модель, проверяет её на `Quality Gate` и регистрирует в `Model Registry`.
- **Level 2 (Полный CI/CD + CT):** коммит в Git автоматически тестирует код
  пайплайна и промпты, собирает контейнеры, деплоит обновленный пайплайн в
  оркестратор, который запускает `CT` и выкатывает прошедшую гейты модель в
  Kubernetes через `Canary` или `Shadow`.

# 3. Зачем нужен контракт данных (Data Validation) перед обучением и чем
Pandera отличается от Great Expectations?
Принцип `Garbage In — Garbage Out`: если во входной таблице или JSON-выгрузке
появились `NULL`, сменилась кодировка или единицы измерения, модель обучится
на мусоре и сломает продакшен.
- **Pandera** — легковесная кодоцентричная библиотека для валидации таблиц
  `pandas` / `polars` прямо внутри Python-кода (декларативные классы в стиле
  `Pydantic`, быстрые векторные проверки типов, диапазонов и регулярок).
- **Great Expectations (GX)** — тяжеловесная платформенная система с
  JSON-каталогом ожиданий (`Expectation Suites`), коннекторами к SQL-хранилищам
  (`Snowflake`, `Postgres`, `Spark`) и генерацией статических HTML-порталов
  (`Data Docs`).

# 4. Как устроен DVC (Data Version Control) под капотом и почему нельзя
хранить датасеты и веса в обычном Git?
Git хранит полные слепки файлов в `.git/objects`: коммит нескольких файлов по
5 ГБ раздует репозиторий и сделает `git clone` невозможным.
- `DVC` хранит сами тяжелые файлы в контент-адресуемом хранилище на S3/MinIO/
  локальном диске по пути, образованному из MD5/SHA256 хэша содержимого:
  `.dvc/cache/files/md5/a1/b2c3d4...` (первые 2 символа хэша — имя подпапки).
- В Git коммитится только крошечный текстовый файл `dataset.parquet.dvc` (~150
  байт) с этим хэшем и размером файла.
- Команда `git checkout <tag> && dvc checkout` мгновенно восстанавливает
  точное соответствие между версией кода и версией данных через симлинки или
  `reflink` (Copy-on-Write) без лишнего копирования гигабайтов.

# 5. Чем файл пайплайна `dvc.yaml` и `dvc.lock` похож на Makefile и зачем он
нужен?
В `dvc.yaml` описываются стадии пайплайна (`stages`: `validate -> train ->
evaluate`), для каждой из которых явно указаны входные зависимости (`deps`),
параметры из `params.yaml` (`params`), команда запуска (`cmd`) и выходные
артефакты (`outs`, `metrics`).
- Файл `dvc.lock` фиксирует точные хэши всех входов и выходов каждого шага.
- При запуске `dvc repro` DVC строит граф зависимостей и перезапускает
  **только те шаги**, у которых реально изменился хэш кода, входного датасета
  или гиперпараметра в `params.yaml`, пропуская неизменившиеся тяжелые стадии.

# 6. Как устроена архитектура MLflow Tracking и почему трекинг-сервер не
должен сам прокачивать гигабайтные веса через свой HTTP-процесс?
В корректной продакшен-схеме MLflow разделен на два независимых хранилища:
1. **Backend Store (PostgreSQL):** хранит только легковесные метаданные
   (`run_id`, гиперпараметры, метрики `F1/loss`, теги, записи `Model
   Registry`).
2. **Artifact Store (S3 / MinIO / SeaweedFS):** хранит тяжелые бинарные файлы
   (веса `.onnx`/`.safetensors`, графики, дампы окружения `uv.lock`).
Если не использовать S3 или включить проксирование всех артефактов через один
Python-процесс MLflow без масштабирования, при одновременной выгрузке весов
десятком воркеров сервер MLflow упадет по памяти (`OOM`) или заблокирует
воркеры Gunicorn.

# 7. Почему в современном MLflow (2.9+) стадии `Staging` и `Production`
заменены на Model Aliases (`@champion`, `@challenger`) и теги?
Жесткий набор стадий (`None`, `Staging`, `Production`, `Archived`) был плохо
адаптирован под A/B-тестирование, Shadow-выкатки и кастомные окружения.
**Model Aliases** — это гибкие мутируемые указатели на конкретную неизменяемую
версию модели (например, `@champion -> version 4`, `@challenger -> version 5`).
Сервис инференса в продакшене всегда запрашивает `models:/doc_router@champion`.
При успешном прохождении `Quality Gate` указатель `@champion` атомарно
переключается на версию 5, а при деградации в один вызов API откатывается
назад на версию 4 без пересборки кода.

# 8. Чем архитектурно отличаются MLflow и ClearML?
- **MLflow** — модульный инструмент, сфокусированный на **Tracking + Model
  Registry** (оркестрацию очередей обучения и управление воркерами нужно
  строить отдельно на Airflow/Prefect/K8s).
- **ClearML** — комбайн «всё в одном»: при добавлении двух строк
  `Task.init(...)` он автоматически перехватывает `git diff`, аргументы CLI,
  графики `matplotlib`/`tensorboard` и консольные логи, а также имеет
  встроенный оркестратор очередей (**ClearML Agent**). Любой эксперимент можно
  клонировать в Web UI, поменять гиперпараметр и отправить в очередь
  `gpu-queue`, откуда свободный `clearml-agent` заберет задачу, соберет
  окружение и обучит модель.

# 9. Сравните оркестраторы ML-пайплайнов: Apache Airflow, Prefect и Kubeflow
Pipelines / Argo Workflows.
- **Apache Airflow:** стандарт для Data Engineering (расписания, backfill), но
  тяжеловесен в развертывании, а для изоляции ML-зависимостей требует запуска
  каждой задачи через `KubernetesPodOperator`.
- **Prefect / Dagster:** современные Python-native оркестраторы с минимальным
  порогом входа (отлично работают локально и в легком K8s), нативной передачей
  типизированных объектов и кэшированием шагов.
- **Kubeflow Pipelines / Argo Workflows:** Kubernetes-native движки, где
  каждый шаг DAG по определению является отдельным контейнером (Pod) со своим
  образом и ресурсами CPU/GPU, а артефакты автоматически перекладываются через
  S3.

# 10. Почему передача `pandas.DataFrame` или весов модели через `XCom` в
Airflow или через `/tmp` на диске — грубый антипаттерн?
- Стандартный `XCom` сериализует возвращаемое значение задачи и записывает его
  в таблицу PostgreSQL самого Airflow. Передача гигабайтного датасета вызовет
  OOM на воркере или положит базу метаданных оркестратора.
- Запись в локальную папку `/tmp` на Шаге 1 не сработает на Шаге 2 в
  распределенном кластере (`CeleryExecutor` / `KubernetesPodOperator`), так
  как второй шаг запустится в другом контейнере или на другой физической ноде.
- **Правильный паттерн:** Шаг 1 сохраняет данные в объектное хранилище S3
  (`s3://mlops/runs/{{ run_id }}/data.parquet`) и передает в `XCom` только
  строку URI (~80 байт) и контрольную сумму.

# 11. Как работает распределенное обучение PyTorch в Kubernetes (`PyTorchJob`)
и какие 4 переменные окружения ему нужны?
Контроллер **Kubeflow Training Operator** поднимает под `Master` (`rank 0`),
поды `Worker` (`rank 1..N`), создает Headless Service для DNS-обнаружения и
прокидывает в контейнеры 4 стандартные переменные `torch.distributed`:
1. `MASTER_ADDR` — хост главного воркера (`rank 0`);
2. `MASTER_PORT` — TCP-порт для рандеву;
3. `WORLD_SIZE` — общее число процессов обучения в кластере;
4. `RANK` (и `LOCAL_RANK`) — порядковый номер текущего процесса.
На каждом шаге обратного распространения ошибки воркеры синхронизируют и
усредняют градиенты через коллективную операцию **`AllReduce`** (поверх
библиотеки `NCCL` на GPU или `Gloo` на CPU).

# 12. Как организовать надежное обучение на дешевых прерываемых (Spot /
Preemptible) узлах в облаке?
Облако может отобрать Spot-ноду в любой момент, послав в Pod сигнал `SIGTERM`
за 30–120 секунд до выключения.
1. Тренировочный скрипт должен сохранять регулярные чекпоинты (веса модели +
   состояние оптимизатора `AdamW` + шаг эпохи + `RNG state`) в S3 каждые $N$
   шагов.
2. В коде регистрируется обработчик `SIGTERM`, который при получении сигнала
   сбрасывает внеочередной чекпоинт в S3 и корректно завершает процесс.
3. При перезапуске пода оркестратором скрипт проверяет папку текущего `RUN_ID`
   в S3 и продолжает обучение с последнего чекпоинта
   (`resume_from_checkpoint`), не теряя часы работы.

# 13. Что такое Feature Store (например, Feast) и какие две фундаментальные
проблемы он решает?
**Feature Store** — централизованное хранилище признаков с единым каталогом
определений. Решает две главные проблемы:
1. **Training-Serving Skew:** устраняет расхождение формул расчета признаков
   между офлайн-обучением (Data Scientist в SQL/Python) и онлайн-инференсом
   (Backend на Go/Python).
2. **Time-Travel Data Leakage (утечка из будущего):** при сборке обучающего
   датасета метод `get_historical_features()` выполняет **`Point-in-Time Join
   (ASOF JOIN)`** — подбирает для каждого события в прошлом ровно то значение
   признака, которое было известно на ту секунду ($t_{\text{feature}} \le
   t_{\text{event}}$), не позволяя модели подсмотреть в будущее.

# 14. Зачем в Feature Store два физических хранилища: `Offline Store` и
`Online Store`?
Потому что у обучения и онлайн-инференса несовместимые профили нагрузки:
- **Offline Store** (`Parquet/S3`, `ClickHouse`, `BigQuery`) хранит глубокую
  историю изменений всех признаков за годы и оптимизирован под пакетное
  колоночное чтение миллионов строк при сборке обучающих выборок (секунды/
  минуты).
- **Online Store** (`Redis`, `DynamoDB`, `SQLite`) хранит **только самое
  последнее значение** признака для каждого ключа `entity_id` в оперативной
  памяти, отдавая его за `1–3 мс` во время синхронного HTTP-запроса к модели
  (поддерживается актуальным через периодический процесс `feast
  materialize-incremental`).

# 15. Из каких уровней состоит пирамида тестирования в CI/CD для ML и что
проверяет тест `Overfit on a Single Batch`?
Пирамида включает 4 слоя:
1. **Unit-тесты кода и фичей** (чистые функции очистки, проверка размерностей
   и смоук-тест **`Overfit on a Single Batch`**: модель обязана за 30 шагов на
   CPU выучить 1 мини-батч из 8 примеров до нулевого `loss` — если `loss` не
   падает, в коде оторван граф градиентов или сломана функция потерь).
2. **Тесты данных (Data CI):** проверка схемы `Pandera`, баланса классов и
   отсутствия пересечения между `train` и `test` по `doc_id`/`user_id`.
3. **Поведенческие тесты модели (`CheckList`):** `MFT`, `INV`, `DIR`.
4. **Quality Gate и нагрузочные тесты:** сравнение с текущей моделью
   `@champion` на замороженном `Golden Dataset` + проверка латентности `p95` и
   памяти.

# 16. Объясните три типа поведенческих тестов модели в CI: `MFT`, `INV` и
`DIR`.
- **MFT (Minimum Functionality Test):** набор простых, однозначных канонических
  примеров («золотых правил»), на которых модель обязана давать 100% точность
  (например, `"Гемоглобин 144 г/л, СОЭ 5"` $\rightarrow$ класс `medicine`).
- **INV (Invariance Test):** предсказание модели не должно меняться при
  сохраняющих смысл возмущениях входа (изменение регистра букв, лишние пробелы
  после OCR, замена ФИО `"Иванов"` на `"Петров"`).
- **DIR (Directional Expectation Test):** при целенаправленном добавлении
  маркеров конкретного класса (например, слов `"ФНС налоговое уведомление ИНН
  КБК"`) вероятность этого класса должна монотонно расти.

# 17. Почему в Quality Gate нельзя опираться только на среднюю метрику `F1` по
всему тестовому датасету (проблема `Slice-based Evaluation`)?
Из-за **Парадокса Симпсона**: новая модель `@challenger` может поднять общий
`F1` с `0.910` до `0.915` за счет улучшения на самом частом и легком классе
(например, обычных кассовых чеках), но при этом уронить полноту (`Recall`) с
`0.95` до `0.70` на редком, но критически важном срезе данных (например,
медицинских заключениях или коротких текстах). Поэтому `Quality Gate` обязан
проверять отдельные пороговые гейты по каждому критическому классу и срезу
(`Data Slices`).

# 18. В чем разница между `Data Drift (Covariate Shift)`, `Label Shift` и
`Concept Drift` в мониторинге моделей?
- **Data / Covariate Shift:** изменилось распределение входных признаков
  $P(X)$ (например, пошли фото документов с телефона вместо чистых PDF), но
  сама зависимость $P(Y \mid X)$ прежняя.
- **Label / Prior Shift:** изменилось распределение классов $P(Y)$ (в налоговый
  сезон 70% входящих документов — уведомления ФНС).
- **Concept Drift:** изменилась сама реальная связь $P(Y \mid X)$ при тех же
  входах $X$ (изменились законы, тарифы или поведение мошенников). `Concept
  Drift` самый опасный, так как без получения `Ground Truth` распределения
  входов $X$ и выходов $\hat{Y}$ выглядят абсолютно нормальными.

# 19. Как считается индекс `PSI (Population Stability Index)`, какие у него
пороги и почему на больших выборках он лучше `p-value` из `KS-test`?
Эталонная выборка (`reference`) делится на 10 равных по частоте бинов (по
$q_i = 10\%$), затем считается доля $p_i$ текущих продакшен-данных в тех же
границах бинов по формуле $\text{PSI} = \sum (p_i - q_i) \ln(p_i / q_i)$.
- Пороги: `< 0.10` — дрейфа нет; `0.10–0.25` — умеренный сдвиг; **`> 0.25` —
  критический дрейф**.
- В отличие от критерия Колмогорова-Смирнова (`KS-test`), где на выборке в
  100 000 запросов в продакшене `p-value` падает ниже `0.05` даже при
  ничтожном шумовом смещении на `0.1%` (вызывая ложные алерты), `PSI` измеряет
  абсолютную величину расхождения и не зависит от размера выборки $N$.

# 20. Как мониторить качество модели в реальном времени, если истинная
разметка (`Ground Truth`) приходит с задержкой в несколько недель или не
приходит вовсе?
Используют косвенные (прокси) сигналы без Ground Truth:
1. **Prediction Drift:** расчет `PSI` по выходным вероятностям модели и долям
   предсказываемых классов.
2. **Confidence Monitoring:** отслеживание доли запросов, где максимальная
   вероятность класса упала ниже порога уверенности (`max_prob < 0.6`).
3. **Data Quality & Top-Feature Drift:** мониторинг доли `NULL`, длины текста,
   доли неизвестных слов (`OOV`) и `PSI` по топ-5 самым важным признакам
   (`SHAP`).
4. **Implicit User Feedback:** доля запросов, где пользователь вручную нажал
   «Исправить категорию» или отменил действие.
