# 1. Как запустить Ansible на 10,000–30,000+ серверов простыми словами?
# В чем проблема классического запуска и как это делают на практике?
Если запустить `ansible-playbook` «в лоб» по SSH на 20,000 серверов,
произойдет катастрофа: либо ваш Control Node упадет от нехватки памяти
(Ansible пытается открыть тысячи SSH-сессий и порождает тысячи тяжелых
процессов Python), либо деплой будет идти сутки, если запускать их
маленькими пачками по 5 штук.

На практике в High-Scale инфраструктурах эту задачу решают 5 шагами:
1. **Переход на модель Pull (ansible-pull):**
   Это главное решение для десятков тысяч машин. Мы переворачиваем схему:
   не сервер управления ломится на 30,000 машин по SSH, а каждый сервер сам
   раз в 15 минут по крону делает `git pull` и применяет плейбук к себе
   локально (`connection: local`). Нагрузка на центральный сервер — нулевая,
   масштабируемость неограниченная.
2. **Волновой накат (Батчинг через `serial`):**
   Если нужен строгий Push-контроль из единого центра, никогда не запускают
   плейбук на все хосты сразу. Накатывают волнами:
   `serial: ["1%", "5%", "20%", "100%"]`. Если на 1% (на первых 200 хостах)
   что-то пошло не так, Ansible аварийно останавливает весь деплой,
   сохраняя остальной прод в живых.
3. **Ускорение SSH (Pipelining и ControlMaster):**
   Включают `pipelining = True` в `ansible.cfg` (код модуля передается
   напрямую в память Python через SSH-пайп, без медленного копирования
   файлов на диск) и `ControlPersist=60s` (SSH-сессия не закрывается после
   каждой задачи, а переиспользуется).
4. **Кэширование или отключение фактов:**
   Сбор фактов (`setup`) на 30k машинах может занять полдня. Либо отключают
   `gather_facts: false`, либо включают кэширование фактов в Redis
   (`fact_caching = redis`), чтобы опрашивать серверы не чаще раза в сутки.
5. **Использование Mitogen или распределение раннеров (AWX / AAP Mesh):**
   Плагин Mitogen ускоряет выполнение задач в 3–5 раз за счет постоянного
   процесса Python на нодах. Либо задачи распределяются между пулом
   Execution-воркеров (Automation Mesh).

# 2. Что такое ansible-pull и как он устроен под капотом?
`ansible-pull` — это встроенная утилита, которая инвертирует топологию
Ansible из Push в Pull.
Как это работает по шагам:
1. На каждом управляемом сервере настраивается cron или systemd-таймер:
   `ansible-pull -U https://gitlab.internal.net/devops/infra.git site.yml`
   Для предотвращения одновременного наплыва на Git-сервер добавляют
   случайную задержку (`sleep $((RANDOM % 300))`).
2. Утилита на целевом сервере делает `git pull` в каталог
   `/var/lib/ansible`.
3. Затем запускает `ansible-playbook` локально с параметрами
   `hosts: localhost` и типом подключения `connection: local`.
4. Сервер сам применяет конфигурацию к себе.

Плюсы:
- Нет единого узкого горлышка по SSH и сети на Control Node.
- Работает за NAT и файрволами — серверам не нужен открытый порт 22 снаружи.
- Масштабируемость O(1) — время наката одинаково для 100 и для 100,000 машин.
Минусы:
- Сложнее отслеживать общий статус деплоя (требуется отправка отчетов в ELK).
- Нельзя легко оркестровать зависимые шаги (обновить балансировщик СТРОГО
  после того, как поднялись все 100 бэкендов).

# 3. Как устроен жизненный цикл выполнения задачи (Task) и Ansiballz?
# Что физически происходит при запуске модуля по SSH?
Когда Ansible выполняет обычный таск (например, `copy` или `apt`):
1. **На Control Node:**
   Ansible берет код модуля на Python, читает переданные параметры таска,
   прогоняет шаблонизацию Jinja2 и упаковывает модуль вместе с библиотеками
   `module_utils` в специальный самораспаковывающийся ZIP-архив (Ansiballz).
2. **Передача на Managed Node (без Pipelining):**
   - Открывается SFTP/SCP сессия, файл модуля сохраняется во временную папку
     (обычно `~/.ansible/tmp/ansible-tmp-XXXXX/AnsiballZ_module.py`).
   - Файлу выставляются права на исполнение (`chmod +x`).
   - Открывается новая SSH-сессия, запускается `python AnsiballZ_module.py`.
   - Модуль распаковывается в памяти, выполняет системные действия и
     выводит результат в stdout в формате JSON.
   - Ansible считывает JSON, удаляет временные файлы и закрывает SSH-сессию.
3. **Передача с включенным Pipelining:**
   Копирование файла на диск исключается. Ansible запускает на удаленном хосте
   команду `python` и передает весь упакованный скрипт напрямую в поток
   стандартного ввода `stdin` через открытый сокет SSH. Это экономит до 70%
   времени на каждой задаче.

# 4. Как настроить транспорт SSH для работы с тысячами хостов?
В секции `[ssh_connection]` файла `ansible.cfg` настраивают связку:
```ini
[ssh_connection]
pipelining = True
ssh_args = -C -o ControlMaster=auto -o ControlPersist=60s
control_path = /tmp/ansible-ssh-%%h-%%p-%%r
```
- `ControlMaster=auto`: первое подключение к хосту создает управляющий
  Unix-сокет в `/tmp/`.
- `ControlPersist=60s`: держит фоновое SSH/TCP соединение открытым еще 60 секунд
  после завершения таска. Следующая задача для этого же хоста подключается
  мгновенно через существующий сокет без повторного TCP 3-way handshake
  и обмена SSH-ключами.
- `pipelining = True`: исполнение в памяти без промежуточного SFTP.
  *Важный нюанс:* в `/etc/sudoers` на серверах должна быть отключена опция
  `Defaults requiretty`, иначе sudo без псевдотерминала упадет с ошибкой.

# 5. Что такое Mitogen for Ansible и почему он кардинально быстрее?
Mitogen — это сторонний C/Python плагин подключения, заменяющий стандартный
механизм запуска задач Ansible.
Как он устроен:
1. Вместо того чтобы на каждый таск заново запускать процесс Python на ноде,
   Mitogen при первом подключении запускает один постоянный Python-демон.
2. Между Control Node и демоном на ноде устанавливается бинарный мультиплексный
   канал по стандартному SSH-туннелю.
3. Для каждого таска Mitogen стримит байт-код модуля напрямую в память
   работающего демона. Модуль вызывается как обычная Python-функция.
Результат:
- Время выполнения плейбуков сокращается в 3–7 раз.
- Нагрузка на CPU Control Node падает на 70–80% (нет тысяч fork процессов).
- Сетевой трафик уменьшается на порядок.

# 6. В чем разница между стратегиями исполнения linear, free и host_pinned?
Стратегия задается в плейбуке (`strategy: linear | free | host_pinned`):
- `linear` (по умолчанию): барьерная синхронизация. Все хосты выполняют
  задачу 1. Пока самый медленный хост не закончит задачу 1, никто не переходит
  к задаче 2. Надежно, но медленно.
- `free`: каждый хост выполняет плейбук от начала до конца в своем темпе,
  не дожидаясь других. Максимальная скорость, но сложно отлаживать, и
  неприменимо для rolling-update.
- `host_pinned` (появилась в Ansible 2.12+): золотая середина. Воркер
  берет сервер из очереди и выполняет для него все задачи последовательно.
  Как только сервер закончил — воркер сразу берет следующий. Это исключает
  простой быстрых серверов и сохраняет логичный порядок действий.

# 7. Как работают асинхронные задачи (async и poll)?
Используются для тяжелых и долгих операций (миграции БД, apt dist-upgrade,
генерация бэкапов), чтобы SSH-сессия не отваливалась по таймауту.
Параметры:
- `async: 3600` — максимальное время работы задачи (в секундах).
- `poll: 0` (Fire-and-Forget) — запустить в фоне и сразу идти дальше.
Пример с последующей проверкой:
```yaml
- name: Start long backup job
  command: /opt/scripts/backup.sh
  async: 1800
  poll: 0
  register: job

- name: Wait for backup completion
  async_status:
    jid: "{{ job.ansible_job_id }}"
  register: job_result
  until: job_result.finished
  retries: 30
  delay: 60
```

# 8. Как масштабировать инвентарь и сбор фактов (Fact Caching) на 30k+ хостов?
1. **Fact Caching:**
   В `ansible.cfg` включают кэширование фактов во внешнюю БД (Redis):
   ```ini
   [defaults]
   gathering = smart
   fact_caching = redis
   fact_caching_connection = localhost:6379:0
   fact_caching_timeout = 86400
   ```
   В режиме `gathering = smart` Ansible запрашивает факты только если кэша
   нет или он протух. На 30,000 серверах это экономит часы времени.
2. **Оптимизация Dynamic Inventory:**
   - В плагине динамического инвентаря (AWS EC2 / NetBox) включают кэш.
   - Используют server-side фильтрацию (запрашивают только тегированные хосты,
     а не всю инфраструктуру облака).
   - Инвентарь делят на подкаталоги по регионам/кластерам.

# 9. Как устроены Handlers под капотом: очередь, дедупликация и listen?
- Хендлер — это отложенная задача (deferred task).
- Когда задача завершается со статусом `changed: true` и вызывает `notify`,
  Ansible добавляет имя хендлера во внутреннюю очередь (Set в памяти).
- **Дедупликация:** поскольку это множество уникальных имен, сколько бы раз
  вы ни вызвали `notify: restart nginx`, хендлер выполнится ровно ОДИН раз
  в конце play.
- Порядок вызова определяется порядком объявления задач в блоке `handlers:`,
  а не порядком вызовов `notify`.
- **Топики listen:** директива `listen` позволяет нескольким хендлерам
  подписаться на одно событие:
  ```yaml
  handlers:
    - name: Restart Nginx
      service: { name: nginx, state: restarted }
      listen: "restart web"

    - name: Restart PHP
      service: { name: php-fpm, state: restarted }
      listen: "restart web"
  ```
  Задача вызывает `notify: restart web`, и оба хендлера сработают вместе.

# 10. Как модуль meta управляет потоком выполнения (flush_handlers, end_play)?
Модуль `meta` выполняет внутренние команды рантайма Ansible:
- `meta: flush_handlers`: немедленно выполняет все накопившиеся в очереди
  хендлеры прямо сейчас, не дожидаясь конца play.
  *Кейс:* перезапустить базу данных прямо сейчас, чтобы следующие задачи
  смогли накатить в нее миграции.
- `meta: refresh_inventory`: перечитывает инвентарь заново (нужно, если
  в первой части плейбука создали новые ВМ).
- `meta: end_play`: штатно завершает текущий play для всех хостов.
- `meta: end_host`: исключает текущий хост из дальнейшего выполнения.
- `meta: clear_host_errors`: сбрасывает статус ошибки у хоста после
  обработки в блоке `rescue`.

# 11. Что такое Ansible Collections (FQCN) и как работать в закрытом контуре?
Начиная с Ansible 2.9+, все модули вынесены в Коллекции (Collections).
- **FQCN (Fully Qualified Collection Name):** полное имя модуля формата
  `namespace.collection.module` (например, `ansible.builtin.copy`,
  `community.docker.docker_container`). Предотвращает конфликты модулей.
- Зависимости описываются в `requirements.yml`:
  ```yaml
  collections:
    - name: community.general
      version: ">=7.0.0"
  ```
  Установка: `ansible-galaxy collection install -r requirements.yml`.
- **Air-Gapped установка (без интернета):**
  1. В открытом контуре скачивают архивы:
     `ansible-galaxy collection download -r requirements.yml -p ./offline_repo`
  2. Переносят папку на закрытый сервер.
  3. Устанавливают локально:
     `ansible-galaxy collection install -r ./offline_repo/requirements.yml`

# 12. Как создать, собрать и опубликовать собственную коллекцию?
1. Инициализация каркаса:
   `ansible-galaxy collection init myorg.monitoring`
2. Структура каталогов:
   - `galaxy.yml` — метаданные (имя, версия, зависимости, автор).
   - `plugins/modules/` — кастомные Python-модули.
   - `plugins/filter/` — кастомные Jinja2 фильтры.
   - `roles/` — встроенные роли.
3. Сборка архива:
   `ansible-galaxy collection build`
   Создается tar.gz архив `myorg-monitoring-1.0.0.tar.gz`.
4. Публикация в приватный репозиторий (Galaxy NG, Automation Hub, Nexus):
   ```bash
   ansible-galaxy collection publish myorg-monitoring-1.0.0.tar.gz \
     --server https://hub.internal/api/galaxy/
   ```

# 13. Как написать собственный модуль на Python с поддержкой идемпотентности?
Собственный модуль использует библиотеку
`ansible.module_utils.basic.AnsibleModule`.
Главное правило идемпотентности: сначала проверяем текущее состояние системы,
и вносим изменения только если оно не совпадает с желаемым.

Шаблон модуля:
```python
#!/usr/bin/python
from ansible.module_utils.basic import AnsibleModule

def run_module():
    module_args = dict(
        name=dict(type="str", required=True),
        state=dict(type="str", default="present", choices=["present", "absent"])
    )
    module = AnsibleModule(
        argument_spec=module_args,
        supports_check_mode=True
    )

    name = module.params["name"]
    target_state = module.params["state"]
    result = dict(changed=False, message="")

    # 1. Проверяем текущее состояние (Read)
    current_state = "absent"  # (реальная проверка в системе)

    # 2. Если состояние уже соответствует целевому — идемпотентный выход
    if current_state == target_state:
        module.exit_json(**result)

    # 3. Если включен check_mode (--check) — возвращаем changed без правок
    if module.check_mode:
        result["changed"] = True
        module.exit_json(**result)

    # 4. Применяем реальные изменения (Mutate)
    result["changed"] = True
    result["message"] = f"Resource {name} changed to {target_state}"
    module.exit_json(**result)

if __name__ == "__main__":
    run_module()
```

# 14. Где размещаются кастомные модули и чем Module отличается от Action Plugin?
- **Где хранятся кастомные модули:**
  1. В папке `library/` на одном уровне с плейбуком.
  2. Внутри роли в подпапке `roles/<role>/library/`.
  3. Внутри коллекции по пути `plugins/modules/`.
- **Отличие Module от Action Plugin:**
  - **Module:** исполняется **на удаленном хосте (Managed Node)**.
    Ansible упаковывает его в Ansiballz, передает по SSH и запускает там.
  - **Action Plugin:** исполняется **на Control Node (локально)**.
    Он запускается до передачи модуля на удаленный сервер и может работать
    с локальной файловой системой мастера (как делают `template` и `copy`),
    подготавливать аргументы или координировать несколько вызовов.
