# 1. Что такое Ansible и в чем его главные преимущества?
Ansible — это open-source система управления конфигурацией и автоматизации.
Главные преимущества:
- Безагентный (Agentless): не требует установки агентов-демонов на серверы,
  работает по стандартному протоколу SSH (или WinRM для Windows).
- Декларативный подход: вы описываете желаемое конечное состояние системы
  на понятном языке YAML (Playbooks).
- Идемпотентность: повторный запуск плейбука безопасен — система меняет
  только то, что не соответствует целевому состоянию.
- Низкий порог входа: не требует знания языков программирования (в отличие
  от Ruby в Chef/Puppet).

# 2. Из каких ключевых компонентов состоит архитектура Ansible?
1. Control Node: хост, на котором установлен Ansible и откуда запускаются
   команды и плейбуки (Linux/macOS; Windows в роли Control Node не работает).
2. Managed Nodes: целевые серверы, которыми управляет Ansible.
3. Inventory (Инвентарь): список серверов с их адресами, группами и
   переменными (INI или YAML).
4. Playbooks (Плейбуки): YAML-сценарии, объединяющие задачи и хосты.
5. Modules (Модули): исполняемые блоки кода (обычно Python), выполняющие
   реальные действия на сервере (создание файлов, установка пакетов).
6. Plugins (Плагины): расширения ядра (connection, lookup, callback, filter).

# 3. Что такое идемпотентность и почему модуль shell ломает её?
# В чем подвох и как сделать shell идемпотентным?
Идемпотентность — свойство операции давать одинаковый результат при
многократном выполнении без нежелательных побочных эффектов.
- Подвох с shell / command: Ansible не знает, что именно делает ваша
  bash-команда. Поэтому модули shell и command ВСЕГДА возвращают статус
  changed: true, ломая логику идемпотентности и ложно триггеря хендлеры.
- Как сделать shell идемпотентным:
  1. Директива creates: задача выполняется ТОЛЬКО если указанного файла
     еще НЕТ на диске (creates: /etc/app.installed).
  2. Директива removes: задача выполняется ТОЛЬКО если указанный файл ЕСТЬ.
  3. Директива changed_when: переопределить статус changed на основе
     кода возврата или вывода (changed_when: false для команд проверки).

# 4. В чем разница между модулями command, shell и raw?
- command — запускает бинарник напрямую через системный вызов execve(),
  минуя оболочку. Не работают пайпы, перенаправления, переменные окружения.
  Самый безопасный модуль (нет инъекций shell).
- shell — запускает команду через оболочку /bin/sh -c. Работают все фичи
  терминала: пайпы, операторы &&, перенаправления потоков. Менее безопасен.
- raw — исполняет чистую SSH-команду БЕЗ передачи Python на удаленный хост.
  Главный кейс: первичный bootstrap сервера, где еще не установлен Python
  (raw: apt-get update && apt-get install -y python3).

# 5. Как устроена иерархия приоритета переменных (Variable Precedence)?
# В чем классический подвох на собеседовании?
В Ansible более 20 уровней приоритета переменных. Главная шкала (от низшего
к высшему):
1. role defaults (в папке defaults/main.yml роли) — САМЫЙ низкий приоритет.
   Их легко переопределить где угодно.
2. inventory vars (group_vars, host_vars в инвентаре).
3. playbook group_vars и host_vars.
4. playbook vars (секция vars: в плейбуке).
5. role vars (в папке vars/main.yml роли) — высокий приоритет, сложно
   переопределить извне роли.
6. block vars и task vars (переменные конкретной задачи).
7. set_fact / зарегистрированные переменные (register).
8. extra vars (-e "key=val" в CLI) — АБСОЛЮТНЫЙ приоритет. Переопределяет
   все переменные везде.
Подвох на собеседовании: переменные из vars/main.yml роли имеют более
высокий приоритет, чем group_vars инвентаря. Поэтому дефолтные переменные
роли ВСЕГДА нужно класть в defaults/, а не в vars/, иначе их нельзя будет
переопределить для отдельной группы серверов в инвентаре!

# 6. В чем разница между import_* и include_* (import_tasks vs include_tasks)?
Это фундаментальная разница между статическим (компиляция) и динамическим
(рантайм) переиспользованием задач и ролей в Ansible:

1. **`import_*` (Статическое переиспользование — Compile-time):**
   - Все `import_tasks` / `import_role` / `import_playbook` обрабатываются
     ДО начала выполнения плейбука, на этапе предварительного парсинга.
     Задачи сразу подставляются в тело плейбука (inlining).
   - **Плюсы:**
     * `ansible-playbook --list-tasks` и `--list-tags` видят все задачи.
     * Теги (`--tags`) и условия (`when`) применяются ко всем задачам внутри.
     * Хэндлеры (handlers) внутри импортированных файлов регистрируются сразу
       и доступны для вызова (`notify`) из любых других задач.
   - **Ограничения:**
     * Нельзя использовать в имени файла переменные, вычисленные во время
       работы плейбука (например, факты `ansible_os_family`).
     * `import_tasks` НЕЛЬЗЯ вызывать внутри цикла `loop`.

2. **`include_*` (Динамическое переиспользование — Runtime):**
   - Файлы `include_tasks` / `include_role` подгружаются В РЕАЛЬНОМ ВРЕМЕНИ,
     только когда очередь выполнения доходит до конкретной задачи.
   - **Плюсы:**
     * Можно использовать в цикле `loop` (например, для пакета сервисов).
     * Имя файла может быть динамическим: `file: "{{ ansible_os_family }}.yml"`.
   - **Ограничения:**
     * `ansible-playbook --list-tasks` не видит внутренние задачи до выполнения.
     * Хэндлеры внутри include не зарегистрированы до тех пор, пока include
       не выполнится физически.

Практическое правило SRE: по умолчанию всегда использовать `import_*` для
предсказуемости и скорости; использовать `include_*` только там, где
действительно требуется динамика (цикл `loop` или выбор файла по фактам ОС).

# 7. Как обрабатывать ошибки: ignore_errors vs failed_when и блоки
# block / rescue / always?
1. ignore_errors: true: задача завершается с ошибкой, но Ansible игнорирует
   ее и продолжает выполнение следующих задач.
2. failed_when: позволяет гибко задать собственное условие падения задачи.
   Например, команда вернула rc=0, но в выводе есть ошибка:
   register: result
   failed_when: "'ERROR' in result.stderr"
3. Конструкция block / rescue / always (аналог try / catch / finally):
   Секция rescue выполнится ТОЛЬКО при сбое в block. Секция always
   выполнится ВСЕГДА (даже при падении), идеально для удаления временных файлов.

# 8. Заковыристый вопрос: что произойдет с Handlers, если задача упала
# посреди плейбука? Чем опасен флаг --force-handlers?
- По умолчанию: если в середине плейбука любая задача падает с ошибкой,
  выполнение немедленно прерывается. Запланированные хендлеры (например,
  restart nginx) НЕ ВЫПОЛНЯЮТСЯ.
  Результат: сервер может остаться в битом состоянии (новый конфиг уже
  скопирован, но сервис не перезапущен).
- Решение: флаг --force-handlers (или force_handlers = True в конфиге)
  заставляет Ansible выполнить накопившиеся хендлеры даже при аварии.
- В чем подвох и опасность: если упавшая задача выполняла проверку
  валидности конфига (nginx -t), принудительный запуск хендлера с невалидным
  конфигом гарантированно уронит рабочий production-сервис!

# 9. Что такое changed_when и как избежать ложных срабатываний changed?
Многие команды только читают статус системы (например, curl или grep),
но модуль command всегда помечает их как changed: true.
Это приводит к двум проблемам: ложные отчеты о дрейфе конфигурации и
случайные триггеры хендлеров.
Решение:
```yaml
- name: Check application health
  command: /opt/check_status.sh
  register: health
  changed_when: false
```
Директива changed_when: false гарантирует, что задача вернет статус ok
вместо changed.

# 10. В чем разница между copy и template?
- copy — переносит файл "как есть" (байт-в-байт) с Control Node на целевой
  сервер. Быстрее для бинарников, сертификатов и готовых статических файлов.
- template — прогоняет файл через шаблонизатор Jinja2 перед отправкой.
  Подставляет переменные ({{ port }}), условия ({% if ssl %}), циклы.
  Используется для конфигурационных файлов (nginx.conf.j2).

# 11. Как работают delegate_to и run_once? Приведите реальный SRE-кейс.
- delegate_to: перенаправляет выполнение конкретной задачи на другой хост
  (например, на localhost или балансировщик), но с переменными текущего хоста.
- run_once: true: выполняет задачу ровно один раз на первом хосте группы,
  а результат транслирует на остальные.
Реальный SRE-кейс (Zero Downtime Rolling Update):
При обновлении 10 веб-серверов для каждого хоста нужно:
1. Зайти на балансировщик и вывести текущий хост из пула:
   delegate_to: load_balancer.
2. Обновить приложение на самом веб-сервере.
3. Вернуть хост обратно в балансировщик:
   delegate_to: load_balancer.

# 12. Что такое register и в чем подвох при использовании с when (skipped)?
Директива register сохраняет результат выполнения задачи в переменную.
Классический подвох на собеседовании:
Если задача была пропущена из-за when: false, Ansible ВСЕ РАВНО перезаписывает
переменную register словарем вида {"changed": false, "skipped": true}.
Попытка прочитать в следующей задаче msg: "{{ conf.stdout }}" упадет
с ошибкой (undefined variable), так как ключа stdout в объекте нет!
Правильное решение: проверять when: conf is not skipped или использовать
дефолтный фильтр: {{ conf.stdout | default("") }}.

# 13. Что такое Ansible Vault и как работать с ним в CI/CD без хардкода?
Ansible Vault шифрует секретные переменные алгоритмом AES256.
Команды: ansible-vault encrypt_string, ansible-vault view/edit.
Как использовать в CI/CD пайплайнах:
1. Пароль от Vault передается через переменную окружения CI/CD:
   export ANSIBLE_VAULT_PASSWORD="$VAULT_SECRET"
   и аргумент --vault-password-file <(echo $ANSIBLE_VAULT_PASSWORD).
2. Либо используется скрипт-провайдер пароля (client script), забирающий
   токен из HashiCorp Vault или AWS Secrets Manager.

# 14. Как работают теги (tags) и в чем нюанс спец-тегов always и never?
Теги позволяют выборочно запускать части плейбука (--tags "nginx") или
пропускать их (--skip-tags "backup").
Специальные теги:
- always: задача с этим тегом выполняется ВСЕГДА, даже если в CLI указаны
  другие теги (например, --tags "deploy"). Отключить можно только явным
  указанием --skip-tags "always".
- never: задача с этим тегом НЕ выполняется НИКОГДА при обычном запуске.
  Она запустится ТОЛЬКО если вы явно укажете ее в CLI: --tags "never,debug".
  Идеально для тяжелых отладочных шагов или задач отката.

# 15. В чем разница между set_fact и обычными vars в плейбуке?
- vars: в плейбуке или роли — статические переменные, определяемые до
  начала выполнения задач.
- set_fact: — динамическое создание или изменение переменной прямо во время
  выполнения плейбука.
Ключевые отличия:
1. Факты сохраняются для хоста на протяжении всех последующих plays в рамках
   одного запуска плейбука.
2. Приоритет set_fact значительно выше, чем у обычных vars из плейбука
   или инвентаря.

# 16. Что такое lookup-плагины и где они физически выполняются?
Lookup-плагины позволяют затягивать данные из внешних источников прямо в
шаблоны или переменные:
lookup('file', '/etc/ssh/id_rsa.pub'), lookup('env', 'HOME').
Подвох на собеседовании:
Все lookup-плагины исполняются НА CONTROL NODE (машине администратора),
а не на удаленных серверах!
Поэтому lookup('file', '/etc/hosts') прочитает локальный файл вашего
ноутбука или CI-раннера, а не управляемого хоста. Если нужен файл с удаленного
хоста — используют модуль slurp или command: cat.

# 17. Что такое loop и with_items: в чем разница в современном Ansible?
with_items, with_dict, with_file — устаревший синтаксис на базе
lookup-плагинов из ранних версий Ansible.
Современный стандарт — ключевое слово loop:
- loop более производителен, так как работает как чистая Jinja2 итерация,
  а не через постоянный вызов lookup-плагинов.
- Для сложных структур данных с loop используются фильтры Jinja2
  (loop: "{{ users | dict2items }}").

# 18. Как ограничить запуск плейбука (лимиты и паттерны хостов)?
Флаг --limit (или -l) позволяет выбрать подмножество инвентаря:
- Один сервер: -l web1.example.com
- Группа: -l webservers
- Пересечение групп (хосты и в web, и в production): -l 'web:&production'
- Исключение (все web, кроме сломанного web3): -l 'web:!web3'
- Хосты с ошибками из прошлого прогона: -l @site.retry (файл retry).

# 19. Как устроен сбор фактов (setup) и зачем его отключать?
Модуль setup автоматически запускается в начале каждого play. Он считывает
сотни параметров ядра, дисков, сети, CPU и IP-адресов целевой системы.
Эти данные складываются в дерево переменных ansible_facts.
Почему его часто отключают (gather_facts: false):
1. На парке в 1,000 серверов сбор фактов может занять 5–10 минут еще до
   начала выполнения полезных задач.
2. Если в плейбуке не используются переменные типа ansible_os_family,
   сбор фактов является бесполезной тратой времени и сетевых ресурсов.

# 20. Как тестируют Ansible-роли с помощью Molecule?
Molecule — стандарт тестирования ролей в изоляции:
1. Поднимает тестовое изолированное окружение (Docker-контейнер, Podman или ВМ).
2. Запускает сценарий converge: накатывает вашу роль на тестовый контейнер.
3. Проверка идемпотентности (idempotence): повторно накатывает роль и
   убеждается, что статус changed == 0. Если что-то изменилось — тест падает!
4. Верификация (verify): запускает тесты (Testinfra / pytest / verifier),
   проверяя реальное состояние: слушает ли порт 80, создан ли пользователь,
   валиден ли синтаксис конфига.
5. Уничтожает тестовое окружение (destroy).
