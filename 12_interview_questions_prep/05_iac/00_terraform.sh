# 1. Что такое Terraform и как он работает?
Terraform — это open-source инструмент для Infrastructure as Code (IaC).
Он позволяет декларативно описывать желаемое состояние облачной
инфраструктуры (сети, серверы, БД) в конфигурационных файлах (HCL -
HashiCorp Configuration Language). Terraform сравнивает текущее состояние
инфраструктуры с желаемым и формирует план действий (Plan) для достижения
желаемого состояния, а затем применяет его (Apply), вызывая API
провайдеров.

# 2. Что такое State-файл (terraform.tfstate) и зачем он нужен?
State-файл — это локальный (или удаленный) JSON файл, в котором Terraform
сохраняет текущее состояние управляемых им ресурсов и маппинг
(соответствие) между ресурсами в коде и реальными объектами в облаке (их
ID, атрибуты). Без него Terraform не знал бы, какие ресурсы он уже создал,
и при каждом запуске пытался бы создать их заново.

# 3. Как безопасно хранить Terraform State при командной работе?
Используются Remote Backends (Удаленные бекенды).
Хранить State в Git небезопасно (там могут быть секреты в открытом виде)
и неудобно для совместной работы из-за отсутствия блокировок (State
Locking).
Обычно стейт хранят в AWS S3 бакете (с версионированием и шифрованием),
а блокировку от одновременных запусков настраивают через DynamoDB таблицу.
Также можно использовать Consul, Terraform Cloud или GitLab Managed State.

# 4. В чем разница между командами terraform plan и terraform apply?
terraform plan: выполняет "dry-run". Он анализирует ваш код HCL, проверяет
текущий State и реальное облако, а затем выводит список изменений (что
будет добавлено, изменено или удалено). Никаких реальных действий с
инфраструктурой не происходит.
terraform apply: применяет эти изменения. По умолчанию он сначала неявно
делает plan и просит пользователя подтвердить действие вводом "yes".

# 5. Что такое Terraform Providers (Провайдеры)?
Провайдеры — это плагины (библиотеки на Go), которые позволяют Terraform
взаимодействовать с внешними API. Без провайдеров Terraform ничего не
умеет. Существуют провайдеры для AWS, GCP, Kubernetes, GitHub, DNS и
тысяч других сервисов. Провайдер транслирует декларативные HCL-блоки в
конкретные HTTP REST API вызовы.

# 6. Что такое Terraform Modules (Модули) и зачем они нужны?
Модуль — это переиспользуемый контейнер, содержащий группу связанных
ресурсов. Любая папка с файлами .tf является модулем (Root module).
Модули позволяют инкапсулировать логику (например, сложную настройку VPC
с публичными и приватными подсетями), параметризовать ее через переменные
(variables) и использовать этот блок многократно в разных проектах,
чтобы не дублировать код (принцип DRY).

# 7. Как передавать переменные (Variables) в Terraform?
1. Через файлы *.auto.tfvars или terraform.tfvars (загружаются
   автоматически).
2. Через аргументы командной строки: terraform apply -var="region=eu"
3. Через переменные окружения ОС с префиксом TF_VAR_:
   export TF_VAR_region="eu-west-1"
4. Интерактивно: если переменная не задана, Terraform попросит ввести ее
   значение при запуске plan или apply.

# 8. Что такое Data Sources (Источники данных)?
Блок data позволяет Terraform читать информацию о ресурсах, которые
существуют в облаке, но НЕ управляются текущим кодом Terraform (например,
они созданы вручную или в другом проекте). Это позволяет динамически
получать их ID или атрибуты для использования в вашем коде (например,
найти ID нужного Amazon Machine Image (AMI) по имени).

# 9. Как работает команда terraform destroy?
Эта команда удаляет ВСЕ ресурсы, описанные в конфигурации (или в текущем
Workspace/стейт-файле). Она анализирует граф зависимостей и удаляет
ресурсы в правильном порядке (например, сначала виртуалки, затем подсети,
затем VPC, в которой они находились).

# 10. Что делает terraform import?
Позволяет "привязать" (импортировать) уже существующий в облаке ресурс
к состоянию Terraform (State).
Для этого нужно сначала написать пустой блок ресурса в HCL, а затем
выполнить команду terraform import <тип_ресурса>.<имя_ресурса>
<реальный_ID_в_облаке>. После этого ресурс появится в terraform.tfstate,
и им можно будет управлять через код.

# 11. Что такое Terraform Workspaces (Рабочие области)?
Workspaces позволяют использовать ОДНУ И ТУ ЖЕ директорию с
конфигурационным кодом для управления несколькими РАЗНЫМИ стейт-файлами
(например, отдельный стейт для dev, stage и prod).
Переменная terraform.workspace внутри кода позволяет динамически менять
префиксы названий или размеры ресурсов в зависимости от активного
воркспейса.

# 12. В чем разница между Count и For_each?
Оба используются для создания нескольких идентичных ресурсов.
- count принимает число (например, count = 3) и создает ресурсы в виде
  списка (индексируются по номерам: aws_instance.web[0]). Проблема: если
  удалить элемент из середины списка, Terraform сдвинет все индексы и
  может пересоздать ресурсы, которые не нужно было трогать.
- for_each принимает map (словарь) или set (множество) строк. Ресурсы
  индексируются по уникальным строковым ключам (например,
  aws_instance.web["db1"]). При удалении одного элемента другие не
  затрагиваются, поэтому for_each предпочтительнее в большинстве
  сценариев.

# 13. Что такое Provisioners в Terraform?
Provisioners (Провижинеры) позволяют выполнять скрипты на локальной или
удаленной машине (по SSH/WinRM) во время создания или удаления ресурса.
Например, remote-exec выполняет команды на запущенном сервере, а
local-exec — на машине, где запущен Terraform. HashiCorp рекомендует
использовать их только как крайнюю меру (last resort), предпочитая
cloud-init, Packer или Ansible для настройки ОС.

# 14. Что такое State Locking (Блокировка состояния)?
Механизм, предотвращающий одновременное изменение стейт-файла двумя и
более запусками Terraform (что может привести к коррупции стейта). При
старте apply Terraform ставит "замок". Если второй инженер попытается
запустить apply, он получит ошибку блокировки и будет ждать. В AWS это
реализуется через таблицу DynamoDB (поле LockID).

# 15. Что делает команда terraform taint и untaint? (Устарело в новых
версиях)
В старых версиях terraform taint <ресурс> помечал ресурс в стейте как
"испорченный/деградировавший". При следующем apply Terraform
принудительно удалял его и пересоздавал с нуля (даже если код не менялся).
В Terraform 0.15.2 и новее taint объявлен устаревшим (deprecated), и
теперь используется флаг: terraform apply -replace="<ресурс>".

# 16. Что такое lifecycle rules в Terraform?
Блок lifecycle позволяет настраивать особое поведение при
создании/изменении ресурсов.
Например:
- create_before_destroy = true: при изменении, требующем пересоздания,
  Terraform сначала создаст новый ресурс, а потом удалит старый (для
  Zero Downtime).
- prevent_destroy = true: защищает ресурс от случайного удаления
  (Terraform выдаст ошибку, если кто-то попытается его удалить).
- ignore_changes: указывает Terraform игнорировать изменения определенных
  атрибутов, если они были изменены вручную в облаке.

# 17. Как скрыть чувствительные данные в логах Terraform?
Можно пометить переменную как чувствительную: sensitive = true. В этом
случае при выполнении plan или apply её значение будет замаскировано
((sensitive value)) в консольном выводе.
Однако стоит помнить, что в самом файле terraform.tfstate эти данные все
равно будут храниться в открытом виде! (Поэтому стейт нужно шифровать в
S3/Vault).

# 18. В чем разница между Локальными переменными (Locals) и Входными
переменными (Variables)?
Входные переменные (variable) — это аргументы, которые можно передать
модулю извне (от пользователя или из другого модуля).
Локальные переменные (locals) — это временные выражения или константы
внутри самого модуля. Они не могут быть переопределены снаружи. Полезны
для вычисления сложных формул один раз и переиспользования результата
внутри кода, чтобы не нарушать DRY (например, склейка префикса среды с
именем проекта).

# 19. Что такое Terragrunt? Зачем его используют вместе с Terraform?
Terragrunt — это популярная обертка (wrapper) над Terraform от компании
Gruntwork.
Он решает проблемы базового Terraform:
- Позволяет держать код DRY, избавляя от дублирования конфигурации
  бекенда (Remote State) в десятках папок.
- Позволяет управлять зависимостями между модулями (сначала развернуть
  VPC, затем EKS, затем БД) и запускать apply-all на все папки разом.
- Упрощает работу со средами (dev, prod) путем наследования переменных.

# 20. Как написать кастомный Terraform Provider?
Terraform провайдеры пишутся на языке Go. Вы используете Terraform
Plugin SDK (или новый Terraform Plugin Framework). Процесс включает:
1. Определение схемы (Schema) провайдера и его ресурсов.
2. Реализацию функций CRUD (Create, Read, Update, Delete) для каждого
   ресурса. Эти функции будут вызывать API вашего сервиса.
3. Сборку бинарного файла и его подключение к Terraform (локально или
   публикацию в Terraform Registry).

# 21. Что такое Configuration drift? Почему это происходит и как усложняет
жизнь?
Configuration drift (Дрейф конфигурации) — это ситуация, когда
фактическое состояние инфраструктуры (в облаке/на серверах) начинает
отличаться от желаемого состояния, описанного в коде (IaC, Terraform) или
конфигурационных файлах (Ansible).
**Почему происходит:**
Кто-то зашел в веб-консоль AWS (или по SSH на сервер) и вручную изменил
параметр (добавил правило в Security Group, поменял размер диска) для
быстрого "тушения пожара" (hotfix), забыв отразить это в коде.
**Чем опасно:**
При следующем запуске terraform apply Terraform увидит расхождение и
попытается "привести облако к коду", тем самым затерев ручной фикс. Это
может привести к поломке продакшена.
**Как бороться:**
Запретить ручные изменения (сделать инфраструктуру Read-Only для
пользователей в облаке). Регулярно запускать автоматические проверки
(drifctl или регулярный terraform plan в CI), которые будут алертить о
появившихся расхождениях.

# 22. Что такое OpenTofu и почему он появился?
OpenTofu — открытый форк Terraform (аналогично тому, как OpenBao —
форк Vault, см. `04_cicd/03_vault.sh`), созданный после того, как
HashiCorp сменила лицензию Terraform с открытой MPL на BUSL (Business
Source License), ограничивающую коммерческое использование
конкурентами. OpenTofu развивается под эгидой Linux Foundation,
полностью совместим с существующим HCL-кодом и state-файлами
Terraform (это тот же язык и тот же формат state), и добавляет
отдельные свои улучшения (например, встроенную поддержку шифрования
state-файла из коробки, без необходимости полагаться только на
шифрование бэкенда, вопрос 3).

# 23. Что такое Policy as Code в Terraform (Sentinel, OPA)?
Позволяет ЗАПРЕТИТЬ `terraform apply`, если план нарушает заданные
организацией правила — не на уровне синтаксиса HCL, а на уровне
бизнес-логики: "запрещено создавать публичные S3-бакеты",
"инстансы дороже определенного типа нельзя создавать без тега
`cost-center`". Проверка выполняется над СГЕНЕРИРОВАННЫМ планом
(JSON-представлением того, что собирается сделать `terraform apply`)
до реального применения.
- **Sentinel** — проприетарный язык политик HashiCorp, встроен в
  Terraform Cloud/Enterprise.
- **OPA (Open Policy Agent)** с языком **Rego** — открытый
  универсальный движок политик (тот же, что используется для
  Kubernetes Admission Webhooks, см. `03_containers_and_orchestration/
  01_kubernetes.sh`, вопрос 34), подключается к Terraform через
  `conftest` — удобен, если одна и та же политика должна применяться
  и к Terraform-планам, и к Kubernetes-манифестам.

# 24. Как тестировать Terraform-код (`terraform test`, Terratest)?
- **`terraform test`** (встроен начиная с Terraform 1.6) — позволяет
  писать тестовые сценарии на том же HCL в файлах `*.tftest.hcl`:
  выполнить `plan` или реальный `apply` в тестовом окружении и
  проверить через `assert`, что определенные атрибуты ресурса приняли
  ожидаемые значения, а затем автоматически уничтожить созданные
  тестовые ресурсы.
- **Terratest** — сторонняя библиотека на Go (от Gruntwork, тех же
  авторов, что и Terragrunt, вопрос 19): реально разворачивает
  инфраструктуру в тестовом окружении, выполняет HTTP-запросы или
  SSH-команды к созданным ресурсам, чтобы проверить, что
  инфраструктура не просто "создалась без ошибок", а ФАКТИЧЕСКИ
  работает как ожидается, и затем уничтожает ресурсы.
Оба подхода стоят дороже обычных unit-тестов (реально создают
облачные ресурсы, стоят денег и времени), поэтому обычно запускаются
не на каждый коммит, а перед релизом модуля.

# 25. Что такое `moved` и декларативный блок `import` в Terraform?
Оба блока — современная (с Terraform 1.1+ для `moved`, 1.5+ для
`import`) замена ручным CLI-командам, позволяющая описывать операции
над state ПРЯМО В КОДЕ, а не одноразовыми командами в терминале.
```hcl
moved {
  from = aws_instance.web
  to   = aws_instance.web_server
}

import {
  to = aws_instance.legacy
  id = "i-0123456789abcdef0"
}
```
`moved` фиксирует переименование/перемещение ресурса в коде (например,
после рефакторинга модуля) — Terraform поймет, что это ТОТ ЖЕ ресурс,
а не "удалить старый, создать новый", избегая ненужного пересоздания.
`import` делает то же самое, что `terraform import` (вопрос 10), но
декларативно в коде, что можно закоммитить и прогнать через обычный
CI-пайплайн, а не выполнять вручную с конкретным ID ресурса в
терминале разработчика.

# 26. Как правильно версионировать сами модули Terraform/OpenTofu?
Версионирование модулей — ключевая практика Infrastructure as Code. Без
строгого версионирования изменения в коде модуля мгновенно и непредсказуемо
ломают инфраструктуру у всех команд, использующих этот модуль.

1. Семантическое версионирование (SemVer: MAJOR.MINOR.PATCH) модулей:
   - **MAJOR (например, 2.0.0 — Breaking Changes):**
     * Удаление существующей переменной (input variable) или изменение её типа
       (например, string на list).
     * Добавление новой обязательной переменной (без значения default).
     * Удаление или переименование ресурсов без применения блоков `moved`
       (иначе Terraform удалит старый ресурс в облаке и создаст новый с
       потерей данных/даунтаймом!).
     * Изменение структуры выходных данных (outputs), на которые полагаются
       вызывающие модули.
     * Повышение минимальной версии Terraform (`required_version`) или
       провайдеров (`required_providers`), несовместимое со старым кодом.
   - **MINOR (например, 1.1.0 — Backward Compatible):**
     * Добавление новых опциональных переменных с безопасным дефолтом
       (`default = null` или `default = false`).
     * Добавление новых ресурсов, включение которых опционально (через флаг
       `count = var.enable_feature ? 1 : 0`).
     * Добавление новых `outputs`.
   - **PATCH (например, 1.0.1 — Bug Fixes):**
     * Исправление внутренней логики выражений (locals, тернарных операторов)
       без изменения публичного интерфейса (inputs/outputs) и без пересоздания
       существующих ресурсов.

2. Организация репозитория и процесс выпуска релизов (Release Flow):
   - Модули хранятся либо в отдельных Git-репозиториях (по соглашению
     `terraform-<provider>-<name>`, например `terraform-aws-vpc`), либо в
     монорепозитории модулей по каталогам.
   - Релизы фиксируются **аннотированными Git-тегами**:
     `git tag -a v1.2.0 -m "Release v1.2.0: add private subnets support"`
     `git push origin v1.2.0`
   - Автоматизация через CI/CD:
     * Форматирование и статический анализ (`tofu fmt -check`, `tflint`).
     * Автогенерация документации: утилита `terraform-docs` обновляет блок
       таблицы Inputs/Outputs в README.md модуля при каждом коммите.
     * Тестирование: запуск `terraform test` или Terratest на временном
       аккаунте/песочнице перед релизом.
     * Release-автоматизация: утилиты Release Please или semantic-release
       на основе Conventional Commits (`feat:`, `fix:`, `feat!:`) сами
       бампают SemVer, генерируют CHANGELOG.md и ставят Git-тег.

3. Дистрибуция модулей:
   - Через Git-теги:
     `source = "git::https://gitlab.com/org/tf-modules/vpc.git?ref=v1.2.0"`
   - Через Private Registry (Terraform Cloud, GitLab/GitHub Package Registry,
     Artifactory): модуль пакуется в архив (`.tar.gz`), что позволяет
     клиентам использовать нативный синтаксис версий:
     `source  = "gitlab.com/org/vpc/aws"`
     `version = "~> 1.2.0"`

4. Дополнительно: подключение на стороне потребителя и почему опасен master:
   - Ссылка на ветку (`?ref=main` или `?ref=master`) опасна: при любом коммите
     в модуль команда `terraform init -upgrade` утянет свежий код, что может
     привести к неконтролируемому дрифту или удалению ресурсов в проде.
   - Стратегии пиннинга версий:
     * Жёсткий пиннинг (`version = "1.2.0"` или `?ref=v1.2.0`) — обязателен
       для продакшн-контуров.
     * Пессимистичный оператор (`version = "~> 1.2"`) — разрешает минорные
       обновления (1.2.1, 1.3.0), но блокирует ломающую версию 2.0.0.
