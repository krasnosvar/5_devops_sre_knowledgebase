# 1. В чем разница между TCP и UDP?
TCP (Transmission Control Protocol) — это протокол с установкой соединения.
Он гарантирует доставку пакетов (отправляет подтверждения - ACK),
упорядочивает их и восстанавливает при потерях. Подходит для веб-трафика
(HTTP), почты, SSH. UDP (User Datagram Protocol) — это протокол без
установки соединения. Он не гарантирует доставку и порядок пакетов, но
работает значительно быстрее за счет отсутствия накладных расходов.
Используется для видео/аудио стриминга, онлайн-игр, DNS, VoIP.

# 2. Опишите процесс TCP Handshake (трехкратное рукопожатие). Трехкратное
рукопожатие используется для установки TCP-соединения между клиентом и
сервером. 1. Клиент отправляет пакет с флагом SYN (Synchronize) серверу,
указывая свой начальный sequence number. 2. Сервер получает пакет и отвечает
пакетом с флагами SYN и ACK (Acknowledgment), подтверждая получение и
указывая свой sequence number. 3. Клиент получает SYN-ACK и отправляет пакет
с флагом ACK, подтверждая получение ответа от сервера. Соединение
установлено.

# 3. Что происходит, когда вы вводите URL (например, google.com) в браузере?
Это классический глубокий архитектурный вопрос. Если расписывать уровень
SRE/Senior:
1. **Парсинг и HSTS:** Браузер проверяет локальный список HSTS (нужно ли
   сразу идти по HTTPS). Применяет Punycode, если есть не-ASCII символы.
2. **DNS Resolution:** Вызывается библиотечная функция `gethostbyname` (или
   `getaddrinfo`). Она проверяет кэш браузера -> кэш ОС (nscd) ->
   `/etc/hosts` -> шлет UDP пакет (порт 53) к локальному DNS-резолверу. Если
   домен не найден, запрос рекурсивно идет к Root и TLD серверам.
3. **Маршрутизация (ARP/BGP):** Чтобы отправить пакет DNS или TCP, ядро ищет
   MAC-адрес шлюза по умолчанию (Default Gateway) через протокол ARP. На
   уровне интернета пакеты маршрутизируются к ближайшему дата-центру Google
   через протокол BGP и Anycast.
4. **Установка соединения (TCP/IP):** Программа открывает сокет (вызов
   `socket()`, затем `connect()`). Происходит TCP 3-way handshake (SYN,
   SYN-ACK, ACK). Ядро выделяет эфемерный исходящий порт (из диапазона
   `ip_local_port_range`).
5. **TLS Handshake:** Так как это HTTPS, клиент шлет `ClientHello` (со
   списком шифров и SNI). Сервер возвращает `ServerHello` с сертификатом.
   Клиент проверяет цепочку доверия сертификата. Генерируется симметричный
   сессионный ключ (через алгоритмы вроде Diffie-Hellman), далее трафик
   шифруется.
6. **HTTP-запрос и рендеринг:** Отправляется HTTP GET запрос. Сервер
   балансирует его (через L7 балансировщики) к бэкенду. Возвращается HTML.
   Движок браузера парсит HTML, строит DOM-дерево, CSSOM-дерево, формирует
   Render Tree и через GPU отрисовывает пиксели на экране (Rasterization).

# 4. Какие существуют уровни модели OSI?
Модель OSI состоит из 7 уровней:
1. Физический (Physical) — биты по кабелю/радио (Ethernet кабель, оптика).
2. Канальный (Data Link) — кадры (frames), MAC-адреса, коммутаторы
   (Switches).
3. Сетевой (Network) — пакеты, IP-адреса, маршрутизаторы (Routers), ICMP.
4. Транспортный (Transport) — сегменты/датаграммы, порты, TCP/UDP.
5. Сеансовый (Session) — управление сессиями связи.
6. Представительский (Presentation) — кодирование, шифрование (SSL/TLS).
7. Прикладной (Application) — HTTP, FTP, DNS, SMTP.

# 5. Что такое DNS и какие типы записей вы знаете?
DNS (Domain Name System) — система, преобразующая доменные имена
(example.com) в IP-адреса и обратно. Основные типы записей:
- A — указывает IPv4-адрес.
- AAAA — указывает IPv6-адрес.
- CNAME (Canonical Name) — алиас на другое доменное имя. Не может указывать
  на IP и не может быть установлен в корне зоны (apex).
- MX (Mail Exchange) — указывает на почтовые серверы домена.
- TXT — текстовые данные (часто для валидации владения, SPF, DKIM).
- NS (Name Server) — указывает на авторитативные DNS-серверы зоны.
- PTR (Pointer) — обратная зона (IP в имя).

# 6. Что такое BGP и как он работает?
BGP (Border Gateway Protocol) — протокол внешней маршрутизации интернета.
BGP обменивается информацией о маршрутизации между автономными системами
(AS). Вместо выбора самого быстрого маршрута (как OSPF), BGP выбирает
маршрут на основе политик, путей и правил (path-vector protocol), что
позволяет маршрутизировать трафик между различными провайдерами глобально.

# 7. В чем разница между HTTP и HTTPS?
HTTP передает данные в открытом виде (plaintext). HTTPS инкапсулирует HTTP в
криптографический протокол SSL/TLS. Данные шифруются, что обеспечивает
конфиденциальность (защита от прослушивания, MITM), целостность (защита от
изменения) и аутентификацию (сервер подтверждает свою подлинность цифровым
сертификатом).

# 8. Что такое NAT и какие виды бывают?
NAT (Network Address Translation) — механизм трансляции IP-адресов.
Позволяет устройствам с приватными (серыми) IP-адресами выходить в интернет
через один или несколько публичных адресов. Виды:
- Static NAT (1 к 1)
- Dynamic NAT (пул серых к пулу белых)
- PAT (Port Address Translation / NAT Overload) — самый частый вид (много к
  одному), трансляция происходит за счет подмены портов источника
  (masquerade).

# 9. Какие существуют классы и диапазоны частных (серых) IP-адресов по RFC
1918?
- Класс A: 10.0.0.0 — 10.255.255.255 (маска /8)
- Класс B: 172.16.0.0 — 172.31.255.255 (маска /12)
- Класс C: 192.168.0.0 — 192.168.255.255 (маска /16) Эти адреса не
  маршрутизируются в публичном интернете.

# 10. Что такое Anycast?
Anycast — метод маршрутизации, при котором один и тот же IP-адрес
назначается нескольким узлам (серверам), физически расположенным в разных
местах. Запрос пользователя направляется маршрутизаторами (через BGP) на
ближайший (с топологической точки зрения) к нему узел. Часто используется в
CDN и корневых DNS.

# 11. Что означает маска подсети, например, /24?
/24 (CIDR нотация) означает, что первые 24 бита IP-адреса выделены под адрес
сети (соответствует маске 255.255.255.0). Оставшиеся 8 бит используются для
адресации хостов, что дает 256 адресов (254 доступных для устройств, т.к.
первый — адрес сети, последний — broadcast).

# 12. Как работает утилита traceroute (tracert)?
traceroute отслеживает маршрут пакетов до целевого хоста. Он использует поле
TTL (Time To Live) в IP-пакете. Сначала отправляет пакет с TTL=1. Первый
маршрутизатор уменьшает TTL до 0 и возвращает ICMP-ответ "Time Exceeded".
traceroute записывает адрес этого маршрутизатора и отправляет следующий
пакет с TTL=2, достигая второго маршрутизатора, и так далее, пока пакет не
достигнет цели (цель ответит ICMP Echo Reply или Port Unreachable).

# 13. Что такое VLAN и зачем он нужен?
VLAN (Virtual Local Area Network) — виртуальная локальная сеть. Механизм
канального уровня (L2), позволяющий логически разделить одну физическую сеть
на несколько изолированных широковещательных доменов (broadcast domains).
Повышает безопасность и уменьшает количество широковещательного трафика.

# 14. Как работает ARP?
ARP (Address Resolution Protocol) — протокол, преобразующий IP-адрес (L3) в
MAC-адрес (L2) в локальной сети. Устройство отправляет широковещательный
запрос (broadcast): "У кого IP 192.168.1.10? Сообщите мне". Устройство с
этим IP отвечает своим MAC-адресом. Полученные данные кэшируются (ARP
table).

# 15. Чем отличается L3-балансировщик от L7-балансировщика?
- L3/L4 балансировщик (например, IPVS, HAProxy в tcp mode) работает на
  сетевом и транспортном уровнях. Он перенаправляет трафик, основываясь на
  IP и портах, не читая содержимое пакетов. Работает очень быстро, но не
  может принимать решения на основе URL или Cookie.
- L7 балансировщик (например, Nginx, HAProxy, Ingress Controller) работает
  на прикладном уровне (HTTP/HTTPS). Он полностью читает запрос и может
  маршрутизировать трафик на основе URL-путей, заголовков, доменов (Host
  header) и Cookie. Требует больше ресурсов (TLS termination).

# 16. Что такое MTU и MSS?
MTU (Maximum Transmission Unit) — максимальный размер полезного блока данных
одного пакета (L2 фрейма), который может быть передан по сети без
фрагментации (обычно 1500 байт для Ethernet). MSS (Maximum Segment Size) —
максимальный размер сегмента TCP (полезная нагрузка), вычисляется как MTU
минус заголовки IP (20 байт) и TCP (20 байт). Обычно MSS = 1460 байт.

# 17. Что такое CDN и зачем она нужна?
CDN (Content Delivery Network) — географически распределенная сеть серверов,
предназначенная для кэширования и доставки статического контента
(изображения, скрипты, видео) пользователям из ближайшей к ним локации.
Уменьшает задержки (latency), снижает нагрузку на origin-сервер и защищает
от DDoS.

# 18. В чем суть атаки DDoS и какие основные типы существуют?
DDoS (Distributed Denial of Service) — атака, направленная на исчерпание
ресурсов сервера или канала связи, делающая ресурс недоступным для
легитимных пользователей. Типы:
- Объемные (Volumetric) - UDP floods, NTP/DNS amplification (забивают полосу
  пропускания).
- Сетевые (Protocol) - SYN floods (исчерпывают таблицы состояний фаерволов и
  серверов).
- Прикладные (Application Layer L7) - HTTP floods (генерация сложных
  запросов для перегрузки CPU/RAM сервера или БД).

# 19. Что такое SNI?
SNI (Server Name Indication) — расширение протокола TLS. Оно позволяет
клиенту передать доменное имя, к которому он пытается подключиться, еще во
время TLS handshake. Это позволяет одному веб-серверу (одному IP-адресу)
хостить несколько HTTPS-сайтов с разными SSL-сертификатами.

# 20. Как происходит завершение TCP-соединения (TCP Teardown)?
TCP завершает соединение с помощью 4 шагов (четырехкратное рукопожатие):
1. Инициатор (клиент) отправляет FIN-пакет.
2. Получатель (сервер) отвечает ACK. (В этот момент полузакрытое соединение,
   сервер еще может передавать данные).
3. Сервер отправляет свой FIN-пакет.
4. Клиент отвечает ACK. Соединение полностью закрыто.

# 21. Какие сетевые топологии вы знаете?
- **Шина (Bus):** Все компьютеры подключены к одному общему кабелю. Дешево,
  но низкая надежность (разрыв кабеля валит всю сеть) и коллизии.
- **Звезда (Star):** Все устройства подключены к центральному узлу
  (коммутатору/хабу). Самая частая современная топология. Легко
  масштабируется, обрыв одного провода не влияет на остальных.
- **Кольцо (Ring):** Узлы соединены последовательно, образуя замкнутое
  кольцо. Данные передаются по кругу (Token Ring).

# 22. Зачем нужен IP-адрес, если MAC-адрес уникален аппаратно?
MAC-адрес работает на уровне L2 и абсолютно плоский (иерархии нет). Если бы
интернет работал только на MAC-адресах, коммутаторам пришлось бы хранить в
памяти таблицы с миллиардами MAC-адресов со всего мира, и каждый
широковещательный ARP-запрос рассылался бы по всей планете, вызывая
"широковещательный шторм". IP-адрес (L3) имеет иерархическую структуру (сети
и подсети). Это позволяет маршрутизаторам использовать агрегацию маршрутов
(например, "все пакеты для 192.168.0.0/16 отправлять на этот порт"), что
делает глобальную маршрутизацию физически возможной.

# 23. В чем разница между Hub (Концентратором) и Switch (Коммутатором L2)?
- **Hub:** Работает на L1 (Физическом уровне). Это просто "тройник". Получая
  кадр на один порт, он бездумно дублирует и рассылает его на ВСЕ остальные
  порты. Это делит общую пропускную способность на всех и создает кучу
  коллизий (полудуплекс).
- **Switch:** Работает на L2 (Канальном уровне). Он интеллектуален, изучает
  MAC-адреса и строит CAM-таблицу. Получая кадр, коммутатор отправляет его
  ТОЛЬКО на тот порт, где находится получатель. Обеспечивает полный дуплекс
  и отсутствие коллизий.

# 24. Что такое шлюз по умолчанию (Default Gateway)?
Это IP-адрес маршрутизатора (роутера) в локальной сети. Если устройство
хочет отправить пакет на IP-адрес, который не входит в его собственную
локальную подсеть (то есть находится в интернете или другой VLAN), оно
отправляет этот пакет на шлюз по умолчанию, чтобы тот передал его дальше.

# 25. Что такое атака DHCP Rogue Server и как от нее защититься?
Злоумышленник запускает в вашей сети свой "левый" DHCP-сервер (Rogue).
Устройства в сети начинают получать от него IP-адреса и настройки, где в
качестве шлюза по умолчанию указан компьютер хакера. Трафик уходит хакеру
(атака Man-In-The-Middle). **Защита:** Настройка функции `DHCP Snooping` на
L2-коммутаторах. Администратор указывает "доверенные" порты (где реально
висит настоящий DHCP-сервер). Коммутатор блокирует любые ответы DHCP,
приходящие со всех остальных (недоверенных) портов.

# 26. У сервера две сетевые карты (NIC). Как объединить их для увеличения
пропускной способности и отказоустойчивости?
Использовать агрегацию каналов (Bonding в Linux / LACP - Link Aggregation
Control Protocol, 802.3ad). Технология LACP позволяет логически объединить
несколько физических линков в один виртуальный (bond0). Если один кабель
порвется, трафик пойдет по второму без прерывания связи. Также это
балансирует нагрузку между кабелями. Важно, чтобы коммутатор, в который
воткнуты провода, также поддерживал и был настроен на LACP.

# 27. Какой порт использует утилита PING?
Никакой. PING использует протокол ICMP (Internet Control Message Protocol),
который работает на сетевом уровне (L3). Понятие "порт" существует только на
транспортном уровне (L4) для TCP и UDP.

# 28. На каком уровне модели OSI работает iptables?
`iptables` (точнее, подсистема `Netfilter` в ядре Linux, которой он
управляет) — это межсетевой экран сетевого уровня (L3) и транспортного
уровня (L4).
- На L3 он фильтрует пакеты по IP-адресам источника и назначения (протокол
  IP).
- На L4 он фильтрует по портам источника и назначения (TCP/UDP), а также
  может отслеживать состояния соединений (ESTABLISHED, RELATED) через модуль
  conntrack. Некоторые расширения (например, `string` или `u32`) позволяют
  заглядывать в payload пакета (L7), но концептуально это инструмент L3/L4.
  Важно помнить: сам `iptables` — это утилита в user space, а фильтрация
  пакетов реально происходит внутри ядра (kernel space).

# 29. В чем эволюция и ключевые различия версий HTTP (HTTP/1.0, HTTP/1.1,
HTTP/2, HTTP/3)?
Развитие протокола HTTP шло по пути снижения задержек (latency), решения
проблем блокировок и оптимизации утилизации транспортного уровня:

1. **HTTP/1.0 (RFC 1945):**
   - На каждый запрос открывалось отдельное TCP-соединение, которое
     закрывалось сервером сразу после передачи ответа (`Connection: close`).
   - Огромный overhead: загрузка страницы с десятками ресурсов требовала
     десятков TCP 3-way handshakes и прохождения фазы медленного старта
     (TCP Slow Start) для каждого объекта, что критично увеличивало RTT.

2. **HTTP/1.1 (RFC 2616 / RFC 9112):**
   - **Keep-Alive по умолчанию:** переиспользование одного TCP-соединения
     для серии запросов (`Connection: keep-alive`), снизившее RTT.
   - **Head-of-Line (HoL) Blocking на уровне приложения:** запросы и
     ответы в рамках одного TCP-соединения обрабатываются строго
     последовательно. Если первый запрос «завис» (тяжелый SQL/бэкенд),
     все последующие ждут. Попытка решить это через Pipelining провалилась
     из-за проблем с промежуточными прокси.
   - Браузеры обходили это открытием до 6–8 параллельных TCP-соединений к
     одному хосту, расходуя память ядра под сокетные буферы (`tcp_rmem`,
     `tcp_wmem`) и перегружая сетевые таблицы.
   - Протокол текстовый. Заголовки не сжимаются и дублируются в каждом
     запросе (Cookie, User-Agent). Появились заголовок `Host` (виртуальные
     хосты на одном IP) и Chunked Transfer Encoding.

3. **HTTP/2 (RFC 7540 / RFC 9113):**
   - **Бинарное фреймирование (Binary Framing):** данные разбиваются на
     типизированные бинарные фреймы (HEADERS, DATA, SETTINGS, RST_STREAM).
   - **Мультиплексирование (Multiplexing):** передача параллельных запросов
     и ответов через ОДНО TCP-соединение. Кадры разных потоков (Streams со
     своим Stream ID) перемежаются и собираются на стороне получателя,
     полностью устраняя Application-level HoL Blocking.
   - **HPACK:** сжатие заголовков с помощью статической и динамической таблиц
     и кодирования Хаффмана, что радикально сокращает размер метаданных.
   - Приоритезация потоков, отмена потоков (`RST_STREAM`) без разрыва TCP и
     Server Push.
   - **Главное ограничение — HoL Blocking на уровне TCP:** протокол
     работает поверх одного TCP-потока байтов. Если в сети теряется один
     TCP-сегмент, ядро ОС приостанавливает отдачу последующих байтов из
     буфера (`sk_buff`) в user space до прихода ретрансмита. В итоге потеря
     одного пакета блокирует ВСЕ потоки HTTP/2 внутри соединения.

4. **HTTP/3 (RFC 9114) и протокол QUIC (RFC 9000):**
   - **Транспорт поверх UDP:** полный отказ от TCP в пользу протокола QUIC,
     работающего в пространстве пользователя (user space) поверх UDP.
   - **Устранение транспортного HoL Blocking:** надежность и порядок доставки
     контролируются отдельно для каждого независимого потока QUIC. Потеря
     пакета одного потока задерживает только его, остальные потоки
     продолжают обрабатываться приложением без задержек.
   - **Встроенный TLS 1.3:** криптографическое рукопожатие объединено с
     транспортным. Соединение устанавливается за 1 RTT (вместо 2-3 RTT в
     TCP + TLS), а для повторных сессий доступен 0-RTT (Early Data).
   - **Connection Migration:** соединение привязано не к 4-tuple (IP и порты),
     а к 64/128-битному `Connection ID`. При переключении сети клиента
     (например, Wi-Fi -> LTE) соединение не рвется и не требует handshake.
   - **QPACK:** новый алгоритм сжатия заголовков, адаптированный под
     неупорядоченную доставку потоков без взаимных блокировок.
   - **Нюансы эксплуатации в SRE:** файрволы и middleboxes могут блокировать
     или шейпить UDP:443; обнаружение поддержки HTTP/3 клиентом происходит
     через отдачу заголовка `Alt-Svc` поверх существующего HTTP/2.

