# 1. Что такое DevSecOps и в чем его главное отличие от традиционной ИБ (Информационной
Безопасности)?
DevSecOps (Development, Security, Operations) — это философия интеграции практик безопасности на
всех этапах жизненного цикла разработки ПО (SDLC), а не только перед релизом.
Главное отличие: традиционная ИБ (InfoSec) обычно проверяет продукт на уязвимости в самом конце
(выступая "бутылочным горлышком"), а DevSecOps реализует принцип Shift-Left — сдвиг проверок влево
по времени (как можно раньше). Безопасность автоматизируется и встраивается в CI/CD-пайплайны.

# 2. Что такое SAST (Static Application Security Testing)?
SAST (Статический анализ) — это анализ исходного кода приложения на наличие уязвимостей
(SQL-инъекции, XSS, хардкод паролей, buffer overflow) без его запуска (White Box тестирование).
Интегрируется в CI пайплайн (например, SonarQube, Checkmarx). Основной минус — много ложных
срабатываний (False Positives).

# 3. Что такое DAST (Dynamic Application Security Testing)?
DAST (Динамический анализ) — это тестирование уже запущенного приложения извне (Black Box). Сканер
отправляет приложению вредоносные HTTP-запросы (SQL инъекции в формы логина, вредоносные куки) и
анализирует ответы. Преимущество — показывает реальные уязвимости, которые можно эксплуатировать.
Часто запускается на staging-окружении. (Примеры: OWASP ZAP, Burp Suite).

# 4. Что такое SCA (Software Composition Analysis)?
SCA — это процесс анализа открытых библиотек и компонентов (open-source dependencies), используемых
в проекте, на наличие известных уязвимостей (CVE). Инструменты (Snyk, OWASP Dependency-Check, Trivy)
проверяют `package.json`, `requirements.txt` или `go.mod` и сверяют версии библиотек с базами
уязвимостей (NVD).

# 5. Что такое CVE и CVSS?
CVE (Common Vulnerabilities and Exposures) — это глобальная база данных (словарь) публично известных
уязвимостей информационной безопасности. Каждой уязвимости присваивается номер, например
`CVE-2021-44228` (знаменитая Log4Shell).
CVSS (Common Vulnerability Scoring System) — открытый стандарт оценки критичности уязвимости (от 0
до 10). Учитывает вектор атаки, сложность, влияние на конфиденциальность, целостность и доступность.

# 6. Что такое OWASP Top 10?
Это регулярно обновляемый список 10 самых критичных и распространенных рисков безопасности
веб-приложений, составляемый организацией OWASP. На него ориентируются все безопасники. Включает
такие уязвимости как: Injection (инъекции), Broken Authentication (сломанная аутентификация),
Sensitive Data Exposure, XSS, SSRF и т.д.

# 7. Что такое SQL-инъекция и как от нее защититься?
SQL Injection — вид атаки, при которой злоумышленник вставляет произвольный SQL-код в поля ввода,
который затем выполняется базой данных (например, ввод `' OR 1=1 --` вместо логина). Это позволяет
украсть или удалить базу данных.
Защита: никогда не конкатенировать (не склеивать) строки SQL-запроса вручную. Использовать
параметризованные запросы (Prepared Statements) или ORM, где параметры передаются отдельно от самого
запроса и безопасно экранируются.

# 8. Что такое XSS (Cross-Site Scripting)?
Межсайтовый скриптинг — атака, при которой злоумышленник внедряет вредоносный JavaScript-код на
легитимную веб-страницу, которую просматривают другие пользователи. Код выполняется в их браузере и
может украсть их Cookies, токены сессий или перенаправить на фишинговый сайт. Защита — строгая
санитизация и эскейпинг ввода и вывода, использование Content Security Policy (CSP).

# 9. Как работает MFA (Multi-Factor Authentication)?
Многофакторная аутентификация требует от пользователя предоставления двух или более доказательств
(факторов) для входа.
Факторы бывают трех видов:
1. Знание (то, что вы знаете) — пароль, PIN-код.
2. Владение (то, что у вас есть) — смартфон (SMS, Authenticator app), аппаратный токен (YubiKey).
3. Биометрия (то, чем вы являетесь) — отпечаток пальца, FaceID.
Если пароль украдут (MFA bypass), злоумышленник не сможет зайти без второго фактора.

# 10. Что такое Zero Trust (Нулевое доверие)?
Архитектура безопасности, основанная на принципе "никогда не доверяй, всегда проверяй" (Never trust,
always verify). Традиционный подход: всё, что внутри корпоративной сети (VPN), надежно. Zero Trust
подход: нет разницы, находитесь вы внутри офисной сети или в кафе; каждый запрос, пользователь и
устройство должны быть аутентифицированы, авторизованы и проверены перед доступом к ЛЮБОМУ ресурсу.

# 11. Что такое Secrets Management и почему нельзя хранить секреты в Git?
Хранение паролей (БД, API, AWS) в открытом виде в коде ведет к их мгновенной компрометации (особенно
если репозиторий публичный). Любой сотрудник с доступом к коду может забрать базу.
Secrets Management — процесс безопасного управления секретами с использованием специализированных
хранилищ (HashiCorp Vault, AWS Secrets Manager). Приложения запрашивают временные секреты по API, а
Vault шифрует их, регулярно ротирует и ведет аудит (кто и когда их читал).

# 12. Что такое контейнерная безопасность и зачем использовать Trivy или Clair?
Контейнеры (Docker-образы) собираются из базовых ОС (Debian, Alpine) и часто содержат системные
уязвимости.
Инструменты вроде Trivy, Clair или Anchore сканируют слои Docker-образа перед деплоем на наличие CVE
в системных пакетах (apt, apk). Это нужно делать в CI-пайплайне. Если найдена критическая уязвимость
(High/Critical) — сборка (пайплайн) должна падать (fail).

# 13. Что такое WAF (Web Application Firewall)?
WAF — файрвол, защищающий веб-приложения на прикладном (L7) уровне модели OSI. В отличие от обычного
сетевого файрвола (который просто открывает порт 80), WAF глубоко инспектирует содержимое
HTTP-запросов (GET, POST параметры) и блокирует типичные атаки из списка OWASP Top 10 (SQLi, XSS), а
также ботов и DDoS-атаки уровня приложения.

# 14. Как защитить Kubernetes-кластер (K8s Security Best Practices)?
- Обновлять K8s до последних версий.
- Использовать RBAC (принцип наименьших привилегий).
- Network Policies: по умолчанию в K8s все поды могут общаться друг с другом. Нужно явно запрещать
  несанкционированный сетевой трафик.
- Не запускать контейнеры с флагом `--privileged` и от пользователя `root`. (Настроить Pod Security
  Standards/Admission Controllers).
- Включить Audit Logs (аудит API-сервера).

# 15. В чем разница между Аутентификацией и Авторизацией?
- Аутентификация (Authentication, AuthN): проверка ТОГО, КЕМ вы являетесь (Проверка пароля, логина,
  биометрии). "Ты Джон?".
- Авторизация (Authorization, AuthZ): проверка ТОГО, ЧТО вам разрешено делать (Проверка прав
  доступа, ролей RBAC). "Можно ли Джону удалить эту базу данных?".

# 16. Что такое DDoS Amplification attack (Атака усиления)?
Это вид DDoS-атаки (обычно через UDP-протоколы типа NTP или DNS), когда злоумышленник отправляет
небольшой запрос на уязвимый публичный сервер с подмененным (Spoofed) IP-адресом жертвы. Сервер
формирует огромный ответ (в десятки раз больше запроса) и отправляет его на IP-адрес жертвы,
перегружая ее канал связи при минимальных затратах со стороны хакера.

# 17. Что такое CSPM (Cloud Security Posture Management)?
Это класс решений для автоматического сканирования облачной инфраструктуры (AWS, GCP, Azure) на
предмет мисконфигураций (неверных настроек). Например, CSPM-система найдет открытый всем в интернете
S3-бакет, отсутствующую MFA у администратора или открытый порт 22 (SSH) для 0.0.0.0/0.

# 18. Почему важно подписывать Docker-образы (Notary / Cosign)?
Если образ не подписан, кто-то (хакер) может подменить образ в Docker Registry, и сервер скачает
вредоносный код. Подписание (Image Signing) гарантирует целостность (что код не был изменен) и
подлинность (кто именно его собрал). K8s с помощью Admission Controller может проверять цифровые
подписи перед запуском подов (разрешать только подписанные доверенным ключом).

# 19. Что такое SSRF (Server-Side Request Forgery)?
Это уязвимость, при которой злоумышленник заставляет веб-сервер выполнить сетевой запрос от своего
(сервера) имени к внутренним ресурсам, которые в обычных условиях недоступны снаружи. Например, к
внутреннему серверу баз данных, административной панели во внутренней сети или, что очень опасно в
облаке, к внутреннему metadata-серверу AWS (169.254.169.254) для кражи IAM-токенов виртуалки.

# 20. Как работают SBOM (Software Bill of Materials)?
SBOM — это "спецификация" (список ингредиентов) для программного обеспечения. Это машиночитаемый
файл (форматы SPDX, CycloneDX), в котором перечислены все библиотеки, зависимости и компоненты, из
которых собрано приложение. Позволяет компаниям быстро понять, подвержены ли их системы новым
CVE-уязвимостям (например, как это было с Log4j), просто проверив SBOM, а не сканируя весь код
заново.
