# 1. В чем разница между Continuous Integration (CI) и Continuous Deployment/Delivery (CD)?
CI (Непрерывная интеграция) — это процесс автоматической сборки, тестирования и проверки кода после
каждого коммита в репозиторий. Цель — быстро находить баги и конфликты слияния.
CDelivery (Непрерывная доставка) — процесс, при котором код готов к деплою в продакшен в любой
момент, но сам релиз происходит по нажатию кнопки (вручную).
CDeployment (Непрерывное развертывание) — полностью автоматизированный процесс, где каждый успешный
коммит, прошедший тесты, автоматически попадает на продакшен-сервер без участия человека.

# 2. Что такое пайплайн (Pipeline) и из каких этапов он обычно состоит?
Pipeline — это набор автоматизированных шагов (стадий), которые проходит код от коммита до
продакшена.
Типичные этапы:
1. Checkout (скачивание кода).
2. Build (компиляция, сборка Docker-образа, установка зависимостей).
3. Test (юнит-тесты, интеграционные тесты, линтеры, SAST).
4. Publish/Push (загрузка артефактов в репозиторий, например Nexus или Docker Registry).
5. Deploy (развертывание на staging или prod окружении).

# 3. Как организовать безопасное хранение секретов в CI/CD (пароли от БД, токены)?
Никогда не хранить секреты в открытом виде в Git-репозитории!
Нужно использовать:
- Встроенные механизмы CI/CD систем (GitLab CI/CD Variables с флагом Masked и Protected, Jenkins
  Credentials, GitHub Secrets).
- Внешние системы управления секретами (HashiCorp Vault, AWS Secrets Manager), которые пайплайн
  будет запрашивать во время выполнения по временным токенам (например, через JWT аутентификацию).

# 4. Что такое GitOps?
GitOps — это парадигма Continuous Deployment (преимущественно для Kubernetes), где Git является
единственным источником истины (Single Source of Truth) для инфраструктуры и приложений.
Вместо того чтобы CI-система "пушила" изменения в кластер (Push model), в кластере стоит агент
(например, ArgoCD или Flux), который постоянно "тянет" (Pull model) манифесты из Git и приводит
кластер к желаемому состоянию.

# 5. Как ускорить выполнение CI/CD пайплайна?
- Использовать кэширование зависимостей (node_modules, .m2, go_modules).
- Кэшировать Docker-слои (Docker Build Cache, флаг --cache-from).
- Запускать независимые тесты и задачи параллельно (Parallel jobs).
- Использовать легковесные и заранее подготовленные Docker-образы для раннеров.
- Пропускать пайплайны для изменений в README (например, [skip ci] в коммите).
- Настроить шардирование долгих интеграционных тестов.

# 6. В чем разница между Jenkins и GitLab CI?
Jenkins:
- Классический, open-source, устанавливается отдельно.
- Основан на плагинах (очень гибкий, но плагины часто ломаются при обновлениях).
- Пайплайны пишутся на Groovy (Jenkinsfile).
- Нет встроенного Git-хостинга.
GitLab CI:
- Интегрирован прямо в GitLab (все в одном флаконе: код + CI + Registry).
- Конфигурация пишется в удобном YAML (.gitlab-ci.yml).
- Раннеры (GitLab Runners) легко запускать в контейнерах.
- Работает по умолчанию быстрее и стабильнее из-за меньшей зависимости от плагинов.

# 7. Что такое Runner / Agent в контексте CI/CD?
Это отдельный сервер или контейнер, который фактически выполняет задачи (jobs), описанные в вашем
пайплайне.
Система CI (мастер) только управляет очередью и логами, а раннеры забирают задачи и выполняют
сборку/тесты на своих ресурсах. Раннеры бывают shared (общие для всех) и specific (для конкретных
проектов).

# 8. Что такое Blue/Green Deployment?
Это стратегия развертывания без даунтайма. 
Существуют два идентичных окружения: Blue (текущий продакшен, обслуживает пользователей) и Green
(новое, с обновленной версией). Деплой происходит на Green, там же проходят тесты (Smoke tests).
Если всё хорошо, балансировщик нагрузки (или Ingress) мгновенно переключает весь трафик на Green.
Если что-то пошло не так, трафик так же быстро переключается обратно на Blue.

# 9. Что такое Canary Deployment (Канареечный релиз)?
Стратегия деплоя, при которой новая версия приложения выкатывается не на всех сразу, а на небольшой
процент пользователей (например, 5% трафика). Если в течение заданного времени метрики (ошибки 5xx,
задержки) остаются в норме, трафик постепенно увеличивают до 100%. Это минимизирует масштаб
проблемы, если новая версия содержит критический баг.

# 10. Как работает кэш (cache) и артефакты (artifacts) в GitLab CI? В чем разница?
Кэш (Cache): используется для ускорения сборки путем сохранения скачанных зависимостей (npm, pip)
между запусками ОДНОЙ И ТОЙ ЖЕ джобы. Не гарантируется его наличие.
Артефакты (Artifacts): файлы (например, скомпилированные бинарники, отчеты о тестах), созданные в
одной джобе, которые ПЕРЕДАЮТСЯ в СЛЕДУЮЩИЕ джобы по пайплайну или сохраняются для скачивания
пользователем. Артефакты гарантированно сохраняются.

# 11. Что означает концепция "Shift Left" в DevOps / CI/CD?
"Сдвиг влево" означает перенос проверок качества (тестирование) и безопасности (SecOps) на более
ранние этапы разработки (влево по временной шкале пайплайна). То есть, ошибки ищутся не перед
релизом на продакшен, а во время локальной разработки или сразу при коммите (с помощью SAST,
линтеров, pre-commit хуков). Это значительно удешевляет стоимость исправления багов.

# 12. Какие виды тестирования вы знаете в контексте CI?
- Юнит-тесты (Unit tests): проверяют отдельные функции/классы в изоляции (самые быстрые).
- Интеграционные тесты (Integration): проверяют взаимодействие нескольких модулей или работу с БД.
- E2E (End-to-End): полная эмуляция действий пользователя через интерфейс.
- Smoke тесты (Дымовые): быстрые базовые проверки после деплоя (работает ли главная страница?).
- Тесты производительности (Load/Stress testing).

# 13. Что такое DAST и SAST в пайплайнах?
SAST (Static Application Security Testing) — статический анализ исходного кода на предмет известных
уязвимостей без его запуска (например, поиск захардкоженных паролей, SQL инъекций в коде).
DAST (Dynamic Application Security Testing) — динамический анализ. Инструмент пытается "взломать"
уже запущенное работающее приложение (отправляет вредоносные HTTP-запросы) извне.

# 14. Как передать данные между разными Stage в GitLab CI?
Используя Artifacts. В первой джобе объявляется путь к файлу/папке, который нужно сохранить в
артефакты. GitLab загрузит их на сервер. Во второй джобе на следующем стейдже эти артефакты будут
скачаны автоматически (по умолчанию, если не указано `dependencies: []`), и скрипт сможет с ними
работать.

# 15. Как запустить CI/CD пайплайн только при создании тега (Release)?
В конфигурации пайплайна нужно использовать правила ветвления (rules или only).
Пример GitLab CI:
```yaml
deploy_prod:
  rules:
    - if: $CI_COMMIT_TAG
```
В GitHub Actions: `if: startsWith(github.ref, 'refs/tags/')`.

# 16. Что такое Immutable Infrastructure?
Неизменяемая инфраструктура — это подход, при котором сервера (или контейнеры) никогда не
модифицируются после создания. Если нужно обновить конфигурацию или код, существующий сервер не
патчится (никаких apt-get upgrade или Ansible на лету), а полностью уничтожается и заменяется новым,
созданным из обновленного базового образа (AMI в AWS или Docker Image).

# 17. Как вы справляетесь с flaky tests (мигающими тестами) в CI?
Flaky test — тест, который то проходит, то падает при одном и том же коде.
- Повторные запуски (retries): временный костыль, разрешающий CI пройти, если тест прошел со 2-3
  раза.
- Помещение в карантин: исключение теста из блокирующих проверок, пока разработчики его не починят.
- Улучшение окружения: часто мигающие тесты связаны с сетевыми задержками, гонками в БД (race
  conditions) или нехваткой CPU на раннере.

# 18. В чем недостаток использования тэга "latest" для Docker-образов в CI/CD?
`latest` — это просто указатель на последнюю собранную версию. Если деплоить по `latest`, то:
1. Вы не знаете точно, какая версия кода сейчас работает на проде.
2. В случае сбоя невозможно быстро сделать rollback на предыдущую версию, так как она уже
   перезаписана.
Всегда нужно использовать уникальные тэги (хеш коммита Git, версию SemVer, пайплайн ID).

# 19. Что делает команда gitlab-runner register?
Эта команда связывает сервер (где установлен раннер) с инстансом GitLab. В процессе регистрации
указывается URL GitLab, регистрационный токен проекта или группы, тэги (tags) для выбора нужных
задач, и Executor (например, docker, shell, kubernetes).

# 20. Что такое ChatOps?
ChatOps — это управление CI/CD, деплоем и мониторингом прямо из корпоративного чата (Slack,
Telegram) с помощью ботов. Разработчик пишет боту команду: `/deploy frontend v1.2 to prod`, бот
триггерит пайплайн, а затем возвращает результат в тот же чат. Это повышает прозрачность процессов
для всей команды.
