# 1. Что такое Terraform и как он работает?
Terraform — это open-source инструмент для Infrastructure as Code (IaC). Он позволяет декларативно
описывать желаемое состояние облачной инфраструктуры (сети, серверы, БД) в конфигурационных файлах
(HCL - HashiCorp Configuration Language). Terraform сравнивает текущее состояние инфраструктуры с
желаемым и формирует план действий (Plan) для достижения желаемого состояния, а затем применяет его
(Apply), вызывая API провайдеров.

# 2. Что такое State-файл (terraform.tfstate) и зачем он нужен?
State-файл — это локальный (или удаленный) JSON файл, в котором Terraform сохраняет текущее
состояние управляемых им ресурсов и маппинг (соответствие) между ресурсами в коде и реальными
объектами в облаке (их ID, атрибуты). Без него Terraform не знал бы, какие ресурсы он уже создал, и
при каждом запуске пытался бы создать их заново.

# 3. Как безопасно хранить Terraform State при командной работе?
Используются Remote Backends (Удаленные бекенды).
Хранить State в Git небезопасно (там могут быть секреты в открытом виде) и неудобно для совместной
работы из-за отсутствия блокировок (State Locking).
Обычно стейт хранят в AWS S3 бакете (с версионированием и шифрованием), а блокировку от
одновременных запусков настраивают через DynamoDB таблицу. Также можно использовать Consul,
Terraform Cloud или GitLab Managed State.

# 4. В чем разница между командами terraform plan и terraform apply?
`terraform plan`: выполняет "dry-run". Он анализирует ваш код HCL, проверяет текущий State и
реальное облако, а затем выводит список изменений (что будет добавлено, изменено или удалено).
Никаких реальных действий с инфраструктурой не происходит.
`terraform apply`: применяет эти изменения. По умолчанию он сначала неявно делает `plan` и просит
пользователя подтвердить действие вводом "yes".

# 5. Что такое Terraform Providers (Провайдеры)?
Провайдеры — это плагины (библиотеки на Go), которые позволяют Terraform взаимодействовать с
внешними API. Без провайдеров Terraform ничего не умеет. Существуют провайдеры для AWS, GCP,
Kubernetes, GitHub, DNS и тысяч других сервисов. Провайдер транслирует декларативные HCL-блоки в
конкретные HTTP REST API вызовы.

# 6. Что такое Terraform Modules (Модули) и зачем они нужны?
Модуль — это переиспользуемый контейнер, содержащий группу связанных ресурсов. Любая папка с файлами
`.tf` является модулем (Root module).
Модули позволяют инкапсулировать логику (например, сложную настройку VPC с публичными и приватными
подсетями), параметризовать ее через переменные (variables) и использовать этот блок многократно в
разных проектах, чтобы не дублировать код (принцип DRY).

# 7. Как передавать переменные (Variables) в Terraform?
1. Через файлы `*.auto.tfvars` или `terraform.tfvars` (загружаются автоматически).
2. Через аргументы командной строки: `terraform apply -var="region=eu-west-1"`.
3. Через переменные окружения ОС с префиксом `TF_VAR_`: `export TF_VAR_region="eu-west-1"`.
4. Интерактивно: если переменная не задана, Terraform попросит ввести ее значение при запуске `plan`
   или `apply`.

# 8. Что такое Data Sources (Источники данных)?
Блок `data` позволяет Terraform читать информацию о ресурсах, которые существуют в облаке, но НЕ
управляются текущим кодом Terraform (например, они созданы вручную или в другом проекте). Это
позволяет динамически получать их ID или атрибуты для использования в вашем коде (например, найти ID
нужного Amazon Machine Image (AMI) по имени).

# 9. Как работает команда terraform destroy?
Эта команда удаляет ВСЕ ресурсы, описанные в конфигурации (или в текущем Workspace/стейт-файле). Она
анализирует граф зависимостей и удаляет ресурсы в правильном порядке (например, сначала виртуалки,
затем подсети, затем VPC, в которой они находились).

# 10. Что делает terraform import?
Позволяет "привязать" (импортировать) уже существующий в облаке ресурс к состоянию Terraform
(State).
Для этого нужно сначала написать пустой блок ресурса в HCL, а затем выполнить команду `terraform
import <тип_ресурса>.<имя_ресурса> <реальный_ID_в_облаке>`. После этого ресурс появится в
`terraform.tfstate`, и им можно будет управлять через код.

# 11. Что такое Terraform Workspaces (Рабочие области)?
Workspaces позволяют использовать ОДНУ И ТУ ЖЕ директорию с конфигурационным кодом для управления
несколькими РАЗНЫМИ стейт-файлами (например, отдельный стейт для `dev`, `stage` и `prod`).
Переменная `terraform.workspace` внутри кода позволяет динамически менять префиксы названий или
размеры ресурсов в зависимости от активного воркспейса.

# 12. В чем разница между Count и For_each?
Оба используются для создания нескольких идентичных ресурсов.
- `count` принимает число (например, `count = 3`) и создает ресурсы в виде списка (индексируются по
  номерам: `aws_instance.web[0]`). Проблема: если удалить элемент из середины списка, Terraform
  сдвинет все индексы и может пересоздать ресурсы, которые не нужно было трогать.
- `for_each` принимает map (словарь) или set (множество) строк. Ресурсы индексируются по уникальным
  строковым ключам (например, `aws_instance.web["db1"]`). При удалении одного элемента другие не
  затрагиваются, поэтому `for_each` предпочтительнее в большинстве сценариев.

# 13. Что такое Provisioners в Terraform?
Provisioners (Провижинеры) позволяют выполнять скрипты на локальной или удаленной машине (по
SSH/WinRM) во время создания или удаления ресурса.
Например, `remote-exec` выполняет команды на запущенном сервере, а `local-exec` — на машине, где
запущен Terraform. HashiCorp рекомендует использовать их только как крайнюю меру (last resort),
предпочитая cloud-init, Packer или Ansible для настройки ОС.

# 14. Что такое State Locking (Блокировка состояния)?
Механизм, предотвращающий одновременное изменение стейт-файла двумя и более запусками Terraform (что
может привести к коррупции стейта). При старте `apply` Terraform ставит "замок". Если второй инженер
попытается запустить `apply`, он получит ошибку блокировки и будет ждать. В AWS это реализуется
через таблицу DynamoDB (поле LockID).

# 15. Что делает команда terraform taint и untaint? (Устарело в новых версиях)
В старых версиях `terraform taint <ресурс>` помечал ресурс в стейте как
"испорченный/деградировавший". При следующем `apply` Terraform принудительно удалял его и
пересоздавал с нуля (даже если код не менялся).
В Terraform 0.15.2 и новее `taint` объявлен устаревшим (deprecated), и теперь используется флаг:
`terraform apply -replace="<ресурс>"`.

# 16. Что такое lifecycle rules в Terraform?
Блок `lifecycle` позволяет настраивать особое поведение при создании/изменении ресурсов.
Например:
- `create_before_destroy = true`: при изменении, требующем пересоздания, Terraform сначала создаст
  новый ресурс, а потом удалит старый (для Zero Downtime).
- `prevent_destroy = true`: защищает ресурс от случайного удаления (Terraform выдаст ошибку, если
  кто-то попытается его удалить).
- `ignore_changes`: указывает Terraform игнорировать изменения определенных атрибутов, если они были
  изменены вручную в облаке.

# 17. Как скрыть чувствительные данные в логах Terraform?
Можно пометить переменную как чувствительную: `sensitive = true`. В этом случае при выполнении
`plan` или `apply` её значение будет замаскировано (`(sensitive value)`) в консольном выводе.
Однако стоит помнить, что в самом файле `terraform.tfstate` эти данные все равно будут храниться в
открытом виде! (Поэтому стейт нужно шифровать в S3/Vault).

# 18. В чем разница между Локальными переменными (Locals) и Входными переменными (Variables)?
Входные переменные (`variable`) — это аргументы, которые можно передать модулю извне (от
пользователя или из другого модуля).
Локальные переменные (`locals`) — это временные выражения или константы внутри самого модуля. Они не
могут быть переопределены снаружи. Полезны для вычисления сложных формул один раз и
переиспользования результата внутри кода, чтобы не нарушать DRY (например, склейка префикса среды с
именем проекта).

# 19. Что такое Terragrunt? Зачем его используют вместе с Terraform?
Terragrunt — это популярная обертка (wrapper) над Terraform от компании Gruntwork.
Он решает проблемы базового Terraform:
- Позволяет держать код DRY, избавляя от дублирования конфигурации бекенда (Remote State) в десятках
  папок.
- Позволяет управлять зависимостями между модулями (сначала развернуть VPC, затем EKS, затем БД) и
  запускать `apply-all` на все папки разом.
- Упрощает работу со средами (dev, prod) путем наследования переменных.

# 20. Как написать кастомный Terraform Provider?
Terraform провайдеры пишутся на языке Go. Вы используете Terraform Plugin SDK (или новый Terraform
Plugin Framework). Процесс включает:
1. Определение схемы (Schema) провайдера и его ресурсов.
2. Реализацию функций CRUD (Create, Read, Update, Delete) для каждого ресурса. Эти функции будут
   вызывать API вашего сервиса.
3. Сборку бинарного файла и его подключение к Terraform (локально или публикацию в Terraform
   Registry).
