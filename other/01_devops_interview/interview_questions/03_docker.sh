# 1. В чем разница между виртуальной машиной и Docker-контейнером?
Виртуальная машина (ВМ) включает в себя полноценную гостевую операционную систему поверх гипервизора
(что требует много памяти и CPU для старта).
Docker-контейнер не имеет своей ОС, он переиспользует ядро хостовой системы через механизмы cgroups
и namespaces, изолируя только окружение (библиотеки, процессы, файловую систему). Контейнеры
запускаются мгновенно и потребляют меньше ресурсов.

# 2. Что такое Dockerfile и из чего он состоит?
Dockerfile — это текстовый файл с инструкциями для автоматической сборки Docker-образа (Image). 
Основные инструкции: 
- FROM (базовый образ)
- RUN (выполнение команд при сборке)
- COPY/ADD (копирование файлов с хоста)
- WORKDIR (установка рабочей директории)
- EXPOSE (указание порта, который слушает приложение)
- ENV (переменные окружения)
- CMD/ENTRYPOINT (команда, выполняемая при старте контейнера).

# 3. В чем разница между командами COPY и ADD в Dockerfile?
COPY просто копирует файлы или директории из локальной файловой системы (build context) в образ.
ADD делает то же самое, но дополнительно умеет автоматически распаковывать локальные архивы (tar) и
может скачивать файлы по URL (хотя скачивание по URL через ADD считается плохой практикой — лучше
использовать RUN curl/wget).

# 4. В чем разница между CMD и ENTRYPOINT?
Обе инструкции задают команду, которая выполняется при запуске контейнера.
ENTRYPOINT задает неизменяемый исполняемый файл (основную команду контейнера). 
CMD передает аргументы по умолчанию для ENTRYPOINT, либо задает команду, если ENTRYPOINT не указан.
Если при `docker run` передать аргументы в конце команды, они переопределят CMD, но ENTRYPOINT
останется прежним и примет эти новые аргументы.

# 5. Как уменьшить размер Docker-образа?
- Использовать легковесные базовые образы (например, Alpine Linux, distroless).
- Использовать многоэтапную сборку (multi-stage builds), чтобы оставлять компиляторы/тулзы в
  builder-слое, а в финальный образ переносить только скомпилированный бинарник.
- Объединять команды RUN (например, `RUN apt-get update && apt-get install... && rm -rf
  /var/lib/apt/lists/*`), чтобы не создавать лишних слоев с временными файлами.
- Использовать файл .dockerignore для исключения локальных файлов из build context.

# 6. Что такое Docker-слои (layers)?
Каждая инструкция в Dockerfile (FROM, RUN, COPY, ADD) создает новый "слой" в файловой системе
(UnionFS). Слои доступны только для чтения и кэшируются на хосте. При запуске контейнера поверх всех
Read-Only слоев добавляется один тонкий Read-Write слой. Это позволяет экономить дисковое
пространство, так как разные образы переиспользуют общие базовые слои.

# 7. Как работает кэширование при сборке Docker-образа (Docker Build Cache)?
Docker кэширует каждый слой, чтобы ускорить повторные сборки. Если инструкция в Dockerfile и файлы,
связанные с ней (например, в COPY), не изменились, Docker берет слой из кэша.
Важное правило: если слой (строка в Dockerfile) изменился (кэш инвалидирован), то кэш автоматически
сбрасывается и для всех последующих строк. Поэтому часто меняющиеся вещи (например, `COPY . .`)
ставят в конец Dockerfile, а редко меняющиеся (установка зависимостей) — в начало.

# 8. Что такое Docker Volumes (тома)?
По умолчанию данные, созданные внутри контейнера, пишутся в тонкий R/W слой и удаляются вместе с
контейнером. Volumes — это механизм персистентного (постоянного) хранения данных. Docker хранит их
на хост-машине (обычно в /var/lib/docker/volumes/) вне зависимости от жизненного цикла контейнера.
Тома можно монтировать в несколько контейнеров одновременно.

# 9. Какие существуют типы сетевых драйверов в Docker?
- bridge (по умолчанию) — создает виртуальную изолированную сеть внутри хоста; контейнеры могут
  общаться друг с другом по IP.
- host — контейнер не изолируется сетево, он использует сетевой стек хоста (порты контейнера = порты
  хоста).
- none — полная изоляция без доступа к сети.
- overlay — позволяет контейнерам общаться между собой, находясь на разных физических хостах
  (используется в Docker Swarm).
- macvlan — назначает контейнеру физический MAC-адрес, делая его видимым в локальной сети как
  физическое устройство.

# 10. Чем отличается Docker-образ (Image) от контейнера (Container)?
Образ — это неизменяемый шаблон, состоящий из слоев (read-only), содержащий ОС, библиотеки и
приложение. Аналог класса в ООП.
Контейнер — это запущенный экземпляр образа (добавляется read-write слой, процессы начинают
выполняться). Аналог объекта в ООП.

# 11. Что делает команда docker-compose и файл docker-compose.yml?
Docker Compose — инструмент для описания и запуска многоконтейнерных приложений. В файле
docker-compose.yml декларативно описываются сервисы (контейнеры), сети, вольюмы и их взаимосвязи.
Команда `docker-compose up` поднимает всю инфраструктуру разом (например, базу данных, бэкенд и
фронтенд).

# 12. Что происходит, когда контейнер падает или завершает свою работу? (Restart policies)
Поведение зависит от политики перезапуска (restart policy):
- no (по умолчанию) — контейнер не перезапускается.
- always — всегда перезапускать контейнер (если он упал или после перезагрузки демона Docker).
- on-failure — перезапускать только если контейнер завершился с ненулевым кодом ошибки (можно задать
  лимит попыток).
- unless-stopped — перезапускать всегда, кроме случаев, когда пользователь явно его остановил
  (docker stop).

# 13. Зачем используется ключ --privileged?
Флаг `--privileged` дает контейнеру почти полный доступ ко всем устройствам хост-машины и снимает
ограничения cgroups/AppArmor/SELinux. Контейнер фактически получает права root-пользователя хоста
(например, может монтировать файловые системы или управлять сетью). Использовать крайне не
рекомендуется из соображений безопасности.

# 14. Как передать переменные окружения в контейнер?
- Через флаг `-e` или `--env` при запуске: `docker run -e MY_VAR="value" image`
- Через файл с переменными (`.env` файл): `docker run --env-file ./env.list image`
- Внутри Dockerfile через инструкцию `ENV` (но это зашивает их в образ).

# 15. Как запустить контейнер в фоне и как к нему подключиться?
Для запуска в фоновом (detached) режиме используется ключ `-d`: `docker run -d nginx`.
Чтобы выполнить команду в запущенном контейнере (подключиться к оболочке), используется `docker
exec`: `docker exec -it <container_id> /bin/bash` (или /bin/sh).

# 16. Что такое Docker Registry? Назовите примеры.
Registry — это хранилище для Docker-образов. Бывает публичным и приватным.
Примеры: Docker Hub (публичный по умолчанию), AWS ECR, Google GCR/Artifact Registry, GitLab
Container Registry, Nexus, Harbor.

# 17. Что такое Docker Swarm?
Docker Swarm — это нативный инструмент оркестрации от Docker для управления кластером Docker-хостов
(Swarm mode). Он позволяет объединять несколько хостов в единый пул ресурсов, управлять деплоем
сервисов, балансировкой нагрузки и отказоустойчивостью. Менее сложен, чем Kubernetes, но сейчас реже
используется в энтерпрайзе.

# 18. Как посмотреть логи контейнера, если он падает сразу после запуска?
Командой `docker logs <container_id_или_name>`.
Даже если контейнер остановился (status Exited), его файловая система и логи сохраняются, пока вы
явно не удалите его командой `docker rm`.

# 19. Что делает команда docker system prune?
Команда очищает неиспользуемые ресурсы Docker, освобождая место на диске. По умолчанию удаляет все
остановленные контейнеры, сети без хотя бы одного контейнера, "болтающиеся" (dangling) образы (слои
без тегов) и кэш сборки. С флагом `-a` также удалит все образы, не связанные с запущенными
контейнерами.

# 20. Что такое multi-stage сборка (multi-stage build)?
Это метод создания Dockerfile с несколькими инструкциями `FROM`. Каждая инструкция FROM начинает
новую стадию сборки. Это позволяет использовать один образ для компиляции кода (со всеми тяжелыми
зависимостями, SDK, компиляторами), а в финальную стадию (из легкого образа) просто скопировать
готовый бинарник (с помощью `COPY --from=builder`). Итог — очень маленький и безопасный финальный
образ.
