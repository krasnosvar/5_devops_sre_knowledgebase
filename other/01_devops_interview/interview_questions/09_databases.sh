# 1. В чем разница между реляционными (SQL) и нереляционными (NoSQL) базами данных?
Реляционные БД (PostgreSQL, MySQL): хранят данные в виде строго структурированных таблиц (с
заданными колонками и типами данных), связанных друг с другом ключами. Гарантируют ACID
(Атомарность, Согласованность, Изолированность, Долговечность), отлично подходят для транзакций и
сложных выборок. Масштабируются вертикально (с трудом горизонтально).
NoSQL БД (MongoDB, Redis, Cassandra): хранят данные в виде документов (JSON), графов, key-value пар
или колонок. Гибкая схема, легко масштабируются горизонтально (по распределенному кластеру). Хороши
для BigData, аналитики и быстрой записи/чтения, но часто жертвуют строгой консистентностью в пользу
доступности (CAP-теорема).

# 2. Что такое ACID в базах данных?
Это требования к транзакциям:
- Atomicity (Атомарность): Транзакция выполняется либо полностью, либо никак (все изменения
  откатываются, если одна команда упала).
- Consistency (Согласованность): Транзакция переводит БД из одного корректного состояния в другое
  (соблюдаются все constraints).
- Isolation (Изолированность): Параллельные транзакции не должны влиять друг на друга (регулируется
  уровнями изоляции).
- Durability (Долговечность): Если транзакция закоммичена, данные останутся в БД даже в случае
  отключения питания (запись в WAL-журнал).

# 3. Объясните CAP-теорему.
CAP-теорема гласит, что в распределенной вычислительной системе можно обеспечить не более двух из
трех свойств одновременно:
1. Consistency (Согласованность) — каждый клиент получает последние записанные данные или ошибку.
2. Availability (Доступность) — любой клиент всегда получает успешный ответ, но данные могут быть не
   самыми свежими.
3. Partition tolerance (Устойчивость к разделению) — система продолжает работать, даже если узлы
   кластера теряют связь друг с другом (network split).
Так как Partition tolerance обязательна для распределенных систем по сети, выбирать приходится между
CP (строгая консистентность, например HBase, MongoDB) и AP (всегда доступно, например Cassandra,
DynamoDB).

# 4. Что такое индексы в базах данных и как они работают под капотом (B-Tree)?
Индексы — это структура данных, повышающая скорость операций поиска данных в таблице за счет
увеличения времени записи и требуемого места на диске.
Чаще всего используется структура B-Tree (сбалансированное дерево). При поиске по индексу, БД не
читает всю таблицу (Full Table Scan), а спускается по ветвям дерева от корня к листьям за
логарифмическое время O(log N).

# 5. Что такое Репликация (Replication) и какие виды вы знаете?
Репликация — это процесс копирования данных с одного сервера базы данных на другие для обеспечения
отказоустойчивости (High Availability) и балансировки нагрузки на чтение.
Виды:
- Master-Slave (Primary-Replica): один узел пишет и читает, остальные только читают. Изменения
  передаются на реплики асинхронно или синхронно.
- Master-Master (Multi-Master): писать можно в любой узел кластера. Сложнее в настройке (нужно
  разрешать конфликты).
- Synchronous vs Asynchronous: в синхронной мастер ждет ответа от реплик перед подтверждением
  транзакции (надежно, но медленно), в асинхронной не ждет (быстро, но есть риск потери последних
  данных при падении).

# 6. Что такое Шардирование (Sharding / Partitioning)?
Шардирование (горизонтальное партиционирование) — это разделение одной большой логической таблицы
(или базы) на несколько меньших, которые размещаются на разных физических серверах (шардах). Это
позволяет масштабировать базу данных для хранения огромных объемов данных и распределить нагрузку на
запись (Write-heavy). Выбор того, на какой шард попадет запись, определяется Шард-ключом (Shard
Key), например ID пользователя.

# 7. Что такое WAL (Write-Ahead Logging) в PostgreSQL?
В целях производительности базы данных не пишут изменения сразу на диск в таблицы. Но для
обеспечения долговечности (Durability) они используют WAL. При любом изменении данных БД сначала
добавляет запись об этом в последовательный файл лога (Write-Ahead Log) на диске. В случае сбоя
сервера после перезагрузки БД восстановит потерянные данные из WAL в память и таблицы.

# 8. В чем разница между Redis и Memcached?
Оба являются in-memory Key-Value хранилищами (кэшами).
Redis гораздо мощнее: поддерживает сложные типы данных (списки, множества, хеши), поддерживает
персистентность (может сбрасывать данные на диск через RDB снапшоты или AOF лог), поддерживает
репликацию, pub/sub, Lua-скрипты.
Memcached очень прост: только key-value строкового типа, данные живут только в ОЗУ, многопоточный
(Redis в основном однопоточный).

# 9. Как найти медленные запросы в PostgreSQL?
Для этого используется расширение `pg_stat_statements`, которое собирает статистику по выполнению
всех запросов (кто запускал, сколько раз, среднее время).
Также можно настроить параметр в `postgresql.conf`: `log_min_duration_statement = 1000` (в
миллисекундах), после чего все запросы, выполняющиеся дольше 1 секунды, будут записываться в лог
файл Postgres.

# 10. Что делает команда EXPLAIN в SQL?
`EXPLAIN` (в Postgres часто используют `EXPLAIN ANALYZE`) показывает план выполнения запроса,
который построил оптимизатор БД. Он показывает:
- Будет ли использоваться индекс или пойдет полный скан (Seq Scan).
- Предполагаемую (и реальную при ANALYZE) стоимость (Cost) выполнения.
- Методы соединения таблиц (Nested Loop, Hash Join).
Это главный инструмент для оптимизации (тюнинга) SQL-запросов.

# 11. Что такое Connection Pooling (Пул соединений) и зачем нужен PgBouncer?
Открытие нового сетевого соединения к базе данных (особенно в Postgres, где каждое соединение — это
отдельный процесс ОС) — это "дорогая" и долгая операция.
Connection Pool (Пул соединений) заранее создает и держит открытыми несколько соединений к БД. Когда
приложению нужен доступ, оно берет готовое соединение из пула, а после завершения — возвращает его
обратно. PgBouncer — это популярный легковесный пул соединений специально для PostgreSQL.

# 12. Что такое Vacuum в PostgreSQL?
В Postgres при обновлении (UPDATE) или удалении (DELETE) строки физически не удаляются сразу (из-за
механизма MVCC, чтобы не блокировать читающих). Они помечаются как "мертвые" (dead tuples). Процесс
Vacuum фоново проходит по таблицам, собирает мусор и освобождает место для новых записей (но не
уменьшает размер файла таблицы). Если Vacuum не справляется, БД раздувается и замедляется. `VACUUM
FULL` сжимает файлы, но полностью блокирует таблицу.

# 13. Что такое нормализация и денормализация БД?
Нормализация — процесс проектирования реляционной БД с целью минимизации дублирования данных (путем
разбиения их на связанные таблицы) и обеспечения целостности (использование Foreign Keys).
Денормализация — обратный процесс: намеренное добавление избыточных данных (слияние таблиц,
кеширование подсчетов) для ускорения операций чтения (SELECT), так как тяжелые JOIN-ы работают
медленно при высоких нагрузках.

# 14. Как сделать бэкап базы данных PostgreSQL?
Логический бэкап (дамп SQL): `pg_dump` для отдельной базы, `pg_dumpall` для всего кластера (роли +
данные). Подходит для небольших баз и переноса между версиями.
Физический бэкап (побитовая копия данных): утилита `pg_basebackup`. Копирует директорию данных
(PGDATA) и WAL. Гораздо быстрее для больших объемов и необходим для настройки репликации или
Point-in-Time Recovery (PITR).

# 15. Какие существуют уровни изоляции транзакций?
По стандарту SQL (от слабого к сильному):
1. Read Uncommitted — транзакция видит незакоммиченные изменения других транзакций (грязное чтение).
   Postgres это не поддерживает, трактуя как Read Committed.
2. Read Committed (обычно по умолчанию) — видит только закоммиченные данные.
3. Repeatable Read — если внутри транзакции вы дважды прочтете одни и те же строки, результат будет
   одинаковым, даже если другая транзакция в это время их изменила (защита от неповторяющегося
   чтения).
4. Serializable — транзакции выполняются так, как если бы они шли строго последовательно (одна за
   другой). Полная изоляция, но сильно снижает производительность.

# 16. Что такое N+1 проблема (N+1 query problem)?
Это проблема производительности (часто вызванная ORM в коде приложения), когда для получения списка
из N родительских записей (например, 10 пользователей) и их дочерних записей (их посты) вместо
одного оптимизированного JOIN-запроса выполняется один запрос для получения пользователей, и затем N
отдельных запросов (циклом) для получения постов каждого пользователя (итого N+1 запросов к БД
вместо одного).

# 17. Что такое Time-Series Database (TSDB)?
Это специализированный вид баз данных (InfluxDB, Prometheus, TimescaleDB, ClickHouse в некоторых
сценариях), оптимизированный для хранения и запросов временных рядов (time-series). Они
сфокусированы на супер-быстрой записи огромного количества данных (поток метрик, IoT датчиков),
упорядоченных по времени, с возможностью быстро сжимать данные и агрегировать их за периоды
(downsampling).

# 18. Что такое ClickHouse и для чего он используется?
ClickHouse — это колоночная (column-oriented) система управления базами данных, оптимизированная для
OLAP (Online Analytical Processing). В отличие от строковых БД (PostgreSQL), данные одной колонки
хранятся физически рядом на диске. Это позволяет фантастически быстро (десятки гигабайт в секунду)
выполнять агрегирующие SQL-запросы (SUM, AVG) по отдельным колонкам над петабайтами данных
(веб-аналитика, логи, статистика).

# 19. Что такое RabbitMQ и Kafka? В чем разница?
Оба являются брокерами сообщений, но с разной архитектурой.
RabbitMQ: "умный брокер, глупый клиент". Маршрутизирует сообщения (через Exchanges), поддерживает
подтверждения, удаляет сообщения после прочтения (очереди сообщений). Отлично подходит для
микросервисного RPC и задач с роутингом (AMQP).
Kafka: "глупый брокер, умный клиент" (распределенный журнал событий). Просто пишет поток сообщений
на диск. Клиенты (consumers) сами запоминают, до какого места (offset) они прочитали. Сообщения не
удаляются после чтения, что позволяет множеству клиентов читать один и тот же поток (Pub/Sub) и
обрабатывать BigData.

# 20. Как избежать Downtime при миграции (изменении структуры) базы данных на продакшене?
Нельзя применять долгие операции вроде блокирующего создания индекса или добавления столбца с
`default` значением на терабайтной таблице в один шаг.
- Вместо `CREATE INDEX` используют `CREATE INDEX CONCURRENTLY` (работает дольше, но не блокирует
  таблицу на запись).
- Миграции приложения и БД разделяются. Например, добавление новой колонки: 1) создать пустую
  колонку, 2) обновить код, чтобы он начал писать в обе колонки, 3) запустить скрипт миграции старых
  строк в фоне, 4) переключить чтение в коде на новую колонку, 5) удалить старую.
