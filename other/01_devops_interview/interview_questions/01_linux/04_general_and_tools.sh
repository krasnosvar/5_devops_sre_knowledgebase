# 1. Как безопасно перезагрузить зависший сервер Linux, если не работает консоль? (Magic SysRq)
Если ядро все еще живо, используются комбинации клавиш (SysRq). Метод называется REISUB:
Alt + SysRq + R (возвращает контроль над клавиатурой)
Alt + SysRq + E (отправляет SIGTERM всем процессам)
Alt + SysRq + I (отправляет SIGKILL всем оставшимся)
Alt + SysRq + S (Sync — сбрасывает буферы на диск)
Alt + SysRq + U (Umount — переводит ФС в режим только для чтения)
Alt + SysRq + B (Reboot — жесткая перезагрузка)

# 2. Что такое chroot и зачем он нужен?
chroot (change root) — операция, изменяющая видимый корневой каталог для текущего процесса и его
дочерних процессов. Приложение, запущенное в chroot, не имеет доступа к файлам за пределами своей
"тюрьмы". Используется для изоляции небезопасных сервисов или тестирования (прообраз контейнеров).

# 3. Как работает команда sudo и где хранится её конфигурация?
Команда sudo позволяет пользователям выполнять команды от имени другого пользователя (чаще всего
root) с проверкой их собственного пароля (в отличие от su). Конфигурация хранится в файле
`/etc/sudoers` и директории `/etc/sudoers.d/`. Редактировать sudoers следует только через утилиту
`visudo`, которая проверяет синтаксис при сохранении, предотвращая блокировку доступа к системе.

# 4. Какова разница между systemctl restart и systemctl reload?
`restart` полностью останавливает сервис и запускает его заново (PID процесса меняется, происходит
даунтайм, если сервис не имеет механизмов бесшовного рестарта).
`reload` отправляет процессу сигнал (обычно SIGHUP) перечитать конфигурационные файлы без завершения
основного процесса. Сервис продолжает обрабатывать соединения.

# 5. Как посмотреть историю команд, и как выполнить поиск по истории?
Команда `history` выводит список ранее введенных команд.
Для быстрого поиска используется сочетание клавиш `Ctrl+R` (reverse-i-search), где можно ввести
часть команды.
Чтобы повторить последнюю команду: `!!`. Чтобы повторить команду по номеру: `!123`.

# 6. Что такое cgroups (Control Groups) в Linux?
cgroups — это механизм ядра Linux, который ограничивает, приоритизирует, учитывает и изолирует
использование ресурсов (CPU, память, дисковый ввод-вывод, сеть) для групп процессов. Это одна из
основополагающих технологий, на которых строятся контейнеры (Docker, LXC).

# 7. Что такое namespaces в Linux?
Namespaces (пространства имен) — это механизм ядра Linux, обеспечивающий изоляцию системных ресурсов
для процессов. Различные пространства имен скрывают друг от друга PID, сеть, точки монтирования
(mount), IPC, UTS (hostname) и пользователей. Вместе с cgroups формируют основу для работы
контейнеров.

# 8. Разница между утилитами grep, awk и sed?
`grep` (Global Regular Expression Print) — утилита для поиска строк, соответствующих регулярному
выражению.
`sed` (Stream Editor) — потоковый текстовый редактор, часто используемый для поиска и замены текста
(`s/old/new/g`).
`awk` — мощный язык обработки текста и извлечения данных, отлично подходящий для работы с табличными
данными (разделенными пробелами или другими разделителями), вычислений и форматирования.
