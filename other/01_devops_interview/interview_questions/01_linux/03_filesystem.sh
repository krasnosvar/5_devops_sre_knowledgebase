# 1. В чем разница между жесткими (hard) и символическими (soft/symlink) ссылками?
Жесткая ссылка указывает непосредственно на inode файла. Если удалить исходный файл, жесткая ссылка
продолжит работать, так как данные не удалятся, пока на inode есть хотя бы одна ссылка. Жесткие
ссылки нельзя создавать для директорий и файлов в других файловых системах.
Символическая ссылка — это отдельный файл, содержащий путь к целевому файлу. Если удалить оригинал,
симлинк станет нерабочим ("битым"). Симлинки работают между разными файловыми системами и могут
указывать на директории.

# 2. Что такое inode в файловой системе Linux?
inode (индексный дескриптор) — это структура данных, которая хранит метаданные о файле: размер,
права доступа, владельца, временные метки и указатели на блоки данных на диске. inode не содержит
имени файла (имя хранится в структуре директории). Когда кончаются свободные inode (даже если есть
место на диске), создание новых файлов становится невозможным.

# 3. Как посмотреть, что занимает место на диске?
Для проверки общего свободного места используется `df -h` (показывает использование дисков в
человекочитаемом формате).
Для поиска самых больших файлов и директорий используется `du -sh *` (показывает размер папок в
текущей директории) или `ncdu`.
Чтобы найти самые большие файлы в системе: `find / -type f -exec du -h {} + | sort -rh | head -n 10`

# 4. Что произойдет, если удалить файл, который сейчас открыт и пишется процессом?
Имя файла исчезнет из директории (ссылка на inode удалится), но место на диске не освободится.
Фактическое удаление данных произойдет только тогда, когда процесс закроет файловый дескриптор.
Чтобы освободить место без перезапуска процесса, можно "обнулить" файл: `> filename` (или `echo "" >
filename`).

# 5. Как изменить права на файлы и директории рекурсивно, но задать разные права?
Использовать команду find в связке с chmod:
Директории (755): find /path -type d -exec chmod 755 {} \;
Файлы (644): find /path -type f -exec chmod 644 {} \;

# 6. Что такое Sticky bit, SUID и SGID?
SUID (Set owner User ID up on execution): позволяет запускать исполняемый файл с правами владельца
файла (например, /usr/bin/passwd запускается от root).
SGID (Set Group ID): аналогично SUID, но для группы. На директориях означает, что все новые файлы
внутри унаследуют группу директории.
Sticky bit: устанавливается на директории (например, /tmp) и означает, что удалить или переименовать
файл может только его владелец.

# 7. Что такое VFS (Virtual File System) и зачем он нужен?
VFS — абстрактный слой ядра Linux, который предоставляет единый интерфейс системных вызовов (`open`,
`read`, `write`, `stat`) для работы с ЛЮБОЙ файловой системой (ext4, xfs, NFS, tmpfs), скрывая от
приложений детали конкретной реализации. Благодаря VFS одна и та же программа может одинаково
работать с локальным диском, сетевой шарой или файлом в оперативной памяти, не зная, с чем именно
она имеет дело физически.

# 8. В чем разница между ext4 и xfs, и когда что выбирать?
ext4 — самая распространенная, зрелая, универсальная ФС по умолчанию во многих дистрибутивах; хорошо
себя ведет на небольших/средних разделах и с большим количеством мелких файлов. xfs изначально
спроектирована для больших файлов и высокопроизводительного параллельного I/O (лучше масштабируется
на многоядерных системах и больших разделах), но исторически сложнее уменьшить размер существующего
xfs-раздела (shrink не поддерживается штатно, в отличие от ext4). Red Hat/CentOS используют xfs по
умолчанию именно из-за производительности на серверных нагрузках.

# 9. Что такое mount namespace и bind mount?
Mount namespace — изолированное дерево точек монтирования: процессы в разных mount namespace могут
видеть совершенно разную файловую структуру, даже работая на одном ядре (основа изоляции контейнеров
на уровне ФС). `bind mount` (`mount --bind /src /dst`) монтирует уже существующую директорию в
другую точку дерева — это не копия, а alias: изменения в `/src` мгновенно видны через `/dst` и
наоборот, так как физически это один и тот же inode/данные.

# 10. Что такое tmpfs и где он обычно используется?
tmpfs — файловая система, полностью находящаяся в оперативной памяти (и, при нехватке RAM, может
использовать swap). Данные в tmpfs исчезают при перезагрузке. Используется для `/tmp` (быстрый
временный storage), `/dev/shm` (POSIX shared memory), а также как `emptyDir` том в Kubernetes с
`medium: Memory` — для сверхбыстрого доступа к временным данным без нагрузки на реальный диск.

# 11. Диск заполнен, но `df` показывает свободное место. Почему?
Классический признак исчерпания inode, а не блоков данных: `df -h` показывает свободное МЕСТО, а не
свободные inode. Если на файловой системе создано огромное количество мелких файлов (например,
миллионы файлов сессий/кэша), можно исчерпать лимит inode, оставаясь при этом с гигабайтами
свободного места. Проверяется командой `df -i` (покажет `IUse% 100%` при исчерпании). Решение —
увеличить лимит inode при форматировании (заранее) или удалить лишние мелкие файлы.

# 12. Что дает журналирование (journaling) в файловой системе и от чего оно защищает?
Журналируемая ФС (ext4, xfs) перед реальной записью данных на диск сначала записывает в специальный
журнал (лог) намерение о предстоящей операции. Если система упадет (отключение питания, kernel
panic) в середине записи, при следующей загрузке ФС читает журнал и либо докатывает, либо откатывает
незавершенную операцию — вместо полного повреждения структуры файловой системы, требующего долгого
`fsck` со сканированием всего диска. Не журналируемые ФС (старый ext2) после сбоя требуют полной
проверки при загрузке.

# 13. Что такое LVM и какую проблему он решает?
LVM (Logical Volume Manager) — слой абстракции между физическими дисками и файловыми системами.
Физические диски (PV — Physical Volumes) объединяются в пул (VG — Volume Group), из которого
нарезаются логические тома (LV — Logical Volumes) произвольного размера, не привязанные к границам
физических дисков. Главное практическое преимущество — можно увеличить размер логического тома "на
лету" (добавив физический диск в VG), не имея возможности сделать то же самое с обычным разделом без
LVM без переразметки/простоя.

# 14. Кратко: чем отличаются уровни RAID 0, 1, 5 и 10?
- RAID 0 (striping) — данные разбиваются между дисками, максимальная скорость, но НУЛЕВАЯ
  отказоустойчивость (один диск умер — данные потеряны полностью).
- RAID 1 (mirroring) — полное дублирование данных на двух дисках, отказоустойчивость ценой 50%
  полезного объема.
- RAID 5 — данные + контрольные суммы четности (parity), распределенные по всем дискам; переживает
  отказ ОДНОГО диска, эффективнее по объему чем RAID 1, но пересборка (rebuild) после замены диска
  нагружает все оставшиеся диски и занимает много времени.
- RAID 10 — сочетание: зеркалирование пар дисков + страйпинг между парами — быстро и
  отказоустойчиво, но требует минимум 4 диска и теряет 50% объема, как RAID 1.

# 15. Что такое `/etc/fstab` и зачем там опция `noatime`?
`/etc/fstab` описывает, какие файловые системы монтировать при загрузке, куда и с какими опциями.
`noatime` отключает обновление времени последнего доступа (atime) при каждом чтении файла — по
умолчанию каждое чтение файла означает ЗАПИСЬ метаданных (обновление atime), что создает лишнюю
нагрузку на диск особенно при большом количестве операций чтения. `noatime` — стандартная
оптимизация производительности для серверов, где точное время последнего доступа к файлам не
критично для бизнес-логики.

# 16. Как Docker использует OverlayFS для слоев образа?
OverlayFS объединяет несколько директорий в единую видимую файловую систему через механизм
upper/lower layers: нижние (lower) слои — read-only (слои образа), верхний (upper) слой — read-write
(изменения, сделанные в запущенном контейнере). При чтении файла ядро ищет его сверху вниз по слоям
(copy-up: если файл нужно изменить, а он лежит в read-only нижнем слое, сначала он копируется в
верхний writable слой, и изменяется уже там, не трогая нижний). Именно это позволяет тысячам
контейнеров шарить одни и те же базовые слои образа (ubuntu, alpine), физически храня их на диске
только один раз.

# 17. Что такое umask и как он влияет на права по умолчанию у создаваемых файлов?
`umask` — маска, которая ВЫЧИТАЕТ права из максимально разрешенных при создании нового
файла/директории (по умолчанию файлы создаются с правами 666, директории — 777, из которых umask
"вырезает" биты). Стандартный `umask 022` дает файлам права 644 (666 минус 022) и директориям 755
(777 минус 022). Проверить текущее значение: `umask`; временно поменять для сессии: `umask 027`
(более строгое, убирает права группе на запись и права остальным вообще).

# 18. Когда и зачем запускать `fsck`, и почему нельзя делать это на смонтированной в режиме записи
ФС?
`fsck` (file system check) проверяет и по возможности исправляет несогласованность файловой системы
— обычно требуется после аварийного выключения (не журналируемая ФС) или при явных признаках
повреждения (ошибки чтения, kernel-сообщения о corruption). Запускать `fsck` на смонтированной
read-write файловой системе опасно: пока идет проверка/исправление структур на диске, ядро может
параллельно менять эти же структуры через обычную работу приложений — гонка состояний почти
гарантированно приведет к еще большему повреждению. Правильно — размонтировать ФС (или загрузиться с
live-образа/recovery-режима) перед запуском `fsck`.

# 19. Что такое ACL (Access Control List) в файловой системе и зачем он нужен, если уже есть chmod?
Классические Unix-права (`rwx` для owner/group/other) не позволяют дать точечный доступ ВТОРОМУ
конкретному пользователю или группе, не входящей в основную группу файла, без создания отдельной
группы под каждый такой случай. ACL (`setfacl`/`getfacl`) решает это точечно: `setfacl -m u:alice:rx
file.txt` дает конкретно пользователю alice права на чтение и выполнение, не меняя базовые
владельца/группу файла и не затрагивая остальных пользователей.

# 20. Почему `du` и `df` иногда показывают РАЗНЫЕ цифры использования диска для одного и того же
раздела?
Кроме случая с удаленными, но открытыми файлами (см. вопрос 4, где `du` их не видит, а место реально
занято), частая причина — что-то ДРУГОЕ примонтировано поверх директории, которую сканирует `du`
(bind mount, отдельный раздел смонтирован внутрь пути) — `du` при обычном вызове может как
учитывать, так и не учитывать содержимое вложенных точек монтирования в зависимости от флагов
(`-x`/`--one-file-system`). `df` всегда показывает статистику именно ФАЙЛОВОЙ СИСТЕМЫ (раздела)
целиком, а `du` — сумму по факту обхода конкретного дерева директорий, что не всегда одно и то же.
