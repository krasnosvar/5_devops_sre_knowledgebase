# 1. Что такое Kubernetes (K8s) и зачем он нужен?
Kubernetes — это открытая платформа для автоматизации развертывания, масштабирования и управления контейнеризированными приложениями (оркестратор контейнеров). Он решает проблемы перезапуска упавших контейнеров, балансировки нагрузки, накатывания обновлений без даунтайма, управления секретами и масштабирования кластера.

# 2. Опишите архитектуру Kubernetes кластера (Control Plane и Worker Nodes).
Кластер делится на управляющий слой (Control Plane) и рабочие узлы (Worker Nodes).
Control Plane (Master):
- kube-apiserver: единая точка входа для всех REST-запросов (от kubectl и других компонентов).
- etcd: распределенное key-value хранилище, где лежит всё состояние кластера.
- kube-scheduler: решает, на какой узел (Node) назначить новые поды на основе ресурсов.
- kube-controller-manager: следит за состоянием кластера и приводит его к желаемому (реплики, эндпоинты, ноды).
Worker Node (Узлы с нагрузкой):
- kubelet: агент на каждой ноде, который следит, чтобы контейнеры в подах работали.
- kube-proxy: управляет сетевыми правилами на ноде (iptables/IPVS) для маршрутизации трафика к подам (сервисы).
- Container Runtime (Containerd, CRI-O, Docker): запускает сами контейнеры.

# 3. Что такое Pod в Kubernetes?
Pod (Под) — это мельчайшая базовая единица развертывания в K8s. Под представляет собой логический хост и может содержать один или несколько контейнеров. Контейнеры внутри одного пода всегда запускаются на одной ноде, делят один сетевой namespace (IP-адрес, localhost) и могут разделять общие тома (Volumes).

# 4. Какие типы Service существуют в K8s?
Service обеспечивает стабильный IP-адрес и DNS-имя для доступа к динамичным Подам (балансировка).
1. ClusterIP (по умолчанию): доступен только внутри кластера по внутреннему IP.
2. NodePort: открывает статический порт (по умолчанию 30000-32767) на каждой ноде кластера, маршрутизируя трафик в поды.
3. LoadBalancer: провижинит внешний балансировщик нагрузки облачного провайдера (AWS ELB, GCP Load Balancer) и направляет трафик на NodePort.
4. ExternalName: мапит сервис на DNS-имя (CNAME), не используя проксирование.

# 5. Что такое Deployment и чем он отличается от StatefulSet?
Deployment управляет приложениями без сохранения состояния (Stateless). Он следит за ReplicaSet, обеспечивая нужное количество реплик подов. Поды в Deployment взаимозаменяемы, их имена генерируются случайно, они могут быть удалены и пересозданы на любых нодах.
StatefulSet используется для приложений с состоянием (Stateful, например БД). Он гарантирует:
- Уникальные постоянные сетевые имена (pod-0, pod-1).
- Строгий порядок создания и удаления подов.
- Привязку к постоянным хранилищам (Persistent Volumes): при пересоздании pod-0 получит тот же диск, что был у него ранее.

# 6. Что такое Ingress и Ingress Controller?
Ingress — это объект API, описывающий правила маршрутизации внешнего HTTP/HTTPS-трафика к внутренним сервисам кластера (маршрутизация на основе URL-путей или доменов, TLS termination).
Ingress Controller (например, Nginx Ingress Controller, Traefik) — это компонент (обычно деплоймент с балансировщиком), который считывает эти правила и фактически реализует проксирование. Сам объект Ingress без контроллера не работает.

# 7. Как K8s управляет секретными данными (пароли, ключи)?
Используются объекты Secret. K8s хранит их в etcd (по умолчанию они просто закодированы в base64, поэтому etcd нужно шифровать в покое — encryption at rest). Секреты можно пробрасывать в контейнеры как файлы через volume (tmpfs) или как переменные окружения.

# 8. Что такое Namespace?
Namespace (Пространство имен) — это логическое разделение кластера K8s. Позволяет разделить ресурсы между разными проектами, командами или окружениями (dev, test, prod) внутри одного физического кластера. Объекты с одинаковым именем могут существовать в разных неймспейсах.

# 9. Объясните, что такое Liveness, Readiness и Startup Probes (Пробы).
Это проверки состояния контейнера.
- Liveness Probe: проверяет, жив ли контейнер (не завис ли дедлоком). Если проверка провалена, kubelet перезапускает контейнер.
- Readiness Probe: проверяет, готово ли приложение принимать сетевой трафик (например, загрузились ли кэши). Если провалена, под исключается из балансировки Service, но не убивается.
- Startup Probe: используется для медленно стартующих приложений. Отключает Liveness/Readiness проверки, пока приложение окончательно не инициализируется.

# 10. Что такое DaemonSet?
DaemonSet гарантирует, что определенный Под будет запущен в единственном экземпляре на каждой Worker-ноде кластера (или на нодах, соответствующих селектору). Часто используется для инфраструктурных задач: сбор логов (Fluentd/Promtail), мониторинг (Node Exporter), сетевые плагины (Kube-proxy, CNI).

# 11. Что такое ConfigMap?
ConfigMap используется для хранения неконфиденциальных конфигурационных данных (конфиг-файлов, переменных окружения, аргументов командной строки) в формате ключ-значение. Отделяет конфигурацию от образа контейнера, позволяя переиспользовать образ в разных окружениях.

# 12. В чем разница между Persistent Volume (PV) и Persistent Volume Claim (PVC)?
- PV — это абстрактный кусок хранилища в кластере (NFS, AWS EBS, локальный диск), созданный администратором или автоматически через StorageClass.
- PVC — это запрос пользователя/пода на выделение хранилища (с определенным объемом и режимом доступа, например ReadWriteOnce). PVC привязывается (binds) к подходящему PV, и затем монтируется в Под.

# 13. Что такое HPA (Horizontal Pod Autoscaler)?
HPA — это механизм K8s, который автоматически изменяет количество реплик подов в Deployment/ReplicaSet на основе наблюдаемых метрик (обычно загрузка CPU или памяти). Требует установленного Metrics Server. При превышении заданного порога HPA создает новые поды, при падении нагрузки — удаляет.

# 14. Что такое Taints и Tolerations?
Это механизм K8s, позволяющий нодам отталкивать (taint) определенные поды.
- Taint применяется к Node (например, нода только для GPU-нагрузок).
- Toleration применяется к Pod, позволяя ему быть запущенным на ноде с соответствующим Taint (разрешает, но не обязывает).
Для обязывания пода запускаться на конкретной ноде используют NodeSelector или NodeAffinity.

# 15. Как происходит процесс обновления Deployment (Rolling Update)?
По умолчанию Deployment использует стратегию RollingUpdate. K8s создает новый ReplicaSet и начинает постепенно (по одному или партиями, контролируется `maxSurge` и `maxUnavailable`) запускать поды новой версии, одновременно убивая старые. Это обеспечивает нулевой даунтайм. Если новые поды падают, выкатка останавливается. Откат осуществляется командой `kubectl rollout undo`.

# 16. Что такое RBAC в Kubernetes?
RBAC (Role-Based Access Control) — система управления доступом на основе ролей.
- Role / ClusterRole — определяет разрешения (verbs: get, list, create, delete) на объекты (pods, secrets). Role действует в рамках неймспейса, ClusterRole — на весь кластер.
- RoleBinding / ClusterRoleBinding — привязывает роль к субъекту (User, Group или ServiceAccount).

# 17. Что такое Helm?
Helm — это пакетный менеджер для Kubernetes. Он упаковывает K8s-манифесты в шаблоны (Charts), позволяя параметризировать их с помощью `values.yaml`. Это позволяет легко деплоить сложные приложения, управлять их версиями (install, upgrade, rollback) и переиспользовать одни и те же манифесты для разных окружений.

# 18. Какова роль etcd в кластере Kubernetes? Можно ли его забекапить?
etcd — это распределенная база данных кластера. Только `kube-apiserver` взаимодействует с etcd. Если etcd упадет и потеряет данные, кластер перестанет функционировать (хотя запущенные поды продолжат работу, вы не сможете ими управлять). etcd бэкапится с помощью утилиты `etcdctl snapshot save`, что является критически важной операцией для DR (Disaster Recovery).

# 19. Что такое CNI и CSI?
CNI (Container Network Interface) — стандарт, описывающий сетевые плагины в K8s (Calico, Flannel, Cilium). Они отвечают за выдачу IP-адресов подам и маршрутизацию между ними (Overlay сети, BGP).
CSI (Container Storage Interface) — стандарт, позволяющий производителям хранилищ писать плагины для K8s, чтобы поды могли динамически монтировать диски (EBS, Ceph) без внесения изменений в ядро Kubernetes.

# 20. Что такое Init Containers?
Init-контейнеры — это специальные контейнеры, которые запускаются до основных контейнеров в поде. Они всегда должны успешно завершиться (код 0). Если init-контейнер падает, K8s будет перезапускать его до успешного завершения. Их используют для подготовки среды: миграции БД, ожидания доступности сервиса (wait-for-it), генерации конфигов, скачивания данных.
