# 1. Что такое AWS VPC (Virtual Private Cloud) и из чего он состоит?
VPC — это изолированная виртуальная сеть в облаке AWS, где вы запускаете свои ресурсы.
Основные компоненты:
- Subnets (Подсети): Public (имеют маршрут к интернету) и Private (не имеют прямого маршрута).
- Route Tables (Таблицы маршрутизации): определяют правила, куда направлять трафик (локально или наружу).
- Internet Gateway (IGW): компонент для доступа VPC в интернет (цепляется к Public Subnets).
- NAT Gateway: позволяет ресурсам в Private подсетях выходить в интернет для скачивания обновлений, не получая при этом публичных IP.
- Security Groups и NACLs: файрволы (на уровне инстанса и на уровне подсети).

# 2. В чем разница между Security Group и Network ACL (NACL)?
Security Group (SG):
- Работает на уровне инстанса (EC2).
- Stateful (с сохранением состояния): если разрешен входящий трафик на порт 80, ответный исходящий разрешается автоматически.
- Поддерживает только разрешающие правила (Allow rules). Все, что не разрешено, запрещено.
NACL:
- Работает на уровне подсети (Subnet). Защищает сразу все инстансы в подсети.
- Stateless (без сохранения состояния): нужно явно прописывать и входящие, и исходящие правила (Ephemeral ports).
- Поддерживает как разрешающие, так и запрещающие правила (Deny rules).

# 3. Что такое IAM и какие у него основные сущности?
IAM (Identity and Access Management) — сервис для управления доступом к ресурсам AWS.
- Users (Пользователи): конкретные люди или приложения (имеют пароли или ключи доступа).
- Groups (Группы): коллекция пользователей для удобной выдачи прав сразу всем.
- Roles (Роли): сущности без постоянных паролей/ключей. Роль можно "надеть" (Assume) на EC2 инстанс, Lambda функцию или пользователя из другого аккаунта для выдачи временных прав (STS).
- Policies (Политики): JSON-документы, описывающие, что разрешено (Effect: Allow/Deny, Action, Resource).

# 4. В чем отличие Amazon S3 от EBS (Elastic Block Store)?
Amazon S3 (Simple Storage Service):
- Объектное хранилище (Object storage).
- Файлы хранятся в бакетах (Buckets) без иерархии папок, доступ осуществляется через HTTP REST API.
- Бесконечно масштабируется, идеально для бекапов, картинок, статических сайтов.
Amazon EBS:
- Блочное хранилище (Block storage).
- Это виртуальный жесткий диск, который подключается (монтируется) к ОДНОМУ запущенному инстансу EC2 по сети.
- На нем создается файловая система (ext4/NTFS), используется для ОС, баз данных. При остановке инстанса данные сохраняются.

# 5. Что такое AWS Lambda и бессерверные (Serverless) вычисления?
AWS Lambda — это сервис FaaS (Function as a Service). Вы пишете только код (функцию) и не управляете серверами (нет EC2 инстансов, ОС, патчинга). 
Lambda запускается в ответ на события (HTTP-запрос через API Gateway, загрузка файла в S3, событие в SQS) и работает максимум 15 минут. Вы платите только за время выполнения кода с точностью до миллисекунды.

# 6. В чем разница между EC2 Spot Instances, Reserved Instances и On-Demand?
- On-Demand (По требованию): платите за секунду работы, пока инстанс включен. Самый гибкий, но самый дорогой вариант.
- Reserved (Зарезервированные): вы обязуетесь использовать инстанс 1 или 3 года, получая огромную скидку (до 72%). Хорошо для стабильной, постоянной нагрузки (базы данных).
- Spot (Спотовые): вы торгуетесь за неиспользуемые мощности AWS. Могут быть дешевле On-Demand до 90%. НО: AWS может забрать инстанс в любой момент с предупреждением за 2 минуты. Идеально для отказоустойчивых/Stateless задач (расчеты, CI/CD раннеры, пакетная обработка).

# 7. Что такое AWS Auto Scaling Group (ASG)?
Сервис, который автоматически добавляет (scale-out) или удаляет (scale-in) EC2 инстансы в зависимости от нагрузки (CPU, память, трафик) или по расписанию. ASG следит за здоровьем инстансов (Health Checks) и автоматически заменяет зависшие или упавшие инстансы новыми, обеспечивая High Availability.

# 8. Какие виды балансировщиков нагрузки (ELB) есть в AWS?
- ALB (Application Load Balancer): L7 (HTTP/HTTPS/gRPC). Маршрутизирует по путям (URL), хостам, поддерживает WAF, WebSocket, аутентификацию (OIDC). Идеален для микросервисов.
- NLB (Network Load Balancer): L4 (TCP/UDP). Экстремально быстрый (обрабатывает миллионы запросов), пробрасывает трафик напрямую. Поддерживает статические (Elastic) IP.
- Classic Load Balancer: устаревший балансировщик (стараются не использовать).
- GWLB (Gateway Load Balancer): для развертывания сторонних виртуальных фаерволов в облаке.

# 9. Что такое Amazon Route 53?
Route 53 — это управляемый DNS-сервис (высокодоступный и масштабируемый).
Умеет: регистрировать домены, маршрутизировать трафик (с поддержкой сложных политик: Weighted, Latency-based, Geolocation, Failover), а также выполнять Health Checks для перенаправления трафика от упавших регионов.

# 10. В чем отличие SQS (Simple Queue Service) от SNS (Simple Notification Service)?
SQS — это очередь сообщений (Message Queue). Модель Pull: потребители (Consumers) сами опрашивают очередь и забирают сообщения. Сообщение хранится, пока его не обработают и не удалят. Гарантирует доставку (решает проблему пиковых нагрузок и связи микросервисов).
SNS — это сервис уведомлений (Pub/Sub). Модель Push: издатель отправляет сообщение в Topic, а SNS рассылает его всем подписавшимся (на Email, SMS, HTTP-эндпоинт, или в ту же SQS очередь). Сообщение не сохраняется.

# 11. Что такое AWS CloudFormation?
CloudFormation — это родной IaC (Infrastructure as Code) инструмент от AWS. Он позволяет декларативно описать нужную инфраструктуру в формате JSON или YAML (Template). CF читает шаблон и автоматически провижинит ресурсы (создавая Stack). Конкурент Terraform (но работает только внутри AWS).

# 12. Разница между AWS EKS и ECS?
Оба являются сервисами оркестрации контейнеров.
ECS (Elastic Container Service) — проприетарный сервис от AWS. Намного проще в настройке, глубоко интегрирован в сервисы AWS (IAM, ALB), меньше накладных расходов.
EKS (Elastic Kubernetes Service) — управляемый (Managed) Kubernetes в AWS. Это стандартный open-source K8s, просто контрол-плейном (мастером) управляет сам AWS. Сложнее, но не привязывает вендорлоком (Vendor Lock-in) к AWS, приложения легко перенести в другое облако.

# 13. Что такое Fargate?
Fargate — это Serverless движок вычислений (Compute) для контейнеров (работает с ECS и EKS).
При использовании EC2 вы сами создаете виртуалки и объединяете их в кластер (нужно следить за их ОС и патчингом). С Fargate вы вообще не управляете инстансами. Вы просто говорите: "запусти мой контейнер, ему нужно 2 CPU и 4 ГБ памяти". AWS сам выделяет ресурсы под контейнер "из воздуха" и берет плату за время работы контейнера.

# 14. Что такое AWS CloudWatch и CloudTrail?
CloudWatch — сервис мониторинга ресурсов AWS (сбор метрик, логов, создание дашбордов и алертов). Например, графики использования CPU инстансами EC2.
CloudTrail — сервис аудита безопасности (API логирование). Он записывает КТО, КОГДА и ОТКУДА сделал API вызов в AWS аккаунте. (Например, "Пользователь John удалил базу данных в 14:05").

# 15. Как работает AWS KMS (Key Management Service)?
KMS используется для создания и управления криптографическими ключами. С помощью KMS можно шифровать данные "at rest" (в покое) в EBS, S3, RDS. Выдачей прав на использование ключей для шифрования/дешифрования управляет IAM. AWS берет на себя безопасное хранение мастер-ключа (Customer Master Key, CMK).

# 16. Что такое Amazon RDS и Aurora?
RDS (Relational Database Service) — управляемый сервис реляционных БД (Postgres, MySQL, Oracle). AWS сам делает бэкапы, ставит патчи на ОС, настраивает репликацию (Multi-AZ) и Failover.
Aurora — это специально созданная (написанная с нуля) AWS реляционная БД, совместимая с MySQL/Postgres. Она отвязывает compute от storage, хранит данные распределенно в 3х зонах доступности (в 6 копиях), работает до 5 раз быстрее стандартного MySQL и поддерживает мгновенные Read Replicas.

# 17. Что такое AWS Transit Gateway?
При большом количестве VPC (сотни аккаунтов) связывать их с помощью VPC Peering становится невозможно (VPC Peering не поддерживает транзитный трафик, и требуется создавать полномостовую топологию — каждый с каждым). 
Transit Gateway (TGW) — это центральный хаб (маршрутизатор), к которому подключаются все VPC, VPN соединения и Direct Connect. Позволяет управлять маршрутизацией централизованно.

# 18. Что такое AWS WAF (Web Application Firewall)?
Это файрвол прикладного уровня, защищающий веб-приложения от распространенных уязвимостей (OWASP Top 10), таких как SQL инъекции, Cross-Site Scripting (XSS), а также от HTTP флудов. Прикрепляется к ALB, API Gateway или CloudFront.

# 19. Что такое CloudFront?
Amazon CloudFront — это глобальная сеть доставки контента (CDN) от AWS. Она кэширует статический (видео, картинки, HTML) и динамический контент на Edge-локациях по всему миру, доставляя его пользователям с минимальными задержками и обеспечивая защиту от DDoS (в связке с AWS Shield).

# 20. Что такое AWS Organizations?
Сервис для централизованного управления несколькими AWS аккаунтами внутри одной компании. Позволяет объединить биллинг (Consolidated Billing, оплата с одной карты и получение общих скидок), а главное — применять глобальные политики безопасности (SCP - Service Control Policies). Например, через SCP можно запретить всем аккаунтам создавать ресурсы вне региона eu-central-1, и это правило обойти нельзя, даже обладая правами Root в дочернем аккаунте.
