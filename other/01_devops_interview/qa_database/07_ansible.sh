# 1. Что такое Ansible и в чем его главные преимущества?
Ansible — это open-source система конфигурационного управления и автоматизации ИТ.
Главные преимущества:
- Безагентный (Agentless): не требует установки агентов на управляемые серверы. Ему нужен только Python и SSH доступ.
- Декларативный синтаксис: конфигурация пишется на простом и читаемом языке YAML (Playbooks).
- Идемпотентность: безопасен для многократного запуска, изменяет только то, что не соответствует желаемому состоянию.

# 2. Из каких основных компонентов состоит Ansible архитектура?
1. Control Node: машина, на которой установлен Ansible и откуда запускаются команды.
2. Managed Nodes: серверы, которыми мы управляем (подключение по SSH/WinRM).
3. Inventory (Инвентарь): список управляемых серверов с их IP и группировкой.
4. Playbooks (Плейбуки): YAML-файлы, описывающие сценарии действий.
5. Modules (Модули): скрипты (обычно на Python), которые выполняют фактическую работу на узлах (создание файлов, установка пакетов).

# 3. Что такое Идемпотентность (Idempotency) в Ansible?
Это ключевое свойство, означающее, что выполнение одной и той же задачи (Task) несколько раз подряд не приведет к непредвиденным изменениям, если система уже находится в нужном состоянии. Например, если модуль `apt` должен установить `nginx`, при первом запуске он его установит, а при втором — проверит, что он уже стоит, и просто вернет статус "ok" (без изменений - changed: false). Не все модули идемпотентны по умолчанию (например, модуль `shell` не идемпотентен, если не настроить условия `creates`).

# 4. В чем разница между модулями shell и command?
Модуль `command` выполняет команду напрямую, минуя оболочку (shell). В нем не будут работать переменные окружения, перенаправления (`>`, `|`), логические операторы (`&&`, `||`). Он считается более безопасным.
Модуль `shell` запускает команду внутри `/bin/sh` (или другой указанной оболочки). Позволяет использовать все фичи терминала (пайпы, переменные $HOME). Оба модуля по умолчанию НЕ идемпотентны.

# 5. Что такое Ansible Roles (Роли)?
Роль — это способ организации плейбуков, переменных и шаблонов в стандартизированную структуру директорий для удобного переиспользования и обмена (например, через Ansible Galaxy).
Обычно роль содержит папки:
- `tasks/` (основные задачи)
- `handlers/` (обработчики событий)
- `defaults/` (переменные по умолчанию с низким приоритетом)
- `vars/` (переменные с высоким приоритетом)
- `templates/` (шаблоны Jinja2)
- `files/` (статичные файлы).

# 6. Что такое Handlers (Обработчики) и как они работают?
Handlers — это специальные задачи, которые выполняются только в том случае, если другая задача изменила состояние системы (status changed) и явно "уведомила" (notify) обработчик. 
Классический пример: если вы изменяете конфиг Nginx, вы добавляете `notify: restart nginx`. Обработчик выполнится только ОДИН раз в самом конце выполнения плейбука (play), даже если его вызвали несколько разных задач.

# 7. Что такое Inventory и какие форматы он поддерживает?
Inventory — это файл или скрипт, содержащий список хостов, которыми управляет Ansible.
Поддерживает форматы INI и YAML.
Хосты можно объединять в группы (например, `[webservers]`, `[dbservers]`), задавать переменные для конкретных хостов или групп. 
Также существует Dynamic Inventory (динамический инвентарь) — скрипты, которые запрашивают список хостов из облачных провайдеров (AWS, GCP) в реальном времени.

# 8. Что такое Ansible Facts (Факты)?
При старте плейбука Ansible по умолчанию запускает специальный модуль `setup` на управляемых хостах. Он собирает огромный объем системной информации (Факты): архитектура CPU, версия ОС, IP и MAC адреса, свободное место на дисках и т.д.
Эти данные становятся доступны в плейбуках в виде переменных (например, `ansible_os_family`). Если факты не нужны для плейбука, сбор можно отключить для ускорения работы: `gather_facts: no`.

# 9. Как использовать переменные в Ansible?
Переменные можно задавать:
- В Inventory (host_vars, group_vars).
- Внутри Playbook (блок `vars`).
- Как аргументы командной строки (`-e "var_name=value"`). ВАЖНО: они имеют самый ВЫСОКИЙ приоритет и переопределяют любые другие переменные.
В плейбуках (или шаблонах) к переменным обращаются через двойные фигурные скобки: `{{ var_name }}`.

# 10. Что такое Jinja2 Templates (Шаблоны) в Ansible?
Jinja2 — это язык шаблонизации Python, используемый в Ansible (модуль `template`). 
Он позволяет создавать динамические конфигурационные файлы. Вы пишете шаблон (например, `nginx.conf.j2`), в котором вставляете переменные `{{ port }}` или логику `{% if ssl_enabled %} ... {% endif %}`. Ansible применит переменные к шаблону и скопирует итоговый файл на сервер.

# 11. Что такое Ansible Vault и зачем он нужен?
Ansible Vault — инструмент для шифрования (AES256) конфиденциальных данных (паролей от БД, ключей API) внутри файлов с переменными, чтобы их можно было безопасно хранить в Git. 
Команды: `ansible-vault encrypt file.yml` или `ansible-vault create secret.yml`. 
При запуске плейбука с зашифрованными данными нужно передать пароль: `--ask-vault-pass` или указать файл с паролем `--vault-password-file`.

# 12. В чем разница между блоками Tasks и Pre_tasks/Post_tasks?
При использовании Ролей, порядок выполнения следующий:
1. `pre_tasks` (задачи, которые выполнятся до ролей).
2. Выполнение всех задач из `roles`.
3. `tasks` (основные задачи плейбука).
4. `post_tasks` (задачи, которые выполнятся после всего остального).
Каждый из этих блоков может триггерить свои handlers.

# 13. Как ограничить выполнение плейбука только на один сервер или группу?
При запуске плейбука используется флаг `--limit` (или `-l`).
Например:
- Ограничить одним хостом: `ansible-playbook site.yml --limit 192.168.1.10`
- Ограничить группой: `ansible-playbook site.yml --limit webservers`
- Выполнить на группе, исключив один хост: `ansible-playbook site.yml --limit 'webservers:!bad_host'`

# 14. Что такое Tags (Теги) и как их использовать?
Теги — это способ пометить определенные задачи (tasks) или роли, чтобы потом можно было запускать только их, пропуская весь остальной плейбук.
Пример: `tags: ['install', 'nginx']`.
Запуск только тасок с тегом: `ansible-playbook site.yml --tags "nginx"`.
Пропуск тасок с тегом: `ansible-playbook site.yml --skip-tags "nginx"`.

# 15. Как обрабатывать ошибки в Ansible (Ignore errors / Rescue)?
- `ignore_errors: yes`: Ansible проигнорирует ошибку в задаче и продолжит выполнение плейбука.
- `failed_when`: позволяет задать свое условие, при котором задача считается проваленной (например, если в выводе команды есть слово "ERROR").
- `block / rescue / always`: аналог try/catch/finally. Если задача в секции `block` падает, выполняется код из секции `rescue`, что позволяет написать логику отката.

# 16. Что такое Ansible Galaxy?
Это публичный репозиторий (hub) для поиска, скачивания и обмена Ansible Ролями (Roles) и Коллекциями (Collections), написанными комьюнити и вендорами. Позволяет не писать код с нуля (например, для установки PostgreSQL), а установить готовую качественную роль: `ansible-galaxy install geerlingguy.postgresql`.

# 17. Что такое Коллекции (Collections) в Ansible?
Начиная с Ansible 2.9, проект перешел на модульную архитектуру. Раньше все модули (тысячи штук) поставлялись "в коробке" с ядром Ansible. Теперь ядро (ansible-core) легкое, а плагины, модули и роли распространяются в виде Коллекций (Collections), которые разрабатываются и обновляются независимо от релиза самого Ansible (например, `community.kubernetes` или `amazon.aws`).

# 18. Чем отличается copy от fetch?
- `copy` копирует файл с Control Node (вашего компьютера) на Managed Node (удаленный сервер).
- `fetch` делает наоборот: скачивает файл с Managed Node на Control Node. (Используется для сбора логов или резервных копий).

# 19. Как повысить скорость работы Ansible?
- Отключить сбор фактов: `gather_facts: no`.
- Использовать конвейеризацию SSH (Pipelining): включает передачу нескольких команд в одной SSH сессии, уменьшая количество переподключений. Настраивается в `ansible.cfg` (`pipelining = True`).
- Использовать `Mitogen`: сторонний плагин, который заменяет стандартный механизм исполнения Ansible, ускоряя выполнение задач в 2-3 раза.
- Увеличить `forks` (по умолчанию 5): количество параллельных потоков подключения к серверам.

# 20. Как запустить задачу только на операционной системе Debian/Ubuntu?
Используя условный оператор `when` и факты (Ansible Facts).
Пример:
```yaml
- name: Install Nginx
  apt:
    name: nginx
    state: present
  when: ansible_os_family == "Debian"
```
Задача будет пропущена (skipped) на CentOS (где `ansible_os_family == "RedHat"`).
