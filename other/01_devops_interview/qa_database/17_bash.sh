# 1. Как в Bash прочитать файл построчно?
Используется цикл `while` в связке с командой `read`.
Пример:
```bash
while IFS= read -r line; do
  echo "Строка: $line"
done < "filename.txt"
```
Флаг `-r` предотвращает интерпретацию бэкслешей (обратных слешей), а `IFS=` сохраняет начальные и конечные пробелы.

# 2. Как перенаправить вывод ошибок (stderr) в стандартный вывод (stdout) в Linux bash?
Используется конструкция `2>&1`.
Файловые дескрипторы: 0 (stdin), 1 (stdout), 2 (stderr).
Пример: `ls /not/exist > output.log 2>&1`
Современный и более короткий синтаксис в bash: `&> output.log`.

# 3. Что означает $? в Bash?
`$?` хранит код возврата (exit status) последней выполненной команды.
Обычно код `0` означает успешное выполнение, а любое число больше нуля (часто от 1 до 255) означает ошибку.
Используется в условных конструкциях: `if [ $? -eq 0 ]; then echo "Success"; fi`.

# 4. Как написать скрипт на Bash, который остановит выполнение при любой ошибке?
В начале скрипта нужно добавить команду `set -e` (или `set -o errexit`). 
По умолчанию Bash продолжает выполнение скрипта, даже если одна из команд завершилась с ошибкой. `set -e` заставит скрипт немедленно завершиться. 
Рекомендуемый заголовок для надежных скриптов: `set -euxo pipefail`.

# 5. Что означает set -o pipefail?
В конвейере (pipe), например `command1 | command2`, код возврата всего пайпа равен коду возврата последней команды (`command2`). Если `command1` упадет, а `command2` выполнится успешно, скрипт (даже с `set -e`) продолжит работу. 
`set -o pipefail` заставляет пайп возвращать статус ошибки, если хотя бы ОДНА команда в цепочке завершилась с ошибкой.

# 6. В чем разница между $*, $@ и "$@"?
Все они используются для получения всех аргументов, переданных скрипту.
- `$*` — все аргументы как одна сплошная строка.
- `$@` — все аргументы как отдельные слова, но без защиты пробелов внутри аргументов.
- `"$@"` — сохраняет аргументы именно так, как они были переданы (с учетом пробелов). Это самый безопасный и правильный способ передачи аргументов (например, в цикле `for arg in "$@"`).

# 7. Как проверить, существует ли файл в Bash скрипте?
Используется оператор `-f` внутри конструкции `if` или `test` (`[ ]`).
```bash
if [ -f "/path/to/file.txt" ]; then
    echo "Файл существует."
fi
```
Для директорий используется `-d`, для символических ссылок `-L`, для проверки на чтение `-r`.

# 8. Что такое Shebang (#!/bin/bash) и зачем он нужен?
Shebang — это последовательность символов `#!` в самом начале скрипта, за которой следует путь к интерпретатору.
Когда вы запускаете скрипт как `./script.sh`, ядро Linux читает эту первую строку и понимает, какой программе передать этот файл на выполнение (например, `/bin/bash`, `/usr/bin/python3`, `/usr/bin/env node`).

# 9. Как в Bash получить текущую дату и время в нужном формате?
Используется команда `date` с форматом, начинающимся со знака `+`.
Например, для формата `ГГГГ-ММ-ДД`: `date +"%Y-%m-%d"`
Для сохранения в переменную (Command Substitution): `CURRENT_DATE=$(date +"%Y-%m-%d")`

# 10. В чем разница между [ ] и [[ ]] в Bash?
`[ ]` — это алиас для стандартной утилиты POSIX `test`. Внутри нужно аккуратно экранировать переменные (двойными кавычками), чтобы избежать проблем с пробелами или пустыми строками.
`[[ ]]` — это расширенный, встроенный синтаксис самого Bash (не поддерживается в чистом `sh`). Он более безопасен (не требует кавычек вокруг переменных, не делает word splitting) и поддерживает регулярные выражения (`=~`) и паттерн-матчинг.

# 11. Что делает команда awk '{print $1}'?
Утилита `awk` по умолчанию разбивает каждую строку ввода на поля (fields), используя пробел или табуляцию в качестве разделителя. Переменные `$1`, `$2` обозначают первое, второе поле. `$0` означает всю строку.
Команда `awk '{print $1}'` выведет только первое слово из каждой переданной ей строки.

# 12. Как с помощью sed заменить текст в файле?
Используется потоковый редактор `sed` с командой `s` (substitute).
`sed -i 's/old_text/new_text/g' file.txt`
Флаг `-i` (in-place) применяет изменения прямо в файле, а не выводит в консоль.
Флаг `g` (global) заменяет все вхождения в строке, а не только первое.

# 13. Что такое xargs?
Утилита `xargs` читает данные из стандартного ввода (stdin) и выполняет указанную команду, передавая ей эти данные в качестве аргументов.
Часто используется с `find`. Например, чтобы найти и удалить все `.log` файлы (даже если их тысячи и обычный `rm` упадет с ошибкой "Argument list too long"):
`find /var/log -name "*.log" | xargs rm -f`

# 14. Как задать значение переменной по умолчанию, если она пустая или не установлена?
Используется синтаксис параметра расширения (Parameter Expansion):
`PORT=${MY_PORT:-8080}`
Если переменная `MY_PORT` не установлена или пуста, переменной `PORT` будет присвоено значение `8080`.

# 15. В чем разница между переменными $VAR и ${VAR}?
Синтаксически это одно и то же — подстановка значения переменной.
Однако фигурные скобки `${VAR}` защищают имя переменной от склеивания с соседним текстом.
Пример: `echo "${VAR}able"`. Если написать `echo "$VARable"`, bash будет искать несуществующую переменную `VARable`.

# 16. Что такое Heredoc (<<EOF) в Bash?
Heredoc — это способ передать многострочный текст на стандартный ввод (stdin) команды, не используя внешние файлы.
Пример:
```bash
cat <<EOF > config.txt
server_name localhost;
listen 80;
EOF
```
Если использовать кавычки `<<"EOF"`, bash не будет интерпретировать переменные (например `$HOME`) внутри текста.

# 17. Как запустить процесс в фоне и как вернуть его на передний план?
Добавление амперсанда `&` в конце команды запускает её в фоновом режиме (background).
Пример: `sleep 100 &`
Команда `jobs` покажет список фоновых задач.
Команда `fg %1` (foreground) вернет первую фоновую задачу на передний план, а `bg %1` возобновит остановленную (через Ctrl+Z) задачу в фоне.

# 18. Как получить длину строки в переменной Bash?
Используется синтаксис параметра расширения с решеткой: `${#VAR_NAME}`.
Пример: 
`MY_STR="hello"`
`echo ${#MY_STR}` (Выведет 5).

# 19. Что такое nohup?
Когда вы закрываете терминал (или SSH-сессию), всем процессам, запущенным в этом терминале, отправляется сигнал `SIGHUP` (Hangup), который их завершает.
Команда `nohup` (No Hangup) запускает процесс с игнорированием этого сигнала, так что процесс продолжит работу даже после вашего отключения. Вывод по умолчанию сохраняется в файл `nohup.out`.
Пример: `nohup ./my_script.sh &`

# 20. Как написать бесконечный цикл на Bash?
```bash
while true; do
    echo "Running..."
    sleep 1
done
```
Или с использованием `for`:
```bash
for (( ; ; )); do
    echo "Running..."
    sleep 1
done
```
