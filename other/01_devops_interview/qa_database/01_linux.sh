# 1. Что такое Load Average в Linux?
Load Average показывает среднее количество процессов, находящихся в очереди на выполнение (в состоянии R - runnable) или ожидающих ввода-вывода (в состоянии D - uninterruptible sleep) за последние 1, 5 и 15 минут. Значение 1.0 на одноядерном процессоре означает, что ядро загружено на 100%.

# 2. В чем разница между жесткими (hard) и символическими (soft/symlink) ссылками?
Жесткая ссылка указывает непосредственно на inode файла. Если удалить исходный файл, жесткая ссылка продолжит работать, так как данные не удалятся, пока на inode есть хотя бы одна ссылка. Жесткие ссылки нельзя создавать для директорий и файлов в других файловых системах.
Символическая ссылка — это отдельный файл, содержащий путь к целевому файлу. Если удалить оригинал, симлинк станет нерабочим ("битым"). Симлинки работают между разными файловыми системами и могут указывать на директории.

# 3. Что такое inode в файловой системе Linux?
inode (индексный дескриптор) — это структура данных, которая хранит метаданные о файле: размер, права доступа, владельца, временные метки и указатели на блоки данных на диске. inode не содержит имени файла (имя хранится в структуре директории). Когда кончаются свободные inode (даже если есть место на диске), создание новых файлов становится невозможным.

# 4. Как найти процесс, который использует определенный порт (например, 80)?
Используются утилиты netstat, ss или lsof.
Примеры:
ss -tulnp | grep :80
lsof -i :80
netstat -tulnp | grep :80

# 5. Как посмотреть, что занимает место на диске?
Для проверки общего свободного места используется `df -h` (показывает использование дисков в человекочитаемом формате).
Для поиска самых больших файлов и директорий используется `du -sh *` (показывает размер папок в текущей директории) или `ncdu`.
Чтобы найти самые большие файлы в системе: `find / -type f -exec du -h {} + | sort -rh | head -n 10`

# 6. В чем разница между процессами в состоянии Zombie (z) и Orphan?
Процесс-зомби завершил свое выполнение, но его родительский процесс еще не считал код его возврата (не вызвал wait()). Зомби не занимают память или CPU, но занимают слот в таблице процессов (PID).
Процесс-сирота (orphan) — это процесс, родительский процесс которого завершился раньше него. Процесс-сирота "удочеряется" процессом init (или systemd, PID 1), который позже корректно его завершит.

# 7. Что произойдет, если удалить файл, который сейчас открыт и пишется процессом?
Имя файла исчезнет из директории (ссылка на inode удалится), но место на диске не освободится. Фактическое удаление данных произойдет только тогда, когда процесс закроет файловый дескриптор. Чтобы освободить место без перезапуска процесса, можно "обнулить" файл: `> filename` (или `echo "" > filename`).

# 8. Что такое OOM Killer и как он работает?
Out Of Memory (OOM) Killer — это механизм ядра Linux, который активируется при критической нехватке оперативной памяти. Он анализирует процессы на основе их `oom_score` (зависит от потребления памяти, прав, времени работы и других факторов) и убивает процесс с наивысшим баллом (обычно тот, что потребляет больше всего памяти), чтобы предотвратить падение всей системы (kernel panic).

# 9. Как безопасно перезагрузить зависший сервер Linux, если не работает консоль? (Magic SysRq)
Если ядро все еще живо, используются комбинации клавиш (SysRq). Метод называется REISUB:
Alt + SysRq + R (возвращает контроль над клавиатурой)
Alt + SysRq + E (отправляет SIGTERM всем процессам)
Alt + SysRq + I (отправляет SIGKILL всем оставшимся)
Alt + SysRq + S (Sync — сбрасывает буферы на диск)
Alt + SysRq + U (Umount — переводит ФС в режим только для чтения)
Alt + SysRq + B (Reboot — жесткая перезагрузка)

# 10. Как изменить права на файлы и директории рекурсивно, но задать разные права?
Использовать команду find в связке с chmod:
Директории (755): find /path -type d -exec chmod 755 {} \;
Файлы (644): find /path -type f -exec chmod 644 {} \;

# 11. Что такое Sticky bit, SUID и SGID?
SUID (Set owner User ID up on execution): позволяет запускать исполняемый файл с правами владельца файла (например, /usr/bin/passwd запускается от root).
SGID (Set Group ID): аналогично SUID, но для группы. На директориях означает, что все новые файлы внутри унаследуют группу директории.
Sticky bit: устанавливается на директории (например, /tmp) и означает, что удалить или переименовать файл может только его владелец.

# 12. В чем разница между TCP-протоколами и UDP на уровне сетевого стека Linux? (В контексте тюнинга)
В Linux TCP требует выделения буферов (tcp_rmem, tcp_wmem), управления конгестией (tcp_congestion_control) и отслеживания состояний соединений (nf_conntrack). UDP — stateless, не требует установления соединения, поэтому при высоких нагрузках не переполняет таблицы состояний, но тюнинг ограничивается размером очередей (rmem_max, wmem_max).

# 13. Что такое chroot и зачем он нужен?
chroot (change root) — операция, изменяющая видимый корневой каталог для текущего процесса и его дочерних процессов. Приложение, запущенное в chroot, не имеет доступа к файлам за пределами своей "тюрьмы". Используется для изоляции небезопасных сервисов или тестирования (прообраз контейнеров).

# 14. Как работает команда sudo и где хранится её конфигурация?
Команда sudo позволяет пользователям выполнять команды от имени другого пользователя (чаще всего root) с проверкой их собственного пароля (в отличие от su). Конфигурация хранится в файле `/etc/sudoers` и директории `/etc/sudoers.d/`. Редактировать sudoers следует только через утилиту `visudo`, которая проверяет синтаксис при сохранении, предотвращая блокировку доступа к системе.

# 15. Какова разница между systemctl restart и systemctl reload?
`restart` полностью останавливает сервис и запускает его заново (PID процесса меняется, происходит даунтайм, если сервис не имеет механизмов бесшовного рестарта).
`reload` отправляет процессу сигнал (обычно SIGHUP) перечитать конфигурационные файлы без завершения основного процесса. Сервис продолжает обрабатывать соединения.

# 16. Как посмотреть историю команд, и как выполнить поиск по истории?
Команда `history` выводит список ранее введенных команд. 
Для быстрого поиска используется сочетание клавиш `Ctrl+R` (reverse-i-search), где можно ввести часть команды.
Чтобы повторить последнюю команду: `!!`. Чтобы повторить команду по номеру: `!123`.

# 17. Что такое cgroups (Control Groups) в Linux?
cgroups — это механизм ядра Linux, который ограничивает, приоритизирует, учитывает и изолирует использование ресурсов (CPU, память, дисковый ввод-вывод, сеть) для групп процессов. Это одна из основополагающих технологий, на которых строятся контейнеры (Docker, LXC).

# 18. Что такое namespaces в Linux?
Namespaces (пространства имен) — это механизм ядра Linux, обеспечивающий изоляцию системных ресурсов для процессов. Различные пространства имен скрывают друг от друга PID, сеть, точки монтирования (mount), IPC, UTS (hostname) и пользователей. Вместе с cgroups формируют основу для работы контейнеров.

# 19. Разница между утилитами grep, awk и sed?
`grep` (Global Regular Expression Print) — утилита для поиска строк, соответствующих регулярному выражению.
`sed` (Stream Editor) — потоковый текстовый редактор, часто используемый для поиска и замены текста (`s/old/new/g`).
`awk` — мощный язык обработки текста и извлечения данных, отлично подходящий для работы с табличными данными (разделенными пробелами или другими разделителями), вычислений и форматирования.

# 20. Как работают сигналы в Linux (SIGTERM, SIGKILL, SIGINT)?
Сигналы используются для межпроцессного взаимодействия (IPC). 
- SIGTERM (15) — сигнал мягкого завершения. Процесс может перехватить его, закрыть файлы, сохранить данные и корректно завершиться. 
- SIGKILL (9) — жесткое завершение. Процесс не может перехватить или проигнорировать его, ядро убивает процесс немедленно. 
- SIGINT (2) — прерывание с клавиатуры (обычно отправляется при нажатии Ctrl+C).
