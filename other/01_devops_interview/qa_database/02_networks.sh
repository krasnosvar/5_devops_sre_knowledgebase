# 1. В чем разница между TCP и UDP?
TCP (Transmission Control Protocol) — это протокол с установкой соединения. Он гарантирует доставку пакетов (отправляет подтверждения - ACK), упорядочивает их и восстанавливает при потерях. Подходит для веб-трафика (HTTP), почты, SSH.
UDP (User Datagram Protocol) — это протокол без установки соединения. Он не гарантирует доставку и порядок пакетов, но работает значительно быстрее за счет отсутствия накладных расходов. Используется для видео/аудио стриминга, онлайн-игр, DNS, VoIP.

# 2. Опишите процесс TCP Handshake (трехкратное рукопожатие).
Трехкратное рукопожатие используется для установки TCP-соединения между клиентом и сервером.
1. Клиент отправляет пакет с флагом SYN (Synchronize) серверу, указывая свой начальный sequence number.
2. Сервер получает пакет и отвечает пакетом с флагами SYN и ACK (Acknowledgment), подтверждая получение и указывая свой sequence number.
3. Клиент получает SYN-ACK и отправляет пакет с флагом ACK, подтверждая получение ответа от сервера. Соединение установлено.

# 3. Что происходит, когда вы вводите URL (например, google.com) в браузере?
1. Браузер ищет IP-адрес домена (кэш браузера -> кэш ОС -> локальный /etc/hosts -> DNS-запрос к DNS-серверу).
2. Браузер инициирует TCP-соединение на порт 80 или 443 найденного IP-адреса.
3. Если используется HTTPS, происходит TLS-хендшейк (обмен сертификатами, генерация сеансовых ключей).
4. Браузер отправляет HTTP-запрос (GET) на сервер.
5. Сервер обрабатывает запрос и возвращает HTTP-ответ (HTML-код, статус 200 OK).
6. Браузер рендерит полученный HTML, запрашивает дополнительные ресурсы (CSS, JS, картинки) и закрывает соединение.

# 4. Какие существуют уровни модели OSI?
Модель OSI состоит из 7 уровней:
1. Физический (Physical) — биты по кабелю/радио (Ethernet кабель, оптика).
2. Канальный (Data Link) — кадры (frames), MAC-адреса, коммутаторы (Switches).
3. Сетевой (Network) — пакеты, IP-адреса, маршрутизаторы (Routers), ICMP.
4. Транспортный (Transport) — сегменты/датаграммы, порты, TCP/UDP.
5. Сеансовый (Session) — управление сессиями связи.
6. Представительский (Presentation) — кодирование, шифрование (SSL/TLS).
7. Прикладной (Application) — HTTP, FTP, DNS, SMTP.

# 5. Что такое DNS и какие типы записей вы знаете?
DNS (Domain Name System) — система, преобразующая доменные имена (example.com) в IP-адреса и обратно.
Основные типы записей:
- A — указывает IPv4-адрес.
- AAAA — указывает IPv6-адрес.
- CNAME (Canonical Name) — алиас на другое доменное имя. Не может указывать на IP и не может быть установлен в корне зоны (apex).
- MX (Mail Exchange) — указывает на почтовые серверы домена.
- TXT — текстовые данные (часто для валидации владения, SPF, DKIM).
- NS (Name Server) — указывает на авторитативные DNS-серверы зоны.
- PTR (Pointer) — обратная зона (IP в имя).

# 6. Что такое BGP и как он работает?
BGP (Border Gateway Protocol) — протокол внешней маршрутизации интернета. BGP обменивается информацией о маршрутизации между автономными системами (AS). Вместо выбора самого быстрого маршрута (как OSPF), BGP выбирает маршрут на основе политик, путей и правил (path-vector protocol), что позволяет маршрутизировать трафик между различными провайдерами глобально.

# 7. В чем разница между HTTP и HTTPS?
HTTP передает данные в открытом виде (plaintext). 
HTTPS инкапсулирует HTTP в криптографический протокол SSL/TLS. Данные шифруются, что обеспечивает конфиденциальность (защита от прослушивания, MITM), целостность (защита от изменения) и аутентификацию (сервер подтверждает свою подлинность цифровым сертификатом).

# 8. Что такое NAT и какие виды бывают?
NAT (Network Address Translation) — механизм трансляции IP-адресов. Позволяет устройствам с приватными (серыми) IP-адресами выходить в интернет через один или несколько публичных адресов.
Виды:
- Static NAT (1 к 1)
- Dynamic NAT (пул серых к пулу белых)
- PAT (Port Address Translation / NAT Overload) — самый частый вид (много к одному), трансляция происходит за счет подмены портов источника (masquerade).

# 9. Какие существуют классы и диапазоны частных (серых) IP-адресов по RFC 1918?
- Класс A: 10.0.0.0 — 10.255.255.255 (маска /8)
- Класс B: 172.16.0.0 — 172.31.255.255 (маска /12)
- Класс C: 192.168.0.0 — 192.168.255.255 (маска /16)
Эти адреса не маршрутизируются в публичном интернете.

# 10. Что такое Anycast?
Anycast — метод маршрутизации, при котором один и тот же IP-адрес назначается нескольким узлам (серверам), физически расположенным в разных местах. Запрос пользователя направляется маршрутизаторами (через BGP) на ближайший (с топологической точки зрения) к нему узел. Часто используется в CDN и корневых DNS.

# 11. Что означает маска подсети, например, /24?
/24 (CIDR нотация) означает, что первые 24 бита IP-адреса выделены под адрес сети (соответствует маске 255.255.255.0). Оставшиеся 8 бит используются для адресации хостов, что дает 256 адресов (254 доступных для устройств, т.к. первый — адрес сети, последний — broadcast).

# 12. Как работает утилита traceroute (tracert)?
traceroute отслеживает маршрут пакетов до целевого хоста. Он использует поле TTL (Time To Live) в IP-пакете. Сначала отправляет пакет с TTL=1. Первый маршрутизатор уменьшает TTL до 0 и возвращает ICMP-ответ "Time Exceeded". traceroute записывает адрес этого маршрутизатора и отправляет следующий пакет с TTL=2, достигая второго маршрутизатора, и так далее, пока пакет не достигнет цели (цель ответит ICMP Echo Reply или Port Unreachable).

# 13. Что такое VLAN и зачем он нужен?
VLAN (Virtual Local Area Network) — виртуальная локальная сеть. Механизм канального уровня (L2), позволяющий логически разделить одну физическую сеть на несколько изолированных широковещательных доменов (broadcast domains). Повышает безопасность и уменьшает количество широковещательного трафика.

# 14. Как работает ARP?
ARP (Address Resolution Protocol) — протокол, преобразующий IP-адрес (L3) в MAC-адрес (L2) в локальной сети. 
Устройство отправляет широковещательный запрос (broadcast): "У кого IP 192.168.1.10? Сообщите мне". Устройство с этим IP отвечает своим MAC-адресом. Полученные данные кэшируются (ARP table).

# 15. Чем отличается L3-балансировщик от L7-балансировщика?
- L3/L4 балансировщик (например, IPVS, HAProxy в tcp mode) работает на сетевом и транспортном уровнях. Он перенаправляет трафик, основываясь на IP и портах, не читая содержимое пакетов. Работает очень быстро, но не может принимать решения на основе URL или Cookie.
- L7 балансировщик (например, Nginx, HAProxy, Ingress Controller) работает на прикладном уровне (HTTP/HTTPS). Он полностью читает запрос и может маршрутизировать трафик на основе URL-путей, заголовков, доменов (Host header) и Cookie. Требует больше ресурсов (TLS termination).

# 16. Что такое MTU и MSS?
MTU (Maximum Transmission Unit) — максимальный размер полезного блока данных одного пакета (L2 фрейма), который может быть передан по сети без фрагментации (обычно 1500 байт для Ethernet).
MSS (Maximum Segment Size) — максимальный размер сегмента TCP (полезная нагрузка), вычисляется как MTU минус заголовки IP (20 байт) и TCP (20 байт). Обычно MSS = 1460 байт.

# 17. Что такое CDN и зачем она нужна?
CDN (Content Delivery Network) — географически распределенная сеть серверов, предназначенная для кэширования и доставки статического контента (изображения, скрипты, видео) пользователям из ближайшей к ним локации. Уменьшает задержки (latency), снижает нагрузку на origin-сервер и защищает от DDoS.

# 18. В чем суть атаки DDoS и какие основные типы существуют?
DDoS (Distributed Denial of Service) — атака, направленная на исчерпание ресурсов сервера или канала связи, делающая ресурс недоступным для легитимных пользователей.
Типы:
- Объемные (Volumetric) - UDP floods, NTP/DNS amplification (забивают полосу пропускания).
- Сетевые (Protocol) - SYN floods (исчерпывают таблицы состояний фаерволов и серверов).
- Прикладные (Application Layer L7) - HTTP floods (генерация сложных запросов для перегрузки CPU/RAM сервера или БД).

# 19. Что такое SNI?
SNI (Server Name Indication) — расширение протокола TLS. Оно позволяет клиенту передать доменное имя, к которому он пытается подключиться, еще во время TLS handshake. Это позволяет одному веб-серверу (одному IP-адресу) хостить несколько HTTPS-сайтов с разными SSL-сертификатами.

# 20. Как происходит завершение TCP-соединения (TCP Teardown)?
TCP завершает соединение с помощью 4 шагов (четырехкратное рукопожатие):
1. Инициатор (клиент) отправляет FIN-пакет.
2. Получатель (сервер) отвечает ACK. (В этот момент полузакрытое соединение, сервер еще может передавать данные).
3. Сервер отправляет свой FIN-пакет.
4. Клиент отвечает ACK. Соединение полностью закрыто.
