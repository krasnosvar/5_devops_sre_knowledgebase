# 1. В чем главные преимущества языка Go (Golang)?
- Высокая производительность: компилируется напрямую в машинный код (без виртуальной машины, как в Java/Python), работает очень быстро.
- Нативная многопоточность: невероятно легкие и мощные механизмы конкурентности (Goroutines и Channels).
- Статическая строгая типизация, предотвращающая множество багов на этапе компиляции.
- Статическая линковка: итоговое приложение — это один единственный бинарный файл без внешних зависимостей (идеально для крошечных Docker-контейнеров).
- Отличная стандартная библиотека (особенно для работы с сетью и HTTP).

# 2. Что такое Горутины (Goroutines) и чем они отличаются от потоков ОС (OS Threads)?
Горутина — это функция, выполняющаяся конкурентно вместе с другими функциями.
- Потоки ОС тяжелые, потребляют мегабайты памяти для стека. Горутины предельно легкие (стек начинается с ~2 KB и растет динамически).
- Переключение контекста между потоками ОС — дорогая операция ядра. Переключение горутин происходит в userspace рантаймом Go (Go Scheduler) и стоит доли микросекунды.
- В программе на Go можно легко запустить миллион горутин, тогда как тысяча потоков ОС убьет производительность сервера.
Создается простым добавлением ключевого слова: `go myFunction()`

# 3. Как устроен Go Scheduler (Планировщик)? Модель M:N.
Go использует модель планирования M:N. Это означает, что он мультиплексирует M горутин на N потоков операционной системы.
Архитектура состоит из трех сущностей:
- G (Goroutine): сама горутина.
- M (Machine): поток ОС.
- P (Processor): логический процессор (контекст выполнения), обычно их количество равно числу логических ядер CPU (`GOMAXPROCS`).
Каждый `P` имеет локальную очередь `G`. Если поток `M` блокируется (например, ожидая ответа от БД), `P` "отвязывается" от него и берет другой свободный `M`, чтобы продолжить выполнять свои горутины, обеспечивая непрерывную загрузку процессора.

# 4. Что такое Каналы (Channels)?
Каналы — это встроенный в Go механизм типизированного обмена данными и синхронизации между горутинами, исключающий состояние гонки (Race Condition).
Девиз Go: "Не общайтесь, разделяя память; разделяйте память, общаясь".
Создание: `ch := make(chan int)`
Запись: `ch <- 42`
Чтение: `val := <-ch`
Каналы бывают небуферизованными (синхронными, запись блокирует отправителя, пока получатель не прочтет) и буферизованными (с заданной емкостью, блокировка только при переполнении).

# 5. Что такое Defer?
Ключевое слово `defer` планирует выполнение переданной функции на момент ПЕРЕД возвратом из текущей (окружающей) функции (либо когда функция доходит до конца, либо при `return`, либо при панике).
Чаще всего используется для гарантированного освобождения ресурсов:
```go
file, err := os.Open("test.txt")
if err != nil { return err }
defer file.Close() // Гарантированно закроет файл
```
Вызовы defer помещаются в стек (LIFO - Last In, First Out), то есть выполняются в обратном порядке от их объявления.

# 6. Как обрабатываются ошибки в Go? В чем отличие от try/catch/except?
В Go нет исключений (exceptions) в классическом понимании. Ошибка — это обычное значение, реализующее встроенный интерфейс `error` (имеющее метод `Error() string`).
Функции, способные завершиться неудачей, возвращают ошибку как последнее значение. Программист обязан проверять ее явно:
```go
res, err := DoWork()
if err != nil {
    return fmt.Errorf("работы не будет: %w", err)
}
```
Это делает поток управления (Control Flow) явным, без скрытых переходов при исключениях, хотя и требует написания множества `if err != nil`.

# 7. Что такое Panic (паника) и Recover (восстановление)?
Паника — это механизм для обработки КРИТИЧЕСКИХ, невосстановимых ошибок программиста (выход за пределы массива, разыменование nil-указателя, тупик/дедлок). Паника немедленно прерывает выполнение текущей функции, вызывает все ее `defer`, и "всплывает" вверх по стеку вызовов, убивая приложение, если ее не остановить.
Остановить (перехватить) панику можно с помощью встроенной функции `recover()`, но только ВНУТРИ `defer` функции. В веб-серверах (Gin/Fiber) panic recovery middleware используется, чтобы при панике не падал весь сервер, а только возвращался HTTP 500 для одного запроса.

# 8. Что такое Интерфейсы (Interfaces) в Go и что значит "неявная реализация" (Implicit satisfaction)?
Интерфейс в Go определяет набор сигнатур методов (поведение).
В отличие от Java или C#, в Go не нужно использовать ключевое слово `implements`. Если структура (тип) имеет все методы, описанные в интерфейсе, значит, она автоматически реализует этот интерфейс (Утиная типизация / Duck Typing). Это позволяет писать интерфейсы постфактум, адаптируя чужой код без его изменения.
Также существует Пустой интерфейс `interface{}` (в новых версиях Go — алиас `any`), который не требует никаких методов, а значит, ему удовлетворяет абсолютно любой тип в Go.

# 9. Разница между Array (Массив) и Slice (Срез)?
- Массив (Array, `[5]int`): имеет ФИКСИРОВАННЫЙ размер, который задается при компиляции и является частью его типа. Нельзя изменить размер. Передается по значению (копируется весь массив). Используется редко.
- Срез (Slice, `[]int`): имеет ДИНАМИЧЕСКИЙ размер. Это просто легковесный дескриптор (структура из трех полей), указывающий на базовый массив: указатель на первый элемент массива, длина (Length, сколько элементов сейчас в срезе) и вместимость (Capacity, сколько памяти зарезервировано в базовом массиве). Срезы используются везде.

# 10. Как работает функция append() для слайсов? Что происходит при нехватке Capacity?
Функция `append(slice, elements...)` добавляет элементы в конец среза.
Если `len` < `cap` (в базовом массиве есть место), элемент просто записывается туда, а `len` увеличивается.
Если места нет (`len` == `cap`), `append` под капотом аллоцирует НОВЫЙ базовый массив большего размера (обычно в 2 раза больше текущего для небольших срезов, или в 1.25 раза для больших), копирует туда все старые элементы, добавляет новый, и возвращает новый срез, указывающий на новый массив. Старый массив удалится сборщиком мусора.

# 11. Что такое Map (Карта/Словарь) в Go и потокобезопасна ли она?
`map[string]int` — это встроенная неупорядоченная структура данных (хеш-таблица) для хранения пар ключ-значение. Сложность доступа в среднем O(1).
ВАЖНО: встроенная `map` НЕ является потокобезопасной (not thread-safe). Если одна горутина пишет в мапу, а другая одновременно читает или пишет, программа мгновенно упадет (Fatal error: concurrent map read and map write). Для конкурентного доступа нужно защищать `map` с помощью мьютекса (`sync.RWMutex`) или использовать `sync.Map`.

# 12. Что такое Context в Go и зачем он нужен?
Пакет `context` — стандартный способ передачи крайних сроков (deadlines), сигналов отмены (cancellation signals) и переменных области видимости (request-scoped values) через границы API (между горутинами).
Пример: к вам пришел HTTP-запрос, вы запустили горутину для долгого запроса в БД. Если пользователь закрыл вкладку в браузере, HTTP соединение рвется, контекст отменяется (`ctx.Done()`), горутина это замечает и отменяет тяжелый запрос в БД, экономя ресурсы сервера. Контекст всегда должен передаваться первым аргументом в функции `(ctx context.Context, ...)`.

# 13. Что такое sync.WaitGroup?
Это примитив синхронизации из пакета `sync`. Используется, когда нужно дождаться завершения группы горутин.
- `wg.Add(1)` — увеличивает счетчик (вызывается в главном потоке перед запуском горутины).
- `wg.Done()` — уменьшает счетчик на 1 (вызывается внутри горутины, обычно через `defer`).
- `wg.Wait()` — блокирует текущую (главную) горутину до тех пор, пока счетчик не станет равен нулю.

# 14. Что такое Мьютекс (sync.Mutex / sync.RWMutex)?
Мьютекс (Mutual Exclusion) — примитив синхронизации, обеспечивающий эксклюзивный доступ к общим данным (предотвращает состояние гонки / Race Condition).
- `Mutex.Lock()` блокирует доступ других горутин. Пока вы не вызовете `Unlock()`, другие горутины, дойдя до `Lock()`, остановятся и будут ждать.
- `RWMutex` (Read-Write Mutex) более эффективен, если данных много читают и редко пишут. `RLock()` позволяет МНОЖЕСТВУ горутин одновременно читать данные. Но `Lock()` (на запись) заблокирует и всех читателей, и других писателей.

# 15. Что такое Race Detector и как его использовать?
Состояние гонки (Data Race) — критический баг, возникающий, когда две горутины обращаются к одной переменной памяти одновременно, и как минимум одна операция — это запись. Поведение программы становится непредсказуемым.
В Go встроен детектор гонок. Его нужно включать во время тестирования или компиляции с флагом `-race` (например, `go test -race ./...` или `go run -race main.go`). Он инструментирует код и при выполнении выдаст подробный отчет, если обнаружит дата-рейс. (В продакшене не используется, так как замедляет код в 2-10 раз).

# 16. Разница между new() и make() в Go?
Обе встроенные функции выделяют память.
- `new(T)`: выделяет память под тип `T`, зануляет ее (Zero Value) и возвращает УКАЗАТЕЛЬ на эту память (`*T`). Используется для инициализации структур.
- `make(T)`: используется ТОЛЬКО для трех встроенных типов: срезов (slices), карт (maps) и каналов (channels). Она выделяет память, инициализирует внутренние структуры данных (указатели, длины) и возвращает ИНИЦИАЛИЗИРОВАННОЕ значение типа `T` (а не указатель). 

# 17. Что такое Zero Value (Нулевое значение)?
В отличие от C, где неинициализированная переменная содержит мусор, в Go переменной, объявленной без начального значения, гарантированно присваивается "Zero Value" (значение по умолчанию для ее типа):
- Числа (int, float) = `0`
- Строки (string) = `""` (пустая строка, а не nil!)
- Булевы (bool) = `false`
- Указатели, функции, интерфейсы, слайсы, мапы и каналы = `nil`.

# 18. Как в Go реализуется наследование (Inheritance)?
В Go нет классов и нет классического ООП с наследованием (нет иерархии типов).
Вместо наследования используется Композиция (Composition). Вы можете встроить (embed) одну структуру (Struct) в другую анонимно. Встроенная структура передает внешнему типу свои поля и методы, но при этом жесткой связи "is-a" не возникает. Это предотвращает проблему "хрупкого базового класса". Полиморфизм же достигается за счет Интерфейсов.

# 19. Что такое init() функция?
Это специальная функция в Go, не принимающая аргументов и ничего не возвращающая: `func init() {}`. Она выполняется АВТОМАТИЧЕСКИ рантаймом перед вызовом `main()`.
Если в пакете несколько файлов с `init()`, они все будут вызваны. Она используется для сложной инициализации глобального состояния пакета (например, регистрации драйвера базы данных). Злоупотреблять `init` не рекомендуется, так как это усложняет тестирование и понимание порядка загрузки.

# 20. Что такое Go Modules?
Go Modules (появились в Go 1.11) — это официальная система управления зависимостями в Go (замена старого GOPATH).
- `go mod init <module-name>`: создает файл `go.mod`, где описывается имя модуля, версия Go и прямые зависимости с их версиями.
- Файл `go.sum`: содержит криптографические хеши скачанных модулей (защита от подмены кода).
- `go mod tidy`: удаляет неиспользуемые зависимости и скачивает недостающие. Зависимости скачиваются в глобальный кэш (`$GOPATH/pkg/mod`), а не в папку проекта (в отличие от node_modules).
